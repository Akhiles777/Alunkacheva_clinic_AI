import type { NextConfig } from "next";

function allowedOrigins(): string[] {
  const domain = process.env.DOMAIN?.trim().replace(/^https?:\/\//, "").replace(/\/$/, "");
  const list = ["localhost:3000", "localhost:3001"];
  if (domain) list.push(domain, `www.${domain}`);
  return list;
}

/**
 * Отпечаток сборки.
 *
 * Платформа установлена как приложение и неделями не закрывается. После
 * обновления открытая вкладка остаётся на прежнем коде, а серверные действия
 * опознаются по идентификатору — у новой сборки он другой. Любая кнопка
 * отвечает «Failed to find Server Action», и снаружи это выглядит как
 * сломанная платформа: цена услуги не сохраняется, сообщение не уходит.
 *
 * Ловить это по тексту ошибки нельзя: в проде Next заменяет его безымянным
 * сообщением о сбое рендера, и до браузера настоящая причина не доезжает.
 * Поэтому сравниваем версии напрямую — значение попадает и в клиентский
 * бандл, и в ответ сервера, а у старой вкладки оно осталось прежним.
 */
const BUILD_ID = process.env.BUILD_ID || String(Date.now());

const nextConfig: NextConfig = {
  env: { NEXT_PUBLIC_BUILD_ID: BUILD_ID },
  generateBuildId: () => BUILD_ID,
  /**
   * Автономная сборка для контейнера: Next кладёт в .next/standalone сервер и
   * только те зависимости, которые действительно нужны. Образ выходит в разы
   * меньше, а на сервере не нужен ни npm install, ни node_modules целиком.
   */
  /*
   * Только когда об этом просят явно. `next start` с автономной сборкой не
   * работает и предупреждает об этом при каждом запуске, а на сервере мы
   * запускаемся именно им (см. ecosystem.config.cjs). Сборщику образа
   * достаточно передать NEXT_OUTPUT=standalone.
   */
  output: process.env.NEXT_OUTPUT === "standalone" ? "standalone" : undefined,
  /**
   * Каталог сборки.
   *
   * По умолчанию `.next` — тот же, из которого работает запущенное
   * приложение. Пересборка на живом сервере чистит его, работающий процесс
   * в это время держит и создаёт там файлы, и удаление падает с ENOTEMPTY.
   * Сборка умирает, оставив каталог разрушенным, — а заметно это становится
   * только при следующем перезапуске, когда сайт отвечает 502.
   *
   * Поэтому деплой собирает в отдельный каталог и подменяет рабочий только
   * после успеха: неудачная сборка не трогает то, что сейчас работает.
   */
  distDir: process.env.NEXT_DIST_DIR || ".next",
  // Значок dev-режима перекрывает профиль в сайдбаре и мешает скриншотам.
  devIndicators: false,
  experimental: {
    serverActions: {
      bodySizeLimit: "4mb",
      /**
       * Домены, с которых принимаются server actions.
       *
       * Формы входа, сохранения настроек и ответа пациенту — это server
       * actions, то есть POST на тот же адрес. Next сверяет заголовок Origin
       * с тем, за какой домен он себя считает, и при расхождении отклоняет
       * запрос. За обратным прокси такое расхождение возникает легко: nginx
       * должен передать и Host, и X-Forwarded-Host, и X-Forwarded-Proto — а
       * забыть один заголовок нечего не стоит. Снаружи это выглядит так, что
       * страница открывается, но любая кнопка её ломает.
       *
       * Список задаётся переменной DOMAIN на этапе сборки.
       */
      allowedOrigins: allowedOrigins(),
    },
  },
};

export default nextConfig;
