/**
 * Точка запуска фоновых задач приложения.
 *
 * Next.js вызывает register() один раз при старте серверного процесса. Это
 * единственное место, где можно завести расписание, не заводя отдельный сервис:
 * приложение под pm2 работает постоянно, и системный cron ему не нужен.
 *
 * Почему не cron: он оказался ненадёжным посредником. Строку вставили в
 * локальный терминал вместо сервера, потом она задвоилась, потом перестала
 * срабатывать — и всё это время никто не знал, идут ли данные, потому что о
 * своих неудачах cron пишет в почту, которую на сервере никто не читает.
 */
export async function register() {
  // Edge-окружение базы данных не видит: расписание только в Node.
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  const { startScheduler } = await import("@/lib/server/scheduler");
  startScheduler();

  /**
   * Отметка о запуске процесса.
   *
   * pm2 убивает приложение по пределу памяти МОЛЧА, и со стороны это выглядит
   * как «платформа слетела»: несколько секунд соединения не принимаются,
   * service worker показывает офлайн-заглушку, человек теряет набранное. Без
   * этой строки перезапуск не отличить от перебоя связи, и чинить приходится
   * наугад.
   *
   * Одна запись на процесс — не нагрузка. Падение здесь ничего не значит для
   * работы: учёт не должен мешать приложению подняться.
   */
  const { recordRestart } = await import("@/lib/server/restarts");
  void recordRestart();
}
