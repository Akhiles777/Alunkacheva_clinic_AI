#!/bin/sh
# Ежедневная резервная копия базы.
#
# Копия делается сжатым дампом в том, который живёт отдельно от данных базы.
# Этого мало: том на том же диске не спасёт от отказа диска или от удаления
# сервера. Копии нужно увозить с машины — как именно, описано в DEPLOY.md.
#
# Скрипт намеренно простой и без внешних зависимостей: чем меньше в нём
# движущихся частей, тем выше шанс, что он работает в тот день, когда
# понадобится.

set -eu

DIR=/backups
KEEP_DAYS="${BACKUP_KEEP_DAYS:-14}"

log() {
  echo "[backup $(date '+%Y-%m-%d %H:%M:%S')] $*"
}

make_backup() {
  stamp=$(date '+%Y%m%d-%H%M%S')
  tmp="$DIR/.in-progress-$stamp.sql.gz"
  final="$DIR/clinic-$stamp.sql.gz"

  # Пишем во временный файл и переименовываем только после успеха: оборванная
  # копия не должна выглядеть как готовая. Именно на этом обычно и обнаруживают,
  # что восстанавливать нечего.
  if ! pg_dump --no-owner --no-privileges 2>"$DIR/.last-error" | gzip -9 > "$tmp"; then
    log "ОШИБКА: pg_dump не отработал"
    sed 's/^/    /' "$DIR/.last-error" | head -5
    rm -f "$tmp"
    return 1
  fi

  # Проверяем содержимое, а не только факт завершения.
  #
  # Самый коварный отказ — несовпадение версий: pg_dump старше сервера
  # завершается с ошибкой, а в файле остаётся заголовок gzip и ничего больше.
  # Формально копия есть, фактически она пустая, и выясняется это в худший
  # момент. Поэтому ищем в дампе признаки настоящей выгрузки.
  if ! gunzip -c "$tmp" 2>/dev/null | head -40 | grep -q "PostgreSQL database dump"; then
    log "ОШИБКА: в копии нет заголовка дампа — проверьте версии pg_dump и сервера"
    sed 's/^/    /' "$DIR/.last-error" | head -5
    rm -f "$tmp"
    return 1
  fi
  if ! gunzip -c "$tmp" 2>/dev/null | grep -qE "^CREATE TABLE"; then
    log "ОШИБКА: в копии нет ни одной таблицы"
    rm -f "$tmp"
    return 1
  fi

  mv "$tmp" "$final"
  tables=$(gunzip -c "$final" | grep -cE "^CREATE TABLE" || true)
  log "готово: $(basename "$final"), $(du -h "$final" | cut -f1), таблиц: $tables"

  find "$DIR" -name 'clinic-*.sql.gz' -mtime "+$KEEP_DAYS" -delete
  log "храним за $KEEP_DAYS дней; файлов: $(find "$DIR" -name 'clinic-*.sql.gz' | wc -l | tr -d ' ')"
}

mkdir -p "$DIR"

# Первая копия сразу при старте: если контейнер подняли и забыли, к утру уже
# будет с чего восстанавливаться. Неудача здесь — повод разобраться немедленно,
# поэтому она видна в журнале контейнера отдельной строкой.
if ! make_backup; then
  log "ПЕРВАЯ КОПИЯ НЕ СОЗДАНА — разберитесь до того, как в базе появятся пациенты"
fi

# Дальше — раз в сутки. Простой цикл вместо cron: одна движущаяся часть вместо
# двух, и всё видно в журнале контейнера.
while true; do
  sleep 86400
  make_backup || true
done
