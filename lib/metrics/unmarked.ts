/**
 * Почему приём остался без отметки.
 *
 * «Не отмечено 2» на экране дня отвечает «сколько», а следующий вопрос
 * заказчика был точнее: «может, это те, кто перенёс запись, а может, админ
 * просто забыл». Это ДВА разных случая с разными действиями — позвонить
 * человеку или попросить администратора проставить отметку, — и гадать между
 * ними нельзя.
 *
 * Что известно наверняка, из устройства выгрузки:
 *
 *   · Перенос ПРАВКОЙ записи (время изменили у той же строки) уносит приём с
 *     сегодняшнего дня в течение короткого круга — трёх минут. В «не отмечено»
 *     он не задерживается.
 *   · Перенос ПЕРЕСОЗДАНИЕМ (запись удалили и завели заново) держится дольше:
 *     удалённые записи вычищает только полный круг, раз в четверть часа, и
 *     лишь по окну, которому можно верить. Всё это время старая строка висит в
 *     сегодняшнем дне и, когда её время прошло, попадает в «не отмечено».
 *   · Забытая отметка не уходит никогда — она так и остаётся до тех пор, пока
 *     человек её не проставит.
 *
 * Отсюда правило: свежая строка без отметки может быть переносом, а висящая
 * дольше получаса — почти наверняка забытая отметка. Но «почти наверняка» на
 * экран не выносится в одиночку: если у пациента есть ДРУГАЯ запись, заведённая
 * позже этой, — это и есть основание, и его показываем словами.
 */

/**
 * Сколько времени приём без отметки ещё может оказаться переносом.
 *
 * Полный круг ходит раз в четверть часа; берём вдвое с запасом на неудачный
 * круг. Дольше — значит выгрузка успела бы убрать перенесённую запись, и
 * причина в другом.
 */
export const MOVE_GRACE_MIN = 30;

export interface UnmarkedVisit {
  appointmentId: string;
  patientId: string | null;
  /** Время, на которое человек был записан: по нему сверяется перенос. */
  startAt: Date;
  /** Когда приём должен был закончиться: от него считается «давно висит». */
  endedAt: Date;
}

/** Другая запись того же пациента — возможный «новый» приём после переноса. */
export interface OtherBooking {
  appointmentId: string;
  startAt: Date;
  /** Когда её завели в YCLIENTS. */
  createdAt: Date;
}

/** Перенос, записанный выгрузкой: факт, а не вывод. */
export interface KnownMove {
  fromStartAt: Date;
  toStartAt: Date;
  exact: boolean;
}

export type UnmarkedKind =
  /** Выгрузка записала перенос этой записи — это факт. */
  | "moved"
  /** У пациента есть запись, заведённая позже этой. Вывод, не факт. */
  | "maybe_moved"
  /** Ничего не нашли, и висит давно: отметку забыли проставить. */
  | "forgotten"
  /** Висит недавно — судить рано. */
  | "too_early";

export interface UnmarkedVerdict {
  kind: UnmarkedKind;
  /** Основание словами. Без него вывод читается как «система так решила» (§9). */
  reason: string;
  /** Куда перенесли, если знаем. */
  movedTo: Date | null;
}

/**
 * Разобрать один приём без отметки.
 *
 * Порядок проверок — от факта к догадке. Записанный выгрузкой перенос не
 * нуждается в выводах; догадка идёт только там, где факта нет, и всегда
 * названа догадкой.
 */
export function explainUnmarked(
  visit: UnmarkedVisit,
  moves: KnownMove[],
  others: OtherBooking[],
  now: Date,
): UnmarkedVerdict {
  /**
   * Перенос именно ЭТОГО слота: сверяем по времени начала, а не по пациенту.
   * У человека бывает несколько записей, и чужой перенос к этой не относится.
   */
  const move = moves.find((m) => m.fromStartAt.getTime() === visit.startAt.getTime());
  if (move) {
    return {
      kind: "moved",
      reason: move.exact
        ? "выгрузка записала перенос этой записи"
        : "запись удалили и завели заново — выгрузка связала их как перенос",
      movedTo: move.toStartAt,
    };
  }

  /**
   * Запись, заведённая ПОСЛЕ того, как этот приём должен был начаться, — самый
   * похожий след переноса: администратор перенёс человека, создав новую.
   * Заведённая раньше ничего не говорит: пациент мог записаться на два приёма
   * заранее.
   */
  const later = others
    .filter((o) => o.createdAt > visit.startAt && o.appointmentId !== visit.appointmentId)
    .sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime())[0];
  if (later) {
    return {
      kind: "maybe_moved",
      reason: "у пациента есть другая запись, заведённая уже после этого приёма",
      movedTo: later.startAt,
    };
  }

  const waitedMin = (now.getTime() - visit.endedAt.getTime()) / 60_000;
  if (waitedMin < MOVE_GRACE_MIN) {
    return {
      kind: "too_early",
      reason: "приём закончился только что — выгрузка могла ещё не узнать о переносе",
      movedTo: null,
    };
  }

  return {
    kind: "forgotten",
    reason: "переноса не нашлось, а времени прошло достаточно: отметку не проставили",
    movedTo: null,
  };
}

/** Как вывод называется на экране. */
export const UNMARKED_LABEL: Record<UnmarkedKind, string> = {
  moved: "перенесён",
  maybe_moved: "похоже на перенос",
  forgotten: "отметку забыли",
  too_early: "судить рано",
};
