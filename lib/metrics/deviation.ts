/**
 * Что считать отклонением.
 *
 * Сводка владельцу существует ради одного: сказать, на что посмотреть. Значит
 * решающий вопрос не «как посчитать метрику», а «когда о ней стоит говорить».
 * Ошибка здесь дороже любой другой в этой функции: сводка, которая каждую
 * неделю кричит о колебаниях, перестаёт читаться за месяц, и вместе с ней
 * перестаёт читаться то единственное сообщение, ради которого она была нужна.
 *
 * Поэтому порог берётся из СОБСТВЕННОГО разброса клиники, а не из круглого
 * процента. «Выручка упала на 15%» ничего не значит само по себе: у клиники,
 * где неделя от недели гуляет на четверть, это будни, а у той, где она стоит
 * ровно, — событие.
 */

/** Сколько недель истории нужно, чтобы вообще было с чем сравнивать (6.5). */
export const MIN_HISTORY = 8;

/**
 * Порог модифицированного z-счёта.
 *
 * 3,5 — общепринятое значение для медианного правила. Взято не «на глаз»:
 * при нормальном разбросе оно отсекает примерно то же, что и три сигмы, но
 * не разваливается от одного выброса.
 */
export const SCORE_THRESHOLD = 3.5;

/**
 * Множитель, переводящий MAD в масштаб стандартного отклонения
 * (0,6745 = обратная величина к 75-му процентилю нормального распределения).
 */
const MAD_TO_SIGMA = 0.6745;

/**
 * Когда разброса нет вовсе.
 *
 * Все восемь недель дали одно и то же число — MAD равен нулю, и деление на
 * него объявило бы сенсацией любое отличие на единицу. На маленькой клинике
 * это обычное дело: «неявок 0, 0, 0, 0, 0, 0, 0, 0».
 *
 * Требование строгое — величина должна как минимум удвоиться. Ряд, который
 * ни разу не шелохнулся, ничего не говорит о том, какое движение для него
 * обычно, и осторожность тут дешевле: три неявки вместо двух это плюс
 * пятьдесят процентов и никакая не новость.
 */
const FLAT_MIN_SHARE = 1;

export type DeviationDirection = "up" | "down";

export interface Deviation {
  /** Насколько текущее значение выделяется. Чем больше, тем заметнее. */
  score: number;
  direction: DeviationDirection;
  /** Обычное значение клиники — медиана истории, а не среднее. */
  median: number;
  /** Разброс истории в тех же единицах. Ноль — недели стояли ровно. */
  spread: number;
  /** Стоит ли об этом говорить. */
  notable: boolean;
  /** Почему сравнения не было, если его не было. */
  skipped: "no-history" | "too-small" | null;
}

const median = (values: number[]): number => {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? (sorted[mid - 1] + sorted[mid]) / 2 : sorted[mid];
};

/**
 * Сравнить текущую неделю с историей клиники.
 *
 * `minAbsolute` — минимальный масштаб, ниже которого разговор бессмысленен:
 * две неявки вместо одной это плюс сто процентов и ничего не значит. Число
 * задаёт вызывающий, потому что оно своё у каждой метрики: для рублей это
 * тысячи, для неявок — единицы.
 */
export function deviationOf(
  history: number[],
  current: number,
  minAbsolute = 0,
): Deviation {
  const base = median(history);
  const direction: DeviationDirection = current >= base ? "up" : "down";
  const spread = median(history.map((v) => Math.abs(v - base)));

  const flat = (skipped: Deviation["skipped"], score = 0): Deviation => ({
    score,
    direction,
    median: base,
    spread,
    notable: false,
    skipped,
  });

  /**
   * Истории мало — сравнивать не с чем, и это говорится словами, а не
   * заменяется сравнением с тем, что есть. Три недели «нормой» не бывают.
   */
  if (history.length < MIN_HISTORY) return flat("no-history");

  const change = Math.abs(current - base);
  // Ничего не изменилось — обсуждать нечего, дальше можно не считать.
  if (change === 0) return flat(null);
  // Разница меньше порога осмысленности — не новость, каким бы ни был счёт.
  if (change < minAbsolute) return flat("too-small");

  if (spread === 0) {
    /**
     * Недели стояли ровно. Отличие настоящее, но масштаб ему задать нечем,
     * поэтому судим по доле от самой величины. Счёт назначаем на границе:
     * сказать «отклонение в бесконечность раз» нельзя.
     */
    const share = base === 0 ? 1 : change / Math.abs(base);
    if (share < FLAT_MIN_SHARE) return flat(null);
    /**
     * Счёт назначаем от порога и умножаем на долю. Плоская величина в
     * бесконечность раз не отклоняется, но упорядочить несколько таких
     * наблюдений между собой надо: без множителя все они получали ровно
     * `SCORE_THRESHOLD`, и в сводку первым попадало не самое заметное, а
     * то, что раньше стояло в списке.
     */
    return {
      score: SCORE_THRESHOLD * share,
      direction,
      median: base,
      spread,
      notable: true,
      skipped: null,
    };
  }

  const score = (MAD_TO_SIGMA * change) / spread;
  return {
    score,
    direction,
    median: base,
    spread,
    notable: score >= SCORE_THRESHOLD,
    skipped: null,
  };
}

/**
 * Достаточно ли в неделе жизни, чтобы о ней вообще что-то говорить.
 *
 * Праздники и отпуск дают неделю с двумя приёмами, и любая доля на ней —
 * шум с видом наблюдения. Такую неделю называем прямо, а не разбираем (6.5).
 */
export function tooQuiet(appointments: number, history: number[]): boolean {
  if (history.length === 0) return appointments === 0;
  const usual = median(history);
  if (usual === 0) return appointments === 0;
  return appointments < usual * 0.3;
}

/** Медиана наружу: ею считаются «обычные» значения и в сводке, и в тестах. */
export { median };
