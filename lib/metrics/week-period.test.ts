import { describe, expect, it } from "vitest";
import { isPeriodKey, isWeekKey, weekBounds, weekKeyOf, weekLabel } from "./types";

/**
 * Календарная неделя как период отчёта. Появилась потому, что график владельца
 * показывал полные недели, а отчёт — последние семь дней: под одним словом
 * «неделя» стояли 205 и 215 тысяч.
 */
describe("неделя как период", () => {
  it("узнаёт ключ недели и не принимает произвольный день", () => {
    expect(isWeekKey("w2026-08-10")).toBe(true); // понедельник
    expect(isWeekKey("w2026-08-12")).toBe(false); // среда
    expect(isWeekKey("2026-08")).toBe(false);
    expect(isPeriodKey("w2026-08-10")).toBe(true);
  });

  it("границы — понедельник и следующий понедельник по времени клиники", () => {
    const { from, to } = weekBounds("w2026-08-10");
    expect(from.toISOString()).toBe("2026-08-09T21:00:00.000Z");
    expect(to.toISOString()).toBe("2026-08-16T21:00:00.000Z");
  });

  it("ключ недели по дате — тот же понедельник", () => {
    // Воскресенье 16 августа поздно вечером всё ещё относится к неделе с 10-го.
    expect(weekKeyOf(new Date("2026-08-16T18:00:00Z"))).toBe("w2026-08-10");
    // Понедельник 17-го — уже следующая неделя.
    expect(weekKeyOf(new Date("2026-08-17T09:00:00Z"))).toBe("w2026-08-17");
  });

  it("полночь клиники в воскресенье не уезжает в следующую неделю", () => {
    // 16 августа 23:30 по Москве = 20:30 UTC. По UTC это всё ещё воскресенье,
    // но проверка нужна именно на пограничном часе.
    expect(weekKeyOf(new Date("2026-08-16T21:30:00Z"))).toBe("w2026-08-17");
  });

  it("подпись читает человек", () => {
    expect(weekLabel("w2026-08-10")).toBe("10–16 авг");
  });
});
