/**
 * Тексты обучения — в одном месте.
 *
 * Подсказка у кнопки и статья в справке отвечают на один и тот же вопрос, и
 * написаны они здесь один раз. Две копии одного объяснения расходятся на
 * второй правке, и человек получает два разных ответа на один вопрос — после
 * этого он не верит ни одному и идёт спрашивать голосом.
 *
 * Правило текстов: сначала ответ, потом причина. Администратор читает первую
 * строку, а не абзац; если ответа в ней нет, он закрывает подсказку.
 */

export interface Hint {
  /** Ключ подсказки: по нему её ставят рядом с элементом. */
  id: string;
  /** Что это. Одна фраза — она показывается при наведении. */
  short: string;
  /** Подробности: показываются в справке под тем же заголовком. */
  long?: string;
}

