/**
 * Как называется визит.
 *
 * У записи бывает несколько услуг: мать записывает себя и ребёнка одной
 * записью, к приёму добавляют капельницу, сеанс курса идут вместе с
 * консультацией. Название визита всё это время бралось у ПЕРВОЙ услуги, а
 * сумма показывалась за все — «Взрослый приём — остеопатия, 13 000 ₽» при цене
 * приёма 8 000. Число противоречило прайсу, и владелец справедливо читал это
 * как ошибку платформы.
 *
 * Правильный ответ: у визита из нескольких услуг нет одного имени. Его имя —
 * это его состав. Одна услуга — её название; несколько — все, через «+».
 *
 * Функция одна на всю систему: карточка пациента, экран дня, разбор выручки,
 * расписание и экран врача называют визит одинаково. Иначе на одном экране
 * приём «Взрослый», на другом «Взрослый + Детский», и это снова две правды об
 * одной записи.
 */

export interface VisitPartName {
  title: string;
}

/** Что показать вместо названия, когда услуги нет вовсе. */
export const NO_SERVICE = "услуга не указана";

/**
 * Название визита по его составу.
 *
 * `fallback` — основная услуга записи: она остаётся именем, пока состав не
 * записан (старые визиты) или пока услуга в нём одна.
 *
 * Повторы схлопываются: две капельницы за приём — это «Внутривенное капельное
 * введение растворов», а не оно же дважды. Сколько их было, видно по составу и
 * по сумме, а в названии повтор только мешает.
 */
export function visitTitle(parts: VisitPartName[] | undefined, fallback: string): string {
  const names = [
    ...new Set((parts ?? []).map((p) => p.title.trim()).filter((t) => t.length > 0)),
  ];
  if (names.length === 0) return fallback.trim() || NO_SERVICE;
  return names.join(" + ");
}

/**
 * Нужно ли расписывать состав отдельной строкой.
 *
 * Одну услугу перечислять незачем — она уже названа. Две и больше объясняют
 * сумму, которая иначе не сходится с прайсом.
 */
export function needsBreakdown(parts: { title: string }[] | undefined): boolean {
  return new Set((parts ?? []).map((p) => p.title.trim()).filter(Boolean)).size > 1;
}
