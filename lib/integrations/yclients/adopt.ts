/**
 * Как справочник клиники сходится со справочником YCLIENTS.
 *
 * Услуги у клиники уже задваивались: одна строка заведена руками в настройках,
 * вторая приехала из YCLIENTS под тем же названием. Визиты ссылались на
 * приезжую, кабинет был указан у заведённой — и кабинет визита не находился
 * вовсе. Чинили это отдельным скриптом, но причина осталась: выгрузка создаёт
 * новую строку всякий раз, когда не узнаёт номер YCLIENTS.
 *
 * То же самое ждёт кабинеты и специалистов. Кабинеты клиника завела у нас
 * руками, потому что в YCLIENTS их как ресурсы не ведут; заведут — и выгрузка
 * добавит вторые три кабинета рядом с первыми.
 *
 * Поэтому перед созданием ищем свою строку с тем же названием и без номера
 * YCLIENTS. Название — единственное, что у этих двух записей общего, и
 * совпадение здесь не случайно: справочник клиники маленький, а названия в нём
 * пишет один и тот же человек.
 */

/**
 * Название к сравнимому виду.
 *
 * Регистр, ё/е, кавычки и лишние пробелы различают строки, которые человек
 * считает одинаковыми: «Кабинет 1 — процедурный» и «Кабинет 1 – Процедурный».
 */
export function normalizeTitle(value: string): string {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"'`]/g, "")
    .replace(/[—–-]/g, "-")
    .replace(/\s+/g, " ")
    .trim();
}

/** Совпадают ли названия с точки зрения человека. */
export function sameTitle(a: string, b: string): boolean {
  return normalizeTitle(a) === normalizeTitle(b) && normalizeTitle(a).length > 0;
}

/**
 * Найти свою строку, которую пора связать с YCLIENTS.
 *
 * Возвращает идентификатор ровно тогда, когда кандидат один. Два одинаковых
 * названия без номера — это уже беспорядок в справочнике клиники, и выбирать
 * за неё нельзя: свяжем не ту, и визиты уедут к чужой услуге.
 */
export function adoptCandidate<T extends { id: string; title: string }>(
  remoteTitle: string,
  ownRows: T[],
  /**
   * Номер уже занят другой нашей строкой.
   *
   * Значит эта услуга из YCLIENTS давно у нас есть — под своим номером и, судя
   * по всему, под тем же названием. Связывать вторую строку с тем же номером
   * нельзя: уникальный ключ этого не позволит, и выгрузка справочника упадёт
   * целиком. Так и случилось на боевом сервере: «Услуги — ошибка, Unique
   * constraint failed».
   *
   * Задвоение при этом никуда не девается, но чинится оно объединением строк,
   * а не подменой номера на ходу.
   */
  alreadyLinked = false,
): string | null {
  if (alreadyLinked) return null;
  const matches = ownRows.filter((r) => sameTitle(r.title, remoteTitle));
  return matches.length === 1 ? matches[0].id : null;
}
