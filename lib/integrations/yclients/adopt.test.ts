import { describe, expect, it } from "vitest";
import { adoptCandidate, normalizeTitle, sameTitle } from "./adopt";

/**
 * Услуги клиники уже задваивались: заведённая руками и приехавшая из YCLIENTS
 * под тем же названием. Визиты ссылались на одну, кабинет был указан у другой,
 * и кабинет визита не находился вовсе.
 */
describe("сопоставление справочников по названию", () => {
  it("различия, которых человек не видит, не мешают", () => {
    expect(sameTitle("Кабинет 1 — процедурный", "Кабинет 1 – Процедурный")).toBe(true);
    expect(sameTitle("Остеопатия, приём Ирины", "остеопатия,  приём ирины")).toBe(true);
    expect(sameTitle("Приём «Лотос»", "Прием Лотос")).toBe(true);
  });

  it("разные услуги не сливаются", () => {
    expect(sameTitle("Остеопатия - дети", "Остеопатия")).toBe(false);
    expect(sameTitle("Кабинет 1", "Кабинет 2")).toBe(false);
  });

  it("пустое название ни с чем не совпадает", () => {
    expect(sameTitle("", "")).toBe(false);
    expect(sameTitle("  ", "Кабинет 1")).toBe(false);
  });

  it("нормализация устойчива", () => {
    expect(normalizeTitle("  Приём   Ирины  ")).toBe("прием ирины");
  });
});

describe("кого связывать с YCLIENTS", () => {
  const own = [
    { id: "a", title: "Кабинет 1 — процедурный" },
    { id: "b", title: "Кабинет 2 — БОС-терапии" },
  ];

  it("одна своя строка с тем же названием — связываем её", () => {
    expect(adoptCandidate("Кабинет 1 - Процедурный", own)).toBe("a");
  });

  it("своей строки нет — создаём новую", () => {
    expect(adoptCandidate("Кабинет 3 — остеопата", own)).toBeNull();
  });

  it("две одинаковые свои строки — не выбираем за клинику", () => {
    // Связать не ту значит увести визиты к чужой услуге. Пусть лучше появится
    // третья строка: беспорядок видно, а данные целы.
    const messy = [
      { id: "a", title: "Массаж" },
      { id: "b", title: "массаж" },
    ];
    expect(adoptCandidate("Массаж", messy)).toBeNull();
  });
});
