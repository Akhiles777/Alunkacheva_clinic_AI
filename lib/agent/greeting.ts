import { CLINIC_NAME } from "@/lib/brand";
import { greetingUsed } from "./text-actions";

/**
 * Что отвечать на приветствие.
 *
 * Здесь ошиблись трижды в одну сторону. Сначала агент не читал приветствие,
 * заданное клиникой, и здоровался словами модели. Потом появилась защита от
 * повторов — и на второе «здравствуйте» пациент стал получать сухое «Слушаю
 * вас», без единого приветственного слова. Потом ответ стал приветствием, но
 * всегда одним и тем же: «здравствуйте» на что угодно.
 *
 * Правило: **как поздоровался пациент, так и отвечаем**. На «доброе утро» —
 * «доброе утро», на «салам алейкум» — «ва алейкум ассалам». Это не
 * украшательство: дежурная фраза на любое приветствие сразу выдаёт
 * автоответчик, а в Дагестане ответ на салам — ещё и обычная вежливость,
 * которую замечают.
 *
 * Дальше — по длине. Первый раз добавляем вводную клиники: там сказано, чем
 * агент может помочь. На повторное приветствие вводную не зачитываем — в
 * середине разговора это выглядит как собеседник, забывший предыдущие реплики.
 */

/** Чем отвечаем на каждое приветствие. Ключи — как в GREETINGS. */
const MIRROR: Record<string, string> = {
  здравствуйте: "Здравствуйте!",
  здравствуй: "Здравствуйте!",
  "добрый день": "Добрый день!",
  "доброе утро": "Доброе утро!",
  "добрый вечер": "Добрый вечер!",
  "доброй ночи": "Доброй ночи!",
  привет: "Привет!",
  приветствую: "Приветствую!",
  // На салам отвечают ответным саламом — это не перевод, а формула ответа.
  салам: "Ва алейкум ассалам!",
  "салам алейкум": "Ва алейкум ассалам!",
  "ассалам алейкум": "Ва алейкум ассалам!",
  "ассаламу алейкум": "Ва алейкум ассалам!",
  hello: "Hello!",
  hi: "Hi!",
};

/** Если приветствие не распознано — здороваемся нейтрально. */
const NEUTRAL = "Здравствуйте!";

/**
 * Вводная клиники без приветственного слова в начале.
 *
 * Клиника пишет в настройках «Здравствуйте! Это клиника…», и если приклеить
 * это к ответному «Доброе утро!», получится «Доброе утро! Здравствуйте! Это
 * клиника…». Здороваться дважды в одном сообщении незачем.
 */
const LEADING_GREETING =
  /^(здравствуйте|здравствуй|добрый день|доброе утро|добрый вечер|доброй ночи|приветствую|привет|hello|hi)[!,.\s—-]*/iu;

export const DEFAULT_INTRO =
  `Это клиника «${CLINIC_NAME}». Расскажу про услуги, цены, адрес, часы работы, ` +
  "подготовку к процедурам и условия отмены. Запись и переносы ведёт администратор — передам ему.";

/** Что говорим после приветствия, когда вводная уже звучала. */
const SHORT_TAIL = "Слушаю вас.";

export function greetingText(input: {
  /** Текст пациента: по нему выбираем ответное приветствие. */
  incoming: string;
  /** Приветствие клиники из «Настройки → Ассистент». */
  configured?: string | null;
  /** Вводная в этом разговоре уже звучала. */
  repeat: boolean;
}): string {
  const used = greetingUsed(input.incoming);
  const hello = (used && MIRROR[used]) || NEUTRAL;

  if (input.repeat) return `${hello} ${SHORT_TAIL}`;

  const own = (input.configured ?? "").trim();
  const intro = (own || DEFAULT_INTRO).replace(LEADING_GREETING, "").trim();
  // Клиника могла завести приветствие, состоящее из одного «Здравствуйте!» —
  // тогда после снятия приветственного слова не остаётся ничего.
  return intro ? `${hello} ${intro}` : hello;
}
