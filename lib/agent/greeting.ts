import { CLINIC_NAME } from "@/lib/brand";

/**
 * Что отвечать на приветствие.
 *
 * Здесь дважды ошиблись в одну сторону. Сначала агент не читал приветствие,
 * заданное клиникой, и здоровался словами модели. Потом появилась защита от
 * повторов — и на второе «здравствуйте» пациент стал получать сухое «Слушаю
 * вас», без единого приветственного слова. Со стороны это выглядит как
 * собеседник, который не хочет здороваться: человек поздоровался, а ему не
 * ответили.
 *
 * Правило простое: **поздоровались — здороваемся в ответ, всегда**. Разница
 * только в длине. Первый раз — полное приветствие клиники: это первое, что
 * видит пациент, и там сказано, чем агент может помочь. Дальше — короткое
 * «Здравствуйте!», потому что зачитывать вводную по второму разу в середине
 * разговора значит показать, что предыдущих реплик собеседник не помнит.
 */

/** Приветствие по умолчанию, если клиника не задала своё в настройках. */
export const DEFAULT_GREETING =
  `Здравствуйте! Это клиника «${CLINIC_NAME}». Расскажу про услуги, цены, адрес, часы работы, ` +
  "подготовку к процедурам и условия отмены. Запись и переносы ведёт администратор — передам ему.";

/** Короткий ответ, когда полное приветствие в этом разговоре уже прозвучало. */
const SHORT_GREETING = "Здравствуйте! Слушаю вас.";

export function greetingText(input: { configured?: string | null; repeat: boolean }): string {
  if (input.repeat) return SHORT_GREETING;
  const own = (input.configured ?? "").trim();
  return own || DEFAULT_GREETING;
}
