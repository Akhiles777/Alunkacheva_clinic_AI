import { describe, expect, it } from "vitest";
import { intakePrompt, looksLikeIntake, DEFAULT_INTAKE_PROMPT, MAX_INSTRUCTION_CHARS, asksForIntake, inIntakeFlow, nameFromIntake,
  asksForPersonalData,
  withoutPersonalDataRequest,
} from "./intake";

/**
 * Строки взяты из живых переписок клиники: именно так пациенты присылают
 * данные для записи, когда администратор их просит.
 */
describe("данные для записи", () => {
  it("узнаёт присланную анкету", () => {
    for (const t of [
      "Магомедова Гульбара Халитовна 23 года 61 кг боли в пояснице,онемение тела",
      "Алиева Малика. 34. 45. Поясница и челюсть.",
      "Вайсулов Умар Магоммедвалиевич 6 лет,22 кл.Энурез",
      "Муталимова Муслимат 22 года",
    ]) {
      expect(looksLikeIntake(t), t).toBe(true);
    }
  });

  it("не принимает за анкету обычные реплики", () => {
    for (const t of [
      "Сколько стоит приём?",
      "Здравствуйте",
      "Хотела записаться к остеопату",
      "Да",
      "Приём нужен взрослому",
      "Ирина Алункачева принимает?",
    ]) {
      expect(looksLikeIntake(t), t).toBe(false);
    }
  });

  it("анкета важнее медицинских слов", () => {
    // В жалобе есть «боли» — по словам это медицинский текст. Если решать по
    // ним, ассистент ответит «уточните у специалиста» на данные, которые сам
    // же и попросил.
    expect(looksLikeIntake("Магомедова Гульбара 23 года 61 кг боли в пояснице")).toBe(true);
  });
});

describe("инструкция ассистента", () => {
  it("пусто — работает по образцу", () => {
    expect(intakePrompt("")).toBe(DEFAULT_INTAKE_PROMPT);
    expect(intakePrompt(null)).toBe(DEFAULT_INTAKE_PROMPT);
    expect(intakePrompt("   ")).toBe(DEFAULT_INTAKE_PROMPT);
  });

  it("текст клиники побеждает образец", () => {
    expect(intakePrompt("Спрашивай только имя и телефон.")).toBe("Спрашивай только имя и телефон.");
  });

  it("образец доводит разговор до записи, а не до отписки", () => {
    // Смысл правки: раньше на «хочу записаться» разговор обрывался шаблоном.
    expect(DEFAULT_INTAKE_PROMPT).toMatch(/ФИО/);
    expect(DEFAULT_INTAKE_PROMPT).toMatch(/цену/);
    expect(DEFAULT_INTAKE_PROMPT).toMatch(/администратор/i);
  });
});

/**
 * Ответ на вопрос, который агент задал сам.
 *
 * Живой случай: агент спросил «для взрослого или ребёнка и с какой жалобой»,
 * пациентка ответила «взрослая женщина, головная боль» — и получила «этот
 * вопрос лучше уточнить у специалиста». Человек выполнил просьбу и был послан
 * по кругу, запись сорвалась.
 */
describe("оформление записи", () => {
  it("узнаёт вопрос агента про данные", () => {
    for (const t of [
      "Это приём для взрослого или для ребёнка? И кратко опишите, с какой жалобой вы обращаетесь.",
      "Пришлите, пожалуйста, данные: ФИО, возраст, вес и город.",
      "Сколько лет ребёнку?",
      "Как к вам обращаться?",
    ]) {
      expect(asksForIntake(t), t).toBe(true);
    }
  });

  it("обычный ответ по справке оформлением не считает", () => {
    for (const t of [
      "Приём остеопата стоит 8000 ₽ и длится 40 минут.",
      "Мы работаем с понедельника по субботу.",
      "Здравствуйте! Слушаю вас.",
    ]) {
      expect(asksForIntake(t), t).toBe(false);
    }
  });

  it("жалоба в ответ на свой же вопрос — часть записи", () => {
    const history = [
      { role: "user" as const, content: "Хотела бы записаться к остеопату" },
      { role: "assistant" as const, content: "Для взрослого или ребёнка? Опишите, с какой жалобой." },
    ];
    expect(inIntakeFlow(history)).toBe(true);
  });

  it("вне оформления медицинские правила работают как прежде", () => {
    const history = [
      { role: "user" as const, content: "Сколько стоит приём?" },
      { role: "assistant" as const, content: "Приём остеопата стоит 8000 ₽." },
    ];
    expect(inIntakeFlow(history)).toBe(false);
  });
});

describe("имя из анкеты", () => {
  it("берёт ФИО из начала строки", () => {
    expect(nameFromIntake("Магомедова Гульбара Халитовна 23 года 61 кг боли в пояснице")).toBe(
      "Магомедова Гульбара Халитовна",
    );
    expect(nameFromIntake("Алиева Малика. 34. 45. Поясница")).toBe("Алиева Малика");
  });

  it("не выдумывает имя там, где его нет", () => {
    expect(nameFromIntake("Взрослая женщина, головная боль")).toBeNull();
    expect(nameFromIntake("сколько стоит приём")).toBeNull();
  });
});

describe("длина инструкции", () => {
  /**
   * Чем длиннее инструкция клиники, тем слабее модель держится за базовые
   * правила, которые идут перед ней. «Не обещай запись» дороже любого
   * регламента, поэтому длину режем.
   */
  it("длинный регламент обрезается", () => {
    const long = "а".repeat(MAX_INSTRUCTION_CHARS + 500);
    expect(intakePrompt(long).length).toBe(MAX_INSTRUCTION_CHARS);
  });

  it("обычная инструкция проходит целиком", () => {
    const text = "Спрашивай ФИО, возраст и жалобу одним сообщением.";
    expect(intakePrompt(text)).toBe(text);
  });
});

/**
 * Согласие берётся перед запросом персональных данных — так в §7 и так в
 * инструкции клиники. Значит надо точно знать, когда мы их просим.
 */
describe("просьба прислать персональные данные", () => {
  it("узнаёт запрос данных", () => {
    for (const t of [
      "Пришлите, пожалуйста, одним сообщением: ФИО, возраст и кратко причину обращения.",
      "Напишите ФИО пациента и дату рождения.",
      "Укажите, пожалуйста, имя и город.",
      "Для записи нужны ФИО ребёнка, возраст и жалобы.",
    ]) {
      expect(asksForPersonalData(t), t).toBe(true);
    }
  });

  it("возрастная группа услуги персональными данными не является", () => {
    for (const t of [
      "Подскажите, для взрослого или для ребёнка?",
      "Приём нужен взрослому или ребёнку?",
      "Взрослый приём — 8000 ₽, 45 минут.",
      "Мы находимся в Махачкале, улица Ленина, 1.",
    ]) {
      expect(asksForPersonalData(t), t).toBe(false);
    }
  });

  it("вырезает просьбу, оставляя полезное", () => {
    const text =
      "Взрослый приём остеопата — 8000 ₽, 45 минут. Пришлите, пожалуйста, ФИО, возраст и кратко причину обращения.";
    const kept = withoutPersonalDataRequest(text);
    expect(kept).toContain("8000");
    expect(kept).not.toContain("ФИО");
  });

  it("ответ без просьбы не трогает", () => {
    const text = "Мы работаем с 09:00 до 21:00. Воскресенье — выходной.";
    expect(withoutPersonalDataRequest(text)).toBe(text);
  });
});

/**
 * Анкета с знаком между именами.
 *
 * «Магомедовы: Ислам 8 лет и Амина 12 лет, оба плохо спят» — двоеточие
 * разрывало правило, сообщение не считалось анкетой, и данные двоих детей
 * были приняты и переданы администратору без согласия на обработку.
 */
describe("анкета в живых формах", () => {
  it("узнаёт данные двоих детей через двоеточие", () => {
    expect(looksLikeIntake("Магомедовы: Ислам 8 лет и Амина 12 лет, оба плохо спят")).toBe(true);
  });

  it("узнаёт имя с возрастом", () => {
    expect(looksLikeIntake("Ислам Русланович 6 лет, часто плачет по ночам")).toBe(true);
  });

  it("приветствие с именем врача анкетой не считает", () => {
    expect(looksLikeIntake("Здравствуйте! Ирина принимает 8 числа?")).toBe(false);
    expect(looksLikeIntake("Добрый день. Разият Ризвановна работает завтра?")).toBe(false);
  });

  /**
   * Флаг `i` рядом с `\p{Lu}` в JavaScript складывает регистры, и «ему 8 лет»
   * проходило как «Имя 8 лет». Ответ «для сына, ему 8 лет» принимался за
   * анкету, хотя ни имени, ни фамилии в нём нет.
   */
  it("строчное слово с возрастом анкетой не считает", () => {
    expect(looksLikeIntake("Для сына, ему 8 лет")).toBe(false);
    expect(looksLikeIntake("мне 34 года, хочу записаться")).toBe(false);
  });

  /**
   * «Опыт 5 лет» — человек искал работу, а сообщение приняли за анкету
   * пациента: вместо ответа руководства он получил юридическую стену.
   */
  it("нарицательное слово с возрастом анкетой не считает", () => {
    expect(looksLikeIntake("Можно ли у вас устроиться массажистом? Опыт 5 лет")).toBe(false);
    expect(looksLikeIntake("Ребёнку 8 лет, что взять с собой?")).toBe(false);
  });

  it("обычные вопросы анкетой не считает", () => {
    expect(looksLikeIntake("Сколько стоит приём остеопата 45 минут?")).toBe(false);
    expect(looksLikeIntake("Записана на 8 сентября")).toBe(false);
  });
});
