import { phraseRe, wordRe } from "./word-boundary";

/**
 * Страховка от обещания записать.
 *
 * По §6 расписанием агент не распоряжается: запись, перенос, отмену и
 * свободное время ведёт администратор. В промпте это написано, но промпт —
 * просьба, а не гарантия: на боевом стенде ассистент всё равно заявил
 * пациенту, что сам его запишет. Цена такой ошибки — пришедший к закрытой
 * двери человек, поэтому решение не должно зависеть только от модели.
 *
 * Проверяем готовый ответ перед отправкой. Нашли обещание — ответ не
 * отправляем, зовём человека.
 */

/**
 * Обороты, которыми модель обещает распорядиться расписанием. Ищем глаголы от
 * первого лица и подтверждения брони, а не само слово «запись»: «запись ведёт
 * администратор» — правильный ответ, его глушить нельзя.
 */
const PROMISE_PATTERNS: RegExp[] = [
  wordRe("запишу|записываю|записал[аи]?|запишем|записываем"),
  wordRe("забронирую|бронирую|забронировал[аи]?|забронируем"),
  phraseRe("поставлю|ставлю|поставил[аи]?", "вас|тебя"),
  // «подберу вам удобное время», «подберём окно» — слова между глаголом и
  // существительным необязательны, поэтому шаблон записан целиком.
  /(?<!\p{L})(?:подберу|подбираю|подбер[её]м)(?:\s+(?:вам|тебе))?(?:\s+удобн\p{L}+)?\s+(?:время|окно|слот)(?!\p{L})/iu,
  phraseRe("оформлю", "вам|вас|запись"),
  phraseRe("вы", "записаны"),
  phraseRe("запись", "создана|оформлена|подтверждена"),
  phraseRe("жд[её]м", "вас", "\\d{1,2}[:.]\\d{2}"),
];

/** Есть ли в ответе обещание записать, перенести или подобрать время. */
export function promisesBooking(text: string): boolean {
  return PROMISE_PATTERNS.some((re) => re.test(text));
}

/**
 * Ответ, который отправляем вместо обещания. Не извиняемся за платформу и не
 * объясняем устройство бота — пациенту важно, что его вопрос дошёл до
 * человека.
 */
export const HANDOVER_REPLY =
  "Записью занимается администратор — я передал ему ваше сообщение, он ответит здесь и подберёт удобное время.";
