import { describe, expect, it } from "vitest";
import { forMessenger } from "./messenger-text";

/**
 * В мессенджере разметки нет. Всё, что модель или справочник поставили как
 * markdown, пациент видит буквально: «**персональный план**» со звёздочками
 * наружу читается как сломанное сообщение.
 */
describe("текст для мессенджера", () => {
  it("убирает звёздочки жирного текста, оставляя слова", () => {
    expect(forMessenger("Направляю **персональный план** восстановления")).toBe(
      "Направляю персональный план восстановления",
    );
  });

  it("убирает курсив и подчёркивание", () => {
    expect(forMessenger("Это *важно* и __нужно__")).toBe("Это важно и нужно");
  });

  it("маркер списка превращает в точку", () => {
    expect(forMessenger("* взрослый приём\n+ детский приём")).toBe("• взрослый приём\n• детский приём");
  });

  it("снимает заголовки решёткой", () => {
    expect(forMessenger("## Услуги\nПриём — 8000 ₽")).toBe("Услуги\nПриём — 8000 ₽");
  });

  it("не трогает звёздочку внутри слова и умножение", () => {
    // «8000*2» и «2*3» — это текст пациента о числах, а не разметка.
    expect(forMessenger("Курс 5 приёмов, 8000*5 = 40000")).toBe("Курс 5 приёмов, 8000*5 = 40000");
  });

  it("убирает одинокую звёздочку от незакрытой разметки", () => {
    expect(forMessenger("Цена 8000 ₽ * без скидки")).toBe("Цена 8000 ₽ без скидки");
  });

  it("обычный текст оставляет как есть", () => {
    const text = "Приём остеопата стоит 8000 ₽ и длится 40 минут.";
    expect(forMessenger(text)).toBe(text);
  });
});
