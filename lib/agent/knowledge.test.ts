import { describe, expect, it } from "vitest";
import { confidentMatch, KNOWLEDGE_MIN_SCORE, matchKnowledge, type KnowledgeRow } from "./knowledge";

/**
 * Подбор справки — место, где ошибка означает выдуманный медицинский ответ
 * пациенту. Проверяем, что при непопадании ассистент молчит, а не «угадывает».
 */
const ROWS: KnowledgeRow[] = [
  { topic: "Адрес", question: "Где вы находитесь?", answer: "Москва, ул. Примерная, 1." },
  {
    topic: "Подготовка к капельнице",
    question: "Как готовиться к IV-терапии?",
    answer: "Лёгкий приём пищи за 1–2 часа до процедуры, обычный питьевой режим.",
  },
  {
    topic: "Противопоказания к остеопатии",
    question: "Кому нельзя остеопатию?",
    answer: "Острые воспаления, онкология в активной фазе, свежие травмы — приём переносится.",
  },
];

describe("matchKnowledge", () => {
  it("находит запись по теме подготовки", () => {
    const m = matchKnowledge("как готовиться к капельнице?", ROWS);
    expect(m?.row.topic).toBe("Подготовка к капельнице");
    expect(m!.score).toBeGreaterThanOrEqual(KNOWLEDGE_MIN_SCORE);
  });

  it("находит противопоказания", () => {
    const m = matchKnowledge("какие противопоказания к остеопатии", ROWS);
    expect(m?.row.topic).toBe("Противопоказания к остеопатии");
    expect(m!.score).toBeGreaterThanOrEqual(KNOWLEDGE_MIN_SCORE);
  });

  it("на посторонний вопрос уверенность ниже порога", () => {
    const m = matchKnowledge("а можно мне пить антибиотики вместе с этим", ROWS);
    expect(m === null || m.score < KNOWLEDGE_MIN_SCORE).toBe(true);
  });

  it("пустой справочник ничего не даёт", () => {
    expect(matchKnowledge("адрес", [])).toBeNull();
  });

  it("пустой вопрос ничего не даёт", () => {
    expect(matchKnowledge("   ", ROWS)).toBeNull();
  });
});

describe("confidentMatch", () => {
  it("односложный вопрос не считается уверенным совпадением", () => {
    // «а капельница?» — одно значимое слово, доля 1.0, но смысл неясен:
    // спрашивают цену или подготовку. Такое отдаём модели с контекстом.
    const m = matchKnowledge("а капельница?", ROWS);
    expect(m!.score).toBeGreaterThanOrEqual(KNOWLEDGE_MIN_SCORE);
    expect(confidentMatch(m)).toBe(false);
  });

  it("развёрнутый вопрос по теме — уверенное совпадение", () => {
    expect(confidentMatch(matchKnowledge("как готовиться к капельнице", ROWS))).toBe(true);
  });

  it("пустое совпадение не уверенное", () => {
    expect(confidentMatch(null)).toBe(false);
  });
});

describe("совпадение по названию темы", () => {
  it("однословный вопрос «адрес» находит тему «Адрес»", () => {
    const m = matchKnowledge("адрес", ROWS);
    expect(m?.row.topic).toBe("Адрес");
    expect(confidentMatch(m)).toBe(true);
  });

  it("«какой у вас адрес» тоже уверенно", () => {
    expect(confidentMatch(matchKnowledge("какой у вас адрес", ROWS))).toBe(true);
  });

  it("слово не из темы одно по себе не даёт уверенности", () => {
    // «режим» нет ни в одной теме — угадывать нельзя.
    expect(confidentMatch(matchKnowledge("режим", ROWS))).toBe(false);
  });
});

/**
 * Случай с боевого стенда: «есть ли услуги остеопата» попадало в запись
 * «Как готовиться к приёму остеопата» — совпали слово «остеопата» и глагол
 * «есть» из фразы «не есть плотно за час». Пациент получал инструкцию по
 * подготовке вместо ответа про услуги.
 */
describe("служебные слова не считаются совпадением", () => {
  const rows = [
    {
      topic: "Подготовка",
      question: "Как готовиться к приёму остеопата?",
      answer: "Приходите в удобной одежде, не есть плотно за час до приёма.",
    },
    {
      topic: "Первый приём",
      question: "Что взять на первый приём?",
      answer: "Паспорт и медицинские документы, если они у вас есть.",
    },
    { topic: "Адрес", question: "Где находитесь?", answer: "Островского 20а, 2 этаж." },
  ];

  it("вопрос про наличие услуги не уходит в подготовку", () => {
    expect(confidentMatch(matchKnowledge("есть ли услуги остеопата", rows))).toBe(false);
    expect(confidentMatch(matchKnowledge("Есть ли у вас остеопат?", rows))).toBe(false);
  });

  it("прямой вопрос по теме по-прежнему отвечается справкой", () => {
    expect(confidentMatch(matchKnowledge("какой адрес", rows))).toBe(true);
    expect(confidentMatch(matchKnowledge("как готовиться к приёму остеопата", rows))).toBe(true);
  });
});

/**
 * «ё» и «е». Пациенты почти никогда не набирают «ё», клиника в справочнике
 * пишет грамотно — без приведения совпадений не было ни одного.
 */
describe("буква ё не мешает совпадению", () => {
  const rows = [
    {
      topic: "Подготовка к остеопатии",
      question: "Как готовиться к приёму остеопата?/ что взять к остеопату?",
      answer: "Приём проводится в нижнем белье.",
    },
  ];

  it("вопрос через «е» находит запись, написанную через «ё»", () => {
    expect(confidentMatch(matchKnowledge("как подготовиться к приему остеопата", rows))).toBe(true);
  });

  it("и наоборот", () => {
    expect(confidentMatch(matchKnowledge("подготовка к приёму остеопата", rows))).toBe(true);
  });
});

describe("вопрос не подменяется похожим", () => {
  /** Две записи клиники, из-за которых пациент получил ответ не по делу. */
  const rows = [
    {
      topic: "прием мужчин",
      question:
        "Принимает ли остеопат мужчин?/ принимает ли Ирина Алилгадживна мужчин?/ принимает ли Разият Ризвановна мужчин?/ принимаете ли мужчин в клинике?",
      answer: "Остеопатический приём взрослых мужчин не проводится.",
    },
    {
      topic: "Сколько стоит приём остеопата и сколько он длится?",
      question:
        "сколько стоит остеопат/ цена остеопата/ стоимость приема/ сколько стоит прием/ сколько длится прием",
      answer: "Взрослый приём — 8 000 ₽.",
    },
  ];

  it("вопрос о цене у конкретного врача попадает в запись о цене", () => {
    // По отдельным словам обе записи совпадают одинаково: в записи про мужчин
    // перечислено «принимает ли Разият Ризвановна мужчин?». Различает порядок
    // слов — «сколько стоит приём» есть только в записи о цене.
    const m = matchKnowledge("К остеопату. Сколько стоит прием у Разият Ризвановны?", rows);
    expect(m?.row.topic).toBe("Сколько стоит приём остеопата и сколько он длится?");
  });

  it("вопрос про мужчин по-прежнему попадает в свою запись", () => {
    const m = matchKnowledge("Принимаете ли вы мужчин?", rows);
    expect(m?.row.topic).toBe("прием мужчин");
  });

  it("незнакомое имя не даёт дословного ответа", () => {
    // Дословный ответ обещает «это ответ именно на ваш вопрос». Если врача в
    // записи нет, обещание ложное — пусть отвечает модель по всему справочнику.
    const m = matchKnowledge("Сколько стоит приём у Магомедовой Патимат Курбановны?", [rows[0]]);
    expect(confidentMatch(m)).toBe(false);
  });
});
