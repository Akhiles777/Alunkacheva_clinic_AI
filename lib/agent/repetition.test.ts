import { describe, expect, it } from "vitest";
import { alreadyGreeted, alreadySaid } from "./repetition";
import type { Turn } from "./llm";

const bot = (content: string): Turn => ({ role: "assistant", content });
const patient = (content: string): Turn => ({ role: "user", content });

const PRICES =
  "В клинике принимают два врача-остеопата: Алункачева Ирина Алилгаджимовна — взрослый приём 8 000 ₽, " +
  "детский 5 000 ₽; Мугадова Разият Ризвановна — взрослый приём 5 000 ₽.";

describe("повторы бота", () => {
  it("узнаёт дословный повтор", () => {
    expect(alreadySaid([bot(PRICES)], PRICES)).toBe(true);
  });

  it("узнаёт повтор с добавленной припиской", () => {
    // Справочная запись уходит то с подсказкой про специалиста, то без неё:
    // строки уже не равны, а пациент видит тот же текст.
    const withTail = `${PRICES}\n\nЕсли есть особенности здоровья — уточните у специалиста.`;
    expect(alreadySaid([bot(withTail)], PRICES)).toBe(true);
  });

  it("другой ответ повтором не считает", () => {
    expect(alreadySaid([bot(PRICES)], "Мы работаем с понедельника по субботу с 08:00 до 16:00.")).toBe(false);
  });

  it("повтор за пациентом повтором не считается", () => {
    // Пациент вправе переспрашивать теми же словами — это не заедание бота.
    expect(alreadySaid([patient(PRICES)], PRICES)).toBe(false);
  });

  it("короткие подтверждения повторять можно", () => {
    // «Спасибо», «Хорошо» — нормальная речь, запрещать их бессмысленно.
    expect(alreadySaid([bot("Хорошо, передал администратору.")], "Хорошо, передал администратору.")).toBe(false);
  });

  it("пустая история повторов не даёт", () => {
    expect(alreadySaid([], PRICES)).toBe(false);
  });
});

describe("повторное приветствие", () => {
  it("после нашего приветствия здороваться заново нельзя", () => {
    expect(alreadyGreeted([bot("Здравствуйте! Чем помочь?"), patient("а цены?")])).toBe(true);
  });

  it("узнаёт приветствие клиники из настроек", () => {
    const hello = "Здравствуйте! Вы обратились в Клинику доктора Алункачевой☘️";
    expect(alreadyGreeted([bot(hello)], hello)).toBe(true);
  });

  it("служебная реплика приветствием не считается", () => {
    // Главная ошибка первой версии: к моменту первого живого «здравствуйте»
    // бот уже прислал запрос согласия, и пациент получал «Слушаю вас» вместо
    // приветствия клиники.
    const consent = "Прежде чем продолжить: нам нужно ваше согласие на обработку персональных данных.";
    expect(alreadyGreeted([bot(consent)])).toBe(false);
    expect(alreadyGreeted([bot("Спасибо!")])).toBe(false);
  });

  it("в начале диалога здороваемся", () => {
    expect(alreadyGreeted([])).toBe(false);
    expect(alreadyGreeted([patient("Добрый день")])).toBe(false);
  });
});

/**
 * Приветствие с обращением впереди.
 *
 * Модель здоровается по-русски: «Патимат, здравствуйте!». Проверка
 * «начинается со здравствуйте» такое не узнавала, и агент дописывал своё —
 * пациент получал «Здравствуйте! Патимат, здравствуйте!».
 */
describe("приветствие узнаётся с обращением", () => {
  const turn = (content: string) => ({ role: "assistant" as const, content });

  it("узнаёт «Имя, здравствуйте!»", () => {
    expect(alreadyGreeted([turn("Патимат, здравствуйте! БОС-терапия — это…")])).toBe(true);
  });

  it("узнаёт «Здравствуйте, Имя!» — обращение после приветствия", () => {
    expect(alreadyGreeted([turn("Здравствуйте, Патимат! БОС-терапия — это…")])).toBe(true);
  });

  it("узнаёт обычное приветствие в начале", () => {
    expect(alreadyGreeted([turn("Здравствуйте! Слушаю вас.")])).toBe(true);
  });

  it("не считает приветствием слово посреди длинной фразы", () => {
    expect(
      alreadyGreeted([turn("Работаем в будни с девяти, добрый день у нас начинается рано")]),
    ).toBe(false);
  });

  it("деловой ответ приветствием не считает", () => {
    expect(alreadyGreeted([turn("Взрослый приём — 8000 ₽, 45 минут.")])).toBe(false);
  });
});
