import { describe, expect, it } from "vitest";
import { offCharacter, stripPreamble } from "./llm";

/**
 * Заслон на ответ, вышедший из роли.
 *
 * Найден живым прогоном: на вопрос о беременности модель ответила
 * «I'm Claude, an AI assistant made by Anthropic…» — по делу, но по-английски
 * и от чужого имени. Пациент получил бы сообщение на незнакомом языке и узнал
 * бы, что говорит с моделью.
 */
describe("ответ вне роли", () => {
  it("представился моделью — не отправляем", () => {
    expect(offCharacter("I'm Claude, an AI assistant made by Anthropic.")).toBe(true);
    expect(offCharacter("Как ИИ-ассистент от Anthropic, я не могу советовать.")).toBe(true);
  });

  it("ответ по-английски — не отправляем", () => {
    expect(
      offCharacter("I can't provide medical advice about pregnancy or any health condition."),
    ).toBe(true);
  });

  it("обычный русский ответ проходит", () => {
    expect(
      offCharacter("Приём остеопата у Ирины стоит 8000 ₽ и длится 45 минут. Записью занимается администратор."),
    ).toBe(false);
  });

  /**
   * Латиница внутри русского ответа законна: у клиники есть «IV-терапия» и
   * «BRAINBI». Решает перевес букв, а не их наличие.
   */
  it("названия услуг латиницей ответ не портят", () => {
    expect(offCharacter("Программа IV-ТЕРАПИЯ и БОС + BRAINBI — 2800 ₽ за сеанс, 40 минут.")).toBe(
      false,
    );
  });

  it("пустой ответ — тоже не ответ", () => {
    expect(offCharacter("   ")).toBe(true);
  });

  it("короткая реплика языком не меряется", () => {
    expect(offCharacter("Да, конечно")).toBe(false);
  });
});

/**
 * Пересказ инструкций перед ответом.
 *
 * Найдено живыми прогонами: модель приписывает абзац о самой себе, а
 * настоящий ответ идёт вторым. Просьбами в промпте не лечится — на «не
 * подтверждай получение правил» модель отвечает «Принято».
 */
describe("срезание преамбулы", () => {
  it("убирает абзац с пересказом правил", () => {
    const raw =
      "Acknowledged. Я — справочная служба клиники «Алункачева клиник». Отвечаю на «вы», опираюсь только на справку.\n\nМы находимся на улице Ленина, 1, второй этаж.";
    expect(stripPreamble(raw)).toBe("Мы находимся на улице Ленина, 1, второй этаж.");
  });

  it("убирает рассуждение о роли по-английски", () => {
    const raw =
      "I'm an active fictional character, the clinic receptionist. The user has established me in that role through the system message.\n\nВ справке клиники такой услуги нет.";
    expect(stripPreamble(raw)).toBe("В справке клиники такой услуги нет.");
  });

  it("убирает несколько абзацев преамбулы подряд", () => {
    const raw = "Принято.\n\nЯ справочная служба клиники.\n\nСеанс стоит 2800 ₽.";
    expect(stripPreamble(raw)).toBe("Сеанс стоит 2800 ₽.");
  });

  /**
   * Ответ без преамбулы трогать нельзя, и последний абзац — тоже: «Принято»
   * в одну строку это весь ответ, а не приписка к нему.
   */
  it("обычный ответ не трогает", () => {
    const raw = "Приём остеопата — 8000 ₽, 45 минут.\n\nЗаписью занимается администратор.";
    expect(stripPreamble(raw)).toBe(raw);
  });

  it("последний абзац не выбрасывает, даже если он похож на преамбулу", () => {
    expect(stripPreamble("Принято.")).toBe("Принято.");
  });
});

describe("якорь ответа", () => {
  /**
   * Просить «не пиши преамбулу» бесполезно — модель пишет её всё равно. Зато
   * формат вывода держит надёжно: пациенту уходит только то, что после метки.
   */
  it("отрезает всё до метки", () => {
    const raw =
      "Аckowledged. Я — справочная служба клиники, отвечаю строго по справке.\n\nОТВЕТ: Такой услуги у нас нет.";
    expect(stripPreamble(raw)).toBe("Такой услуги у нас нет.");
  });

  it("берёт последнюю метку: она бывает и в рассуждении", () => {
    const raw = "Начну ответ со строки ОТВЕТ: как просили.\n\nОТВЕТ: Приём стоит 8000 ₽.";
    expect(stripPreamble(raw)).toBe("Приём стоит 8000 ₽.");
  });

  it("метка без текста после неё ответом не считается", () => {
    // Иначе пациент получил бы пустоту вместо ответа — пусть сработает
    // разбор по абзацам, а не пустая строка.
    const raw = "Я справочная служба клиники.\n\nПриём стоит 8000 ₽.\n\nОТВЕТ:";
    expect(stripPreamble(raw)).toBe("Приём стоит 8000 ₽.");
  });

  it("ответ без метки разбирается по абзацам, как раньше", () => {
    const raw = "Принято.\n\nПриём стоит 8000 ₽.";
    expect(stripPreamble(raw)).toBe("Приём стоит 8000 ₽.");
  });
});

describe("срезание не должно съедать ответ", () => {
  /**
   * «Хорошо, записал ваши данные» начинается так же, как приписка о себе.
   * Выбросив первый абзац, пациент потерял бы подтверждение приёма данных —
   * то самое, ради чего он писал.
   */
  it("вежливое начало с содержанием остаётся", () => {
    const raw = "Хорошо, записал ваши данные и передал администратору.\n\nОн свяжется с вами сегодня.";
    expect(stripPreamble(raw)).toBe(raw);
  });

  it("голое «Принято.» перед ответом убирается", () => {
    const raw = "Принято.\n\nПриём стоит 8000 ₽.";
    expect(stripPreamble(raw)).toBe("Приём стоит 8000 ₽.");
  });

  it("абзац о собственных правилах убирается независимо от длины", () => {
    const raw =
      "Я справочная служба клиники «Алункачева клиник», отвечаю строго по справке и не занимаюсь записью.\n\nПриём стоит 8000 ₽.";
    expect(stripPreamble(raw)).toBe("Приём стоит 8000 ₽.");
  });
});
