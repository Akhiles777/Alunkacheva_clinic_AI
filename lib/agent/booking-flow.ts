import { complexMedical } from "./specialist-rules";

/**
 * Порядок разговора о записи — одним местом.
 *
 * Он собирался из отдельных дописок: здесь цены, там вопрос про возраст, рядом
 * выбор врача, ниже просьба о данных. Каждая дописка проверяла свои условия, и
 * каждая новая правка ломала соседнюю: то согласие приходило на шаге выбора, то
 * рядом с вопросом «взрослый или ребёнок?» стояли только взрослые цены, то
 * врачи исчезали из разговора вовсе. Заказчик прав: так и должно было
 * получиться — у разговора не было одного хозяина.
 *
 * Теперь шаг один и решается здесь:
 *
 *   1. услуга     — что человеку нужно;
 *   2. для кого    — взрослый или ребёнок, если у услуги есть оба варианта;
 *   3. врач        — если услугу ведут двое и больше;
 *   4. данные      — ФИО, возраст, причина (перед ними платформа берёт согласие);
 *   5. администратор ставит время.
 *
 * Функция чистая: она не знает ни про базу, ни про модель. Ей говорят, что уже
 * известно, — она отвечает, какой шаг сейчас и нужно ли задавать вопрос самим.
 */

export type BookingStep = "service" | "whom" | "doctor" | "data";

export interface BookingState {
  /** Речь вообще о записи: без этого шагов нет. */
  booking: boolean;
  /** Услуга названа — прямо или через врача, который её ведёт. */
  service: boolean;
  /** Сказано, для кого приём. */
  whom: boolean;
  /**
   * У услуги есть и детский, и взрослый вариант.
   *
   * Если вариант один, спрашивать «для взрослого или для ребёнка» незачем: цена
   * от ответа не меняется, а лишний вопрос человек воспринимает как анкету.
   */
  whomMatters: boolean;
  /** Услугу ведут двое и больше — значит выбор есть. */
  doctorMatters: boolean;
  /** Врач назван самим пациентом. */
  doctor: boolean;
  /** Данные уже присланы или уже запрошены. */
  dataDone: boolean;
  /** Агент отказал в услуге — дальше по шагам не идём. */
  refused: boolean;
  /** О чём модель уже спросила сама: второй раз то же не спрашиваем. */
  askedByModel: Partial<Record<BookingStep, boolean>>;
}

/**
 * Где сейчас разговор и нужно ли спрашивать самим.
 *
 * `step` — шаг, на котором стоит разговор (по нему решается, какие цены
 * показать). `ask` — надо ли дописать наш вопрос: если модель уже спросила
 * ровно это, второй раз не спрашиваем, иначе выходит два вопроса подряд.
 */
export function bookingStep(s: BookingState): { step: BookingStep | null; ask: boolean } {
  if (!s.booking || s.refused) return { step: null, ask: false };

  const at = (step: BookingStep) => ({ step, ask: !s.askedByModel[step] });

  if (!s.service) return at("service");
  if (s.whomMatters && !s.whom) return at("whom");
  if (s.doctorMatters && !s.doctor) return at("doctor");
  if (!s.dataDone) return at("data");
  return { step: null, ask: false };
}

/**
 * Сотрудник написал, что запись оформлена: «Записала», «Вы записаны на…».
 *
 * Закрывает просьбу записать только это (и запись в YCLIENTS, созданная после
 * просьбы). Любая другая реплика сотрудника — «здравствуйте», вопрос, эхо
 * ответа самого агента — запись не оформляет: живой диалог 2 октября остался
 * без согласия и без просьбы о данных именно из-за такой реплики.
 */
const BOOKED_BY_STAFF =
  /(?<!\p{L})(?:записал[аи]?|записали|вы\s+записаны|записаны\s+на|запись\s+(?:оформлен\p{L}*|подтвержд\p{L}*|создан\p{L}*))(?!\p{L})/iu;

export function staffConfirmedBooking(text: string): boolean {
  return BOOKED_BY_STAFF.test(text);
}

/**
 * Жалоба — причина записи, а не медицинский вопрос.
 *
 * Живой диалог 4 октября: агент спросил «приём для взрослого или для
 * ребёнка?», мама ответила «Ребенок, новорожденный, 12 дней. Выгибание шеи
 * когда лежит» — и услышала «Этот вопрос лучше уточнить у специалиста». Она
 * ничего не спрашивала: она ответила на наш вопрос и сказала, с чем идёт, — то
 * самое «кратко причину обращения», которое мы всё равно попросим. Медицинское
 * правило (§6.1) запрещает агенту ОТВЕЧАТЬ на медицинские вопросы, а не
 * записывать людей с жалобами.
 *
 * Поэтому жалоба посреди записи — ответ, если в ней нет вопроса: ни знака «?»,
 * ни вопроса словами («можно ли», «поможет», «подойдёт», «что делать»,
 * «ребёнку 2 недели можно»). Срочное («температура», «судороги», «кровь»)
 * правилу не подлежит: о нём администратор должен узнать как о медицинском.
 * Вопрос к врачу по существу (`complexMedical`) — тоже: его агент доносит
 * врачу, а не прячет в анкету.
 */
const URGENT =
  /(?<!\p{L})(?:температур\p{L}*|судорог\p{L}*|кровотеч\p{L}*|кров[ьи](?!\p{L})|сознани\p{L}*|задыха\p{L}*|не\s+дыш\p{L}*|скор(?:ая|ую|ой)(?!\p{L})|срочн\p{L}*|рвот\p{L}*|травм\p{L}*|упал\p{L}*|ударил\p{L}*)/iu;

const ASKS_IN_WORDS = [
  /(?<!\p{L})(?:можно|нужно|стоит|надо|реально|возможно|опасно|вредно)\s+ли(?!\p{L})/iu,
  /(?<!\p{L})(?:помож\p{L}*|помога\p{L}*|подойд\p{L}*|подход\p{L}*\s+ли|посовету\p{L}*|что\s+делать|как\s+(?:быть|лечить)|не\s+знаю)(?!\p{L})/iu,
  // «Ребёнку 2 недели можно» — вопрос о показаниях без знака.
  /(?<!\p{L})(?:ему|ей|нам|мне|сын\p{L}*|доч\p{L}*|реб[её]н\p{L}*|дет\p{L}*|внук\p{L}*|мужу|жене|новорожд\p{L}*|грудничк\p{L}*|младенц\p{L}*|месячн\p{L}*|недельн\p{L}*)(?:\s+\d{1,2}\s*\p{L}+)?\s+можно(?!\p{L})/iu,
];

export function complaintAsReason(
  text: string,
  /** Идёт разговор о записи: просьба записать, вопрос об окне или наш вопрос шага. */
  bookingContext: boolean,
): boolean {
  if (!bookingContext || /\?/.test(text)) return false;
  if (URGENT.test(text) || ASKS_IN_WORDS.some((re) => re.test(text))) return false;
  return !complexMedical(text);
}
