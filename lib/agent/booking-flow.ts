/**
 * Порядок разговора о записи — одним местом.
 *
 * Он собирался из отдельных дописок: здесь цены, там вопрос про возраст, рядом
 * выбор врача, ниже просьба о данных. Каждая дописка проверяла свои условия, и
 * каждая новая правка ломала соседнюю: то согласие приходило на шаге выбора, то
 * рядом с вопросом «взрослый или ребёнок?» стояли только взрослые цены, то
 * врачи исчезали из разговора вовсе. Заказчик прав: так и должно было
 * получиться — у разговора не было одного хозяина.
 *
 * Теперь шаг один и решается здесь:
 *
 *   1. услуга     — что человеку нужно;
 *   2. для кого    — взрослый или ребёнок, если у услуги есть оба варианта;
 *   3. врач        — если услугу ведут двое и больше;
 *   4. данные      — ФИО, возраст, причина (перед ними платформа берёт согласие);
 *   5. администратор ставит время.
 *
 * Функция чистая: она не знает ни про базу, ни про модель. Ей говорят, что уже
 * известно, — она отвечает, какой шаг сейчас и нужно ли задавать вопрос самим.
 */

export type BookingStep = "service" | "whom" | "doctor" | "data";

export interface BookingState {
  /** Речь вообще о записи: без этого шагов нет. */
  booking: boolean;
  /** Услуга названа — прямо или через врача, который её ведёт. */
  service: boolean;
  /** Сказано, для кого приём. */
  whom: boolean;
  /**
   * У услуги есть и детский, и взрослый вариант.
   *
   * Если вариант один, спрашивать «для взрослого или для ребёнка» незачем: цена
   * от ответа не меняется, а лишний вопрос человек воспринимает как анкету.
   */
  whomMatters: boolean;
  /** Услугу ведут двое и больше — значит выбор есть. */
  doctorMatters: boolean;
  /** Врач назван самим пациентом. */
  doctor: boolean;
  /** Данные уже присланы или уже запрошены. */
  dataDone: boolean;
  /** Агент отказал в услуге — дальше по шагам не идём. */
  refused: boolean;
  /** О чём модель уже спросила сама: второй раз то же не спрашиваем. */
  askedByModel: Partial<Record<BookingStep, boolean>>;
}

/**
 * Где сейчас разговор и нужно ли спрашивать самим.
 *
 * `step` — шаг, на котором стоит разговор (по нему решается, какие цены
 * показать). `ask` — надо ли дописать наш вопрос: если модель уже спросила
 * ровно это, второй раз не спрашиваем, иначе выходит два вопроса подряд.
 */
export function bookingStep(s: BookingState): { step: BookingStep | null; ask: boolean } {
  if (!s.booking || s.refused) return { step: null, ask: false };

  const at = (step: BookingStep) => ({ step, ask: !s.askedByModel[step] });

  if (!s.service) return at("service");
  if (s.whomMatters && !s.whom) return at("whom");
  if (s.doctorMatters && !s.doctor) return at("doctor");
  if (!s.dataDone) return at("data");
  return { step: null, ask: false };
}

/**
 * Сотрудник написал, что запись оформлена: «Записала», «Вы записаны на…».
 *
 * Закрывает просьбу записать только это (и запись в YCLIENTS, созданная после
 * просьбы). Любая другая реплика сотрудника — «здравствуйте», вопрос, эхо
 * ответа самого агента — запись не оформляет: живой диалог 2 октября остался
 * без согласия и без просьбы о данных именно из-за такой реплики.
 */
const BOOKED_BY_STAFF =
  /(?<!\p{L})(?:записал[аи]?|записали|вы\s+записаны|записаны\s+на|запись\s+(?:оформлен\p{L}*|подтвержд\p{L}*|создан\p{L}*))(?!\p{L})/iu;

export function staffConfirmedBooking(text: string): boolean {
  return BOOKED_BY_STAFF.test(text);
}

/**
 * Администратор сам ведёт запись: предложил время или попросил данные.
 *
 * Живой диалог 9 октября: администратор написала «Есть свободное окошко на
 * завтра в 9:30, записать Вас?», «Могу предложить во вторник 13 октября в
 * 13:30» и «Для записи пришлите информацию о ребёнке». Через четыре часа
 * диалог вернулся агенту, и тот начал запись с начала — «Если вы про
 * остеопатию — у нас принимают два врача… к кому записать?». Бот,
 * перебивающий администратора, — худший баг этой системы (§6.4).
 *
 * «К кому хотите записаться?» сюда НЕ входит: это вопрос шага, который агент
 * умеет продолжить, и именно таким бывает эхо его собственного ответа (живой
 * диалог 2 октября). Закрывает только то, что дальше шагов агента: время и
 * просьба о данных.
 */
const STAFF_HANDLES_BOOKING = [
  /(?<!\p{L})(?:могу|можем)\s+предложить(?!\p{L})/iu,
  /(?<!\p{L})есть\s+(?:\p{L}+\s+){0,2}?(?:окошк\p{L}*|окн[оа]|время)(?!\p{L})/iu,
  /(?<!\p{L})(?:записать|запишу|запишем)\s+(?:вас|тебя|его|е[её]|ребенка|ребёнка|сына|дочь|дочку)(?!\p{L})/iu,
  /(?<!\p{L})удобно\s+(?:будет|ли|вам)(?!\p{L})/iu,
  /(?<!\p{L})(?:на|в)\s+\d{1,2}[:.]\d{2}(?!\d)/u,
  /(?<!\p{L})для\s+записи\s+(?:\p{L}+\s+){0,2}?(?:пришлите|напишите|отправьте|скиньте|нужн\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:пришлите|напишите|отправьте|скиньте)\s+(?:\p{L}+\s+){0,3}?(?:ф\.?\s*и\.?\s*о|данные|информацию)/iu,
];

export function staffHandlesBooking(text: string): boolean {
  return STAFF_HANDLES_BOOKING.some((re) => re.test(text));
}

/**
 * Жалоба — причина записи, а не медицинский вопрос.
 *
 * Живой диалог 4 октября: агент спросил «приём для взрослого или для
 * ребёнка?», мама ответила «Ребенок, новорожденный, 12 дней. Выгибание шеи
 * когда лежит» — и услышала «Этот вопрос лучше уточнить у специалиста». Она
 * ничего не спрашивала: она ответила на наш вопрос и сказала, с чем идёт, — то
 * самое «кратко причину обращения», которое мы всё равно попросим. Медицинское
 * правило (§6.1) запрещает агенту ОТВЕЧАТЬ на медицинские вопросы, а не
 * записывать людей с жалобами.
 *
 * Поэтому жалоба посреди записи — ответ, если в ней нет вопроса: ни знака «?»,
 * ни вопроса словами («можно ли», «поможет», «подойдёт», «что делать»,
 * «ребёнку 2 недели можно»). Срочное («температура», «судороги», «кровь»)
 * правилу не подлежит: о нём администратор должен узнать как о медицинском.
 * Вопрос к врачу по существу (`complexMedical`) — тоже: его агент доносит
 * врачу, а не прячет в анкету.
 */
const URGENT =
  /(?<!\p{L})(?:температур\p{L}*|судорог\p{L}*|кровотеч\p{L}*|кров[ьи](?!\p{L})|сознани\p{L}*|задыха\p{L}*|не\s+дыш\p{L}*|скор(?:ая|ую|ой)(?!\p{L})|срочн\p{L}*|рвот\p{L}*|травм\p{L}*|упал\p{L}*|ударил\p{L}*)/iu;

const ASKS_IN_WORDS = [
  /(?<!\p{L})(?:можно|нужно|стоит|надо|реально|возможно|опасно|вредно)\s+ли(?!\p{L})/iu,
  /(?<!\p{L})(?:помож\p{L}*|помога\p{L}*|подойд\p{L}*|подход\p{L}*\s+ли|посовету\p{L}*|что\s+делать|как\s+(?:быть|лечить)|не\s+знаю)(?!\p{L})/iu,
  // «Ребёнку 2 недели можно» — вопрос о показаниях без знака.
  /(?<!\p{L})(?:ему|ей|нам|мне|сын\p{L}*|доч\p{L}*|реб[её]н\p{L}*|дет\p{L}*|внук\p{L}*|мужу|жене|новорожд\p{L}*|грудничк\p{L}*|младенц\p{L}*|месячн\p{L}*|недельн\p{L}*)(?:\s+\d{1,2}\s*\p{L}+)?\s+можно(?!\p{L})/iu,
];

export function complaintAsReason(
  text: string,
  /** Идёт разговор о записи: просьба записать, вопрос об окне или наш вопрос шага. */
  bookingContext: boolean,
  /**
   * Человек сам просит записать — «у дочки сколиоз, хотим к остеопату, сколько
   * стоит и можно ли на субботу?» (проверка 5 октября). Диагноз здесь — причина
   * записи, а вопросы — о цене и дне, не о лечении. Тогда допустимы и
   * названный диагноз, и вопросы о цене и времени.
   */
  explicitBooking = false,
): boolean {
  if (!bookingContext) return false;
  if (URGENT.test(text)) return false;
  const rest = explicitBooking ? withoutPriceAndTimeQuestions(text) : text;
  if (/\?/.test(rest) || ASKS_IN_WORDS.some((re) => re.test(rest))) return false;
  return explicitBooking || !complexMedical(text);
}

/** Вопросы о цене и дне — не медицинские: «сколько стоит», «можно ли на субботу». */
function withoutPriceAndTimeQuestions(text: string): string {
  return text
    .replace(/сколько\s+(?:\p{L}+\s+){0,2}?(?:стоит|стоят|будет|выйдет)[^,.!?]*[?]?/giu, " ")
    .replace(
      /можно\s+(?:ли\s+)?(?:на|в|во)\s+(?:суббот\p{L}*|воскресень\p{L}*|понедельник\p{L}*|вторник\p{L}*|сред\p{L}*|четверг\p{L}*|пятниц\p{L}*|завтра|сегодня|утр\p{L}*|вечер\p{L}*|\d{1,2}(?::\d{2})?)[^,.!?]*[?]?/giu,
      " ",
    )
    .replace(/(?<!\p{L})(?:и|а)\s*\?/gu, " ")
    // «Не знаю, к какому врачу» — сомнение в выборе врача, а не вопрос о лечении (проверка 9 октября).
    .replace(/не\s+знаю,?\s+(?:к\s+)?(?:какому|кому|какого|какой)(?:\s+(?:из\s+)?(?:врач\p{L}*|доктор\p{L}*|специалист\p{L}*))?/giu, " ");
}

/**
 * Данные для этой записи уже присланы и приняты.
 *
 * Живой диалог 5 октября: анкета «Султанова Джамиля 13 лет. 35 кг. Энурез.» →
 * «Спасибо, передал(а) ваши данные администратору» → «Если можно запишите с
 * утра на 9 часов в ближайший свободный день» — и агент снова попросил ФИО,
 * возраст, вес и причину. Признак «данные есть» смотрел только на нашу
 * последнюю реплику: просили ли мы их только что.
 *
 * Идём от конца разговора: наш ответ «данные приняты» встретился раньше, чем
 * наша новая просьба о данных или новая просьба человека записать, — значит
 * данные у нас. Вторая запись («ещё сына», «и дочку тоже», «второго») — уже
 * другой человек, его данных нет.
 */
const DATA_ACCEPTED = /(?:переда\p{L}*(?:\(а\))?\s+ваши\s+данные|данные\s+переда\p{L}*)/iu;
const ANOTHER_PERSON = /(?<!\p{L})(?:ещ[её]|втор\p{L}*|тоже|также)(?!\p{L})/iu;

export function dataAlreadyReceived(
  history: { role: "user" | "assistant"; content: string }[],
  own: string,
): boolean {
  if (ANOTHER_PERSON.test(own)) return false;
  for (let i = history.length - 1; i >= 0; i -= 1) {
    const { role, content } = history[i];
    if (role === "assistant") {
      if (DATA_ACCEPTED.test(content)) return true;
      if (asksForIntake(content) || asksForPersonalData(content)) return false;
    } else if (wantsToBook(content)) {
      return false;
    }
  }
  return false;
}

/**
 * Суммы в рублях из текста: «3 тыс», «3000», «5 000 ₽», «2,5 т.р.». Часы и даты
 * («10:30», «12 октября») суммами не считаются: меньше 300 — не цена.
 */
export function moneyIn(text: string): number[] {
  const out: number[] = [];
  for (const m of text.matchAll(/(?<![\p{L}\d])(\d+(?:[.,]\d+)?)\s*(?:тыс\p{L}*|т\.?\s?р\.?|к)(?![\p{L}\d])/giu)) {
    out.push(Math.round(Number.parseFloat(m[1].replace(",", ".")) * 1000));
  }
  for (const m of text.matchAll(/(?<![\p{L}\d.,:])(\d{1,3}(?:[\s ]\d{3})+|\d{3,6})(?![\d.,:]|\s*(?:тыс|т\.?\s?р))/giu)) {
    const n = Number(m[1].replace(/\D/g, ""));
    if (n >= 300) out.push(n);
  }
  return out;
}

/**
 * Человек называет другую цену, чем назвали мы: «Ирина говорила 3 тыс».
 *
 * Живой диалог 6 октября: агент назвал повторный приём по прайсу — 5000 ₽, мама
 * ответила «Ирина говорила 3 тыс» и получила тот же ответ с той же ценой и ту
 * же просьбу о данных. Спорить о цене агенту нечем: прайс у нас, а договорённость
 * — у врача, и решает здесь администратор. Узнаём по сумме, которой не было в
 * нашей последней реплике, рядом со словами «говорила», «сказали», «было»,
 * «почему», «дешевле».
 */
const OBJECTION_CUE =
  /(?<!\p{L})(?:говорил\p{L}*|сказал\p{L}*|называл\p{L}*|обещал\p{L}*|озвучил\p{L}*|писал\p{L}*|было|был[аи]?|же|ведь|вроде|почему|дешевле|дороже|разве)(?!\p{L})/iu;

export function priceObjection(text: string, lastAgent: string): boolean {
  if (!lastAgent || !OBJECTION_CUE.test(text)) return false;
  const ours = moneyIn(lastAgent);
  if (ours.length === 0) return false;
  // «Ирина говорила, повторный бесплатно», «обещали скидку» — та же договорённость без суммы.
  if (/(?<!\p{L})(?:бесплатн\p{L}*|без\s+оплат\p{L}*|скидк\p{L}*|даром)(?!\p{L})/iu.test(text)) return true;
  const theirs = moneyIn(text);
  return theirs.length > 0 && theirs.some((n) => !ours.includes(n));
}

/**
 * Вопрос пациенту о предпочтительном дне и времени — убираем из разговора о
 * записи. Время определяет администратор (заказчик, 6 октября), и вопрос
 * «какой день и время вам удобны?» обещает выбор, которого у агента нет.
 * Убираются только вопросы (со знаком «?») про удобное время и день; «время
 * подберёт администратор» и прочие утверждения остаются.
 */
const TIME_PREFERENCE =
  /(?<!\p{L})(?:удобн\p{L}*|како[ей]\s+(?:время|день|число|дату)|какой\s+день|когда\s+(?:вам|вы|сможете|хотите|планируете|хотели)|на\s+какое\s+(?:время|число)|в\s+какое\s+время|какие\s+дни)(?!\p{L})/iu;

export function withoutTimePreferenceQuestion(text: string): string {
  return text
    .split("\n")
    .map((line) =>
      line
        .split(/(?<=[.!?…])\s+/)
        .filter((sentence) => !(sentence.includes("?") && TIME_PREFERENCE.test(sentence)))
        .join(" "),
    )
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * «К любому», «без разницы», «кто свободен» — врача человек выбрал: того, у кого
 * раньше найдётся время. Агент переспрашивал «к кому хотите записаться?» по
 * кругу (проверка 9 октября).
 */
const ANY_DOCTOR =
  /(?<!\p{L})(?:(?:к\s+)?(?:любому|любой|любого)(?:\s+(?:врачу|врач|доктору|специалисту))?|без\s+разницы|вс[её]\s+равно|не\s*важно|кто\s+(?:будет\s+)?(?:свобод\p{L}*|раньше|ближе)|к\s+кому\s+(?:угодно|скорее|раньше)|у\s+кого\s+(?:раньше|быстрее|ближе)\p{L}*)(?!\p{L})/iu;

export function anyDoctor(text: string): boolean {
  if (/(?<!\p{L})не\s+(?:к\s+)?любо\p{L}*/iu.test(text)) return false;
  return ANY_DOCTOR.test(text);
}

/**
 * «Кто из врачей лучше?», «к кому посоветуете?» — сравнения врачей у нас нет, и
 * выдумывать его нельзя. Но и молчать на прямой вопрос нельзя: шаг записи
 * отвечал ценами и «к кому хотите?», будто вопроса не было (проверка 9 октября).
 */
const COMPARES_DOCTORS =
  /(?<!\p{L})(?:кто\s+(?:из\s+(?:врачей|них|докторов|специалистов)\s+)?(?:лучше|опытнее|сильнее)|как(?:ой|ая)\s+(?:из\s+(?:врачей|них)\s+)?(?:врач\p{L}*\s+)?лучше|к\s+кому\s+лучше|кого\s+(?:вы\s+)?(?:посоветуете|порекомендуете)|кого\s+(?:лучше\s+)?выбрать)/iu;

export function comparesDoctors(text: string): boolean {
  return COMPARES_DOCTORS.test(text);
}

