import { describe, expect, it } from "vitest";
import { keepOneQuestion, questionCount } from "./one-question";

/**
 * Живой диалог: пациентка написала «ребёнку 6 лет… хотела записаться», а
 * получила два вопроса сразу — про то, что уже сказала, и про то, что агент
 * и так знает.
 */
describe("один вопрос за раз", () => {
  it("оставляет первый вопрос, убирает остальные", () => {
    const text =
      "Для ребёнка 6 лет подойдёт диагностика — 1000 ₽. Уточните, запись для ребёнка, верно? И к какому специалисту хотели бы попасть?";
    const out = keepOneQuestion(text);
    expect(questionCount(out)).toBe(1);
    expect(out).toContain("1000 ₽");
    expect(out).toContain("запись для ребёнка");
    expect(out).not.toContain("к какому специалисту");
  });

  it("ответ с одним вопросом не трогает", () => {
    const text = "Взрослый приём — 8000 ₽, 45 минут. Для взрослого или для ребёнка?";
    expect(keepOneQuestion(text)).toBe(text);
  });

  it("ответ без вопросов не трогает", () => {
    const text = "Мы работаем с 09:00 до 21:00. Воскресенье — выходной.";
    expect(keepOneQuestion(text)).toBe(text);
  });

  /**
   * Список цен склеивался в кашу: «Взрослый приём — 8000 ₽, 45 мин
   * Записывает администратор…». Переносы строк — часть ответа, их трогать
   * нельзя.
   */
  it("переносы строк сохраняются", () => {
    const text = "Взрослый приём — 8000 ₽, 45 мин\nДетский приём — 5000 ₽, 40 мин\n\nЗаписывает администратор.";
    expect(keepOneQuestion(text)).toBe(text);
  });

  it("утверждения после вопроса остаются", () => {
    const text = "Для взрослого или для ребёнка? Время подберёт администратор. А что вас интересует?";
    const out = keepOneQuestion(text);
    expect(out).toContain("Время подберёт администратор");
    expect(questionCount(out)).toBe(1);
  });
});
