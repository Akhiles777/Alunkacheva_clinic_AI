/**
 * Границы слова для русского текста.
 *
 * `\b` в JavaScript опирается на латинский `\w`, поэтому рядом с кириллицей
 * границы не находит вовсе: `/\bзапишу\b/` не совпадает со строкой «запишу
 * вас» никогда. Правило, написанное через `\b`, выглядит рабочим, но молча
 * не срабатывает — а здесь на таких правилах держатся триггеры эскалации и
 * запрет обещать запись.
 *
 * Поэтому границу задаём через отсутствие соседней буквы: так работает и для
 * кириллицы, и для латиницы.
 */

/** Регулярное выражение «слово целиком» из готового тела шаблона. */
export function wordRe(body: string): RegExp {
  return new RegExp(`(?<!\\p{L})(?:${body})(?!\\p{L})`, "iu");
}

/** Несколько слов подряд, каждое — целиком: «поставлю вас», «запись создана». */
export function phraseRe(...parts: string[]): RegExp {
  const body = parts.map((p) => `(?:${p})`).join("\\s+");
  return new RegExp(`(?<!\\p{L})${body}(?!\\p{L})`, "iu");
}
