/**
 * Разговор уже передан администратору — что агент говорит дальше.
 *
 * Живая переписка, из-за которой это правило появилось:
 *
 *   пациент: «Можете перенести нашу запись» (ответом на запись 8 сентября 09:00)
 *   агент:   «Передал(а) администратору — он подберёт время…»
 *   пациент: «В 9:00 у нас реабилитация»
 *   агент:   «Передаю администратору, что вам нужно перенести запись
 *             на 8 сентября в 09:00 из-за реабилитации»
 *
 * Человек сказал ровно обратное: в девять он не может, потому и просит
 * перенести. Агент пересказал просьбу своими словами и перевернул её смысл —
 * и пациент читает это как «меня не поняли», а администратор, если поверит
 * пересказу, поставит то же самое время снова.
 *
 * Вывод простой: подробности переноса агент не пересказывает НИКОГДА.
 * Администратор видит переписку целиком, пересказ ему не нужен, а цена ошибки
 * в нём — время приёма. Пока вопрос у администратора, на уточнения по времени
 * агент отвечает коротким подтверждением, без единой цифры от себя.
 */

/** Фразы, которыми агент передаёт разговор человеку. */
const HANDOVER_SAID = [
  /переда(?:л|ла|л\(а\)|ю|ём|ем)\p{L}*\s+администратору/iu,
  /администратор\p{L}*\s+(?:подбер|напиш|свяж|ответ)/iu,
  /время\s+подбер[её]т\s+администратор/iu,
];

/**
 * Идёт ли передача администратору: последнее слово агента было именно об этом.
 *
 * Смотрим только на последнюю его реплику. Двумя репликами раньше он мог
 * передать другой вопрос, который давно закрыт, — и тогда молчать о новом
 * незачем.
 */
export function inHandoverFlow(history: { role: "user" | "assistant"; content: string }[]): boolean {
  for (let i = history.length - 1; i >= 0; i -= 1) {
    if (history[i].role !== "assistant") continue;
    return HANDOVER_SAID.some((re) => re.test(history[i].content));
  }
  return false;
}

/**
 * Уточнение по времени: когда человеку удобно, когда он занят, какой день.
 *
 * Нужно, чтобы отличить продолжение разговора о переносе от нового вопроса.
 * Справочный вопрос посреди ожидания администратора агент отвечать обязан —
 * «а сколько стоит приём» не должно превращаться в «передал администратору».
 */
const TIME_DETAIL = [
  /(?<!\p{L})\d{1,2}[:.]\d{2}(?!\p{L})/u,
  /(?<!\p{L})(?:в|с|до|после|около)\s+\d{1,2}(?:[:.]\d{2})?(?!\p{L})/iu,
  /(?<!\p{L})\d{1,2}\s*(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)(?!\p{L})/iu,
  /(?<!\p{L})(?:сегодня|завтра|послезавтра|утром|днём|днем|вечером|обед\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:понедельник\p{L}*|вторник\p{L}*|сред[ауы]|четверг\p{L}*|пятниц\p{L}*|суббот\p{L}*|воскресень\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:удобно|неудобно|заняты|занята|занят|свободн\p{L}*|сможем|сможе\p{L}*|не\s+сможем)(?!\p{L})/iu,
];

export function timeDetail(text: string): boolean {
  return TIME_DETAIL.some((re) => re.test(text));
}
