/**
 * Подбор ответа из справочника клиники.
 *
 * Ассистент отвечает на медицинские темы (подготовка, противопоказания,
 * условия приёма) только тем текстом, который клиника завела и утвердила сама
 * — дословно. Модель не сочиняет и не «дополняет по смыслу»: её роль здесь
 * ограничена подбором подходящей записи. Нет записи — вопрос уходит человеку.
 *
 * Это компромисс, о котором договорились с заказчиком: он хочет, чтобы бот
 * отвечал про подготовку и противопоказания, но выдумывать такое нельзя.
 */

export interface KnowledgeRow {
  /**
   * Идентификатор записи. Необязателен: тесты правила работают с обычными
   * объектами, а идентификатор нужен только журналу — по нему считается,
   * сколько раз запись действительно составила ответ.
   */
  id?: string;
  topic: string;
  question: string;
  answer: string;
}

/**
 * Служебные слова. Совпадение по ним ничего не значит, а вреда много:
 * вопрос «есть ли услуги остеопата» попадал в запись «Как готовиться к приёму
 * остеопата», потому что в её тексте было «не есть плотно за час». Два
 * совпадения — «есть» и «остеопата» — считались уверенным ответом, и пациент
 * получал инструкцию по подготовке вместо ответа про услуги.
 */
const STOP_WORDS = new Set([
  "как", "что", "где", "когда", "какой", "какая", "какие", "кто", "чем", "зачем", "почему",
  "есть", "быть", "был", "была", "вас", "вам", "вами", "мне", "меня", "нас", "они", "его",
  "это", "этот", "эта", "эти", "для", "или", "тоже", "также", "если", "чтобы", "надо",
  "нужно", "можно", "ваш", "ваша", "ваши", "наш", "наша", "наши", "там", "тут", "уже",
  "ещё", "еще", "все", "всё", "про", "при", "над", "под", "без", "меня", "себя",
]);

/** Значимые слова: длиннее двух букв, без пунктуации и без служебных. */
function words(text: string): string[] {
  return text
    .toLowerCase()
    /**
     * «ё» приводим к «е». Пациенты почти никогда не набирают «ё», а клиника в
     * справочнике пишет грамотно: вопрос «как подготовиться к приему» не
     * находил запись со словом «приёму» — совпадения не было ни одного, и
     * ассистент звал человека при готовом ответе.
     */
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOP_WORDS.has(w));
}

/**
 * Нормализация словоформ по общему началу слова.
 *
 * Прежний вариант отрезал два последних символа, и родственные слова расходились:
 * «подготовиться» → «подготовитьс», «подготовка» → «подготов». Из-за этого
 * вопрос «как подготовиться к приёму остеопата» не находил запись «Подготовка
 * к остеопатии», и ассистент звал человека при готовом ответе в справочнике.
 *
 * Русское словоизменение меняет окончание, а не корень, поэтому сравнение по
 * первым пяти буквам устойчивее: «остеопата» и «остеопатии» → «остео»,
 * «приёму» и «приёма» → «приём». Ложные совпадения гасит требование двух
 * совпавших слов в confidentMatch.
 */
const STEM_LENGTH = 5;

function stem(word: string): string {
  return word.length > STEM_LENGTH ? word.slice(0, STEM_LENGTH) : word;
}

/**
 * Значимые слова текста, приведённые к основе.
 *
 * Та же нормализация, которой агент ищет ответ, — её же использует разбор
 * пробелов в справочнике. Две разные нормализации означали бы, что вопросы,
 * которые агент считает одинаковыми, на экране «Пробелы» окажутся в разных
 * группах, и наоборот.
 */
export function stemsOf(text: string): string[] {
  return words(text).map(stem);
}

/**
 * Лучшая запись справочника для вопроса и её оценка (0..1).
 * Оценка — доля слов вопроса, нашедшихся в записи.
 */
/** Пары соседних слов: «сколько стоит» отличает вопрос о цене от вопроса о том, кого принимают. */
function pairs(list: string[]): string[] {
  const out: string[] = [];
  for (let i = 0; i + 1 < list.length; i++) out.push(`${list[i]} ${list[i + 1]}`);
  return out;
}

/**
 * Слова, которыми названы услуги в прайсе клиники: «остео», «капел», «инфуз»,
 * «лотос», «бос», «нак», «анали». Общие слова прайса («приём», «курс»,
 * «детский», «терапия») услугу не называют и сюда не идут.
 */
const GENERIC_SERVICE_STEMS = new Set([
  "прием", "детск", "дети", "взрос", "курс", "сеанс", "назва", "персо", "станд", "терап", "проце",
  "консу", "повто", "перви", "введе", "внутр", "препа", "своег", "струй", "пакет", "анкет", "экспе",
  "ауди", "назна", "проток",
]);

export function serviceStems(titles: string[]): Set<string> {
  const out = new Set<string>();
  for (const t of titles) {
    for (const w of words(t.replace(/[«»"]/g, " "))) {
      const s = stem(w);
      if (!GENERIC_SERVICE_STEMS.has(s)) out.add(s);
    }
  }
  return out;
}

export type KnowledgeMatch = {
  row: KnowledgeRow;
  score: number;
  hits: number;
  topicCoverage: number;
  specificCoverage: number;
  /** Доля названных услуг, которые есть в записи; null — услугу не называли. */
  serviceCoverage?: number | null;
  /** Тема или вопросы записи называют услугу клиники («безопасность IV», «подготовка к остеопатии»). */
  rowNamesService?: boolean;
};

/**
 * Все записи по убыванию совпадения — для справки модели.
 *
 * Прежде записи для модели оценивались по одной, и общие пары слов решали
 * больше, чем названная услуга. Боевой справочник (62 записи, снимок 9
 * октября): «Что взять с собой к остеопату?» находило «как подготовиться к
 * КАПЕЛЬНИЦЕ» — у неё в вопросах «что взять с собой», — а «Что такое НАК?
 * Ребёнку 5 лет, задержка речи» находило запись о БОС при ЗПРР. На двенадцати
 * записях песочницы этого не было видно.
 *
 * Теперь слово, называющее услугу клиники (`serviceStems`), решает: запись,
 * где названной услуги нет, теряет очки, где есть — получает.
 */
export function rankKnowledge(question: string, rows: KnowledgeRow[], services: Set<string> = new Set()): KnowledgeMatch[] {
  return rows
    .map((row) => scoreRow(question, row, services))
    .filter((m): m is KnowledgeMatch => m !== null)
    .sort((a, b) => b.score - a.score);
}

/**
 * Части вопроса: «Сколько стоит детский приём, сколько длится и что взять с
 * собой?» — три вопроса в одном. Режем по знакам конца и по «и/,» перед
 * вопросительным словом.
 */
export function questionParts(question: string): string[] {
  return question
    .split(/[?!.\n]+|,\s*(?:и\s+|а\s+)?(?=(?:что|сколько|где|когда|как|какой|какая|какие|можно|нужно|есть|во\s+сколько|до\s+скольки)(?!\p{L}))|\s+(?:и|а)\s+(?=(?:что|сколько|где|когда|как|какой|какая|какие|можно|нужно|есть|во\s+сколько|до\s+скольки)(?!\p{L}))/iu)
    .map((p) => p.trim())
    .filter((p) => words(p).length > 0)
    // «Здравствуйте!», «Спасибо» — не часть вопроса: «Здравствуйте! Сколько стоит?» — один вопрос.
    .filter(
      (p) =>
        !/^(?:здравствуйте|здрасте|здравствуй|добрый\s+(?:день|вечер)|доброе\s+утро|привет|ассаляму?\s+алейкум|салам\p{L}*|спасибо|пожалуйста|извините|подскажите(?:\s+пожалуйста)?|скажите(?:\s+пожалуйста)?)[\s,!.🌸🌺☺️🙂]*$/iu.test(p),
    );
}

/**
 * Записи справки для модели — по КАЖДОЙ части вопроса, а не по всему разом.
 *
 * Снимок боевых данных 9 октября: «Сколько стоит детский приём, сколько длится
 * и что взять с собой?» — слово «сколько» набирало очки у десятка записей, и
 * «Подготовка к остеопатии» до модели не доходила: агент отвечал «что взять с
 * собой, не знаю», хотя справка у клиники есть. По частям каждая находит своё.
 *
 * Часть без названной услуги («а что взять с собой?») ищется вместе с услугой из
 * свежих слов пациента: в разговоре об остеопатии это подготовка к остеопатии,
 * а не к капельнице.
 */
/**
 * Вопрос без названной услуги — вместе с услугой из свежих слов пациента: «А
 * ребёнку 7 лет можно?» в разговоре о БОС — это вопрос о возрасте для БОС, а
 * не о любой услуге (снимок боевых данных 9 октября).
 */
export function withTalkService(question: string, services: Set<string>, context: string[]): string {
  const namedIn = (text: string) => words(text).filter((w) => services.has(stem(w)));
  if (namedIn(question).length > 0) return question;
  /**
   * Разговор о самочувствии после процедуры — услугу не подмешиваем: «И ещё
   * слабость какая-то» после «после капельницы кружится голова» иначе находило
   * меню капельниц. Это вопрос врачу, а не справке.
   */
  if (context.slice(0, 3).some((t) => AFTER_EFFECT.test(t))) return question;
  /**
   * Услуги из нескольких свежих реплик, а не из одной: «Диагностика отдельно
   * оплачивается?» называет строку «Диагностика… на БОС-терапию», а разговор
   * весь о БОС, названной тремя репликами раньше.
   */
  const contextWords = [...new Set(context.slice(0, 6).flatMap(namedIn).map((w) => w.toLowerCase()))];
  return contextWords.length > 0 ? `${question} ${contextWords.join(" ")}` : question;
}

export function rankForModel(
  question: string,
  rows: KnowledgeRow[],
  services: Set<string> = new Set(),
  /** Слова пациента за разговор, свежие первыми. */
  context: string[] = [],
): KnowledgeRow[] {
  const namedIn = (text: string) => words(text).filter((w) => services.has(stem(w)));
  const contextWords = context.map(namedIn).find((found) => found.length > 0) ?? [];
  const parts = questionParts(question);

  const lists: KnowledgeRow[][] = [];
  for (const part of parts.length > 1 ? parts : []) {
    const query = namedIn(part).length === 0 && contextWords.length > 0 ? `${part} ${contextWords.join(" ")}` : part;
    lists.push(rankKnowledge(query, rows, services).filter((m) => m.score > 0).slice(0, 3).map((m) => m.row));
  }
  const whole = question.trim() && namedIn(question).length === 0 && contextWords.length > 0
    ? `${question} ${contextWords.join(" ")}`
    : question;
  lists.push(rankKnowledge(whole, rows, services).filter((m) => m.score > 0).map((m) => m.row));
  // Вперемешку: первая находка каждой части раньше вторых находок остальных.
  const out: KnowledgeRow[] = [];
  const depth = Math.max(...lists.map((l) => l.length), 0);
  for (let i = 0; i < depth; i += 1) {
    for (const list of lists) {
      const row = list[i];
      if (row && !out.includes(row)) out.push(row);
    }
  }
  return out;
}

export function matchKnowledge(
  question: string,
  rows: KnowledgeRow[],
  services: Set<string> = new Set(),
): KnowledgeMatch | null {
  return rankKnowledge(question, rows, services)[0] ?? null;
}

function scoreRow(question: string, row: KnowledgeRow, services: Set<string>): KnowledgeMatch | null {
  const asked = words(question).map(stem);
  if (asked.length === 0) return null;
  const rows = [row];

  /**
   * Значимые слова вопроса: имена, названия услуг, редкие термины.
   *
   * Короткие слова есть почти в каждой записи и ничего не различают. Длинные
   * различают: «Разият», «Ризвановны», «остеопат». Без их учёта вопрос
   * «сколько стоит приём у Разият Ризвановны» совпал с записью про то, что
   * взрослых мужчин клиника не принимает, — общим было одно слово «приём», а
   * имя врача не значило ничего. Пациент получил ответ не по своему вопросу.
   */
  const specific = asked.filter((w) => w.length >= 5);

  /**
   * Пары соседних слов вопроса.
   *
   * Отдельные слова здесь бессильны. Запись «приём мужчин» содержит и
   * «остеопат», и «Разият Ризвановна», и «приём» — потому что там перечислено
   * «принимает ли Разият Ризвановна мужчин?». По словам она совпадает с
   * вопросом «сколько стоит приём у Разият Ризвановны» не хуже записи о цене,
   * и пациент получал ответ про то, что мужчин не принимают.
   *
   * Различает их порядок: «сколько стоит» и «стоит приём» есть только в
   * записи о цене. Пары слов — самый дешёвый способ это увидеть.
   */
  const askedPairs = pairs(asked);

  let best: KnowledgeMatch | null = null;
  for (const row of rows) {
    /**
     * Совпадения считаем по теме и вопросу записи, а не по тексту ответа.
     *
     * Ответ — это проза в несколько предложений, и случайные пересечения с ней
     * неизбежны: «возьмите документы, если они у вас есть» цеплялось к любому
     * вопросу со словом «есть». Тема и вопрос — то, о чём запись, и решать
     * должны они.
     */
    /**
     * Вопрос в справочнике клиника заполняет списком через «/»: «показания
     * БОС/ кому подходит БОС/ с чем работает». Это перечисление формулировок,
     * а не одна фраза, — разделитель заменяем пробелом, иначе «БОС/» и «БОС»
     * считались бы разными словами.
     */
    const haystack = new Set(words(`${row.topic} ${row.question}`.replace(/\//g, " ")).map(stem));
    const topicWords = words(row.topic).map(stem);
    const hits = asked.filter((w) => haystack.has(w)).length;
    // Насколько вопрос покрывает саму тему. «Адрес» — одно слово, покрытие
    // 100%: спрашивают именно это. «Капельница» покрывает «Подготовку к
    // капельнице» лишь наполовину — вопрос может быть и про цену, тут гадать
    // нельзя, пусть отвечает модель с контекстом переписки.
    const topicCoverage =
      topicWords.length === 0
        ? 0
        : topicWords.filter((w) => asked.includes(w)).length / topicWords.length;
    const specificCoverage =
      specific.length === 0 ? 1 : specific.filter((w) => haystack.has(w)).length / specific.length;

    const rowPairs = new Set(pairs(words(`${row.topic} ${row.question}`.replace(/\//g, " ")).map(stem)));
    const pairCoverage =
      askedPairs.length === 0 ? 0 : askedPairs.filter((p) => rowPairs.has(p)).length / askedPairs.length;

    /**
     * Названная услуга решает. Спросили про остеопата — запись о капельнице не
     * годится, сколько бы общих слов («взять с собой») в ней ни было.
     */
    const named = asked.filter((w) => services.has(w));
    const serviceCoverage = named.length === 0 ? 0 : named.filter((w) => haystack.has(w)).length / named.length;
    const serviceBonus = named.length === 0 ? 0 : serviceCoverage > 0 ? serviceCoverage * 0.6 : -0.6;

    const score = hits / asked.length + topicCoverage * 0.5 + specificCoverage * 0.5 + pairCoverage + serviceBonus;
    if (!best || score > best.score) {
      const rowNamesService = words(`${row.topic} ${row.question}`.replace(/\//g, " "))
        .map(stem)
        .some((w) => services.has(w));
      best = {
        row,
        score,
        hits,
        topicCoverage,
        specificCoverage,
        serviceCoverage: named.length === 0 ? null : serviceCoverage,
        rowNamesService,
      };
    }
  }
  return best;
}

/**
 * Достаточно ли уверенное совпадение, чтобы отвечать справкой.
 *
 * Одной доли мало: у короткого вопроса «а капельница?» одно значимое слово, и
 * доля выходит 1.0 — бот отвечал про подготовку, когда спрашивали цену.
 * Поэтому для коротких вопросов требуем не меньше двух совпавших слов, а
 * односложные отдаём модели: у неё есть контекст переписки.
 */
/**
 * Вопрос о самочувствии ПОСЛЕ процедуры: «после остеопатии поднялась
 * температура, это нормально?». Справки «поможет ли остеопат» и «что взять»
 * на него не отвечают, сколько бы слов ни совпало, — это вопрос врачу.
 */
const AFTER_EFFECT =
  /(?<!\p{L})(?:после\s+(?:остеопат\p{L}*|капельниц\p{L}*|процедур\p{L}*|при[её]ма|сеанс\p{L}*|бос\p{L}*|инфузи\p{L}*|занят\p{L}*)|это\s+нормально|поднял\p{L}*\s+температур\p{L}*|стало\s+(?:хуже|плохо))/iu;

export function confidentMatch(
  m: {
    score: number;
    hits: number;
    topicCoverage: number;
    specificCoverage?: number;
    serviceCoverage?: number | null;
    rowNamesService?: boolean;
  } | null,
  /** Сам вопрос: нужен, чтобы не отвечать справкой на вопрос о самочувствии после процедуры. */
  question?: string,
): boolean {
  if (!m) return false;
  if (m.score < KNOWLEDGE_MIN_SCORE) return false;
  /**
   * Вопрос услугу не называет, а запись — о конкретной услуге: дословно не
   * отвечаем, о чём речь, знает только разговор. Снимок боевых данных 9
   * октября: пациентка записывалась к остеопату и спросила «А это опасно? Может
   * это давление?» — и получила справку о безопасности капельниц.
   */
  if (m.serviceCoverage == null && m.rowNamesService && m.topicCoverage < 0.5) return false;
  /**
   * Названа услуга, а в записи её нет — запись не о том: «Что за тихая
   * терапия?» получало перечень анализов перед капельницей (снимок 9
   * октября). Обратного послабления («услуга совпала — значит уверенно») нет
   * намеренно: «после остеопатии поднялась температура, это нормально?» с ним
   * получало справку «поможет ли остеопат» — медицинский вопрос дословной
   * справкой отвечается только при строгом совпадении.
   */
  if (m.serviceCoverage === 0) return false;
  /**
   * Запись про НАЗВАННУЮ услугу, тема записи покрыта хотя бы наполовину —
   * годится, даже если человек добавил подробности о себе: «Что такое НАК?
   * Ребёнку 5 лет, задержка речи», «Постоянная усталость… у вас капельницы
   * есть» (запись клиники «Капельницы от усталости»). Иначе подробности
   * разбавляли совпадение, и человек слышал «уточните у специалиста» при
   * готовом ответе клиники. Вопрос о самочувствии после процедуры — никогда.
   */
  if (
    question !== undefined &&
    m.serviceCoverage === 1 &&
    m.hits >= 2 &&
    m.topicCoverage >= 0.5 &&
    !AFTER_EFFECT.test(question)
  ) {
    return true;
  }

  /**
   * Значимые слова вопроса должны хотя бы наполовину найтись в записи.
   *
   * Дословный ответ — обещание «это ответ именно на ваш вопрос». Если пациент
   * назвал врача или услугу, а в записи их нет, обещание ложное. Такой вопрос
   * лучше отдать модели: она видит весь справочник и ответит по делу, а не
   * подменит вопрос похожим.
   */
  if (m.specificCoverage !== undefined && m.specificCoverage < 0.5) return false;
  // Двух совпавших слов достаточно. Одного — только если вопрос покрывает тему
  // целиком: «адрес» → тема «Адрес», но не «капельница» → «Подготовка к
  // капельнице», где спрашивать могли и про цену.
  return m.hits >= 2 || m.topicCoverage >= 0.99;
}

/** Порог уверенности: ниже него отвечать нельзя, вопрос уходит человеку. */
export const KNOWLEDGE_MIN_SCORE = 0.34;

/**
 * Можно ли отвечать этой записью.
 *
 * Медицинская справка идёт пациенту дословно (§6, правило 1), поэтому
 * утверждает её врач. Неутверждённая медицинская запись для агента не
 * существует — не «показывается с оговоркой», а не существует: оговорку
 * пациент не увидит, он увидит текст.
 */
export function knowledgeUsable(entry: {
  isActive: boolean;
  needsDoctorApproval?: boolean;
  approvedAt?: Date | null;
}): boolean {
  if (!entry.isActive) return false;
  if (!entry.needsDoctorApproval) return true;
  return entry.approvedAt != null;
}

/**
 * Условие отбора записей, которыми агент вправе отвечать.
 *
 * Одно на все места чтения: три одинаковых `{ isActive: true }` в разных
 * функциях означали бы, что новое правило забудут в одном из них — и
 * неутверждённая медицинская справка уйдёт пациенту именно оттуда.
 */
export function usableKnowledgeWhere(companyId: string) {
  return {
    companyId,
    isActive: true,
    OR: [{ needsDoctorApproval: false }, { approvedAt: { not: null } }],
  };
}
