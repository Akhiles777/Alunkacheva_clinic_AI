/**
 * Подбор ответа из справочника клиники.
 *
 * Ассистент отвечает на медицинские темы (подготовка, противопоказания,
 * условия приёма) только тем текстом, который клиника завела и утвердила сама
 * — дословно. Модель не сочиняет и не «дополняет по смыслу»: её роль здесь
 * ограничена подбором подходящей записи. Нет записи — вопрос уходит человеку.
 *
 * Это компромисс, о котором договорились с заказчиком: он хочет, чтобы бот
 * отвечал про подготовку и противопоказания, но выдумывать такое нельзя.
 */

export interface KnowledgeRow {
  /**
   * Идентификатор записи. Необязателен: тесты правила работают с обычными
   * объектами, а идентификатор нужен только журналу — по нему считается,
   * сколько раз запись действительно составила ответ.
   */
  id?: string;
  topic: string;
  question: string;
  answer: string;
}

/**
 * Служебные слова. Совпадение по ним ничего не значит, а вреда много:
 * вопрос «есть ли услуги остеопата» попадал в запись «Как готовиться к приёму
 * остеопата», потому что в её тексте было «не есть плотно за час». Два
 * совпадения — «есть» и «остеопата» — считались уверенным ответом, и пациент
 * получал инструкцию по подготовке вместо ответа про услуги.
 */
const STOP_WORDS = new Set([
  "как", "что", "где", "когда", "какой", "какая", "какие", "кто", "чем", "зачем", "почему",
  "есть", "быть", "был", "была", "вас", "вам", "вами", "мне", "меня", "нас", "они", "его",
  "это", "этот", "эта", "эти", "для", "или", "тоже", "также", "если", "чтобы", "надо",
  "нужно", "можно", "ваш", "ваша", "ваши", "наш", "наша", "наши", "там", "тут", "уже",
  "ещё", "еще", "все", "всё", "про", "при", "над", "под", "без", "меня", "себя",
]);

/** Значимые слова: длиннее двух букв, без пунктуации и без служебных. */
function words(text: string): string[] {
  return text
    .toLowerCase()
    /**
     * «ё» приводим к «е». Пациенты почти никогда не набирают «ё», а клиника в
     * справочнике пишет грамотно: вопрос «как подготовиться к приему» не
     * находил запись со словом «приёму» — совпадения не было ни одного, и
     * ассистент звал человека при готовом ответе.
     */
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOP_WORDS.has(w));
}

/**
 * Нормализация словоформ по общему началу слова.
 *
 * Прежний вариант отрезал два последних символа, и родственные слова расходились:
 * «подготовиться» → «подготовитьс», «подготовка» → «подготов». Из-за этого
 * вопрос «как подготовиться к приёму остеопата» не находил запись «Подготовка
 * к остеопатии», и ассистент звал человека при готовом ответе в справочнике.
 *
 * Русское словоизменение меняет окончание, а не корень, поэтому сравнение по
 * первым пяти буквам устойчивее: «остеопата» и «остеопатии» → «остео»,
 * «приёму» и «приёма» → «приём». Ложные совпадения гасит требование двух
 * совпавших слов в confidentMatch.
 */
const STEM_LENGTH = 5;

function stem(word: string): string {
  return word.length > STEM_LENGTH ? word.slice(0, STEM_LENGTH) : word;
}

/**
 * Лучшая запись справочника для вопроса и её оценка (0..1).
 * Оценка — доля слов вопроса, нашедшихся в записи.
 */
/** Пары соседних слов: «сколько стоит» отличает вопрос о цене от вопроса о том, кого принимают. */
function pairs(list: string[]): string[] {
  const out: string[] = [];
  for (let i = 0; i + 1 < list.length; i++) out.push(`${list[i]} ${list[i + 1]}`);
  return out;
}

export function matchKnowledge(
  question: string,
  rows: KnowledgeRow[],
): { row: KnowledgeRow; score: number; hits: number; topicCoverage: number; specificCoverage: number } | null {
  const asked = words(question).map(stem);
  if (asked.length === 0 || rows.length === 0) return null;

  /**
   * Значимые слова вопроса: имена, названия услуг, редкие термины.
   *
   * Короткие слова есть почти в каждой записи и ничего не различают. Длинные
   * различают: «Разият», «Ризвановны», «остеопат». Без их учёта вопрос
   * «сколько стоит приём у Разият Ризвановны» совпал с записью про то, что
   * взрослых мужчин клиника не принимает, — общим было одно слово «приём», а
   * имя врача не значило ничего. Пациент получил ответ не по своему вопросу.
   */
  const specific = asked.filter((w) => w.length >= 5);

  /**
   * Пары соседних слов вопроса.
   *
   * Отдельные слова здесь бессильны. Запись «приём мужчин» содержит и
   * «остеопат», и «Разият Ризвановна», и «приём» — потому что там перечислено
   * «принимает ли Разият Ризвановна мужчин?». По словам она совпадает с
   * вопросом «сколько стоит приём у Разият Ризвановны» не хуже записи о цене,
   * и пациент получал ответ про то, что мужчин не принимают.
   *
   * Различает их порядок: «сколько стоит» и «стоит приём» есть только в
   * записи о цене. Пары слов — самый дешёвый способ это увидеть.
   */
  const askedPairs = pairs(asked);

  let best: { row: KnowledgeRow; score: number; hits: number; topicCoverage: number; specificCoverage: number } | null =
    null;
  for (const row of rows) {
    /**
     * Совпадения считаем по теме и вопросу записи, а не по тексту ответа.
     *
     * Ответ — это проза в несколько предложений, и случайные пересечения с ней
     * неизбежны: «возьмите документы, если они у вас есть» цеплялось к любому
     * вопросу со словом «есть». Тема и вопрос — то, о чём запись, и решать
     * должны они.
     */
    /**
     * Вопрос в справочнике клиника заполняет списком через «/»: «показания
     * БОС/ кому подходит БОС/ с чем работает». Это перечисление формулировок,
     * а не одна фраза, — разделитель заменяем пробелом, иначе «БОС/» и «БОС»
     * считались бы разными словами.
     */
    const haystack = new Set(words(`${row.topic} ${row.question}`.replace(/\//g, " ")).map(stem));
    const topicWords = words(row.topic).map(stem);
    const hits = asked.filter((w) => haystack.has(w)).length;
    // Насколько вопрос покрывает саму тему. «Адрес» — одно слово, покрытие
    // 100%: спрашивают именно это. «Капельница» покрывает «Подготовку к
    // капельнице» лишь наполовину — вопрос может быть и про цену, тут гадать
    // нельзя, пусть отвечает модель с контекстом переписки.
    const topicCoverage =
      topicWords.length === 0
        ? 0
        : topicWords.filter((w) => asked.includes(w)).length / topicWords.length;
    const specificCoverage =
      specific.length === 0 ? 1 : specific.filter((w) => haystack.has(w)).length / specific.length;

    const rowPairs = new Set(pairs(words(`${row.topic} ${row.question}`.replace(/\//g, " ")).map(stem)));
    const pairCoverage =
      askedPairs.length === 0 ? 0 : askedPairs.filter((p) => rowPairs.has(p)).length / askedPairs.length;

    const score = hits / asked.length + topicCoverage * 0.5 + specificCoverage * 0.5 + pairCoverage;
    if (!best || score > best.score) best = { row, score, hits, topicCoverage, specificCoverage };
  }
  return best;
}

/**
 * Достаточно ли уверенное совпадение, чтобы отвечать справкой.
 *
 * Одной доли мало: у короткого вопроса «а капельница?» одно значимое слово, и
 * доля выходит 1.0 — бот отвечал про подготовку, когда спрашивали цену.
 * Поэтому для коротких вопросов требуем не меньше двух совпавших слов, а
 * односложные отдаём модели: у неё есть контекст переписки.
 */
export function confidentMatch(
  m: { score: number; hits: number; topicCoverage: number; specificCoverage?: number } | null,
): boolean {
  if (!m) return false;
  if (m.score < KNOWLEDGE_MIN_SCORE) return false;

  /**
   * Значимые слова вопроса должны хотя бы наполовину найтись в записи.
   *
   * Дословный ответ — обещание «это ответ именно на ваш вопрос». Если пациент
   * назвал врача или услугу, а в записи их нет, обещание ложное. Такой вопрос
   * лучше отдать модели: она видит весь справочник и ответит по делу, а не
   * подменит вопрос похожим.
   */
  if (m.specificCoverage !== undefined && m.specificCoverage < 0.5) return false;
  // Двух совпавших слов достаточно. Одного — только если вопрос покрывает тему
  // целиком: «адрес» → тема «Адрес», но не «капельница» → «Подготовка к
  // капельнице», где спрашивать могли и про цену.
  return m.hits >= 2 || m.topicCoverage >= 0.99;
}

/** Порог уверенности: ниже него отвечать нельзя, вопрос уходит человеку. */
export const KNOWLEDGE_MIN_SCORE = 0.34;
