/**
 * Какие услуги подходят под вопрос пациента.
 *
 * Модели давался весь прайс — шесть десятков строк, среди которых «Остеопатия
 * — дети, приём Ирины» за 4900 и «Взрослый приём — остеопатия» за 8000. На
 * прямой вопрос «хотела ребёнка записать» она назвала взрослую цену. Это не
 * та ошибка, которую чинят уговорами в промпте: выбирать из шести десятков
 * похожих строк — работа для кода, а не для модели.
 *
 * Здесь мы сами отбираем подходящие услуги и отдаём их отдельным списком с
 * пометкой «цену бери отсюда». Модель формулирует ответ, но цену не выбирает.
 */

import { collapseFormulas, courtesyFormulaWord } from "./courtesy-words";

/** Насколько слабее лучшего совпадения может быть соседнее в том же ответе. */
const CLOSE_ENOUGH = 0.75;

export interface ServiceLike {
  title: string;
  price: number;
  durationMin: number;
}

/**
 * Нижний регистр, «ё» как «е» и частые опечатки в названии основной услуги:
 * «астеопат», «остиопат» (проверка 5 октября: «хачу записатся к астеопату»
 * не находило услугу вовсе).
 */
const norm = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/(?<!\p{L})астео/gu, "остео")
    .replace(/(?<!\p{L})ост[иы]опат/gu, "остеопат");

/** Для кого приём — по словам пациента. */
export type Whom = "child" | "adult" | "unknown";

const CHILD_WORDS =
  /(?<!\p{L})(ребен|ребён|детск|дет[еяи]|сын|доч|мальчик|девочк|малыш|подрост|годик|месяц\p{L}*\s+ребен)/iu;
/**
 * Основы пишем без границы справа: «взросл» продолжается «ый», и запрет буквы
 * после основы не давал совпасть ни разу. Целые слова — с границей, иначе
 * «мне» найдётся внутри «мнение».
 */
/**
 * Голое «мне» и «мама» взрослого не значат (заказчик, 8 октября: агент сам
 * решил «взрослый» и не спросил). «Подскажите мне цены» — не про возраст, а
 * «мама Зарема» в анкете — подпись родителя ребёнка. Взрослого называют
 * «маму записать», «для мамы», «маме», «для меня», «сама».
 */
const ADULT_WORDS =
  /(?<!\p{L})(?:взросл\p{L}*|муж\p{L}*|жен[еуы]|себя|для меня|для мамы|для папы|бабушк\p{L}*|дедушк\p{L}*|свекров\p{L}*|(?:маме|папе|маму|папу|сама|самой)(?!\p{L}))/iu;

/**
 * Возраст в годах, который бывает только у взрослого: «маму 60 лет». Годы сами
 * по себе ребёнком не делают, а вот восемнадцать и больше — взрослым делают.
 */
function adultYears(text: string): boolean {
  // «Мне 34, сыну 7» — возраст говорящего без «лет»: «мне» с числом от 18.
  const own = [...text.matchAll(/(?<!\p{L})(?:мне|я)\s+(\d{2,3})(?![\d\p{L}])/giu)];
  return [...text.matchAll(/(?<!\d)(\d{2,3})\s*(?:лет|года|год)(?!\p{L})/giu), ...own].some((m) => {
    const n = Number(m[1]);
    return n >= 18 && n <= 110;
  });
}

/**
 * «Записаться» взрослого НЕ значит (решение заказчика, 8 октября).
 *
 * Прежде возвратный глагол считался «для себя»: «Хотела записаться на приём»
 * получало только взрослые цены обоих остеопатов и «к кому записать?», а
 * администратору потом приходилось спрашивать «на взрослый или детский
 * приём?». Мамы пишут «хотела записаться» и про ребёнка. Взрослым запись
 * считается только по прямым словам: «запишите меня», «записать себя», «для
 * себя», «сама», «взрослый» (`ADULT_WORDS`) — иначе агент спрашивает.
 */
const SELF_BOOKING =
  /(?<!\p{L})(?:(?:запиши(?:те)?|записать|запишете|записали)\s+меня|меня\s+(?:записать|запишите|запишете|записали)|записать\s+себя)(?!\p{L})/iu;

/**
 * Возраст, который бывает только у ребёнка.
 *
 * «МагомедХабибов Шамиль, 2,5 месяца» — возраст назван прямо, а слова
 * «ребёнок» в сообщении нет, и агент через реплику снова спросил «для кого —
 * взрослому или ребёнку». Месяцы у взрослых не считают; годы — считают, и
 * «33 года» ребёнком не делает, поэтому здесь только месяцы.
 */
const AGE_IN_MONTHS = /(?<!\p{L})\d+(?:[.,]\d+)?\s*мес/iu;

/**
 * Дата рождения не старше восемнадцати лет — тоже ребёнок.
 * «Абдулкадирова Халима 01.11.2023 г» — анкета ребёнка, присланная родителем.
 */
function recentBirthDate(t: string, now: Date = new Date()): boolean {
  const m = t.match(/(?<!\d)(\d{1,2})[./](\d{1,2})[./](\d{4})(?!\d)/);
  if (!m) return false;
  const year = Number(m[3]);
  const age = now.getFullYear() - year;
  return year > 1900 && age >= 0 && age < 18;
}

/**
 * Для кого приём — по всему разговору, свежие реплики первыми.
 *
 * Решает самая свежая реплика, где про это хоть что-то сказано. Порядок важен:
 * вызовы собирали список как «текущая реплика, затем прошлые с самой ранней»,
 * и «Взрослый» трёхнедельной давности перебивал сегодняшнее «малышу 2
 * месяца». Старые слова не перебивают новых и в обратную сторону: мама,
 * месяц назад записывавшая сына, сегодня пишет «хочу записаться» — это про неё.
 */
export function whomAcross(textsNewestFirst: string[]): Whom {
  for (const text of textsNewestFirst) {
    const w = whomFor(text);
    if (w !== "unknown") return w;
  }
  return "unknown";
}

/**
 * Возраст одного человека уже назван — «записать сына 6 лет», «малышу 2
 * месяца». Тогда в анкете его не спрашиваем: переспрос сказанного читается как
 * «вас не слушали» (проверка 5 октября). Возрастов несколько или речь о
 * нескольких детях — спрашиваем как обычно: чей это возраст, не угадываем.
 * «Через 2 дня», «на 3 дня» — не возраст.
 */
const AGE_MENTION =
  /(?<!(?:^|[^\p{L}])(?:через|на|за)\s{1,3})(?<![\p{L}\d.,])\d{1,2}(?:[.,]\d)?\s*(?:год\p{L}*|лет|мес\p{L}*|недел\p{L}*|дн\p{L}*|день)(?!\p{L})/giu;
const SEVERAL = /(?<!\p{L})(?:дети|детей|детям|двоих|троих|обоих|обеих)(?!\p{L})|(?:сын\p{L}*|доч\p{L}*)\s+и\s+(?:сын\p{L}*|доч\p{L}*)/iu;
export function ageStated(textsNewestFirst: string[], whom: Whom): boolean {
  if (whom === "unknown") return false;
  const joined = textsNewestFirst.slice(0, 4).join("\n");
  if (SEVERAL.test(joined)) return false;
  const hits = joined.match(AGE_MENTION) ?? [];
  if (hits.length !== 1) return false;
  // «Мне 34 года» не отвечает на возраст сына, «сыну 6 лет» — на возраст взрослого.
  const n = Number.parseFloat(hits[0].replace(",", "."));
  const years = /год|лет/iu.test(hits[0]);
  const childAge = !years || n < 18;
  return whom === "child" ? childAge : years && n >= 18;
}

/** Названы и взрослый, и ребёнок: «записаться сама и сына привести». */
export function bothAges(text: string): boolean {
  const t = norm(text);
  return (CHILD_WORDS.test(t) || AGE_IN_MONTHS.test(t) || recentBirthDate(t)) && (ADULT_WORDS.test(t) || adultYears(t));
}

export function whomFor(text: string): Whom {
  const t = norm(text);
  const child = CHILD_WORDS.test(t) || AGE_IN_MONTHS.test(t) || recentBirthDate(t);
  const adult = ADULT_WORDS.test(t) || adultYears(t);
  // Сказали и то и другое («записать ребёнка и себя») — выбирать нельзя.
  if (child && adult) return "unknown";
  if (child) return "child";
  if (adult) return "adult";
  if (SELF_BOOKING.test(t)) return "adult";
  return "unknown";
}

/**
 * В сообщении названо только «для кого» — и больше ничего.
 *
 * Живой диалог: «Здравствуйте» → «Ребенку 11 лет» → и в ответ дословная справка
 * про то, с какого возраста делают БОС-терапию и что при ЗРР бывает НАК.
 * Человек ни о БОС, ни о НАК не спрашивал: он назвал возраст и ждал, что
 * спросят дальше. Такой ответ выглядит как разговор не с ним.
 *
 * Поэтому голое «для кого» — не вопрос и не повод для справки: это начало
 * записи, и следующий шаг один — спросить услугу.
 */
export function onlyWhomStated(text: string): boolean {
  if (text.includes("?")) return false;
  if (whomFor(text) === "unknown") return false;
  const parts = norm(text)
    .split(/[^\p{L}\d]+/u)
    .filter((w) => w.length > 0);
  // Четыре слова — это «ребенку 11 лет» и «приём для взрослого». Больше —
  // человек сказал что-то ещё, и решать за него нельзя.
  if (parts.length === 0 || parts.length > 4) return false;
  /**
   * И все слова — о человеке. «Перезвоните мне пожалуйста» — четыре слова и
   * «мне», но это просьба позвонить, а не ответ «для кого»: агент спросил
   * «на какую услугу вы хотите записаться» (проверка 5 октября).
   */
  return parts.every((w) => WHOM_TOKEN.test(w));
}

const WHOM_TOKEN =
  /^(?:\d+|для|на|это|мне|нам|меня|нас|у|и|а|приём|прием|пожалуйста|человек\p{L}*|взросл\p{L}*|детск\p{L}*|реб[её]н\p{L}*|дет\p{L}*|сын\p{L}*|доч\p{L}*|мальчик\p{L}*|девочк\p{L}*|малыш\p{L}*|младен\p{L}*|грудн\p{L}*|новорожд\p{L}*|внук\p{L}*|внучк\p{L}*|племянн\p{L}*|мам\p{L}*|пап\p{L}*|муж\p{L}*|жен\p{L}*|бабушк\p{L}*|дедушк\p{L}*|себ\p{L}*|сам\p{L}*|лет|год\p{L}*|месяц\p{L}*|мес|недел\p{L}*|дн\p{L}*|день|одн\p{L}*|два|две|двух|три|тр[её]х|четыр\p{L}*|пят\p{L}*|шест\p{L}*|сем\p{L}*|восьм\p{L}*|восем\p{L}*|девят\p{L}*|десят\p{L}*|полгода|полтора|полутора)$/u;

/** Услуга детская по названию. */
function isChildService(title: string): boolean {
  return /(?<!\p{L})(дет[си]|ребен|ребён|подрост)/iu.test(norm(title));
}

/** Услуга для беременных — отдельная, ни к детям, ни к обычным взрослым. */
function isPregnancyService(title: string): boolean {
  return /беремен/i.test(norm(title));
}

