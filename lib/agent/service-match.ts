/**
 * Какие услуги подходят под вопрос пациента.
 *
 * Модели давался весь прайс — шесть десятков строк, среди которых «Остеопатия
 * — дети, приём Ирины» за 4900 и «Взрослый приём — остеопатия» за 8000. На
 * прямой вопрос «хотела ребёнка записать» она назвала взрослую цену. Это не
 * та ошибка, которую чинят уговорами в промпте: выбирать из шести десятков
 * похожих строк — работа для кода, а не для модели.
 *
 * Здесь мы сами отбираем подходящие услуги и отдаём их отдельным списком с
 * пометкой «цену бери отсюда». Модель формулирует ответ, но цену не выбирает.
 */

/** Насколько слабее лучшего совпадения может быть соседнее в том же ответе. */
const CLOSE_ENOUGH = 0.75;

export interface ServiceLike {
  title: string;
  price: number;
  durationMin: number;
}

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/** Для кого приём — по словам пациента. */
export type Whom = "child" | "adult" | "unknown";

const CHILD_WORDS =
  /(?<!\p{L})(ребен|ребён|детск|дет[еяи]|сын|доч|мальчик|девочк|малыш|подрост|годик|месяц\p{L}*\s+ребен)/iu;
/**
 * Основы пишем без границы справа: «взросл» продолжается «ый», и запрет буквы
 * после основы не давал совпасть ни разу. Целые слова — с границей, иначе
 * «мне» найдётся внутри «мнение».
 */
const ADULT_WORDS =
  /(?<!\p{L})(?:взросл\p{L}*|муж\p{L}*|жен[еуы]|себя|для меня|(?:мне|маме|папе)(?!\p{L}))/iu;

/**
 * «Записаться» — про себя, «записать» — про кого-то.
 *
 * Пациентка написала «хочу записаться на приём к остеопату», и агент
 * переспросил, для взрослого или для ребёнка. Она не говорила про ребёнка:
 * возвратный глагол означает «себя», и переспрашивать тут нечего. Детские
 * слова правило отменяют — «хочу записаться с ребёнком» решает не оно.
 */
/**
 * Только от первого лица: «хочу записаться», «можно записаться», «запишите
 * меня». «Как записаться на приём к Ирине?» — вопрос о порядке, а не о себе:
 * живой диалог 1 октября начался именно так, следующей репликой мама написала
 * «Малышу 2 месяца», а агент уже решил «взрослый» и после согласия попросил
 * взрослую анкету — без имени родителя и без веса.
 */
const SELF_BOOKING =
  /(?<!\p{L})(?:(?:хочу|хотим|хотел\p{L}*|хотелось|можно|могу|нужно|надо|мне|я)\s+(?:(?:бы|ли|мне|я|тоже|снова|ещё|еще|к\s+вам)\s+)*записаться|записаться\s+(?:можно|мне|хочу|хотел\p{L}*)|запишите\s+меня|записать\s+себя|хочу\s+к\s+)/iu;

/**
 * Возраст, который бывает только у ребёнка.
 *
 * «МагомедХабибов Шамиль, 2,5 месяца» — возраст назван прямо, а слова
 * «ребёнок» в сообщении нет, и агент через реплику снова спросил «для кого —
 * взрослому или ребёнку». Месяцы у взрослых не считают; годы — считают, и
 * «33 года» ребёнком не делает, поэтому здесь только месяцы.
 */
const AGE_IN_MONTHS = /(?<!\p{L})\d+(?:[.,]\d+)?\s*мес/iu;

/**
 * Дата рождения не старше восемнадцати лет — тоже ребёнок.
 * «Абдулкадирова Халима 01.11.2023 г» — анкета ребёнка, присланная родителем.
 */
function recentBirthDate(t: string, now: Date = new Date()): boolean {
  const m = t.match(/(?<!\d)(\d{1,2})[./](\d{1,2})[./](\d{4})(?!\d)/);
  if (!m) return false;
  const year = Number(m[3]);
  const age = now.getFullYear() - year;
  return year > 1900 && age >= 0 && age < 18;
}

/**
 * Для кого приём — по всему разговору, свежие реплики первыми.
 *
 * Решает самая свежая реплика, где про это хоть что-то сказано. Порядок важен:
 * вызовы собирали список как «текущая реплика, затем прошлые с самой ранней»,
 * и «Взрослый» трёхнедельной давности перебивал сегодняшнее «малышу 2
 * месяца». Старые слова не перебивают новых и в обратную сторону: мама,
 * месяц назад записывавшая сына, сегодня пишет «хочу записаться» — это про неё.
 */
export function whomAcross(textsNewestFirst: string[]): Whom {
  for (const text of textsNewestFirst) {
    const w = whomFor(text);
    if (w !== "unknown") return w;
  }
  return "unknown";
}

export function whomFor(text: string): Whom {
  const t = norm(text);
  const child = CHILD_WORDS.test(t) || AGE_IN_MONTHS.test(t) || recentBirthDate(t);
  const adult = ADULT_WORDS.test(t);
  // Сказали и то и другое («записать ребёнка и себя») — выбирать нельзя.
  if (child && adult) return "unknown";
  if (child) return "child";
  if (adult) return "adult";
  if (SELF_BOOKING.test(t)) return "adult";
  return "unknown";
}

/**
 * В сообщении названо только «для кого» — и больше ничего.
 *
 * Живой диалог: «Здравствуйте» → «Ребенку 11 лет» → и в ответ дословная справка
 * про то, с какого возраста делают БОС-терапию и что при ЗРР бывает НАК.
 * Человек ни о БОС, ни о НАК не спрашивал: он назвал возраст и ждал, что
 * спросят дальше. Такой ответ выглядит как разговор не с ним.
 *
 * Поэтому голое «для кого» — не вопрос и не повод для справки: это начало
 * записи, и следующий шаг один — спросить услугу.
 */
export function onlyWhomStated(text: string): boolean {
  if (text.includes("?")) return false;
  if (whomFor(text) === "unknown") return false;
  const parts = norm(text)
    .split(/[^\p{L}\d]+/u)
    .filter((w) => w.length > 0);
  // Четыре слова — это «ребенку 11 лет» и «приём для взрослого». Больше —
  // человек сказал что-то ещё, и решать за него нельзя.
  return parts.length > 0 && parts.length <= 4;
}

/** Услуга детская по названию. */
function isChildService(title: string): boolean {
  return /(?<!\p{L})(дет[си]|ребен|ребён|подрост)/iu.test(norm(title));
}

/** Услуга для беременных — отдельная, ни к детям, ни к обычным взрослым. */
function isPregnancyService(title: string): boolean {
  return /беремен/i.test(norm(title));
}

