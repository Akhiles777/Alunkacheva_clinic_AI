/**
 * Значимые слова вопроса: по ним ищем услугу.
 *
 * Имя врача считается значимым: у клиники приём «Ирины» и приём «Разият» —
 * разные услуги с разными ценами.
 */
function words(text: string): string[] {
  return collapseFormulas(norm(text).replace(/[^\p{L}\p{N}]+/gu, " "))
    .split(" ")
    /**
     * «Амин» — не услуга. Живой диалог 9 октября: на «амин» агент ответил
     * «вы выбрали инфузию „Амино-Архитектура“ — 8500 ₽»: четыре буквы совпали
     * с началом названия, и слово весило как название целиком.
     */
    .filter((w) => w.length >= 3 && !NOISE.has(w) && !courtesyFormulaWord(w));
}

/**
 * Насколько название услуги отвечает вопросу.
 *
 * Считаем не долю совпавших СЛОВ, а долю совпавших БУКВ: длинное слово говорит
 * об услуге больше короткого. «Остеопатия» — это услуга; «лет», «прием»,
 * «терапия» встречаются у половины прайса.
 *
 * Простой подсчёт слов ломался на живых вопросах в обе стороны. «Здравствуйте,
 * сколько стоит остеопатия ребёнку 6 лет?» — одно совпадение из трёх слов, и
 * услуга не находилась вовсе. «А БОС-терапия что даёт?» — одно совпадение из
 * двух, и рядом с БОС вставало «Внутривенное капельное введение растворов
 * (IV-терапия)»: общее слово «терапия» весило столько же, сколько «БОС».
 */
/**
 * Слова о ЧЕЛОВЕКЕ, а не об услуге: кто, сколько лет, как зовут.
 *
 * Живой диалог 29 сентября: «К остеопату Ирина Алункачева есть окошко для
 * записи» и следом «К остеопату, ребенок, трех месяцев» — услуга названа
 * дважды, а агент дважды спросил «на какую услугу записываемся?». Имя врача,
 * «ребенок», «трех месяцев» разбавили «остеопату» до 0,30 при пороге 0,5.
 * Список NOISE ловил это по одному слову — «ребенка» был, «ребенок» нет, — и
 * каждая новая форма означала новый живой провал.
 *
 * Поэтому здесь не слова, а ВИДЫ слов: возраст и числительные, родня и дети в
 * любом падеже, отчество и фамилия по окончанию, имя с заглавной буквы
 * посреди фразы. Из доли они выпадают, только если ни в одном названии прайса
 * их нет: «Детский приём» и «Остеопатия, приём Ирины» по-прежнему находятся
 * по этим словам. Всё остальное незнакомое долю разбавляет как раньше — иначе
 * «сын занимается спортом» находил бы инфузию «(Спорт и выносливость)».
 */
const PERSON_WORD =
  /^(?:реб[её]н\p{L}*|малыш\p{L}*|младен\p{L}*|сын\p{L}*|доч\p{L}*|девочк\p{L}*|мальчик\p{L}*|внук\p{L}*|внучк\p{L}*|племянн\p{L}*|муж|мужа|мужу|жена|жену|жене|мам[аеуы]?|маму|пап[аеуы]?|бабушк\p{L}*|дедушк\p{L}*|месяц\p{L}*|месячн\p{L}*|мес|недел\p{L}*|лет|год\p{L}{0,4}|один|одна|одного|одному|два|две|двух|двум|три|тр[её]х|тр[её]м|четыре|четыр[её]х|пять|пяти|шесть|шести|семь|семи|восемь|восьми|девять|девяти|десять|десяти|одиннадцат\p{L}*|двенадцат\p{L}*|полгода|полтора|полутора|\p{L}+(?:овн|евн|ичн)\p{L}*|\p{L}+(?:ович|евич)\p{L}*|\p{L}{3,}(?:ова|ева|овой|евой|ову|еву|овым|евым))$/u;

/** Слово, у которого в прайсе нет ни одного похожего. */
function foreignToCatalog(w: string, vocabulary: Set<string>): boolean {
  for (const x of vocabulary) {
    if (w === x) return false;
    let i = 0;
    while (i < w.length && i < x.length && w[i] === x[i]) i += 1;
    if (i >= 4) return false;
  }
  return true;
}

/**
 * Слова вопроса, которые в долю не идут: о человеке и незнакомые прайсу.
 * Имя с заглавной буквы посреди фразы — тоже о человеке («к остеопату Ирина
 * Алункачева»), первое слово фразы с заглавной пишут всегда, его не трогаем.
 */
function aboutPerson(question: string, vocabulary: Set<string>): Set<string> {
  const out = new Set<string>();
  const raw = question.replace(/[^\p{L}\p{N}.!?]+/gu, " ").split(" ").filter(Boolean);
  raw.forEach((token, i) => {
    const w = norm(token.replace(/[.!?]+$/u, ""));
    if (w.length < 3 || !foreignToCatalog(w, vocabulary)) return;
    const sentenceStart = i === 0 || /[.!?]$/u.test(raw[i - 1]);
    const capitalized = /^\p{Lu}\p{Ll}/u.test(token) && !sentenceStart;
    if (capitalized || PERSON_WORD.test(w)) out.add(w);
  });
  return out;
}

function relevance(title: string, question: string, ignore: Set<string> = new Set()): number {
  const q = words(question).filter((w) => !ignore.has(w));
  const t = words(title);
  if (q.length === 0 || t.length === 0) return 0;

  /**
   * Сравниваем по четырём первым буквам.
   *
   * На пяти «Ирине» и «Ирины» не совпадали, и вопрос «хотела ребёнка записать
   * к Ирине Алункачевой» не находил ни одной услуги: пациентка назвала врача,
   * а не услугу, и подбор возвращал пустоту. Четырёх букв хватает на падежи и
   * мало для случайных совпадений: «приём» и «привет» расходятся уже здесь.
   */
  /**
   * Сколько букв слова действительно совпало — по общему НАЧАЛУ, а не по
   * четырём буквам целиком.
   *
   * Живой ответ: на «К остеопату записаться можно?» в список цен попало «Остео
   * бьюти — 2000 ₽». Четырёхбуквенного «осте» хватало, чтобы косметическая
   * услуга весила столько же, сколько «Остеопатия, приём Ирины»: «остео» и
   * «остеопатия» по такому правилу неразличимы.
   *
   * Теперь слово получает ровно столько, сколько букв у него совпало с
   * названием: «остеопату» против «остеопатия» — восемь, против «остео» —
   * пять. Порог в четыре буквы остаётся, иначе «прием» и «привет» начнут
   * совпадать на «при».
   */
  const credit = (w: string) => {
    let best = 0;
    for (const x of t) {
      /**
       * Короткое слово, совпавшее с названием ЦЕЛИКОМ, — это название услуги:
       * «БОС», «УЗИ», «МРТ», «ОАК». По правилу четырёх букв «БОС» не весило
       * ничего, и в ответ на «БОС-терапию» рядом вставала «IV-терапия» —
       * общим было одно слово «терапию».
       */
      if (w === x && w.length >= 3) return w.length;
      let i = 0;
      while (i < w.length && i < x.length && w[i] === x[i]) i += 1;
      if (i > best) best = i;
    }
    return best >= 4 ? best : 0;
  };

  let hit = 0;
  let total = 0;
  let strong = false;
  for (const w of q) {
    total += w.length;
    const c = Math.min(credit(w), w.length);
    hit += c;
    if (c >= STRONG_STEM && w.length - c <= 4) strong = true;
  }
  if (total === 0) return 0;
  return strong ? Math.max(hit / total, STRONG_SCORE) : hit / total;
}

/**
 * Длинная основа, совпавшая с названием почти целиком, — услуга названа,
 * сколько бы слов ни стояло рядом.
 *
 * Живой диалог 4 октября: «Сколько стоит запись на прием с остеопату Ирине и
 * когда у нее есть свободное окно» — доля «остеопату» 0,47 при пороге 0,5, и
 * агент спросил «на какую услугу записываемся?». Тот же провал у жалобы: «для
 * ребенка 3 года? У него плоскостопие» — «плоскостопие» длиннее «остеопата».
 * Каждое новое слово в NOISE чинило один такой случай; правило по виду слова
 * чинит их все. Семь общих букв и не больше четырёх на окончание: «капельница»
 * против «капельное» (семь из десяти) — услуга, «спортом» против «Спорт» (пять
 * букв) и «беременность» против «беременных» (семь из двенадцати) — нет.
 */
const STRONG_STEM = 7;
const STRONG_SCORE = 0.5;

/**
 * Услуги, подходящие под вопрос. Пустой список означает «ничего не нашли» —
 * тогда модель работает по общему прайсу, как раньше.
 */
export function matchServices<T extends ServiceLike>(
  question: string,
  services: T[],
  limit = 6,
  /**
   * Насколько уверенным должно быть совпадение.
   *
   * Ноль — «хоть что-то общее»: так и надо, когда список идёт модели, у неё
   * есть контекст переписки. Но когда список уходит человеку карточкой с
   * ценой, порог нужен: на «Доброго дня» приходил прайс случайной услуги,
   * потому что одно слово из семи в названии нашлось.
   */
  minScore = 0,
  /**
   * Для кого приём — если это уже известно снаружи.
   *
   * «К остеопату записаться можно?» — возвратный глагол даёт «взрослый», и
   * детские услуги в список не попадали. А агент в этом же ответе спрашивал
   * «для взрослого или для ребёнка?»: значит он НЕ знает, и цены надо называть
   * обе. Передать «unknown» — сказать «не решай за человека».
   */
  whomOverride?: Whom,
): T[] {
  const whom = whomOverride ?? whomFor(question);

  const vocabulary = new Set(services.flatMap((s) => words(s.title)));
  const ignore = aboutPerson(question, vocabulary);
  const scored = services
    .map((s) => ({ s, score: relevance(s.title, question, ignore) }))
    .filter((x) => x.score > 0 && x.score >= minScore);
  if (scored.length === 0) return [];

  /**
   * Отсев по возрасту — главное. Спросили про ребёнка: взрослые услуги в
   * список не идут вовсе, иначе модель снова назовёт цену взрослого приёма.
   */
  const fits = scored.filter(({ s }) => {
    /**
     * Услуга для беременных — только когда про беременность и спросили.
     *
     * Прежде она уходила всем, о ком неизвестно, для кого приём: на обычное
     * «сколько стоит остеопатия?» первой строкой шла «Остеопатия для
     * беременных». Человеку это ни о чём, а в первом сообщении клиники
     * выглядит как разговор не с ним.
     */
    if (isPregnancyService(s.title)) return /беремен/i.test(norm(question));
    if (whom === "child") return isChildService(s.title);
    if (whom === "adult") return !isChildService(s.title);
    return true;
  });

  const use = fits.length > 0 ? fits : scored;
  const ranked = use.sort((a, b) => b.score - a.score || a.s.price - b.s.price);

  /**
   * Слабые совпадения к сильному не добавляем.
   *
   * На «а БОС-терапия что даёт?» рядом с БОС-терапией шло «Внутривенное
   * капельное введение растворов (IV-терапия)» — совпало общее слово
   * «терапия». Формально это совпадение, а для пациента — чужая услуга в
   * ответе на прямой вопрос. Оставляем только то, что близко к лучшему.
   */
  const best = ranked[0].score;
  return ranked
    .filter((x) => x.score >= best * CLOSE_ENOUGH)
    .slice(0, limit)
    .map((x) => x.s);
}
