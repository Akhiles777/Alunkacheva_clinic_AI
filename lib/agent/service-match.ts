/**
 * Какие услуги подходят под вопрос пациента.
 *
 * Модели давался весь прайс — шесть десятков строк, среди которых «Остеопатия
 * — дети, приём Ирины» за 4900 и «Взрослый приём — остеопатия» за 8000. На
 * прямой вопрос «хотела ребёнка записать» она назвала взрослую цену. Это не
 * та ошибка, которую чинят уговорами в промпте: выбирать из шести десятков
 * похожих строк — работа для кода, а не для модели.
 *
 * Здесь мы сами отбираем подходящие услуги и отдаём их отдельным списком с
 * пометкой «цену бери отсюда». Модель формулирует ответ, но цену не выбирает.
 */

/** Насколько слабее лучшего совпадения может быть соседнее в том же ответе. */
const CLOSE_ENOUGH = 0.75;

export interface ServiceLike {
  title: string;
  price: number;
  durationMin: number;
}

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/** Для кого приём — по словам пациента. */
export type Whom = "child" | "adult" | "unknown";

const CHILD_WORDS =
  /(?<!\p{L})(ребен|ребён|детск|дет[еяи]|сын|доч|мальчик|девочк|малыш|подрост|годик|месяц\p{L}*\s+ребен)/iu;
/**
 * Основы пишем без границы справа: «взросл» продолжается «ый», и запрет буквы
 * после основы не давал совпасть ни разу. Целые слова — с границей, иначе
 * «мне» найдётся внутри «мнение».
 */
const ADULT_WORDS =
  /(?<!\p{L})(?:взросл\p{L}*|муж\p{L}*|жен[еуы]|себя|для меня|(?:мне|маме|папе)(?!\p{L}))/iu;

/**
 * «Записаться» — про себя, «записать» — про кого-то.
 *
 * Пациентка написала «хочу записаться на приём к остеопату», и агент
 * переспросил, для взрослого или для ребёнка. Она не говорила про ребёнка:
 * возвратный глагол означает «себя», и переспрашивать тут нечего. Детские
 * слова правило отменяют — «хочу записаться с ребёнком» решает не оно.
 */
const SELF_BOOKING = /(?<!\p{L})(?:записаться|запишите\s+меня|записать\s+себя|хочу\s+к\s+)/iu;

export function whomFor(text: string): Whom {
  const t = norm(text);
  const child = CHILD_WORDS.test(t);
  const adult = ADULT_WORDS.test(t);
  // Сказали и то и другое («записать ребёнка и себя») — выбирать нельзя.
  if (child && adult) return "unknown";
  if (child) return "child";
  if (adult) return "adult";
  if (SELF_BOOKING.test(t)) return "adult";
  return "unknown";
}

/** Услуга детская по названию. */
function isChildService(title: string): boolean {
  return /(?<!\p{L})(дет[си]|ребен|ребён|подрост)/iu.test(norm(title));
}

/** Услуга для беременных — отдельная, ни к детям, ни к обычным взрослым. */
function isPregnancyService(title: string): boolean {
  return /беремен/i.test(norm(title));
}

/**
 * Слова, которые ничего не говорят об услуге.
 *
 * Из-за них живой вопрос не находил услугу вовсе. «Здравствуйте сколько стоит
 * остеопатия?» — четыре значимых слова, в названии услуги нашлось одно, доля
 * 0,25, порог не пройден. Пациенту ушёл ВЕСЬ прайс клиники: двадцать пять
 * строк подряд, от «Забор крови» до «Инфузии „Ферро-Баланс“», — на прямой
 * вопрос про остеопатию. Первое, что человек увидел от клиники.
 *
 * Вежливость и обороты вопроса в долю входить не должны: услугу называет одно
 * слово, а не то, сколько слов человек написал вокруг него.
 */
const NOISE = new Set([
  /**
   * Короткие служебные слова. Они здесь потому, что порог длины пришлось
   * опустить до трёх букв: «БОС», «УЗИ», «МРТ», «ОАК» — это названия услуг, а
   * не мусор. Пока порог был четыре, самое важное слово вопроса «а БОС-терапия
   * что даёт?» выбрасывалось, и услуга находилась по одному слову «терапия» —
   * вместе с «Внутривенным введением растворов (IV-терапия)» за 500 ₽.
   */
  "что", "как", "где", "для", "или", "это", "вам", "нам", "она", "они", "оно", "мне",
  "его", "ещё", "еще", "так", "уже", "при", "над", "под", "без", "вас", "тут", "там",
  "вот", "кто", "чем", "чём", "был", "про", "тот", "эти", "все", "всё", "нас", "нет",
  "да", "но", "и", "а",
  // Возраст: «ребёнку 6 лет» — про человека, а не про услугу.
  "лет", "год", "года", "годик", "годика", "годиков", "месяц", "месяца", "месяцев",
  "здравствуйте", "здраствуйте", "доброго", "добрый", "доброе", "привет", "приветствую",
  "салам", "алейкум", "ассаламу",
  "сколько", "стоит", "стоить", "стоимость", "цена", "цены", "прайс", "почем", "почём",
  "обойдется", "обойдётся", "будет",
  "скажите", "подскажите", "подскажете", "пожалуйста", "спасибо", "интересует", "вопрос",
  "хотел", "хотела", "хочу", "можно", "нужно", "надо", "нужен", "нужна",
  "какая", "какие", "какой", "какое", "этой", "этого", "этот", "эта",
  "ваша", "ваши", "ваше", "вашей", "вашего", "услуга", "услуги", "услугу",
]);

/**
 * Значимые слова вопроса: по ним ищем услугу.
 *
 * Имя врача считается значимым: у клиники приём «Ирины» и приём «Разият» —
 * разные услуги с разными ценами.
 */
function words(text: string): string[] {
  return norm(text)
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .split(" ")
    .filter((w) => w.length >= 3 && !NOISE.has(w));
}

/**
 * Насколько название услуги отвечает вопросу.
 *
 * Считаем не долю совпавших СЛОВ, а долю совпавших БУКВ: длинное слово говорит
 * об услуге больше короткого. «Остеопатия» — это услуга; «лет», «прием»,
 * «терапия» встречаются у половины прайса.
 *
 * Простой подсчёт слов ломался на живых вопросах в обе стороны. «Здравствуйте,
 * сколько стоит остеопатия ребёнку 6 лет?» — одно совпадение из трёх слов, и
 * услуга не находилась вовсе. «А БОС-терапия что даёт?» — одно совпадение из
 * двух, и рядом с БОС вставало «Внутривенное капельное введение растворов
 * (IV-терапия)»: общее слово «терапия» весило столько же, сколько «БОС».
 */
function relevance(title: string, question: string): number {
  const q = words(question);
  const t = words(title);
  if (q.length === 0 || t.length === 0) return 0;

  /**
   * Сравниваем по четырём первым буквам.
   *
   * На пяти «Ирине» и «Ирины» не совпадали, и вопрос «хотела ребёнка записать
   * к Ирине Алункачевой» не находил ни одной услуги: пациентка назвала врача,
   * а не услугу, и подбор возвращал пустоту. Четырёх букв хватает на падежи и
   * мало для случайных совпадений: «приём» и «привет» расходятся уже здесь.
   */
  const matches = (w: string) => {
    const stem = w.slice(0, 4);
    return t.some((x) => x.startsWith(stem) || w.startsWith(x.slice(0, 4)));
  };

  let hit = 0;
  let total = 0;
  for (const w of q) {
    total += w.length;
    if (matches(w)) hit += w.length;
  }
  return total === 0 ? 0 : hit / total;
}

/**
 * Услуги, подходящие под вопрос. Пустой список означает «ничего не нашли» —
 * тогда модель работает по общему прайсу, как раньше.
 */
export function matchServices<T extends ServiceLike>(
  question: string,
  services: T[],
  limit = 6,
  /**
   * Насколько уверенным должно быть совпадение.
   *
   * Ноль — «хоть что-то общее»: так и надо, когда список идёт модели, у неё
   * есть контекст переписки. Но когда список уходит человеку карточкой с
   * ценой, порог нужен: на «Доброго дня» приходил прайс случайной услуги,
   * потому что одно слово из семи в названии нашлось.
   */
  minScore = 0,
): T[] {
  const whom = whomFor(question);

  const scored = services
    .map((s) => ({ s, score: relevance(s.title, question) }))
    .filter((x) => x.score > 0 && x.score >= minScore);
  if (scored.length === 0) return [];

  /**
   * Отсев по возрасту — главное. Спросили про ребёнка: взрослые услуги в
   * список не идут вовсе, иначе модель снова назовёт цену взрослого приёма.
   */
  const fits = scored.filter(({ s }) => {
    /**
     * Услуга для беременных — только когда про беременность и спросили.
     *
     * Прежде она уходила всем, о ком неизвестно, для кого приём: на обычное
     * «сколько стоит остеопатия?» первой строкой шла «Остеопатия для
     * беременных». Человеку это ни о чём, а в первом сообщении клиники
     * выглядит как разговор не с ним.
     */
    if (isPregnancyService(s.title)) return /беремен/i.test(norm(question));
    if (whom === "child") return isChildService(s.title);
    if (whom === "adult") return !isChildService(s.title);
    return true;
  });

  const use = fits.length > 0 ? fits : scored;
  const ranked = use.sort((a, b) => b.score - a.score || a.s.price - b.s.price);

  /**
   * Слабые совпадения к сильному не добавляем.
   *
   * На «а БОС-терапия что даёт?» рядом с БОС-терапией шло «Внутривенное
   * капельное введение растворов (IV-терапия)» — совпало общее слово
   * «терапия». Формально это совпадение, а для пациента — чужая услуга в
   * ответе на прямой вопрос. Оставляем только то, что близко к лучшему.
   */
  const best = ranked[0].score;
  return ranked
    .filter((x) => x.score >= best * CLOSE_ENOUGH)
    .slice(0, limit)
    .map((x) => x.s);
}
