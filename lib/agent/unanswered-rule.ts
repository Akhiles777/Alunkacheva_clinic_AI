/**
 * Правило добора: на какое сообщение агент обязан ответить второй раз.
 *
 * Живёт отдельно от самого добора, потому что решение здесь дороже механики.
 * Ответить лишний раз — перебить сотрудника или написать поверх законченного
 * разговора; не ответить — оставить человека писать дважды. Отдельный файл
 * позволяет проверить это правило тестами, не поднимая ни базы, ни каналов.
 */

/** Сколько ждём, прежде чем считать сообщение неотвеченным. */
export const QUIET_MINUTES = 3;

/** Насколько старые сообщения ещё имеет смысл догонять. */
export const MAX_AGE_HOURS = 6;

export interface SweepCandidate {
  /** Последнее сообщение переписки: чьё оно и когда. */
  last?: { direction: "IN" | "OUT"; createdAt: Date };
  /** Пауза после ручного ответа сотрудника (§6.4). */
  botPausedUntil?: Date | null;
}

/**
 * Отвечать ли на этот диалог добором.
 *
 * Статус диалога и открытые эскалации отсекаются запросом к базе — сюда
 * доходят только те, где разговор ведёт агент.
 */
export function needsAnswer(conv: SweepCandidate, now: Date): boolean {
  const last = conv.last;
  // Последним говорил не пациент — отвечать нечего.
  if (!last || last.direction !== "IN") return false;

  // Пауза после ручного ответа сотрудника добор не отменяет.
  if (conv.botPausedUntil && conv.botPausedUntil > now) return false;

  /**
   * Сообщение пришло, пока диалог вёл человек, — агент его не подхватывает.
   *
   * Диалог возвращается агенту через четыре часа тишины (§6.4), и добор
   * находил там последнее сообщение пациента — то самое, на которое отвечал
   * администратор четыре часа назад. Разговор давно кончился («Ок» в 13:50), а
   * в 17:54 приходило «Хорошо, если появятся вопросы — я здесь». Со стороны
   * это выглядит как бот, который очнулся и заговорил сам с собой.
   *
   * Возврат даёт агенту право отвечать на НОВЫЕ сообщения, а не переигрывать
   * старую переписку. Границей служит конец паузы: всё, что было до него, вёл
   * человек. Кнопка «Вернуть агенту» паузу снимает совсем — там администратор
   * осознанно передаёт разговор, включая последний вопрос.
   */
  if (conv.botPausedUntil && last.createdAt < conv.botPausedUntil) return false;

  const age = now.getTime() - last.createdAt.getTime();
  // Сообщение только что пришло: обычная обработка ещё в пути.
  if (age < QUIET_MINUTES * 60_000) return false;
  // Слишком старое: человек уже ушёл, ответ через полдня хуже молчания.
  if (age > MAX_AGE_HOURS * 3600_000) return false;

  return true;
}
