/**
 * Правило добора: на какое сообщение агент обязан ответить второй раз.
 *
 * Живёт отдельно от самого добора, потому что решение здесь дороже механики.
 * Ответить лишний раз — перебить сотрудника или написать поверх законченного
 * разговора; не ответить — оставить человека писать дважды. Отдельный файл
 * позволяет проверить это правило тестами, не поднимая ни базы, ни каналов.
 */

/** Сколько ждём, прежде чем считать сообщение неотвеченным. */
export const QUIET_MINUTES = 3;

/** Насколько старые сообщения ещё имеет смысл догонять. */
export const MAX_AGE_HOURS = 6;

export interface SweepCandidate {
  /** Последнее сообщение переписки: чьё оно, когда и что в нём. */
  last?: { direction: "IN" | "OUT"; createdAt: Date; body?: string };
  /** Пауза после ручного ответа сотрудника (§6.4). */
  botPausedUntil?: Date | null;
}

/**
 * Сообщение, на которое отвечать нечего.
 *
 * Пациентка подтвердила запись у администратора и прислала сердечко. Через
 * несколько часов агент написал сам: «Рады видеть, что вы подтвердили запись.
 * Если появятся вопросы — я здесь». Разговор был закончен, вопроса не было,
 * человек получил сообщение ночью — и это ровно то, чего делать нельзя:
 * агент не пишет первым и не заполняет тишину.
 *
 * Считаем «нечем отвечать», если после снятия эмодзи, знаков и коротких
 * благодарностей не остаётся ничего. Вопросительный знак или лишние слова
 * сразу отменяют правило: «Спасибо, а во сколько?» — обычный вопрос.
 */
const COURTESY = [
  "спасибо",
  "спс",
  "благодарю",
  "пожалуйста",
  "хорошо",
  "ок",
  "окей",
  "понятно",
  "поняла",
  "понял",
  "принято",
  "да",
  "ага",
  "угу",
  "отлично",
  "супер",
  "здорово",
  "договорились",
  "буду",
  "приду",
];

/**
 * Слова-довески, которые сами по себе ничего не спрашивают: «благодарю ВАС»,
 * «спасибо БОЛЬШОЕ». Убираем их до сверки, иначе вежливость из двух слов
 * перестаёт узнаваться.
 */
const FILLER = ["вас", "тебя", "вам", "тебе", "большое", "огромное", "всё", "все", "очень"];

export function nothingToAnswer(body: string | undefined): boolean {
  /**
   * Тела нет вовсе — значит мы его не знаем, а не что оно пустое. Молчать в
   * таком случае нельзя: неизвестность не повод не отвечать человеку.
   */
  if (body === undefined) return false;
  const text = body.trim();
  if (text.length === 0) return true;
  // Вопрос — всегда повод ответить, чем бы он ни был обставлен.
  if (text.includes("?")) return false;

  /**
   * Убираем всё, что не буква и не цифра: эмодзи, знаки, символы вложений.
   * Пустой остаток означает сообщение из одних картинок — сердечко, палец
   * вверх, стикер.
   */
  const words = text
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
  if (words.length === 0) return true;
  const meaningful = words.filter((w) => !FILLER.includes(w));
  if (meaningful.length === 0) return true;
  // Больше трёх слов — уже сообщение, а не жест вежливости.
  if (meaningful.length > 3) return false;
  return meaningful.every((w) => COURTESY.includes(w));
}

/**
 * Отвечать ли на этот диалог добором.
 *
 * Статус диалога и открытые эскалации отсекаются запросом к базе — сюда
 * доходят только те, где разговор ведёт агент.
 */
export function needsAnswer(conv: SweepCandidate, now: Date): boolean {
  const last = conv.last;
  // Последним говорил не пациент — отвечать нечего.
  if (!last || last.direction !== "IN") return false;

  /**
   * Сердечко, «спасибо» и «ок» ответа не требуют.
   *
   * Добор существует, чтобы догнать оставшийся без ответа ВОПРОС, а не чтобы
   * реагировать на жест вежливости в конце разговора. Ответ на сердечко
   * приходит человеку как сообщение от клиники — часто ночью и ни о чём.
   */
  if (nothingToAnswer(last.body)) return false;

  // Пауза после ручного ответа сотрудника добор не отменяет.
  if (conv.botPausedUntil && conv.botPausedUntil > now) return false;

  /**
   * Сообщение пришло, пока диалог вёл человек, — агент его не подхватывает.
   *
   * Диалог возвращается агенту через четыре часа тишины (§6.4), и добор
   * находил там последнее сообщение пациента — то самое, на которое отвечал
   * администратор четыре часа назад. Разговор давно кончился («Ок» в 13:50), а
   * в 17:54 приходило «Хорошо, если появятся вопросы — я здесь». Со стороны
   * это выглядит как бот, который очнулся и заговорил сам с собой.
   *
   * Возврат даёт агенту право отвечать на НОВЫЕ сообщения, а не переигрывать
   * старую переписку. Границей служит конец паузы: всё, что было до него, вёл
   * человек. Кнопка «Вернуть агенту» паузу снимает совсем — там администратор
   * осознанно передаёт разговор, включая последний вопрос.
   */
  if (conv.botPausedUntil && last.createdAt < conv.botPausedUntil) return false;

  const age = now.getTime() - last.createdAt.getTime();
  // Сообщение только что пришло: обычная обработка ещё в пути.
  if (age < QUIET_MINUTES * 60_000) return false;
  // Слишком старое: человек уже ушёл, ответ через полдня хуже молчания.
  if (age > MAX_AGE_HOURS * 3600_000) return false;

  return true;
}
