import { describe, expect, it } from "vitest";
import { promisesBooking, promisesHuman, admitsInability } from "./booking-promise";

/**
 * §6: расписанием агент не распоряжается. Проверка появилась после боевого
 * случая — ассистент сказал пациенту, что сам его запишет и ведёт запись.
 */
describe("promisesBooking", () => {
  it("ловит обещание записать", () => {
    expect(promisesBooking("Хорошо, запишу вас на завтра в 15:00")).toBe(true);
    expect(promisesBooking("Записываю вас к остеопату")).toBe(true);
    expect(promisesBooking("Я забронирую для вас это время")).toBe(true);
    expect(promisesBooking("Поставлю вас на 14:00")).toBe(true);
    expect(promisesBooking("Подберу вам удобное время")).toBe(true);
    expect(promisesBooking("Оформлю запись прямо сейчас")).toBe(true);
  });

  it("ловит подтверждение брони", () => {
    expect(promisesBooking("Готово, вы записаны на пятницу")).toBe(true);
    expect(promisesBooking("Запись создана, ждём вас")).toBe(true);
    expect(promisesBooking("Ждём вас 15:00 в кабинете 3")).toBe(true);
  });

  it("не мешает правильным ответам про запись", () => {
    expect(promisesBooking("Запись ведёт администратор — передал ему ваш вопрос.")).toBe(false);
    expect(
      promisesBooking("Записью занимается администратор, он свяжется с вами здесь."),
    ).toBe(false);
    expect(promisesBooking("Приём остеопата стоит 7000 ₽ и длится 60 минут.")).toBe(false);
    expect(promisesBooking("Наш адрес: Островского 20а, 2 этаж.")).toBe(false);
  });
});

/**
 * Обещание позвать человека должно исполняться: эскалацию создаёт код, а не
 * текст ответа. На живом диалоге ассистент написал «позову администратора» и
 * не позвал — администратор о вопросе не узнал, пациентка ждала.
 */
describe("promisesHuman", () => {
  it("узнаёт обещание передать человеку", () => {
    for (const t of [
      "Позову администратора, чтобы она помогла связаться с врачом.",
      "Передам ваш вопрос администратору.",
      "Уточню у специалиста и вернусь с ответом.",
      "Хорошо, я передам вашу просьбу администратору — он свяжется с вами.",
    ]) {
      expect(promisesHuman(t), t).toBe(true);
    }
  });

  it("вежливое продолжение передачей не считает", () => {
    // Агент назвал адрес и добавил, что администратор пришлёт геолокацию.
    // Вопрос закрыт — звать человека незачем.
    for (const t of [
      "Мы на ул. Островского, 20А. Если нужна геолокация — администратор отправит точку на карте.",
      "Приём длится 40 минут. Администратор подскажет удобное время.",
    ]) {
      expect(promisesHuman(t), t).toBe(false);
    }
  });

  it("не срабатывает на обычный ответ по справке", () => {
    for (const t of [
      "Приём остеопата стоит 8000 ₽ и длится 40 минут.",
      "Мы работаем с понедельника по субботу, в воскресенье выходной.",
      "Запись ведёт администратор клиники.",
    ]) {
      expect(promisesHuman(t), t).toBe(false);
    }
  });
});

/**
 * Ответ, в котором агент рассказывает о себе вместо помощи.
 *
 * «Прошу прощения, но я — справочная служба клиники в мессенджере, и у меня нет
 * доступа к фотографиям счётчиков» — четыре строки о себе там, где человеку
 * нужен был администратор.
 */
describe("admitsInability", () => {
  it("узнаёт рассказ о собственном бессилии", () => {
    for (const t of [
      "Прошу прощения, но я — справочная служба клиники, и у меня нет доступа к фотографиям счётчиков.",
      "Я не могу отправлять фото счётчиков — у меня нет доступа к таким документам.",
      "Я не располагаю такой информацией.",
    ]) {
      expect(admitsInability(t), t).toBe(true);
    }
  });

  it("отказ клиники в услуге не глушит", () => {
    // «У нас нет такой услуги» — нормальный ответ клиники, а не рассказ о себе.
    for (const t of [
      "У нас нет услуги МРТ.",
      "Остеопаты консультации не ведут: запись сразу на приём.",
      "Приём остеопата стоит 8000 ₽.",
    ]) {
      expect(admitsInability(t), t).toBe(false);
    }
  });
});
