import { describe, expect, it } from "vitest";
import { promisesBooking, promisesHuman, admitsInability,
  bookingPromiseFound,
  withoutBookingPromise,
  defersToDoctor,
  withoutHandoverPromise,
} from "./booking-promise";

/**
 * §6: расписанием агент не распоряжается. Проверка появилась после боевого
 * случая — ассистент сказал пациенту, что сам его запишет и ведёт запись.
 */
describe("promisesBooking", () => {
  it("ловит обещание записать", () => {
    expect(promisesBooking("Хорошо, запишу вас на завтра в 15:00")).toBe(true);
    expect(promisesBooking("Записываю вас к остеопату")).toBe(true);
    expect(promisesBooking("Я забронирую для вас это время")).toBe(true);
    expect(promisesBooking("Поставлю вас на 14:00")).toBe(true);
    expect(promisesBooking("Подберу вам удобное время")).toBe(true);
    expect(promisesBooking("Оформлю запись прямо сейчас")).toBe(true);
  });

  it("ловит подтверждение брони", () => {
    expect(promisesBooking("Готово, вы записаны на пятницу")).toBe(true);
    expect(promisesBooking("Запись создана, ждём вас")).toBe(true);
    expect(promisesBooking("Ждём вас 15:00 в кабинете 3")).toBe(true);
  });

  it("не мешает правильным ответам про запись", () => {
    expect(promisesBooking("Запись ведёт администратор — передал ему ваш вопрос.")).toBe(false);
    expect(
      promisesBooking("Записью занимается администратор, он свяжется с вами здесь."),
    ).toBe(false);
    expect(promisesBooking("Приём остеопата стоит 7000 ₽ и длится 60 минут.")).toBe(false);
    expect(promisesBooking("Наш адрес: Островского 20а, 2 этаж.")).toBe(false);
  });
});

/**
 * Обещание позвать человека должно исполняться: эскалацию создаёт код, а не
 * текст ответа. На живом диалоге ассистент написал «позову администратора» и
 * не позвал — администратор о вопросе не узнал, пациентка ждала.
 */
describe("promisesHuman", () => {
  it("узнаёт обещание передать человеку", () => {
    for (const t of [
      "Позову администратора, чтобы она помогла связаться с врачом.",
      "Передам ваш вопрос администратору.",
      "Уточню у специалиста и вернусь с ответом.",
      "Хорошо, я передам вашу просьбу администратору — он свяжется с вами.",
    ]) {
      expect(promisesHuman(t), t).toBe(true);
    }
  });

  it("вежливое продолжение передачей не считает", () => {
    // Агент назвал адрес и добавил, что администратор пришлёт геолокацию.
    // Вопрос закрыт — звать человека незачем.
    for (const t of [
      "Мы на ул. Островского, 20А. Если нужна геолокация — администратор отправит точку на карте.",
      "Приём длится 40 минут. Администратор подскажет удобное время.",
    ]) {
      expect(promisesHuman(t), t).toBe(false);
    }
  });

  it("не срабатывает на обычный ответ по справке", () => {
    for (const t of [
      "Приём остеопата стоит 8000 ₽ и длится 40 минут.",
      "Мы работаем с понедельника по субботу, в воскресенье выходной.",
      "Запись ведёт администратор клиники.",
    ]) {
      expect(promisesHuman(t), t).toBe(false);
    }
  });
});

/**
 * Ответ, в котором агент рассказывает о себе вместо помощи.
 *
 * «Прошу прощения, но я — справочная служба клиники в мессенджере, и у меня нет
 * доступа к фотографиям счётчиков» — четыре строки о себе там, где человеку
 * нужен был администратор.
 */
describe("admitsInability", () => {
  it("узнаёт рассказ о собственном бессилии", () => {
    for (const t of [
      "Прошу прощения, но я — справочная служба клиники, и у меня нет доступа к фотографиям счётчиков.",
      "Я не могу отправлять фото счётчиков — у меня нет доступа к таким документам.",
      "Я не располагаю такой информацией.",
    ]) {
      expect(admitsInability(t), t).toBe(true);
    }
  });

  it("отказ клиники в услуге не глушит", () => {
    // «У нас нет такой услуги» — нормальный ответ клиники, а не рассказ о себе.
    for (const t of [
      "У нас нет услуги МРТ.",
      "Остеопаты консультации не ведут: запись сразу на приём.",
      "Приём остеопата стоит 8000 ₽.",
    ]) {
      expect(admitsInability(t), t).toBe(false);
    }
  });
});

/**
 * Ответ выбрасывался целиком из-за одной фразы: модель успела назвать услугу,
 * цену и попросить данные, а пациентка получала «записью занимается
 * администратор» и разговор обрывался на полпути. Заказчик: сначала оформить
 * клиента, потом передавать.
 */
describe("ответ без обещания записать", () => {
  it("убирает обещание, оставляя суть", () => {
    const answer =
      "Детский приём остеопата стоит 4900 ₽ и длится 30 минут. " +
      "Я запишу вашего сына на завтра. " +
      "Напишите, пожалуйста, имя и возраст ребёнка и кратко причину обращения.";
    const cleaned = withoutBookingPromise(answer);
    expect(cleaned).toContain("4900");
    expect(cleaned).toContain("имя и возраст");
    expect(cleaned).not.toContain("запишу");
    expect(promisesBooking(cleaned)).toBe(false);
  });

  it("ответ целиком из обещания схлопывается в пустоту", () => {
    // Тогда отправлять нечего — зовём человека, как и раньше.
    expect(withoutBookingPromise("Я запишу вас на завтра.").length).toBeLessThan(20);
  });

  it("правильный ответ не трогает", () => {
    const ok = "Записью занимается администратор. Приём стоит 4900 ₽.";
    expect(withoutBookingPromise(ok)).toBe(ok);
  });

  it("называет найденную фразу — иначе причину не узнать", () => {
    expect(bookingPromiseFound("Я запишу вас на завтра")).toMatch(/запишу/i);
    expect(bookingPromiseFound("Приём стоит 4900 ₽")).toBeNull();
  });
});

/**
 * «Вы записаны» — факт из базы, когда записи пациента мы видим.
 *
 * Пациентка спросила «а к кому я записана?», агент ответил верно, и эта фраза
 * была вырезана как обещание записать. От ответа осталось меньше строки, и
 * человек получил «записью занимается администратор» на вопрос, ответ на
 * который только что назвали.
 */
describe("рассказ о существующей записи", () => {
  const answer = "Вы записаны к Ирине Алилгаджиевне на 8 сентября, 09:00.";

  it("без записей в справке остаётся обещанием", () => {
    expect(bookingPromiseFound(answer)).not.toBeNull();
  });

  it("с записями пациента — это пересказ факта", () => {
    expect(bookingPromiseFound(answer, true)).toBeNull();
  });

  it("настоящее обещание не пропускает и с записями", () => {
    expect(bookingPromiseFound("Записываю вас на завтра в 10:00.", true)).not.toBeNull();
    expect(bookingPromiseFound("Подберу вам удобное время.", true)).not.toBeNull();
  });

  it("чистка ответа щадит рассказ о записи", () => {
    const text = `${answer} Перенести её может только администратор.`;
    expect(withoutBookingPromise(text, true)).toContain("Вы записаны");
    expect(withoutBookingPromise(text, false)).not.toContain("Вы записаны");
  });
});

/**
 * Ответ отсылает к врачу — значит вопрос к врачу.
 *
 * Живой прогон: «Возможно ли уточнить у неё, можно ли сыну продолжать занятия
 * борьбой» — ни одно правило по словам не сработало, а модель ответила
 * «это вопрос к специалисту, который видел вашего сына». Она поняла, что
 * вопрос медицинский, код — нет, и врача никто не спросил.
 */
describe("ответ отсылает к врачу", () => {
  it("узнаёт передачу специалисту", () => {
    for (const t of [
      "К сожалению, я не могу ответить на этот вопрос — это касается здоровья, такие вещи обсуждает только специалист. Передаю ваш вопрос администратору.",
      "Это лучше уточнить у специалиста, который видел вашего сына на приёме.",
      "В справке этого нет — расскажет врач на приёме, я передам вопрос.",
    ]) {
      expect(defersToDoctor(t), t).toBe(true);
    }
  });

  it("узнаёт разные формулировки, которыми модель признаётся в незнании", () => {
    for (const t of [
      "По этому вопросу у меня точных данных нет — это расскажет специалист. Передаю ваш вопрос администратору.",

      "В справке клиники этого нет, врач расскажет на приёме.",
    ]) {
      expect(defersToDoctor(t), t).toBe(true);
    }
  });

  it("имя врача считается упоминанием врача", () => {
    const text = "Передаю администратору — он уточнит у Ирины Алилгаджиевны и ответит вам здесь же.";
    expect(defersToDoctor(text)).toBe(false);
    expect(defersToDoctor(text, ["Ирина Алилгаджиевна"])).toBe(true);
  });

  it("передачу администратору врачом не считает", () => {
    for (const t of [
      "Поняла, передал(а) администратору — он подберёт время и напишет здесь же.",
      "Передал(а) администратору — он ответит здесь же.",
      "Время подберёт администратор — он напишет здесь же.",
    ]) {
      expect(defersToDoctor(t), t).toBe(false);
    }
  });

  it("справку о враче передачей не считает", () => {
    expect(defersToDoctor("Взрослый приём — 8000 ₽, 45 минут. Приём ведёт Ирина Алилгаджиевна.")).toBe(
      false,
    );
  });
});

/**
 * Два обещания в одном сообщении.
 *
 * Вопрос врачу мы уже задали и дописываем «уточню у врача». Без чистки в
 * ответе оставалось её собственное «передам администратору, он уточнит у
 * Ирины Алилгаджиевны» — пациент читает это как двух собеседников сразу.
 */
describe("чистка обещаний передать", () => {
  it("убирает предложение с передачей, оставляя полезное", () => {
    const text =
      "Взрослый приём остеопата — 8000 ₽, 45 минут. Передаю ваш вопрос администратору, он уточнит у врача.";
    const kept = withoutHandoverPromise(text);
    expect(kept).toContain("8000");
    expect(kept).not.toContain("администратору");
  });

  it("справку о враче не трогает", () => {
    const text = "Детский приём — 5000 ₽, 40 минут. Приём ведёт Ирина Алилгаджиевна.";
    expect(withoutHandoverPromise(text)).toBe(text);
  });

  it("ответ без обещаний остаётся как есть", () => {
    const text = "Работаем с 09:00 до 21:00. Воскресенье — выходной.";
    expect(withoutHandoverPromise(text)).toBe(text);
  });
});
