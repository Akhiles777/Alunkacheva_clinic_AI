import { phraseRe, wordRe } from "./word-boundary";

/**
 * Темы, по которым агент обязан позвать человека (§6).
 *
 * Правила были написаны через `\b`, который в JavaScript опирается на
 * латинский `\w` и рядом с кириллицей границы не находит. «боль», «человека»,
 * «окно», «доза» не срабатывали никогда: правило выглядело рабочим, а по
 * факту молчало. Границы теперь задаёт wordRe.
 */
/**
 * Расписание — зона администратора. Сюда же отмены и переносы: заказчик хочет
 * держать эти решения за человеком.
 */
const SCHEDULE_PATTERNS = [
  /запиш|записать|записаться/i, wordRe("запись|записи"), /свободн/i,
  /окошк/i, wordRe("окно|окна|окон"),
  /перенест|перенос/i, /отменит|отмена записи|отменить запись/i,
  /когда можно прийти|на какое время/i,
  /**
   * «Не смогу прийти» — это отмена, сказанная по-человечески.
   *
   * Пациентка написала «извините, но я не могу придти, всю ночь озноб» — и
   * получила совет связаться с администратором самой. Ни одно правило выше
   * здесь не срабатывало, а между тем это отмена записи на сегодня, и
   * администратору о ней нужно знать немедленно.
   */
  /не\s+(?:смогу|могу|получится)\s+(?:прийти|придти|подойти|быть|приехать|попасть)/i,
  /не\s+(?:придём|придем|приду|приедем)/i,
];

/**
 * Вопрос про свободное время. Отдельно от остальной записи: здесь агенту
 * нечего уточнять — расписания он не видит, и любой его вопрос только оттянет
 * ответ. Пациентка спросила «ещё свободно окошко?», а услышала «на какую
 * услугу вы хотите записаться и для кого» — при том что и услуга, и врач были
 * видны из сообщения, на которое она отвечала.
 */
const SLOT_PATTERNS = [
  /свободн/i, /окошк/i, wordRe("окно|окна|окон"),
  /на какое время|когда можно прийти|какие\s+(?:есть\s+)?(?:окна|окошки|時)/i,
  /есть\s+(?:ли\s+)?(?:время|места|запись)\s+на/i,
];

export function asksForSlot(text: string): boolean {
  return SLOT_PATTERNS.some((re) => re.test(text));
}

/**
 * «Не смогу прийти» — отмена или перенос, о которых нужно знать немедленно.
 *
 * Отдельно от остальной записи, потому что здесь важен и тон, и скорость.
 * Пациентка написала «извините, не могу придти, всю ночь озноб» — и услышала,
 * что по симптомам ей ответит врач, а связаться с администратором надо самой.
 * Ей же нужно было только одно: чтобы запись на сегодня не пропала.
 */
const CANT_COME_PATTERNS = [
  /не\s+(?:смогу|могу|получится)\s+(?:прийти|придти|подойти|быть|приехать|попасть)/i,
  /не\s+(?:придём|придем|приду|приедем)/i,
  /(?:отмен\p{L}+|перенес\p{L}+|перенос\p{L}*)\s+(?:запись|приём|прием|визит)/iu,
];

export function cantCome(text: string): boolean {
  return CANT_COME_PATTERNS.some((re) => re.test(text));
}

/**
 * Просьба перенести уже существующую запись.
 *
 * «Здравствуйте, мы записаны были 20 августа в 10:30, можно, пожалуйста, после
 * 12 любое время — мальчик будет в саду» — и в ответ «напишите, на какую услугу
 * вы хотите записаться и для кого». Всё уже обговорено: услуга выбрана, запись
 * существует, человек просит другое время. Переспрашивать здесь — значит
 * показать, что предыдущий разговор забыт.
 *
 * Отличаем от новой записи по упоминанию существующей: «мы записаны», «наша
 * запись», «перенести», «сдвинуть», «можно пораньше».
 */
const RESCHEDULE_PATTERNS = [
  /(?<!\p{L})(?:записан\p{L}*|запись\s+(?:на|у нас)|наша\s+запись)(?!\p{L})/iu,
  /перенес\p{L}*|перенест\p{L}*|сдвин\p{L}*|переписа\p{L}*/iu,
  /(?:можно|давайте)\s+(?:после|до|пораньше|попозже|раньше|позже|на другое)/i,
  /другое\s+время|другой\s+день/i,
];

export function wantsReschedule(text: string): boolean {
  return RESCHEDULE_PATTERNS.some((re) => re.test(text));
}

/**
 * Личное: жалобы и вопросы про конкретного пациента. Всегда человеку — здесь
 * и врачебная тайна, и репутационный риск.
 */
const PERSONAL_PATTERNS = [
  /жалоб/i, /претенз/i, /вернуть деньги|возврат/i, /юрист/i, /врач ошибс/i,
  /мой визит|моя запись|мои записи/i, /мой анализ|мои анализ/i,
];

/**
 * Медицинские темы. Отвечаем на них ТОЛЬКО дословной справкой клиники; если
 * подходящей записи нет — человеку.
 */
const MEDICAL_PATTERNS = [
  /симптом/i, /диагноз/i, /болит|болел/i, wordRe("боль|боли|болью"),
  /лечени[ея]/i, /назнач/i, /дозировк/i, wordRe("доза|дозы"),
  /противопоказан/i, /анализ[ыа]?\s+показал/i, /побочн/i,
  /таблетк|препарат|лекарств/i, /беременн/i, /температур/i, /давлени[ея]/i,
  /подготов|готовит/i, phraseRe("можно", "ли", "мне"), /опасно ли/i, /вредно ли/i,
  /**
   * Вопросы про исход лечения. На живом диалоге пациентка спросила «можно ли
   * исправить форму черепа у ребёнка, или уже поздно» — ни одно правило выше
   * не сработало, и ассистент принялся рассуждать сам. Такие вопросы решает
   * врач после осмотра, а не справочник.
   */
  /(?:можно|получится|реально|возможно)\s+ли\s+(?:.{0,20}?)?(?:исправ|поправ|вылеч|излеч|убра|устран|скорректиров|помоч)/i,
  /вылеч|излеч|лечится|лечатся|обратим/i,
  /помож(?:ет|ут)\s+ли|поможет ли/i,
  /(?:уже|не)\s+поздно/i,
  /в каком возрасте/i,
  /как(?:ой|ие|ая)\s+резул/i,
  /**
   * Человек описывает состояние — своё или ребёнка.
   *
   * «Ребёнок плохо говорит, невролог посоветовал что-то для развития речи» —
   * ни одно правило выше здесь не срабатывало, и ассистент начинал сам решать,
   * подходит ли услуга. Это тяжёлый медицинский вопрос: подбирать помощь по
   * описанию состояния может только врач после осмотра.
   *
   * Обычные вопросы про клинику под это не подпадают: «есть ли у вас парковка»
   * — не про здоровье, на такое агент отвечает сам, в том числе «нет».
   */
  /(?:плохо|не)\s+(?:говорит|разговаривает|спит|ест|ходит|слышит|видит|засыпает)/i,
  /задержк\p{L}*\s+(?:реч|развит|психо)/iu,
  /отстаёт\s+в\s+развит/i,
  /(?:невролог|невропатолог|ортопед|логопед|педиатр|психолог|психиатр)\p{L}*\s+(?:посоветовал|направил|назначил|сказал|рекомендовал|поставил)/iu,
  /нам\s+поставили\s+диагноз|поставили\s+диагноз/i,
  /(?:энурез|заикан|заикается|гиперактивн|аутизм|дцп|сколиоз|кривошея|дисплази)/i,
];

const HUMAN_PATTERNS = [
  /админист/i, /оператор/i, /человек/i, /живой|живого|живым/i, /менеджер/i, /жалоб/i,
  /вернуть деньги|возврат/i, /юрист/i, /врач ошибс/i,
];


export function medical(text: string): boolean {
  return MEDICAL_PATTERNS.some((re) => re.test(text));
}
export function scheduleTopic(text: string): boolean {
  // Просьба перенести — тоже расписание, и администратор о ней узнать обязан.
  // «Мы записаны были 20 августа, можно после 12» не попадало сюда вовсе:
  // слова «записаться» нет, а запись есть.
  return SCHEDULE_PATTERNS.some((re) => re.test(text)) || wantsReschedule(text);
}
export function personalTopic(text: string): boolean {
  return PERSONAL_PATTERNS.some((re) => re.test(text));
}
export function wantsHuman(text: string): boolean {
  return HUMAN_PATTERNS.some((re) => re.test(text));
}
