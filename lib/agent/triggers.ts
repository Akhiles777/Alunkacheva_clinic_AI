import { phraseRe, wordRe } from "./word-boundary";

/**
 * Темы, по которым агент обязан позвать человека (§6).
 *
 * Правила были написаны через `\b`, который в JavaScript опирается на
 * латинский `\w` и рядом с кириллицей границы не находит. «боль», «человека»,
 * «окно», «доза» не срабатывали никогда: правило выглядело рабочим, а по
 * факту молчало. Границы теперь задаёт wordRe.
 */
/**
 * «Как можно попасть на приём?» — просьба записаться, а не справочный вопрос.
 *
 * Живой диалог: человек спросил именно это и получил дословную справку про то,
 * что взрослых мужчин на остеопатию не принимают, с телефоном другого врача.
 * Ни про мужчин, ни про остеопатию он не говорил — просто в записи справочника
 * нашлось слово «приём». Ни одно правило записи этот вопрос не ловило:
 * `wantsToBook` требует слова «запись», а его здесь нет.
 */
const HOW_TO_BOOK_PATTERNS = [
  /как\s+(?:можно\s+|мне\s+|нам\s+|у\s+вас\s+|к\s+вам\s+)*(?:попасть|записаться|записать|прийти|придти|подойти|оформить)/i,
  /(?:хочу|хотел\p{L}*|можно|нужно|надо)\s+(?:\p{L}+\s+){0,3}(?:попасть|прийти|придти)\s+(?:к\s+вам|на\s+приём|на\s+прием|на\s+консультаци\p{L}*)/iu,
  /попасть\s+(?:к\s+вам|на\s+приём|на\s+прием|на\s+консультаци\p{L}*)/iu,
  /(?:хочу|хотел\p{L}*|можно)\s+(?:на\s+)?(?:приём|прием|консультаци\p{L}*)(?!\p{L})/iu,
  /**
   * «Я всё-таки хотела бы на повторный приём попасть» (живой диалог 5 октября)
   * — между желанием и приёмом стоят «бы», «повторный», а «попасть» — в конце.
   * Ни одно правило выше этого не ловило, и запись вела модель.
   */
  /(?:хочу|хотел\p{L}*|можно|нужно|надо)\s+(?:\p{L}+\s+){0,3}?(?:на\s+)(?:повторн\p{L}*\s+|первичн\p{L}*\s+)?(?:приём|прием|консультаци\p{L}*)(?!\p{L})/iu,
  /(?:приём|прием|консультаци\p{L}*)\s+(?:\p{L}+\s+){0,2}?попасть(?!\p{L})/iu,
];

/** Спрашивают, как попасть на приём. Отмена и перенос — не сюда. */
export function asksHowToBook(text: string): boolean {
  if (cantCome(text) || wantsReschedule(text)) return false;
  return HOW_TO_BOOK_PATTERNS.some((re) => re.test(text));
}

/**
 * Человеку уже сказали прийти — значит нужен приём, а не ответ.
 *
 * «Мне Ирина Алилгаджиевна говорила, если проблема повторится, то надо прийти
 * сразу не ждать следующего приёма». Заказчик указал на это прямо: врач уже
 * знает и сама назначила прийти, это только про запись. Сначала агент отвечал
 * на такое справкой про приём мужчин, потом — вопросом к врачу, и оба ответа
 * лишние: спрашивать её не о чем, а человеку нужно время приёма.
 *
 * Кто именно сказал — врач, администратор, невролог, — правилу знать не нужно:
 * ответ один и тот же, время подбирает администратор.
 *
 * Медицинские слова это правило не отменяет: «мне врач сказала прийти, у сына
 * температура 39» остаётся медицинской темой и идёт своей веткой, потому что
 * `medical` проверяется раньше.
 */
const TOLD_TO_COME_PATTERNS = [
  /(?:говорил\p{L}*|сказал\p{L}*|советовал\p{L}*|рекомендовал\p{L}*|велел\p{L}*|назначил\p{L}*|просил\p{L}*)[^.!?]{0,80}?(?:прийти|придти|приход\p{L}*|подойти|показаться|повторить)/iu,
  /(?:прийти|придти|приход\p{L}*|подойти|показаться)[^.!?]{0,40}?(?:говорил\p{L}*|сказал\p{L}*|советовал\p{L}*|велел\p{L}*|назначил\p{L}*)/iu,
];

export function wasToldToCome(text: string): boolean {
  return TOLD_TO_COME_PATTERNS.some((re) => re.test(text));
}

/**
 * Расписание — зона администратора. Сюда же отмены и переносы: заказчик хочет
 * держать эти решения за человеком.
 */
const SCHEDULE_PATTERNS = [
  /запиш|записать|записаться/i, wordRe("запись|записи"), /свободн/i,
  /**
   * Упоминание своей записи — тоже тема расписания.
   *
   * «Я записана 11:30» просьбой перенести не является (см. RESCHEDULE_PATTERNS),
   * но администратор о таком сообщении знать должен: человек говорит о своём
   * визите, и дальше почти всегда следует «опаздываю», «не смогу», «а к кому
   * я записана».
   */
  wordRe("записан|записана|записаны|записано"),
  /окошк/i, wordRe("окно|окна|окон"),
  /перенест|перенос/i, /отменит|отмена записи|отменить запись/i,
  /когда можно прийти|на какое время/i,
  // «Как можно попасть на приём?» — тот же разговор о записи (asksHowToBook).
  ...HOW_TO_BOOK_PATTERNS,
  // «Врач говорила прийти сразу» — тоже про приём, и время подбирает человек.
  ...TOLD_TO_COME_PATTERNS,
  /**
   * «Не смогу прийти» — это отмена, сказанная по-человечески.
   *
   * Пациентка написала «извините, но я не могу придти, всю ночь озноб» — и
   * получила совет связаться с администратором самой. Ни одно правило выше
   * здесь не срабатывало, а между тем это отмена записи на сегодня, и
   * администратору о ней нужно знать немедленно.
   */
  /не\s+(?:смогу|могу|получится)\s+(?:прийти|придти|подойти|быть|приехать|попасть)/i,
  /не\s+(?:придём|придем|приду|приедем)/i,
];

/**
 * Вопрос про свободное время. Отдельно от остальной записи: здесь агенту
 * нечего уточнять — расписания он не видит, и любой его вопрос только оттянет
 * ответ. Пациентка спросила «ещё свободно окошко?», а услышала «на какую
 * услугу вы хотите записаться и для кого» — при том что и услуга, и врач были
 * видны из сообщения, на которое она отвечала.
 */
const SLOT_PATTERNS = [
  /свободн/i, /окошк/i, wordRe("окно|окна|окон"),
  /на какое время|когда можно прийти|какие\s+(?:есть\s+)?(?:окна|окошки|時)/i,
  /есть\s+(?:ли\s+)?(?:время|места|запись)\s+на/i,
];

export function asksForSlot(text: string): boolean {
  return SLOT_PATTERNS.some((re) => re.test(text));
}

/**
 * «Не смогу прийти» — отмена или перенос, о которых нужно знать немедленно.
 *
 * Отдельно от остальной записи, потому что здесь важен и тон, и скорость.
 * Пациентка написала «извините, не могу придти, всю ночь озноб» — и услышала,
 * что по симптомам ей ответит врач, а связаться с администратором надо самой.
 * Ей же нужно было только одно: чтобы запись на сегодня не пропала.
 */
const CANT_COME_PATTERNS = [
  /не\s+(?:смогу|могу|получится)\s+(?:прийти|придти|подойти|быть|приехать|попасть)/i,
  /не\s+(?:придём|придем|приду|приедем)/i,
  /(?:отмен\p{L}+|перенес\p{L}+|перенос\p{L}*)\s+(?:запись|приём|прием|визит)/iu,
];

export function cantCome(text: string): boolean {
  return CANT_COME_PATTERNS.some((re) => re.test(text));
}

/**
 * Просьба перенести уже существующую запись.
 *
 * «Здравствуйте, мы записаны были 20 августа в 10:30, можно, пожалуйста, после
 * 12 любое время — мальчик будет в саду» — и в ответ «напишите, на какую услугу
 * вы хотите записаться и для кого». Всё уже обговорено: услуга выбрана, запись
 * существует, человек просит другое время. Переспрашивать здесь — значит
 * показать, что предыдущий разговор забыт.
 *
 * Отличаем от новой записи по упоминанию существующей: «мы записаны», «наша
 * запись», «перенести», «сдвинуть», «можно пораньше».
 */
/**
 * Просьба перенести — это ПРОСЬБА, а не упоминание записи.
 *
 * Здесь первым правилом стояло голое слово «записан*», и любое предложение с
 * ним читалось как просьба сдвинуть время. Пациентка написала «Я записана
 * 11:30» — просто сказала, на когда записана, — и услышала «передал(а)
 * администратору, он подберёт время из тех, что вы просите». Она ничего не
 * просила: ей нужно было подтверждение, что запись на месте.
 *
 * Упоминание записи оставляем как контекст (`scheduleTopic`), а переносом
 * считаем только явное желание изменить время.
 */
const RESCHEDULE_PATTERNS = [
  /(?<!\p{L})(?:перенес\p{L}*|перенест\p{L}*|сдвин\p{L}*|переписа\p{L}*)/iu,
  /**
   * Между просьбой и временем встают вежливые слова: «можно, пожалуйста,
   * после 12». Пропускаем до двух — дальше это уже другое предложение.
   */
  /**
   * Границы слова обязательны с обеих сторон. Без правой «до» находилось в
   * начале «ДОчку» и «ДОчь»: «Хочу записать дочку 4 года к Ирине» считалось
   * просьбой о переносе, и человек слышал «подберёт время из тех, что вы
   * просите» (прогон 4 октября).
   */
  /(?<!\p{L})(?:можно|давайте|хотел\p{L}*|хочу|нужно)(?:[\s,]+\p{L}+){0,2}[\s,]+(?:после|до|пораньше|попозже|раньше|позже|на\s+другое)(?!\p{L})/iu,
  /другое\s+время|другой\s+день/i,
];

export function wantsReschedule(text: string): boolean {
  return RESCHEDULE_PATTERNS.some((re) => re.test(text));
}

/**
 * Спрашивают о СВОЕЙ записи, а не просят её перенести.
 *
 * «К какому специалисту я записана?» попадало под правило переноса — слово
 * «записана» там же, — и агент отвечал «передал администратору, он подберёт
 * время». Пациентка спросила, что у неё за запись, а услышала про подбор
 * времени, которого не просила. Ответ при этом лежит в базе: агент видит и
 * услугу, и врача, и день.
 *
 * Отличаем по трём признакам сразу: речь о своей записи, это вопрос, и в нём
 * нет просьбы что-то изменить. Любое сомнение решается в пользу человека —
 * распоряжаться расписанием агент не может (§6).
 */
const OWN_BOOKING = /(?<!\p{L})(?:записан\p{L}*|запис[ьи]|визит\p{L}*|приём|прием)(?!\p{L})/iu;
const ASKING =
  /\?|(?<!\p{L})(?:напомн\p{L}*|подскаж\p{L}*|как(?:ой|ая|ому|ому|ое|ому)?|когда|куда|во сколько|в какое|уточни\p{L}*)(?!\p{L})/iu;
const WANTS_CHANGE =
  /(?<!\p{L})(?:перенес\p{L}*|перенест\p{L}*|сдвин\p{L}*|переписа\p{L}*|пораньше|попозже|отмен\p{L}*|другое\s+время|другой\s+день)(?!\p{L})/iu;

/**
 * Речь о СВОЕЙ записи, а не о приёме вообще.
 *
 * Без этого «Сколько стоит приём остеопата?» считалось вопросом о собственной
 * записи: слово «приём» есть, знак вопроса есть. Вопрос про прайс к
 * расписанию отношения не имеет.
 */
const SELF = /(?<!\p{L})(?:я|мне|меня|мо[йяею]|мою|моей|моего|нас|наш\p{L}*|у меня)(?!\p{L})/iu;

export function asksAboutOwnBooking(text: string): boolean {
  if (!SELF.test(text)) return false;
  if (!OWN_BOOKING.test(text)) return false;
  if (!ASKING.test(text)) return false;
  if (WANTS_CHANGE.test(text)) return false;
  // Жалобы, претензии, деньги и анализы остаются человеку в любом виде: это
  // не вопрос про расписание, и агенту там делать нечего (§6).
  return !/жалоб|претенз|вернуть деньги|возврат|юрист|врач ошибс|анализ/i.test(text);
}

/**
 * Пациент СООБЩАЕТ о своей записи, а не просит записать.
 *
 * «Записана на 8 сентября» — это утверждение: человек говорит, что запись уже
 * есть. В ответ на него агент завёл оформление с нуля — «на какую услугу вы
 * хотите записаться и для кого», — то есть не увидел записи, о которой ему
 * только что сказали, и повёл человека по кругу. Правильный ответ здесь
 * короткий: подтвердить, что запись видим, и назвать её.
 *
 * Отличаем от просьбы записать (её слова другие: «запишите», «хочу
 * записаться»), от просьбы перенести и от вопроса — вопрос разбирает
 * asksAboutOwnBooking.
 */
const BOOKING_MENTION = /(?<!\p{L})(?:записан\p{L}*|запис[ьи]|записались|записалась|записался)(?!\p{L})/iu;
const ASKS_TO_BOOK =
  /(?<!\p{L})(?:запиш\p{L}*|записаться|записать|хочу|хотел\p{L}*|можно ли|нужно)(?!\p{L})/iu;

export function statesOwnBooking(text: string): boolean {
  if (!BOOKING_MENTION.test(text)) return false;
  // Вопрос — другая ветка: на него отвечает agent по данным пациента.
  if (text.includes("?")) return false;
  if (ASKS_TO_BOOK.test(text)) return false;
  if (WANTS_CHANGE.test(text)) return false;
  if (CANT_COME_PATTERNS.some((re) => re.test(text))) return false;
  // Жалобы и деньги остаются человеку в любом виде (§6).
  return !/жалоб|жалова|претенз|вернуть деньги|возврат|юрист|врач ошибс/i.test(text);
}

/**
 * Просьба записать — новая запись, а не перенос и не отмена.
 *
 * Нужна там, где модель не справилась и ответ пришлось составлять самим: если
 * речь о новой записи, спрашиваем данные, а не обрываем разговор словами
 * «записью занимается администратор».
 */
export function wantsToBook(text: string): boolean {
  const asks =
    /(?<!\p{L})(?:запиш\p{L}*|записаться|записать|записывать)(?!\p{L})/iu.test(text) ||
    // «Как попасть на приём», «хочу на консультацию» — та же просьба другими словами.
    HOW_TO_BOOK_PATTERNS.some((re) => re.test(text));
  if (!asks) return false;
  if (wantsReschedule(text)) return false;
  return !cantCome(text);
}

/**
 * Человек опаздывает.
 *
 * Отдельно от «не смогу прийти»: там визит отменяется, здесь — нет, и решает
 * администратор, ждать ли. Агенту тут сказать нечего, и попытка что-то
 * добавить выходит боком: на живом прогоне он посоветовал позвонить в клинику
 * и «уточнить номер у администратора». Отправлять человека за телефоном
 * клиники к администратору — глупость, которой лучше не быть вовсе.
 */
const LATE_PATTERNS = [
  /(?<!\p{L})опозда\p{L}*|опазд\p{L}*/iu,
  /(?<!\p{L})задерж\p{L}*(?!\p{L})/iu,
  /(?<!\p{L})буду\s+(?:позже|попозже)(?!\p{L})/iu,
  /(?<!\p{L})не\s+успева\p{L}*/iu,
];

export function runningLate(text: string): boolean {
  return LATE_PATTERNS.some((re) => re.test(text));
}

/**
 * Личное: жалобы и вопросы про конкретного пациента. Всегда человеку — здесь
 * и врачебная тайна, и репутационный риск.
 */
const PERSONAL_PATTERNS = [
  // «Буду жаловаться» — жалоба, в которой слова «жалоба» нет. Правило искало
  // только его, и прямая угроза жалобой проходила мимо человека.
  /жалоб/i, /жалова|жалу[юе]тс?/i, /претенз/i, /верн\p{L}*\s+(?:мне\s+|нам\s+)?деньг|возврат/iu, /юрист/i, /врач ошибс/i,
  /мой визит|моя запись|мои записи/i, /мой анализ|мои анализ/i,
];

/**
 * Медицинские темы. Отвечаем на них ТОЛЬКО дословной справкой клиники; если
 * подходящей записи нет — человеку.
 */
const MEDICAL_PATTERNS = [
  /симптом/i, /диагноз/i, /болит|болел/i, wordRe("боль|боли|болью"),
  /лечени[ея]/i, /назнач/i, /дозировк/i, wordRe("доза|дозы"),
  /противопоказан/i, /анализ[ыа]?\s+показал/i, /побочн/i,
  /таблетк|препарат|лекарств/i, /беременн/i, /температур/i, /давлени[ея]/i,
  /подготов|готовит/i, phraseRe("можно", "ли", "мне"), /опасно ли/i, /вредно ли/i,
  /**
   * Вопросы про исход лечения. На живом диалоге пациентка спросила «можно ли
   * исправить форму черепа у ребёнка, или уже поздно» — ни одно правило выше
   * не сработало, и ассистент принялся рассуждать сам. Такие вопросы решает
   * врач после осмотра, а не справочник.
   */
  /(?:можно|получится|реально|возможно)\s+ли\s+(?:.{0,20}?)?(?:исправ|поправ|вылеч|излеч|убра|устран|скорректиров|помоч)/i,
  /**
   * «Ему подойдёт?» — вопрос о показаниях, а не о времени.
   *
   * Мама спросила «Сыну 8, ему подойдёт?» про БОС-терапию. Агент правильно
   * отказался отвечать сам — и человека при этом не позвал никто: под
   * медицинские правила фраза не попадала. Женщина осталась с вопросом, на
   * который ей никто не ответил.
   *
   * Требуем рядом человека — «ему», «сыну», «ребёнку»: без этого правило
   * ловило бы «подойдёт ли вторник», а это про расписание.
   */
  /(?<!\p{L})(?:ему|ей|нам|мне|сын\p{L}*|доч\p{L}*|ребен\p{L}*|ребён\p{L}*|внук\p{L}*|мужу|жене)\s+(?:это\s+)?(?:подойд|подход)/iu,
  /**
   * «А ребёнку 7 лет можно?» — тот же вопрос о показаниях, только короче.
   *
   * На него агент ответил «Да, ребёнку 7 лет БОС-терапия подходит»: решил за
   * специалиста, кому процедура показана. Возраст между словами необязателен —
   * «мне можно?» ровно про то же.
   */
  /(?<!\p{L})(?:ему|ей|нам|мне|сын\p{L}*|доч\p{L}*|ребен\p{L}*|ребён\p{L}*|дет[яеи]\p{L}*|внук\p{L}*|мужу|жене|новорожд\p{L}*|грудничк\p{L}*|младенц\p{L}*|месячн\p{L}*|недельн\p{L}*)\s+(?:\d{1,2}\s*(?:лет|года|год|мес\p{L}*|недел\p{L}*)\s+)?можно(?!\p{L})/iu,
  /**
   * Возраст ребёнка сам по себе — медицинский вопрос.
   *
   * «А новорождённого двухнедельного можно?» модель разобрала сама и ответила
   * «двухнедельный малыш подходит» — вывод, которого в справке нет. С какого
   * возраста принимают, решает клиника, а не догадка по названию услуги.
   */
  /(?<!\p{L})(?:новорожд\p{L}*|грудничк\p{L}*|грудн\p{L}*\s+ребен\p{L}*|младенц\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})с\s+какого\s+возраста(?!\p{L})/iu,
  /(?:что|какая|какой|какое|чем)\s+(?:мне|нам|ему|ей|лучше)\s*(?:подойд|подход|посовету|выбрать|помож)/iu,
  /(?:посоветуйте|что посоветуете|что лучше вз)/i,
  /**
   * Состояние, с которым человек пришёл: «постоянная усталость», «не сплю»,
   * «упадок сил». Подбирать по такому описанию услугу — работа врача, а не
   * справочной службы. Пациентка написала про усталость и получила названную
   * капельницу с ценой — назначение от имени клиники.
   */
  /(?<!\p{L})(?:усталост\p{L}*|устаю|устал\p{L}*|слабост\p{L}*|упадок\s+сил|нет\s+сил|бессонниц\p{L}*|не\s+сплю|плохо\s+сплю|тревог\p{L}*|депресс\p{L}*|паническ\p{L}*|выгоран\p{L}*|мигрен\p{L}*|головокружен\p{L}*|тошнот\p{L}*|отёк\p{L}*|отек[иа]|иммунит\p{L}*|похуде\p{L}*|анеми\p{L}*|гемоглобин\p{L}*|гормон\p{L}*)(?!\p{L})/iu,
  /(?:подойд[её]т|подход[ия]т)\s+ли\s+(?:это\s+)?(?:ему|ей|нам|мне|сын|доч|ребен|ребён|внук|муж|жен)/i,
  /вылеч|излеч|лечится|лечатся|обратим/i,
  /помож(?:ет|ут)\s+ли|поможет ли/i,
  /(?:уже|не)\s+поздно/i,
  /в каком возрасте/i,
  /как(?:ой|ие|ая)\s+резул/i,
  /**
   * Человек описывает состояние — своё или ребёнка.
   *
   * «Ребёнок плохо говорит, невролог посоветовал что-то для развития речи» —
   * ни одно правило выше здесь не срабатывало, и ассистент начинал сам решать,
   * подходит ли услуга. Это тяжёлый медицинский вопрос: подбирать помощь по
   * описанию состояния может только врач после осмотра.
   *
   * Обычные вопросы про клинику под это не подпадают: «есть ли у вас парковка»
   * — не про здоровье, на такое агент отвечает сам, в том числе «нет».
   */
  /(?:плохо|не)\s+(?:говорит|разговаривает|спит|ест|ходит|слышит|видит|засыпает)/i,
  /задержк\p{L}*\s+(?:реч|развит|психо)/iu,
  /отстаёт\s+в\s+развит/i,
  /(?:невролог|невропатолог|ортопед|логопед|педиатр|психолог|психиатр)\p{L}*\s+(?:посоветовал|направил|назначил|сказал|рекомендовал|поставил)/iu,
  /нам\s+поставили\s+диагноз|поставили\s+диагноз/i,
  /(?:энурез|заикан|заикается|гиперактивн|аутизм|дцп|сколиоз|кривошея|дисплази)/i,
];

const HUMAN_PATTERNS = [
  /админист/i, /оператор/i, /менеджер/i, /жалоб/i,
  /**
   * «Человек» — только когда его просят позвать.
   *
   * Голое слово ловило «для взрослого человека»: пациентка отвечала на вопрос
   * агента, кому нужен приём, а разговор уходил администратору как просьба
   * позвать живого сотрудника. Агент при этом замолкал.
   */
  /(?:живой|живого|живым)\s+человек\p{L}*/iu,
  /(?:позов\p{L}*|позвать|соедин\p{L}*|переключ\p{L}*|дайте|можно)\s+(?:мне\s+)?(?:с\s+)?человек\p{L}*/iu,
  /(?:с\s+человеком|человека\s+можно|человека\s+позов\p{L}*)/iu,
  // «Нужен человек», «хочу к человеку» — та же прямая просьба.
  /(?:нужен|нужна|хочу|хотел\p{L}*)\s+(?:к\s+)?человек\p{L}*/iu,
  // «Можно с сотрудником?» — та же прямая просьба, и она не ловилась.
  /сотрудник/i,
  /верн\p{L}*\s+(?:мне\s+|нам\s+)?деньг|возврат/iu, /юрист/i, /врач ошибс/i,
  /жалова|жалу[юе]тс?/i,
];


export function medical(text: string): boolean {
  return MEDICAL_PATTERNS.some((re) => re.test(text));
}
export function scheduleTopic(text: string): boolean {
  // Просьба перенести — тоже расписание, и администратор о ней узнать обязан.
  // «Мы записаны были 20 августа, можно после 12» не попадало сюда вовсе:
  // слова «записаться» нет, а запись есть.
  return SCHEDULE_PATTERNS.some((re) => re.test(text)) || wantsReschedule(text);
}
export function personalTopic(text: string): boolean {
  return PERSONAL_PATTERNS.some((re) => re.test(text));
}

/**
 * Жалоба НА КЛИНИКУ — а не жалоба на здоровье.
 *
 * В анкете «жалобы» — это симптомы: «Магомедов Али, 6 лет, жалобы на осанку»,
 * «Аламова Айша, 15 лет. Жалобы на спину». Правило личных тем ловит слово
 * «жалоб» целиком, и такая анкета уходила как жалоба на клинику: пациент
 * слышал «передал администратору» вместо «данные приняты», а руководству
 * уходило письмо о претензии, которой не было.
 *
 * Для анкеты жалобой считаем только то, что о клинике: на врача, на
 * администратора, на обслуживание, претензия, возврат денег, юрист.
 */
const CLINIC_COMPLAINT = [
  /жалоб\p{L}*\s+на\s+(?:врач|доктор|клиник|администрат|персонал|сотрудник|обслуживан|отношени)/iu,
  /(?<!\p{L})(?:пожалуюсь|пожаловаться|буду\s+жаловат\p{L}*|напишу\s+жалоб\p{L}*)/iu,
  /претенз/i, /верн\p{L}*\s+(?:мне\s+|нам\s+)?деньг|возврат/iu, /юрист/i, /врач ошибс/i,
];

export function complainsAboutClinic(text: string): boolean {
  return CLINIC_COMPLAINT.some((re) => re.test(text));
}
export function wantsHuman(text: string): boolean {
  return HUMAN_PATTERNS.some((re) => re.test(text));
}
