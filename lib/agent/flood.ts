/**
 * Поток сообщений — не разговор.
 *
 * Каждый ответ агента — платный запрос к модели. Ни предела, ни проверки не
 * было: один человек, засыпающий бота сообщениями (или скрипт с десятка
 * номеров), тратил бы бюджет клиники без остановки. Живой пациент столько не
 * пишет — поэтому за пределом модель не зовём, а зовём администратора: один
 * раз, а не на каждое сообщение, иначе вместо бюджета засыпаны были бы уже
 * администраторы.
 */

/** Окно, за которое считаем сообщения пациента. */
export const FLOOD_WINDOW_MS = 10 * 60_000;

/** Сколько сообщений за окно — ещё разговор. Анкета строками и три уточнения укладываются с запасом. */
export const FLOOD_LIMIT = 20;

/** За пределом? */
export function flooding(recentIncoming: number): boolean {
  return recentIncoming > FLOOD_LIMIT;
}

/** Первое сообщение за пределом — единственное, о котором зовём человека. */
export function floodJustStarted(recentIncoming: number): boolean {
  return recentIncoming === FLOOD_LIMIT + 1;
}
