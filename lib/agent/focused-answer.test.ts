import { describe, expect, it } from "vitest";
import { focusedAnswer } from "./focused-answer";

/** Живая запись справочника клиники — та самая, что ушла пациенту целиком. */
const OSTEO = [
  "В Клинике доктора Алункачевой принимают два врача-остеопата 🌿",
  "",
  "☘️Алункачева Ирина Алилгаджиевна",
  "👩Взрослый приём — 8 000 ₽, 🕐длительность до 30 минут.",
  "👧Детский приём — 5 000 ₽,🕐 длительность около 20 минут.",
  "",
  "☘️Разият Ризвановна, врач-остеопат",
  "👩Взрослый приём — 5 000 ₽, 🕐длительность до 40 минут.",
  "👧Детский приём — 4 000 ₽, 🕐длительность 30–40 минут.",
  "",
  "⌛Продолжительность остеопатического приёма может немного различаться.",
].join("\n");

const EVERYONE = ["Алункачева Ирина Алилгаджиевна", "Разият Ризвановна", "Сафия Гаджиевна"];

describe("ответ про того, о ком спросили", () => {
  it("спросили про Ирину — Разият в ответ не попадает", () => {
    const out = focusedAnswer(OSTEO, "Алункачева Ирина Алилгаджиевна", EVERYONE);
    expect(out).toContain("8 000 ₽");
    expect(out).not.toContain("Разият");
    expect(out).not.toContain("4 000 ₽");
  });

  it("вступление и общий хвост остаются", () => {
    const out = focusedAnswer(OSTEO, "Алункачева Ирина Алилгаджиевна", EVERYONE);
    expect(out).toContain("принимают два врача-остеопата");
    expect(out).toContain("может немного различаться");
  });

  it("спросили про Разият — остаётся её блок", () => {
    const out = focusedAnswer(OSTEO, "Разият Ризвановна", EVERYONE);
    expect(out).toContain("до 40 минут");
    expect(out).not.toContain("Алилгаджиевна");
  });

  it("о ком спросили — неизвестно, отдаём как есть", () => {
    expect(focusedAnswer(OSTEO, null, EVERYONE)).toBe(OSTEO);
  });

  it("в записи один человек — резать нечего", () => {
    const one = "Сафия Гаджиевна ведёт забор анализов.\nСтоимость — 1 500 ₽.";
    expect(focusedAnswer(one, "Сафия Гаджиевна", EVERYONE)).toBe(one);
  });

  it("названного в записи нет — отдаём как есть", () => {
    expect(focusedAnswer(OSTEO, "Сафия Гаджиевна", EVERYONE)).toBe(OSTEO);
  });

  it("от записи остался огрызок — лучше отдать целиком", () => {
    const short = ["Принимают:", "Ирина Алилгаджиевна", "Разият Ризвановна"].join("\n");
    expect(focusedAnswer(short, "Ирина Алилгаджиевна", EVERYONE)).toBe(short);
  });

  it("отчество в вопросе не обязательно", () => {
    const out = focusedAnswer(OSTEO, "Ирина", EVERYONE);
    // «Ирина» короче четырёх букв не бывает, но и одного имени достаточно.
    expect(out).toContain("8 000 ₽");
  });
});
