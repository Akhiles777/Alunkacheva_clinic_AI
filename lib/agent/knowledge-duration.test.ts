import { describe, expect, it } from "vitest";
import { durationsFromKnowledge } from "./knowledge-duration";

/** Запись справочника клиники «Сколько стоит приём остеопата» (снимок 9 октября). */
const ANSWER = [
  "В Клинике доктора Алункачевой принимают два врача-остеопата 🌿",
  "",
  "☘️Алункачева Ирина Алилгаджиевна",
  "👩Взрослый приём — 8 000 ₽, 🕐длительность до 30 минут.",
  "👧Детский приём — 5 000 ₽,🕐 длительность около 20 минут.",
  "",
  "☘️Разият Ризвановна, врач-остеопат",
  "👩Взрослый приём — 5 000 ₽, 🕐длительность до 40 минут.",
  "👧Детский приём — 4 000 ₽, 🕐длительность 30–40 минут.",
].join("\n");
const STAFF = ["Ирина Алилгаджиевна", "Мугадова Разият Ризвановна", "Ирина Омарова", "Сафия Гаджиевна"];
const SERVICES = [
  { id: "a", title: "Остеопатия, приём Ирины", price: 8000 },
  { id: "b", title: "Остеопатия - дети, прием Ирины", price: 5000 },
  { id: "c", title: "Остеопатия, прием Разият", price: 5000 },
  { id: "d", title: "Остеопатия - дети, прием Разият", price: 4000 },
  { id: "e", title: "БОС-терапия", price: 2800 },
];

describe("длительность из справки клиники", () => {
  it("врач, цена и длительность в строке справки — длительность её, а не слота YCLIENTS", () => {
    const m = durationsFromKnowledge([ANSWER], STAFF, SERVICES);
    expect(Object.fromEntries(m)).toEqual({ a: 30, b: 20, c: 40, d: 40 });
  });

  it("«Гаджиевна» медсестры не путается с «Алилгаджиевной»", () => {
    expect(durationsFromKnowledge([ANSWER], STAFF, SERVICES).get("a")).toBe(30);
  });

  it("две записи с разной длительностью — не выбираем", () => {
    const other = "Алилгаджиевна\nВзрослый приём — 8 000 ₽, длительность 45 минут.";
    expect(durationsFromKnowledge([ANSWER, other], STAFF, SERVICES).has("a")).toBe(false);
  });

  it("без врача над строкой ничего не берём", () => {
    expect(durationsFromKnowledge(["Взрослый приём — 8 000 ₽, длительность до 30 минут."], STAFF, SERVICES).size).toBe(0);
  });
});
