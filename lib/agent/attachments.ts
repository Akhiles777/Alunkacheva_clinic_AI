/**
 * Вложения пациента: голосовые, фото, видео, документы.
 *
 * Зачем отдельный слой. Раньше в Telegram такое сообщение исчезало целиком:
 * разбор вебхука читал только текст, у голосового текста нет, и агент выходил
 * на первой же проверке. Сообщение не сохранялось, в инбоксе не появлялось,
 * уведомление не уходило. Пациент записал голосовое — и об этом не узнавал
 * никто. Потерянное обращение в клинике стоит дороже любого бага в интерфейсе.
 *
 * Что здесь важно по существу:
 *
 *   1. Храним идентификатор файла у провайдера, а не готовую ссылку. Ссылка
 *      Telegram содержит токен бота — в базе ей не место, и живёт она час.
 *   2. Отдаём файл только через свой адрес, вошедшему сотруднику. Прямая
 *      ссылка на голосовое пациента, открытая любому, — это разглашение
 *      сведений о обращении за помощью (§7, ст. 13 323-ФЗ).
 *   3. Подпись у вложения есть всегда. Пустая строка в переписке выглядит как
 *      поломка платформы, хотя пациент просто прислал фотографию.
 */

export type AttachmentKind =
  | "voice"
  | "audio"
  | "video"
  | "photo"
  | "document"
  | "sticker"
  | "location"
  | "contact"
  | "other";

export interface IncomingAttachment {
  kind: AttachmentKind;
  /** Что показать вместо содержимого: «голосовое сообщение», «фотография». */
  label: string;
  /**
   * Где взять файл. У Telegram — идентификатор, по которому сервер получит
   * ссылку в момент показа; у провайдера WhatsApp — прямая ссылка, она у них
   * долгоживущая и токена не содержит.
   */
  source:
    | { provider: "TELEGRAM"; fileId: string }
    | { provider: "WHATSAPP"; url: string }
    | { provider: "NONE" };
  mimeType?: string;
  fileName?: string;
  durationSec?: number;
  sizeBytes?: number;
}

/** Названия в единственном числе — они попадают в текст переписки. */
export const KIND_LABEL: Record<AttachmentKind, string> = {
  voice: "голосовое сообщение",
  audio: "аудиозапись",
  video: "видео",
  photo: "фотография",
  document: "документ",
  sticker: "стикер",
  location: "геопозиция",
  contact: "контакт",
  other: "вложение",
};

/**
 * Текст сообщения в переписке.
 *
 * Подпись пациента важнее нашей: если к фотографии он написал «вот анализы»,
 * администратор должен увидеть именно это. Наша подпись идёт рядом, чтобы было
 * понятно, что к сообщению приложен файл.
 */
export function messageBody(text: string, attachments: IncomingAttachment[]): string {
  const caption = text.trim();
  if (!attachments.length) return caption;

  const marks = attachments.map((a) => `[${a.label}]`).join(" ");
  return caption ? `${marks} ${caption}` : marks;
}

/**
 * Умеет ли ассистент понять это сообщение сам.
 *
 * Не умеет: он читает текст. Голосовое, фотографию направления или видео
 * должен посмотреть человек. Попытка ответить на непрочитанное — худший
 * исход: пациент получит бодрый ответ не по делу и решит, что его не читают.
 */
export function needsHuman(attachments: IncomingAttachment[]): boolean {
  // Стикер — не обращение, отвечать на него человеку незачем.
  return attachments.some((a) => a.kind !== "sticker");
}
