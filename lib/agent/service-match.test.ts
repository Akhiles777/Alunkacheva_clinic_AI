import { describe, expect, it } from "vitest";
import { matchServices, whomFor } from "./service-match";

/** Прайс клиники — те самые строки, на которых ассистент ошибся. */
const SERVICES = [
  { title: "Остеопатия - дети, прием Ирины", price: 4900, durationMin: 45 },
  { title: "Остеопатия, приём Ирины", price: 8000, durationMin: 45 },
  { title: "Остеопатия, прием Разият", price: 5000, durationMin: 45 },
  { title: "Остеопатия - дети, прием Разият", price: 4000, durationMin: 45 },
  { title: "Беременная - остеопатия", price: 8000, durationMin: 45 },
  { title: "БОС-терапия", price: 5000, durationMin: 40 },
  { title: "Забор крови", price: 900, durationMin: 10 },
];

describe("для кого приём", () => {
  it("узнаёт ребёнка", () => {
    for (const t of [
      "Хотела ребенка записать к Ирине Алункачевой",
      "Записать сына к остеопату",
      "Детский приём сколько стоит?",
      "Дочке 6 лет, нужен остеопат",
    ]) {
      expect(whomFor(t), t).toBe("child");
    }
  });

  it("узнаёт взрослого", () => {
    expect(whomFor("Хочу записаться на взрослый приём")).toBe("adult");
    expect(whomFor("Записать мужа к остеопату")).toBe("adult");
  });

  it("не выбирает, когда сказано и то и другое", () => {
    // «Записать ребёнка и себя» — две услуги; гадать нельзя.
    expect(whomFor("Хочу записать ребенка и себя")).toBe("unknown");
    expect(whomFor("Сколько стоит приём остеопата?")).toBe("unknown");
  });
});

describe("подбор услуги под вопрос", () => {
  it("про ребёнка — только детские услуги", () => {
    const out = matchServices("Хотела ребенка записать к остеопату Ирине", SERVICES);
    expect(out.length).toBeGreaterThan(0);
    // Ровно та ошибка, из-за которой всё затевалось: взрослая цена 8000 в
    // ответе на вопрос про ребёнка.
    expect(out.every((s) => /дет/i.test(s.title))).toBe(true);
    expect(out.map((s) => s.price)).not.toContain(8000);
  });

  it("про взрослого — детские не предлагает", () => {
    const out = matchServices("Взрослый приём к остеопату Ирине", SERVICES);
    expect(out.every((s) => !/дет/i.test(s.title))).toBe(true);
  });

  it("имя врача сужает выбор", () => {
    const out = matchServices("Остеопатия к Разият для ребенка", SERVICES);
    expect(out[0].title).toContain("Разият");
    expect(out[0].price).toBe(4000);
  });

  it("беременность — отдельная услуга, не «взрослая вообще»", () => {
    const out = matchServices("Я беременна, хочу к остеопату", SERVICES);
    expect(out.some((s) => /беремен/i.test(s.title))).toBe(true);
  });

  it("ничего не подошло — пустой список, а не случайная услуга", () => {
    expect(matchServices("Сколько стоит МРТ?", SERVICES)).toEqual([]);
  });

  it("вопрос без возраста — показывает варианты, не выбирая за пациента", () => {
    const out = matchServices("Сколько стоит остеопатия?", SERVICES);
    expect(out.length).toBeGreaterThan(1);
  });
});

/**
 * Порог уверенности для карточки с ценой.
 *
 * Список услуг для модели можно собирать вольно — у неё есть контекст. Но тот
 * же список уходит человеку карточкой, когда модель не ответила, и там одно
 * случайно совпавшее слово превращалось в прайс не по теме: на «Доброго дня»
 * приходила «Тихая терапия „Перезагрузка“ — 4000 ₽».
 */
describe("порог совпадения услуги", () => {
  const services = [
    { title: 'Тихая терапия "Перезагрузка" (при тревожности и выгорании)', price: 4000, durationMin: 0 },
    { title: "Взрослый прием - остеопатия", price: 5000, durationMin: 60 },
  ];

  it("без порога совпадает по одному слову — это для модели", () => {
    expect(matchServices("сколько стоит терапия", services).length).toBeGreaterThan(0);
  });

  it("с порогом случайное пересечение отсекается", () => {
    expect(matchServices("доброго дня", services, 3, 0.5)).toEqual([]);
  });

  it("настоящий вопрос про услугу порог проходит", () => {
    const found = matchServices("тихая терапия перезагрузка", services, 3, 0.5);
    expect(found).toHaveLength(1);
    expect(found[0].price).toBe(4000);
  });
});

/**
 * Полный прайс клиники — тридцать девять строк с кавычками, скобками и
 * дублями. На коротком списке подбор прощал ошибки: почти любой вопрос
 * находил нужную услугу, потому что услуг было пять.
 *
 * На настоящем прайсе «Здравствуйте сколько стоит остеопатия?» не нашло
 * НИЧЕГО: доля считалась от всех слов вопроса, «здравствуйте», «сколько» и
 * «стоит» её и разбавили. Пациенту в ответ ушёл весь прайс подряд — двадцать
 * пять строк, от забора крови до инфузий, — на прямой вопрос про остеопатию.
 */
const PRICE_LIST = [
  { title: "Взрослый прием - остеопатия", price: 8000, durationMin: 45 },
  { title: "Детский прием до 10 л - остеопатия", price: 5000, durationMin: 40 },
  { title: "БОС-терапия", price: 2800, durationMin: 40 },
  { title: "БОС-терапия, курс", price: 28000, durationMin: 40 },
  { title: "Консультация", price: 1000, durationMin: 30 },
  { title: "Внутривенное капельное введение растворов", price: 500, durationMin: 60 },
  { title: "Анкета - Экспертный аудит и назначение IV-протокола", price: 3000, durationMin: 30 },
  { title: "Внутримышечный укол", price: 300, durationMin: 10 },
  { title: "Диагностика/консультация на БОС-терапию", price: 1000, durationMin: 30 },
  { title: "Забор крови", price: 200, durationMin: 15 },
  { title: 'Инфузия "NAD+Био-Генезис" (Молекула молодости)', price: 9500, durationMin: 60 },
  { title: 'Инфузия "Абсолютный ресурс"', price: 9000, durationMin: 60 },
  { title: 'Инфузия "Анти-Спазм"', price: 6500, durationMin: 55 },
  { title: 'Инфузия "Гепато-Ресурс" (Защита печени)', price: 6000, durationMin: 60 },
  { title: 'Инфузия "Ферро-Баланс" (Энергия крови)', price: 5500, durationMin: 60 },
  { title: "Остеопатия для беременных", price: 8000, durationMin: 45 },
  { title: "Массаж классический", price: 3000, durationMin: 60 },
];

describe("живой вопрос про цену на полном прайсе", () => {
  const titles = (q: string) => matchServices(q, PRICE_LIST, 3, 0.5).map((s) => s.title);

  it("находит остеопатию, как её ни спроси", () => {
    for (const q of [
      "Здравствуйте сколько стоит остеопатия?",
      "Здравствуйте! Подскажите пожалуйста, сколько стоит остеопатия",
      "остеопатия цена",
      "Сколько будет стоить приём остеопата",
    ]) {
      const found = titles(q);
      expect(found.length, q).toBeGreaterThan(0);
      expect(found.some((t) => /остеопат/i.test(t)), `${q} → ${found.join(", ")}`).toBe(true);
    }
  });

  it("детский вопрос не приносит взрослую цену", () => {
    const found = titles("Здравствуйте, сколько стоит остеопатия ребёнку 6 лет?");
    expect(found).toContain("Детский прием до 10 л - остеопатия");
    expect(found).not.toContain("Взрослый прием - остеопатия");
  });

  it("вежливость сама по себе услугу не находит", () => {
    expect(titles("Доброго дня")).toEqual([]);
    expect(titles("Здравствуйте!")).toEqual([]);
    expect(titles("Сколько стоит?")).toEqual([]);
    expect(titles("Спасибо большое")).toEqual([]);
  });

  it("услуги, которой нет, не находит", () => {
    expect(titles("Сколько стоит МРТ?")).toEqual([]);
    expect(titles("А иглоукалывание делаете?")).toEqual([]);
  });

  it("находит названную инфузию, а не весь список инфузий", () => {
    const found = titles("Сколько стоит инфузия Ферро-Баланс?");
    expect(found[0]).toBe('Инфузия "Ферро-Баланс" (Энергия крови)');
  });

  it("услуга для беременных не лезет в обычный вопрос", () => {
    expect(titles("Здравствуйте сколько стоит остеопатия?")).not.toContain(
      "Остеопатия для беременных",
    );
    expect(titles("Я беременна, сколько стоит остеопатия?")).toContain("Остеопатия для беременных");
  });

  it("находит БОС и забор крови по одному слову", () => {
    expect(titles("а БОС-терапия сколько?").some((t) => /БОС/.test(t))).toBe(true);
    expect(titles("сколько стоит забор крови")).toContain("Забор крови");
  });

  /**
   * Общее слово не тянет за собой чужую услугу.
   *
   * «А БОС-терапия что даёт?» приводило рядом с БОС «Внутривенное капельное
   * введение растворов (IV-терапия)» за 500 ₽: совпало слово «терапия».
   * Пациент спросил про одно, а первой строкой увидел другое, вдвое дешевле.
   */
  it("общее слово «терапия» не приводит чужую услугу", () => {
    const found = titles("А БОС-терапия что даёт?");
    expect(found.some((t) => /БОС/.test(t))).toBe(true);
    expect(found.some((t) => /Внутривенное/.test(t))).toBe(false);
  });
});

/**
 * «Хочу записаться» — человек записывает себя.
 *
 * Пациентка написала «хочу записаться на приём к остеопату», и агент
 * переспросил, для взрослого или для ребёнка. Она про ребёнка не говорила.
 */
describe("кого записывают", () => {
  it("возвратный глагол означает себя", () => {
    expect(whomFor("Хочу записаться на прием к остеопату Ирина Алункачевой")).toBe("adult");
    expect(whomFor("Запишите меня")).toBe("adult");
  });

  it("ребёнок правило отменяет", () => {
    expect(whomFor("Хочу записать ребенка")).toBe("child");
    expect(whomFor("Хочу записаться с ребёнком")).toBe("child");
  });

  it("вопрос без записи остаётся неопределённым", () => {
    expect(whomFor("Сколько стоит приём?")).toBe("unknown");
  });
});
