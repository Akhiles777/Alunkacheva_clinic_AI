/**
 * Один уточняющий вопрос за раз.
 *
 * Правило есть и в инструкции клиники, и в промпте — и всё равно нарушается.
 * Живой диалог: пациентка написала «ребёнку 6 лет, 2 дня как установили
 * аппарат, хотела записаться на консультацию», а в ответ получила сразу два
 * вопроса и следом стену согласия: «уточните, запись для ребёнка, верно? И к
 * какому специалисту хотели бы попасть — например, к БОС-терапевту Ирине
 * Омаровой?». Первый вопрос — про то, что она уже сказала; второй — про то,
 * что агент и так знает.
 *
 * Просьбами это не лечится, поэтому лишние вопросы срезаются кодом: остаётся
 * первый, остальные убираются. Текст от этого только сокращается — придумать
 * он ничего не может.
 */

/** Предложение, которое спрашивает. Риторическое «Чем могу помочь?» — тоже вопрос. */
function isQuestion(sentence: string): boolean {
  return sentence.trim().endsWith("?");
}

/**
 * Убрать все вопросы, кроме первого.
 *
 * Порядок сохраняем: утверждения остаются на своих местах, режутся только
 * вопросительные предложения после первого.
 */
export function keepOneQuestion(text: string): string {
  /**
   * Строки сохраняем как есть.
   *
   * Первая версия разбивала весь текст на предложения и склеивала обратно
   * пробелом — и список цен превращался в кашу: «Взрослый приём — 8000 ₽, 45
   * мин Записывает администратор…». Режем внутри строк, переносы не трогаем.
   */
  let seen = false;
  const lines = text.split("\n").map((line) => {
    const parts = line.split(/(?<=[.!?])\s+/);
    const kept = parts.filter((p) => {
      if (!isQuestion(p)) return true;
      if (seen) return false;
      seen = true;
      return true;
    });
    return kept.join(" ").replace(/[ \t]{2,}/g, " ").trim();
  });
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

/** Сколько вопросов в тексте — для тестов и журнала. */
export function questionCount(text: string): number {
  return text.split(/(?<=[.!?])\s+/).filter(isQuestion).length;
}
