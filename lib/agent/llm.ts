/**
 * history — последние реплики диалога. Без неё ассистент отвечал на каждое
 * сообщение как на первое: «а сколько это стоит?» после вопроса об остеопатии
 * он уже не понимал.
 */
/**
 * Ответ вышел из роли — отправлять его пациенту нельзя.
 *
 * Живой прогон на вопросе «можно ли капельницу при беременности» вернул:
 * «I'm Claude, an AI assistant made by Anthropic. I can't provide medical
 * advice…». Всё по делу — но по-английски и от чужого имени: пациент клиники
 * получил бы сообщение на незнакомом языке, узнал бы, что говорит с моделью, и
 * остался бы без ответа. Модель срывается в собственную защитную формулировку
 * непредсказуемо, и полагаться на просьбы в промпте здесь нельзя.
 *
 * Такой ответ считается несостоявшимся: агент промолчит и позовёт человека —
 * ровно то, что и требуется на медицинском вопросе (§6).
 */
/**
 * Срезать пересказ инструкций перед ответом.
 *
 * Модель приписывает к ответу абзац о самой себе: «Acknowledged. Я —
 * справочная служба клиники, отвечаю на «вы», опираюсь только на справку…».
 * Иногда по-английски и с рассуждением о роли. Пациент получает это в
 * мессенджере первым, а настоящий ответ — вторым абзацем, если тот вообще
 * поместился в лимит.
 *
 * Просьбами в промпте это не лечится: на «не подтверждай получение правил»
 * модель отвечает «Принято» — то есть подтверждает. Поэтому режем на выходе,
 * детерминированно: это единственный способ гарантировать, что пациент
 * пересказ не увидит.
 *
 * Режем ТОЛЬКО когда есть что оставить: последний абзац из одного «Принято»
 * не абзац-преамбула, а весь ответ, и выбрасывать его нельзя.
 */
/**
 * Границы слова здесь — через отсутствие соседней буквы, а не `\b`.
 *
 * `\b` в JavaScript опирается на латинский `\w` и рядом с кириллицей не
 * находит границ вовсе: `/принято\b/` не совпадает со строкой «Принято.»
 * никогда. Правило выглядит рабочим и молча не срабатывает — ровно на этом
 * уже обжигался код агента, для чего и заведён `lib/agent/word-boundary.ts`.
 */
/**
 * Приписка о себе — узнаётся по разговору о правилах и о роли, а не по
 * вежливому началу.
 *
 * «Хорошо, записал ваши данные» начинается так же, как «Хорошо. Я справочная
 * служба…», и выбросить первый абзац значило бы потерять сам ответ. Поэтому
 * голое подтверждение отрезается, только если оно короткое и ничего не несёт.
 */
const META_MARKERS = [
  /**
   * Представление собой. Ищется в любом месте абзаца, а не только в начале:
   * модель начинает с «Acknowledged.» и представляется вторым предложением.
   */
  /(я|i)\s*[—–-]?\s*(справочная служба|am the|'m the|am an|'m an)/iu,
  /я\s+справочная\s+служба/iu,
  /(системн\p{L}+ сообщени|system message|в роли|fictional character|ai assistant)/iu,
  /^(начинаю отвечать|отвечаю на ваш вопрос|готов[аы]? помочь)(?!\p{L})/iu,
];

/** Метка, после которой начинается сам ответ. */
const ANSWER_ANCHOR = /ОТВЕТ\s*:/iu;

/**
 * Обрезать по последнему законченному предложению.
 *
 * Если законченного предложения нет вовсе (ответ короче одного), возвращаем
 * как есть: обрывок хуже целого, но пустота хуже обрывка.
 */
export function trimToSentence(text: string): string {
  const cut = Math.max(text.lastIndexOf("."), text.lastIndexOf("!"), text.lastIndexOf("?"));
  return cut > 40 ? text.slice(0, cut + 1).trim() : text;
}

export function stripPreamble(text: string): string {
  /**
   * Метка — главный способ: всё до неё отрезается целиком, что бы там ни
   * было. Берём последнюю: модель иногда упоминает метку и в рассуждении.
   */
  let body = text;
  if (ANSWER_ANCHOR.test(text)) {
    const chunks = text.split(ANSWER_ANCHOR);
    const tail = chunks[chunks.length - 1].trim();
    /**
     * Метка нашлась — но разбор абзацев на этом не заканчивается.
     *
     * Модель ставит представление о себе и ПОСЛЕ метки: «ОТВЕТ: я справочная
     * служба клиники… \n\n По вашему вопросу: …». Возвращая хвост как есть,
     * мы отдавали пациенту ровно ту приписку, ради которой метка и заводилась.
     */
    if (tail.length > 0) {
      body = tail;
    } else {
      /**
       * Метка есть, а текста после неё нет: модель поставила её в конце. Ответ
       * стоит до метки — саму метку убираем, иначе пациент получит «ОТВЕТ:»
       * последней строкой.
       */
      body = chunks.slice(0, -1).join(" ").trim();
    }
  }

  const parts = body.split(/\n{2,}/).map((p) => p.trim()).filter(Boolean);
  // Возвращаем `body`, а не исходный текст: иначе отрезанное меткой вернулось бы
  // обратно, стоило ответу оказаться в один абзац.
  if (parts.length < 2) return body.trim();

  /** Короткое подтверждение без содержания: «Принято.», «Acknowledged.». */
  const bareAck = (p: string) =>
    /^(acknowledged|understood|got it|принято|понял[аи]?|подтверждаю|хорошо|готов[аы]?)(?!\p{L})/iu.test(p) &&
    p.split(/\s+/).length <= 3;

  let i = 0;
  while (i < parts.length - 1 && (META_MARKERS.some((re) => re.test(parts[i])) || bareAck(parts[i]))) {
    i += 1;
  }
  return parts.slice(i).join("\n\n");
}

export function offCharacter(text: string): boolean {
  if (!text.trim()) return true;
  /** Представился моделью или поставщиком — это не наша справочная служба. */
  if (/(anthropic|openai|chatgpt|я\s+—?\s?claude|i'?m\s+claude|language model|ai assistant)/i.test(text)) {
    return true;
  }
  /**
   * Язык определяем по доле кириллицы среди букв. Отдельные латинские слова
   * в русском ответе законны («IV-терапия», «BRAINBI»), поэтому порог мягкий:
   * решает перевес, а не наличие.
   */
  const letters = text.match(/\p{L}/gu) ?? [];
  if (letters.length < 12) return false;
  const cyrillic = letters.filter((c) => /[Ѐ-ӿ]/.test(c)).length;
  return cyrillic / letters.length < 0.5;
}

