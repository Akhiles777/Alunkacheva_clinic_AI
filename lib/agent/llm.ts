export interface Turn {
  role: "user" | "assistant";
  content: string;
}

/**
 * history — последние реплики диалога. Без неё ассистент отвечал на каждое
 * сообщение как на первое: «а сколько это стоит?» после вопроса об остеопатии
 * он уже не понимал.
 */
export async function answerLLM(
  question: string,
  clinicContext: string,
  history: Turn[] = [],
  /**
   * Инструкция клиники из настроек. Дописывается к базовым правилам, а не
   * заменяет их: не обещать запись, не выдумывать цены и не лезть в медицину
   * агент обязан независимо от того, что клиника напишет в своём тексте (§6).
   */
  extraRules?: string,
  /**
   * Имя собеседника. Передаём отдельно, а не надеемся, что модель найдёт его в
   * переписке: в промпт уходят последние реплики, и представившийся пациент
   * через десяток сообщений становится безымянным. Только имя — ни диагнозов,
   * ни остальных данных (§7).
   */
  patientName?: string | null,
): Promise<string | null> {
  const key = process.env.ROUTER_AI;
  if (!key) {
    /**
     * Без ключа ассистент не отвечает вообще: каждый вопрос уходит человеку, и
     * со стороны это выглядит как «бот сломался». Именно так и случилось после
     * переезда на сервер — в окружении осталось пустое значение из образца.
     * Пишем в журнал при каждом обращении: молчать об этом нельзя.
     */
    console.error("[agent] не задан ROUTER_AI — ассистент не может отвечать, всё уходит человеку");
    return null;
  }

  try {
    const res = await fetch(`${BASE_URL}/chat/completions`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${key}` },
      body: JSON.stringify({
        model: MODEL,
        temperature: 0.3,
        max_tokens: 400,
        messages: [
          { role: "system", content: PATIENT_PROMPT },
          ...(extraRules?.trim()
            ? [{ role: "system" as const, content: `Инструкция клиники:\n${extraRules.trim()}` }]
            : []),
          ...(patientName?.trim()
            ? [{ role: "system" as const, content: `Собеседника зовут ${patientName.trim()}. Обращайтесь по имени.` }]
            : []),
          { role: "system", content: `Справка клиники:\n${clinicContext}` },
          // Последние реплики — чтобы «а сколько это стоит?» понималось в контексте.
          /**
           * Двадцать реплик, а не десять: на десяти пациент, назвавший себя в
           * начале разговора, к середине становился незнакомым — и агент честно
           * отвечал, что имени не знает.
           */
          ...history.slice(-20),
          { role: "user", content: question },
        ],
      }),
      // Вебхук должен уложиться в срок ожидания мессенджера, иначе он
      // пришлёт сообщение повторно и пациент получит два ответа.
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });

    if (!res.ok) {
      /**
       * Причину видно в журнале сервера. Раньше отказ молча превращался в
       * null, и на экране это выглядело как «ассистент вдруг перестал
       * отвечать» — ровно так же, как когда-то молчали push-уведомления.
       */
      const body = await res.text().catch(() => "");
      console.error(`[agent] модель ответила ${res.status}: ${body.slice(0, 200)}`);
      return null;
    }

    const json = (await res.json()) as {
      choices?: { message?: { content?: string }; finish_reason?: string }[];
    };
    const choice = json.choices?.[0];
    const text = choice?.message?.content?.trim();
    if (!text) {
      console.error(
        `[agent] модель вернула пустой ответ (finish_reason: ${choice?.finish_reason ?? "нет"}), ` +
          `длина справки ${clinicContext.length} знаков`,
      );
      return null;
    }
    return text;
  } catch (e) {
    const name = (e as Error)?.name;
    console.error(
      name === "TimeoutError"
        ? `[agent] модель не ответила за ${TIMEOUT_MS} мс, длина справки ${clinicContext.length} знаков`
        : `[agent] сбой обращения к модели: ${String((e as Error)?.message ?? e).slice(0, 200)}`,
    );
    return null;
  }
}
