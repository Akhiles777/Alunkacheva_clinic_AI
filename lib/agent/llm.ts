import { CLINIC_NAME } from "@/lib/brand";

/**
 * Ответ пациенту по справке клиники. Тот же провайдер, что у ассистента в
 * панели (routerai.ru, OpenAI-совместимый), но промпт другой: здесь собеседник
 * — пациент, а не сотрудник.
 *
 * В модель уходит только справочник клиники (услуги, цены, часы) и текущий
 * вопрос. Персональные данные и медицинская информация не передаются (§7).
 * Нет ключа или сбой — возвращаем null, и агент честно говорит, что не знает,
 * вместо выдумки.
 */
const BASE_URL = (process.env.ROUTER_AI_BASE_URL || "https://routerai.ru/api/v1").replace(/\/+$/, "");
/**
 * Модель бота пациентов — Haiku 4.5: здесь не нужен глубокий разбор, нужно
 * аккуратно ответить по справочнику клиники. На замере вышло 0.07 за ответ
 * против 0.87 у старшей модели — в двенадцать раз дешевле при том же
 * результате. Отдельная переменная: у бота и у аналитика разные задачи.
 */
const MODEL = process.env.ROUTER_AI_BOT_MODEL || process.env.ROUTER_AI_MODEL || "anthropic/claude-haiku-4.5";

/**
 * Сколько ждём модель. На бессерверном хостинге предел был жёстким (у Vercel
 * на Hobby десять секунд), на своём сервере запас можно дать больше — но не
 * бесконечный: мессенджер повторит доставку, и пациент получит два ответа.
 */
const TIMEOUT_MS = Number(process.env.ROUTER_AI_TIMEOUT_MS ?? 20_000);

/**
 * Правила поведения из §6: зона агента — справочные вопросы, расписанием он
 * не распоряжается.
 *
 * Запрет обещать запись прописан отдельно и подробно, потому что модель к
 * этому естественно склонна: её просят «предложить следующий шаг», и она
 * отвечает «записываю вас на завтра». На боевом стенде так и произошло —
 * ассистент заявил пациенту, что сам ведёт запись. Для клиники это прямой
 * убыток: человек ждёт подтверждения, которого не будет.
 */
const PATIENT_PROMPT = [
  `Ты — справочная служба клиники «${CLINIC_NAME}» в мессенджере.`,
  "Отвечай по-человечески, на «вы», живым языком. Обычно 2–4 предложения; если вопрос требует деталей — можно подробнее.",
  "Не отделывайся одной строкой: добавь то, что человеку полезно знать рядом (длительность, что взять с собой, как удобнее прийти), если это есть в справке.",
  "Опирайся СТРОГО на справку клиники ниже: услуги, цены, часы работы, адрес.",
  "Если в справке ответа нет — так и скажи и предложи позвать администратора. Ничего не выдумывай.",
  "ЗАПИСЬЮ ТЫ НЕ ЗАНИМАЕШЬСЯ. Запись, перенос, отмена и свободное время — только у администратора.",
  "Никогда не говори «запишу», «записываю», «забронирую», «поставлю вас на время», «подберу окно»,",
  "не называй свободные окна и не подтверждай запись — у тебя нет доступа к расписанию.",
  "Если человек хочет записаться, перенести или отменить приём, спросить про свободное время —",
  "скажи, что передаёшь администратору, и он свяжется. Помочь можно только справкой: услуга, цена, длительность, адрес, часы.",
  "НИКОГДА не обсуждай симптомы, диагнозы, лечение, препараты, противопоказания и результаты анализов:",
  "на такие вопросы отвечай, что позовёшь специалиста.",
  "Не запрашивай персональные данные, кроме имени. Не обещай того, чего нет в справке.",
  "Не используй разметку: никаких #, *, списков со звёздочками. Пиши обычным текстом.",
].join(" ");

export interface Turn {
  role: "user" | "assistant";
  content: string;
}

/**
 * history — последние реплики диалога. Без неё ассистент отвечал на каждое
 * сообщение как на первое: «а сколько это стоит?» после вопроса об остеопатии
 * он уже не понимал.
 */
export async function answerLLM(
  question: string,
  clinicContext: string,
  history: Turn[] = [],
): Promise<string | null> {
  const key = process.env.ROUTER_AI;
  if (!key) return null;

  try {
    const res = await fetch(`${BASE_URL}/chat/completions`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${key}` },
      body: JSON.stringify({
        model: MODEL,
        temperature: 0.3,
        max_tokens: 400,
        messages: [
          { role: "system", content: PATIENT_PROMPT },
          { role: "system", content: `Справка клиники:\n${clinicContext}` },
          // Последние реплики — чтобы «а сколько это стоит?» понималось в контексте.
          ...history.slice(-10),
          { role: "user", content: question },
        ],
      }),
      // Вебхук должен уложиться в срок ожидания мессенджера, иначе он
      // пришлёт сообщение повторно и пациент получит два ответа.
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });

    if (!res.ok) {
      /**
       * Причину видно в журнале сервера. Раньше отказ молча превращался в
       * null, и на экране это выглядело как «ассистент вдруг перестал
       * отвечать» — ровно так же, как когда-то молчали push-уведомления.
       */
      const body = await res.text().catch(() => "");
      console.error(`[agent] модель ответила ${res.status}: ${body.slice(0, 200)}`);
      return null;
    }

    const json = (await res.json()) as {
      choices?: { message?: { content?: string }; finish_reason?: string }[];
    };
    const choice = json.choices?.[0];
    const text = choice?.message?.content?.trim();
    if (!text) {
      console.error(
        `[agent] модель вернула пустой ответ (finish_reason: ${choice?.finish_reason ?? "нет"}), ` +
          `длина справки ${clinicContext.length} знаков`,
      );
      return null;
    }
    return text;
  } catch (e) {
    const name = (e as Error)?.name;
    console.error(
      name === "TimeoutError"
        ? `[agent] модель не ответила за ${TIMEOUT_MS} мс, длина справки ${clinicContext.length} знаков`
        : `[agent] сбой обращения к модели: ${String((e as Error)?.message ?? e).slice(0, 200)}`,
    );
    return null;
  }
}
