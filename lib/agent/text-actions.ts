import { wordRe } from "./word-boundary";
import { CONSENT_ACCEPT, CONSENT_DECLINE } from "./consent";

/**
 * Действия, набранные словами.
 *
 * В Telegram пациент нажимает кнопку, и агент получает готовый код действия.
 * В WhatsApp через Green API кнопок нет вовсе: подсказки уходят строками, и
 * ответить на них можно только текстом. Без разбора этого текста согласие на
 * обработку персональных данных в WhatsApp дать невозможно физически — а без
 * согласия мы не имеем права вести переписку (§7, 152-ФЗ).
 *
 * Поэтому здесь — перевод обычных слов в те же коды, что приходят с кнопок.
 * Разбор намеренно узкий: агенту нельзя угадывать. Согласие принимается
 * только когда мы его действительно ждём, а пункты меню — только при почти
 * дословном совпадении с подписью кнопки. Всё остальное идёт обычным путём,
 * через справочник и модель.
 */

/** Каналы, где кнопки есть. Остальным подсказки уходят текстом. */
export function supportsButtons(channel: "TELEGRAM" | "WHATSAPP" | "INSTAGRAM"): boolean {
  // Кнопки есть только у Telegram. В WhatsApp через Green API и в Instagram
  // Direct их нет — там подсказки понимаются словами.
  return channel === "TELEGRAM";
}

const YES = [
  "да",
  "согласен",
  "согласна",
  "согласны",
  "соглашаюсь",
  "принимаю",
  "подтверждаю",
  "разрешаю",
  "ага",
  "конечно",
  "yes",
  "ok",
  "ок",
];

const NO = [
  "нет",
  "не согласен",
  "не согласна",
  "не сейчас",
  "отказываюсь",
  "откажусь",
  "позже",
  "no",
];

/**
 * Ответ на вопрос о согласии.
 *
 * Вызывать только когда согласие действительно запрошено и ещё не получено.
 * Вне этого «да» в переписке значит что угодно, и принять его за согласие на
 * обработку медицинских данных было бы подлогом.
 */
export function consentFromText(raw: string): string | null {
  const text = normalize(raw);
  if (!text) return null;

  // «Не согласен» проверяем первым: иначе «согласен» внутри него сработает
  // раньше и отказ будет прочитан как согласие.
  if (NO.some((w) => hit(text, w))) return CONSENT_DECLINE;
  if (YES.some((w) => hit(text, w))) return CONSENT_ACCEPT;
  return null;
}

/**
 * Подписи кнопок главного меню → коды действий.
 *
 * Здесь только то, что человек набирает вместо нажатия: сами подписи и их
 * короткие синонимы. Начала вопросов вроде «сколько стоит» или «во сколько
 * работаете» сюда не попадают намеренно — на проверке они перехватывали
 * «Сколько стоит остеопатия?» и выдавали общий прайс вместо ответа
 * справочника про двух конкретных врачей.
 */
const MENU: { data: string; phrases: string[] }[] = [
  { data: "prices", phrases: ["услуги и цены", "услуги", "цены", "прайс", "стоимость"] },
  { data: "address", phrases: ["адрес"] },
  { data: "hours", phrases: ["часы работы", "график работы", "режим работы", "график"] },
  {
    data: "human",
    phrases: [
      "позвать администратора",
      "администратор",
      "позовите администратора",
      "позвать человека",
      "оператор",
      "живой человек",
    ],
  },
];

/**
 * Пункт меню, набранный текстом.
 *
 * Совпадение требуем почти дословное — по подписи кнопки целиком, а не по
 * отдельному слову. Иначе вопрос «а сколько стоит приём остеопата и есть ли
 * скидки?» превратился бы в сухой прайс-лист вместо ответа по справочнику.
 * Развёрнутые вопросы должны идти обычным путём.
 */
/**
 * Вопросительные слова. Их наличие означает вопрос, а не нажатие кнопки.
 *
 * «Какие у вас услуги?» короче тридцати знаков и содержит слово «услуги» — и
 * перехватывалось как нажатие, отвечая сухим прайс-листом вместо связного
 * ответа. Человек, набравший вопрос, ждёт ответа на вопрос.
 */
const QUESTION_WORDS = [
  "какие",
  "какая",
  "какой",
  "каких",
  "сколько",
  "где",
  "как",
  "что",
  "почему",
  "зачем",
  "когда",
  "можно",
  "есть",
];

export function menuActionFromText(raw: string): string | null {
  const text = normalize(raw);
  if (!text) return null;
  // Длинную фразу считаем вопросом, а не нажатием: кнопку набирают коротко.
  if (text.length > 30) return null;
  if (QUESTION_WORDS.some((w) => wordRe(w).test(text))) return null;

  for (const item of MENU) {
    for (const phrase of item.phrases) {
      if (text === phrase) return item.data;
      // Допускаем обрамление вежливостью: «адрес?», «здравствуйте, цены».
      if (text.length <= phrase.length + 12 && hit(text, phrase)) return item.data;
    }
  }
  return null;
}

export function normalize(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function hit(text: string, phrase: string): boolean {
  return wordRe(phrase).test(text);
}

/**
 * Приветствие и ничего больше.
 *
 * Нужно, чтобы на «Добрый день» ответить приветствием клиники из настроек, а
 * не отправлять модель сочинять своё. Требуем, чтобы сообщение состояло из
 * приветствия целиком: «Здравствуйте, а сколько стоит приём?» — это вопрос, и
 * отвечать на него дежурной фразой было бы отпиской.
 */
const GREETINGS = [
  "здравствуйте",
  "здравствуй",
  "добрый день",
  "доброе утро",
  "добрый вечер",
  "доброй ночи",
  "привет",
  "приветствую",
  "салам",
  "салам алейкум",
  "ассалам алейкум",
  "ассаламу алейкум",
  "hello",
  "hi",
];

/** Вежливые довески, которые не делают приветствие вопросом. */
const FILLER = ["пожалуйста", "скажите", "подскажите", "а", "и", "ну", "вам", "вас"];

/**
 * Каким именно приветствием поздоровался человек.
 *
 * Нужно, чтобы ответить тем же: на «салам алейкум» полагается «ва алейкум
 * ассалам», на «доброе утро» — «доброе утро», и никак иначе. Дежурное
 * «здравствуйте» на всё подряд читается как автоответчик.
 *
 * Возвращаем самое длинное совпадение: «салам» иначе съест «салам алейкум».
 */
export function greetingUsed(raw: string): string | null {
  const text = normalize(raw);
  if (!text) return null;
  for (const g of [...GREETINGS].sort((a, b) => b.length - a.length)) {
    if (wordRe(g).test(text)) return g;
  }
  return null;
}

export function isGreeting(raw: string): boolean {
  const text = normalize(raw);
  if (!text) return false;

  let rest = text;
  let matched = false;
  // Длинные приветствия убираем первыми: иначе «салам» съест «салам алейкум»
  // и остаток «алейкум» будет принят за посторонние слова.
  for (const g of [...GREETINGS].sort((a, b) => b.length - a.length)) {
    if (wordRe(g).test(rest)) {
      rest = rest.replace(wordRe(g), " ");
      matched = true;
    }
  }
  if (!matched) return false;

  const leftovers = rest.split(/\s+/).filter((w) => w && !FILLER.includes(w));
  return leftovers.length === 0;
}
