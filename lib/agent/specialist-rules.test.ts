import { describe, expect, it } from "vitest";
import { linkToQuery,
  complexMedical,
  declinesRelay,
  managementTopic,
  refFromQuote,
  refMark,
} from "./specialist-rules";

/**
 * Заказчик описал этот случай прямо: «если руководитель напишет „не отправляй
 * ответ, я сама отвечу“, бот не должен думать, что это ответ пациенту».
 */
describe("специалист просит не передавать ответ", () => {
  it("узнаёт прямой отказ", () => {
    for (const t of [
      "Не отправляй ничего, я сама отвечу",
      "не пересылай пока",
      "Не отвечай ей, я позвоню",
      "Я сама напишу",
      "Разберусь сама",
      "Погоди, не надо",
      "Не передавай это пациенту",
      "Позвоню ей сама",
    ]) {
      expect(declinesRelay(t), t).toBe(true);
    }
  });

  it("настоящий ответ врача отказом не считает", () => {
    for (const t of [
      "Да, можно продолжать занятия борьбой, но без ударов головой в ближайший месяц",
      "После родов приходить можно через 6 недель, если нет осложнений",
      "Головные боли на фоне цикла — это нормально, пусть придёт на повторный приём",
      "Новорождённых принимаем с двух недель",
      "Пусть запишется на приём, посмотрю",
    ]) {
      expect(declinesRelay(t), t).toBe(false);
    }
  });
});

describe("вопрос к руководству, а не к врачу", () => {
  it("узнаёт деловые темы", () => {
    for (const t of [
      "Здравствуйте! Можно ли к вам устроиться массажистом?",
      "У вас есть вакансии?",
      "Вам нужна реклама в инстаграме?",
      "Предлагаю сотрудничество, я блогер",
      "Хотим предложить коммерческое предложение по оборудованию",
      "Сдаёте ли вы кабинет в аренду?",
    ]) {
      expect(managementTopic(t), t).toBe(true);
    }
  });

  it("пациентские вопросы деловыми не считает", () => {
    for (const t of [
      "Сколько стоит приём остеопата?",
      "Можно записать ребёнка 2 недель?",
      "У меня болит голова после приёма",
      "Во сколько вы работаете?",
    ]) {
      expect(managementTopic(t), t).toBe(false);
    }
  });
});

describe("метка вопроса", () => {
  it("находится в цитате ответа", () => {
    const quote = `В ответ на: «Вопрос от пациента — Пахай (WhatsApp) · ${refMark(12)}`;
    expect(refFromQuote(quote)).toBe(12);
  });

  it("нет метки — нет номера", () => {
    expect(refFromQuote("Да, можно")).toBeNull();
  });
});

/**
 * Не всякий медицинский вопрос стоит того, чтобы будить врача.
 *
 * Письма по пустякам перестают читать, а вместе с ними перестают читать и
 * настоящие. Заказчик привёл пример вопроса, ради которого функция и нужна:
 * человек описал ДЦП и просит решить, что ему делать.
 */
describe("сложный вопрос против мелкого уточнения", () => {
  it("состояние, тактика и разговор после приёма — к врачу", () => {
    for (const t of [
      "Дело в том что у меня ДЦП и я не знаю что и как мне нужно делать. И нужно ли вообще",
      "Думала просто может консультация. Потом подберут лечение. Я не знаю",
      "Она говорила отписаться по поводу головных болей",
      "Мы были на приеме у Ирины, она сказала что есть проблема с черепом",
      "У сына ДЦП, 4 года. Остеопатия ему поможет?",
      "Через сколько после родов можно на остеопатию?",
      "Невролог направил на БОС, нужно ли нам это",
    ]) {
      expect(complexMedical(t), t).toBe(true);
    }
  });

  it("самочувствие после процедуры — к врачу", () => {
    for (const t of [
      "После капельницы кружится голова, это нормально?",
      "После БОС ребёнок стал хуже спать",
      "После сеанса болит шея, так и должно быть?",
    ]) {
      expect(complexMedical(t), t).toBe(true);
    }
  });

  it("мелкие уточнения врача не беспокоят", () => {
    for (const t of [
      "А это больно?",
      "Сколько длится приём?",
      "Можно ли поесть перед приёмом?",
      "Что взять с собой?",
      "А в какой одежде приходить?",
      "Сколько стоит капельница от усталости?",
      "Записаться можно на завтра?",
    ]) {
      expect(complexMedical(t), t).toBe(false);
    }
  });

  it("служебная переписка сотрудников врача не беспокоит", () => {
    for (const t of [
      "Завтра придёт Гулбарият, взять ОАК",
      "Оплату не брать, она по курсу",
      "И гомоцистеин добавь",
    ]) {
      expect(complexMedical(t), t).toBe(false);
    }
  });
});

/**
 * Привязка переписки со специалистом к вопросам.
 *
 * Живой случай: у врача два открытых вопроса, она ответила обычным сообщением,
 * без свайпа, — и ответ не засчитался. Показывать его надо, но приписывать
 * конкретному пациенту без основания нельзя.
 */
describe("к какому вопросу относится сообщение", () => {
  const at = (iso: string) => new Date(iso);
  const q1 = { id: "q1", ref: 1, askedAt: at("2026-09-13T08:50:00Z"), answeredAt: null };
  const q2 = { id: "q2", ref: 2, askedAt: at("2026-09-13T08:56:00Z"), answeredAt: null };

  it("наше письмо с меткой — его вопрос", () => {
    expect(linkToQuery({ body: "Вопрос от пациента — Анна (WhatsApp) · #2", at: at("2026-09-13T08:56:01Z") }, [q1, q2])).toBe("q2");
  });

  it("ответ свайпом — по метке в цитате", () => {
    expect(
      linkToQuery({ body: "Да, лечим", quoted: "Вопрос от пациента — Анна · #1", at: at("2026-09-13T09:30:00Z") }, [q1, q2]),
    ).toBe("q1");
  });

  it("ответ без метки при ОДНОМ открытом вопросе — к нему", () => {
    expect(linkToQuery({ body: "Да, лечим", at: at("2026-09-13T08:55:00Z") }, [q1, q2])).toBe("q1");
  });

  it("ответ без метки при НЕСКОЛЬКИХ открытых — неизвестно, не гадаем", () => {
    expect(linkToQuery({ body: "Да, лечим", at: at("2026-09-13T09:30:00Z") }, [q1, q2])).toBeNull();
  });

  it("метка несуществующего вопроса — тоже неизвестно", () => {
    expect(linkToQuery({ body: "ок", quoted: "#99", at: at("2026-09-13T09:30:00Z") }, [q1, q2])).toBeNull();
  });
});

describe("сообщение про несколько вопросов сразу", () => {
  it("переспрос «открыто несколько: #1, #2» ни к одному не привязывается", () => {
    const at = new Date("2026-09-13T09:31:00Z");
    const qs = [
      { id: "q1", ref: 1, askedAt: new Date("2026-09-13T08:50:00Z"), answeredAt: null },
      { id: "q2", ref: 2, askedAt: new Date("2026-09-13T08:56:00Z"), answeredAt: null },
    ];
    expect(linkToQuery({ body: "Сейчас открыто несколько вопросов: #1, #2. Ответьте на нужное.", at }, qs)).toBeNull();
  });
});
