/**
 * Справка о тех, о ком не спрашивали, пациенту не уходит.
 *
 * Одна и та же запись справочника — «Приём мужчин» — ушла пациентам ТРИ раза
 * подряд, и ни один из них про мужчин не спрашивал:
 *
 *   • «Как можно попасть на приём ?» → «Остеопатический приём взрослых мужчин
 *     не проводится… рекомендуем врача-остеопата Исаева, 8 966 745-18-44»;
 *   • «Ок» (свайпом на справку о приёме) → та же запись;
 *   • «Мне Ирина Алилгаджиевна говорила, если проблема повторится, то надо
 *     прийти сразу не ждать следующего приёма» → снова она.
 *
 * Каждый раз причина была своя, и каждый раз её чинили отдельно: то слово
 * «приём» вытаскивало запись подбором, то цитата превращала «Ок» в вопрос. Но
 * общее у всех случаев одно: пациенту ушёл текст про КАТЕГОРИЮ ЛЮДЕЙ, которой
 * он не называл. Женщина, записанная на остеопатию, читает, что клиника не
 * принимает мужчин, и получает телефон чужого врача — так выглядит отказ
 * человеку, который ни о чём не просил.
 *
 * Поэтому проверка кодовая и стоит у выхода наружу: правило в промпте на этот
 * счёт стоит дважды («отвечай на заданный вопрос, а не пересказывай запись») и
 * нарушалось всё равно.
 *
 * Чего здесь нет намеренно:
 *   • симметрии ради симметрии. Записи «женщин не принимаем» у клиники нет, и
 *     выдумывать правило под несуществующий текст значит однажды вырезать из
 *     ответа «приём ведёт врач-женщина». Таблица заведена так, что новую строку
 *     добавить легко — когда для неё будет живой случай;
 *   • догадок про пол пациента. Мы не выводим его ни из имени, ни из карточки:
 *     решают только слова самого человека.
 */

/**
 * Предложение про ПРИЁМ людей, а не про врача или процедуру.
 *
 * Без этого условия правило цеплялось бы к чему угодно, где встретилось слово
 * «мужской». Нас интересует ровно одно: клиника говорит, кого она принимает,
 * кому отказывает и к кому отправляет.
 */
const ABOUT_ADMISSION =
  /(?<!\p{L})(?:принима\p{L}*|приём\p{L}*|прием\p{L}*|проводит\p{L}*|провод\p{L}*|вед[её]\p{L}*|записыва\p{L}*|рекоменд\p{L}*|обслужива\p{L}*|рады\s+видеть|не\s+работаем)(?!\p{L})/iu;

interface Audience {
  /** Как их называет справка клиники. */
  inAnswer: RegExp;
  /**
   * Что должен сказать сам пациент, чтобы разговор был о них.
   *
   * Список нарочно широкий: ошибиться в сторону «промолчали о мужчинах, хотя
   * спрашивали о них» дороже, чем оставить лишнее предложение. «Сына»,
   * «ребёнку», «подростку» сюда входят: правило клиники про мальчиков — это
   * ответ родителю ребёнка, даже если пол он не назвал.
   */
  inQuestion: RegExp;
  /** Для журнала: о ком была справка. */
  name: string;
}

const AUDIENCES: Audience[] = [
  {
    name: "мужчины и мальчики",
    inAnswer: /(?<!\p{L})(?:мужчин\p{L}*|мужчина|мужск\p{L}*|мальчик\p{L}*|юнош\p{L}*)(?!\p{L})/iu,
    inQuestion:
      /(?<!\p{L})(?:мужчин\p{L}*|мужчина|мужск\p{L}*|муж|мужа|мужу|мужем|супруг\p{L}*|парн\p{L}*|парень|брат\p{L}*|отец|отц\p{L}*|пап\p{L}*|дед\p{L}*|сын\p{L}*|мальчик\p{L}*|юнош\p{L}*|внук\p{L}*|племянник\p{L}*|ребен\p{L}*|ребён\p{L}*|дет[иеяй]\p{L}*|детск\p{L}*|подрост\p{L}*|школьник\p{L}*|малыш\p{L}*)(?!\p{L})/iu,
  },
];

/**
 * Предложения ответа вместе с их знаками: текст потом собирается обратно.
 *
 * Кусок, начатый со строчной буквы или цифры, — продолжение предыдущего, а не
 * новое предложение. Иначе перенос строки посреди фразы отрывал её хвост:
 * прогон 4 октября — справку про мужчин вырезали, а пациенту ушло «8 966
 * 745-18-44, у нас же можем предложить IV-терапию» — телефон чужого врача без
 * единого слова о том, чей он.
 */
function sentences(text: string): string[] {
  const out: string[] = [];
  for (const part of text.split(/(?<=[.!?\n])/)) {
    const head = part.trimStart();
    if (out.length > 0 && head.length > 0 && /^[\p{Ll}\d]/u.test(head)) out[out.length - 1] += part;
    else out.push(part);
  }
  return out;
}

/** О ком в этом предложении говорит клиника, если пациент о них не спрашивал. */
function unaskedIn(sentence: string, asked: string): Audience | null {
  if (!ABOUT_ADMISSION.test(sentence)) return null;
  for (const audience of AUDIENCES) {
    if (!audience.inAnswer.test(sentence)) continue;
    if (audience.inQuestion.test(asked)) continue;
    return audience;
  }
  return null;
}

/** Слова пациента — только его собственные, без цитат нашего же текста. */
function askedText(patientTexts: string[]): string {
  return patientTexts.join("\n");
}

/**
 * Ответ вообще говорит о какой-то категории людей.
 *
 * Дешёвая проверка перед дорогой: разбирать слова пациента стоит запроса в
 * базу, а таких ответов единицы из сотни. Ничего похожего в тексте нет —
 * значит и сверять не с чем.
 */
export function audienceMentioned(answer: string): boolean {
  return sentences(answer).some((s) => unaskedIn(s, "") !== null);
}

/**
 * Справка не по делу: ответ говорит о категории людей, которой пациент не
 * называл. Возвращает само предложение — по нему в журнале видно, что именно
 * ушло бы человеку.
 */
export function unaskedAudience(answer: string, patientTexts: string[]): string | null {
  const asked = askedText(patientTexts);
  for (const s of sentences(answer)) {
    if (unaskedIn(s, asked)) return s.trim();
  }
  return null;
}

/**
 * Тот же ответ без таких предложений.
 *
 * Убираем только их: модель успевает в одном сообщении назвать цену по делу и
 * приписать абзац из чужой записи, и выбрасывать из-за него весь ответ — значит
 * не сказать человеку то, что он спрашивал. Не осталось ничего осмысленного —
 * решает вызывающая сторона: она зовёт администратора.
 */
export function withoutUnaskedAudience(answer: string, patientTexts: string[]): string {
  const asked = askedText(patientTexts);
  return sentences(answer)
    .filter((s) => !unaskedIn(s, asked))
    .join("")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
