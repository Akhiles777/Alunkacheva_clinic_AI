import { wordRe } from "./word-boundary";

/**
 * Что заметить в ответе администратора ДО отправки.
 *
 * Это подсказка, а не запрет. Администратор знает ситуацию лучше системы:
 * цена может быть особой по договорённости, время — только что освободившимся.
 * Поэтому отправку не блокируем ни при каком предупреждении — иначе человек
 * научится обходить платформу, а не читать подсказки.
 *
 * Проверки идут на нашей стороне и по нашим данным: ни текст ответа, ни
 * переписка никуда не отправляются (§7).
 */

export interface DraftFacts {
  /** Цены прайса — с ними сверяется названная сумма. */
  prices: { title: string; price: number }[];
  /**
   * Свободно ли в клинике названное время. Ключ — «14:00»; значение false
   * означает «в это время всё занято». Неизвестное время не проверяется.
   */
  freeAt: Record<string, boolean>;
  /** Есть ли у пациента будущая запись — по ней проверяются обещания. */
  hasFutureBooking: boolean;
  /** Готовый ответ клиники на медицинскую тему, если он есть в справочнике. */
  knowledgeAnswer: { topic: string; answer: string } | null;
}

export interface DraftWarning {
  kind: "price" | "time" | "medical" | "promise";
  /** Что не так — одной фразой, без обвинений. */
  text: string;
  /** Что предложить вместо. Пусто — предлагать нечего, только заметить. */
  suggestion?: string;
}

/** Суммы вида «8000 ₽», «8 000 руб», «8000р». */
const MONEY = /(\d[\d\s]{2,})\s*(?:₽|руб|р\.|рублей|рубля)/gi;
/** Время вида «14:00», «в 14.30». */
const TIME = /\b([01]?\d|2[0-3])[:.]([0-5]\d)\b/g;

/** Слова, которыми обещают запись. Голое «запись» сюда не входит (§6). */
const PROMISE = [
  "записал",
  "записала",
  "записали",
  "забронировал",
  "забронировала",
  "поставила вас",
  "поставил вас",
  "оставил за вами",
  "оставила за вами",
];

/**
 * Медицинские слова — тот же широкий список, что у ассистента: лишнее
 * согласование стоит минуты, пропущенное противопоказание — здоровья.
 */
const MEDICAL = [
  "боль",
  "боли",
  "болит",
  "болеть",
  "болезн",
  "побаливает",
  "противопоказан",
  "беременн",
  "давлени",
  "температур",
  "диагноз",
  "лечен",
  "препарат",
  "капельниц",
  "грыж",
  "воспален",
  "аллерг",
];

function digitsToNumber(raw: string): number {
  return Number(raw.replace(/\s+/g, ""));
}

export function draftWarnings(text: string, facts: DraftFacts): DraftWarning[] {
  const draft = text.trim();
  if (draft.length < 3) return [];
  const low = draft.toLowerCase();
  const out: DraftWarning[] = [];

  /**
   * Цена, которой нет в прайсе.
   *
   * Сверяем ровное совпадение суммы: «8000» есть в прайсе — вопросов нет.
   * Похожие суммы не считаем ошибкой: клиника называет скидки и доплаты, и
   * подсказка на каждую из них перестанет читаться.
   */
  for (const m of draft.matchAll(MONEY)) {
    const value = digitsToNumber(m[1]);
    if (!Number.isFinite(value) || value <= 0) continue;
    if (facts.prices.some((p) => Math.round(p.price) === Math.round(value))) continue;
    out.push({
      kind: "price",
      text: `Суммы ${value.toLocaleString("ru-RU")} ₽ нет в прайсе.`,
      suggestion: facts.prices.length
        ? `В прайсе: ${facts.prices
            .slice(0, 3)
            .map((p) => `${p.title} — ${p.price.toLocaleString("ru-RU")} ₽`)
            .join(", ")}`
        : undefined,
    });
    break;
  }

  /** Время, которое занято. Проверяем только то, о чём мы знаем наверняка. */
  for (const m of draft.matchAll(TIME)) {
    const at = `${m[1].padStart(2, "0")}:${m[2]}`;
    if (facts.freeAt[at] === false) {
      out.push({
        kind: "time",
        text: `В ${at} всё занято — свободных окон в это время нет.`,
      });
      break;
    }
  }

  /**
   * Обещание записи без записи.
   *
   * Записью занимается администратор, и «записала вас на четверг» может быть
   * правдой, которую он только что сделал в YCLIENTS. Поэтому это подсказка
   * «проверьте», а не обвинение.
   */
  if (!facts.hasFutureBooking && PROMISE.some((w) => wordRe(w).test(low))) {
    out.push({
      kind: "promise",
      text: "В расписании будущей записи у этого пациента нет — проверьте, что запись создана.",
    });
  }

  /**
   * Медицинская тема, на которую у клиники есть готовый ответ.
   *
   * Не «вы не имеете права отвечать», а «клиника уже сформулировала это»:
   * согласованный текст точнее, и пациент получит его же в следующий раз от
   * ассистента.
   */
  if (facts.knowledgeAnswer && MEDICAL.some((w) => low.includes(w))) {
    out.push({
      kind: "medical",
      text: `Тема медицинская, а в справочнике есть готовый ответ клиники («${facts.knowledgeAnswer.topic}»).`,
      suggestion: facts.knowledgeAnswer.answer,
    });
  }

  return out;
}
