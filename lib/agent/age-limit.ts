/**
 * Возрастная граница — правило клиники, а не вывод из названия услуги.
 *
 * Живой прогон: ребёнку 11 лет, и агент ответил «детский приём остеопата
 * ведётся только до 10 лет включительно, а вашему ребёнку 11 — для подростков
 * приём не предусмотрен». Звучит как правило клиники, а взято из строки прайса
 * «Детский прием до 10 л - остеопатия». В справке клиники при этом написано
 * другое: «Мальчиков принимаем до 14 лет включительно».
 *
 * Название услуги — это ценник, а не регламент: в нём пишут «до 10 л», чтобы
 * различать две цены, а не чтобы отказывать людям. Отказ по возрасту стоит
 * человеку зря потраченного дня и потерянного пациента, поэтому проверяем его
 * так же, как показания (`inventedIndication`): граница обязана стоять в
 * СПРАВКЕ. Нет — ответ не отправляем и зовём администратора.
 *
 * Цену с возрастом в названии это не задевает: «Детский приём до 10 лет —
 * 5000 ₽» ничего не запрещает, и правило его не трогает.
 */

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/** Возрастная граница: «до 10 лет», «старше 10 лет», «с 4 лет». */
const AGE_LIMIT = /(?:до|старше|с|от)\s+(\d{1,2})(?:[.,]\d)?\s*(?:лет|года|год)(?!\p{L})/giu;

/**
 * Слова, которые превращают число в ЗАПРЕТ.
 *
 * «Детский приём до 10 лет — 5000 ₽» — ценник. «Только до 10 лет»,
 * «не принимаем», «не предусмотрен» — правило, по которому человеку
 * отказывают. Разница в этих словах, поэтому смотрим на них, а не на само
 * число.
 */
const RESTRICTION =
  /(?<!\p{L})(?:только|исключительно|включительно|нельзя|невозможно|не\s+(?:принима\p{L}*|провод\p{L}*|предусмотр\p{L}*|подход\p{L}*|дела\p{L}*|вед[её]\p{L}*|получится)|старше|младше|ограничен\p{L}*)(?!\p{L})/iu;

/**
 * Слова, по которым видно ПРАВИЛО приёма, а не ценник.
 *
 * «Мальчиков принимаем до 14 лет включительно» — правило. «Детский приём до 10
 * лет — 5000 ₽» — цена, и отказывать по ней нельзя.
 */
const RULE_WORDS =
  /(?<!\p{L})(?:принима\p{L}*|включительно|не\s+старше|не\s+младше|только|с\s+рождения|допуска\p{L}*|разреш\p{L}*|ограничен\p{L}*)(?!\p{L})/iu;

/** Цена в том же предложении означает, что это строка прайса. */
const PRICE_WORDS = /₽|руб(?:\.|л\p{L}*)?(?!\p{L})/iu;

/** Сколько символов вокруг границы считаем её окружением. */
const WINDOW = 140;

/**
 * Отказ по возрасту, которого нет в справке. Возвращает саму формулировку —
 * её видно в журнале, и по ней понятно, что именно агент выдумал.
 *
 * `knowledge` — только справка клиники. Прайс сюда передавать нельзя: именно
 * из него и берётся выдуманная граница.
 */
export function ungroundedAgeLimit(answer: string, knowledge: string): string | null {
  const text = norm(answer);
  const ref = norm(knowledge);

  for (const m of text.matchAll(AGE_LIMIT)) {
    const at = m.index ?? 0;
    const from = Math.max(0, at - WINDOW / 2);
    const window = text.slice(from, at + WINDOW / 2);
    if (!RESTRICTION.test(window)) continue;

    /**
     * Та же граница в справке — значит правило клиники, и агент его только
     * повторяет. Ищем число рядом со словом «лет» в любом падеже: клиника
     * пишет и «до 14 лет», и «с 14 лет», и «14 лет включительно».
     */
    const years = m[1];
    /**
     * Та же граница в справке — но именно как ПРАВИЛО приёма, а не как ценник.
     *
     * Первая редакция сверяла только число, и отказ «детям старше 10 лет не
     * проводится» проходил: в справке стояла строка «Детский приём до 10 лет —
     * 5000 ₽». Это цена, а не правило, и отказывать по ней нельзя — тем более
     * что рядом в справке написано «мальчиков принимаем до 14 лет
     * включительно».
     *
     * Поэтому смотрим предложение целиком: в нём должно быть слово о ПРИЁМЕ
     * («принимаем», «включительно», «не старше») и не должно быть цены. Слева
     * от числа обязательно не цифра: «4 лет» иначе находится внутри «14 лет».
     */
    const here = new RegExp(`(?<!\\d)${years}\\s*(?:лет|года|год)(?!\\p{L})`, "u");
    const grounded = ref
      .split(/(?<=[.!?\n])/)
      .some((sentence) => here.test(sentence) && RULE_WORDS.test(sentence) && !PRICE_WORDS.test(sentence));
    if (!grounded) return m[0];
  }
  return null;
}

/**
 * Слова о возрасте — с числом и без: «месячному малышу», «в этом возрасте»,
 * «младше 3 месяцев», «новорождённым».
 */
const AGE_WORDS =
  /(?<!\p{L})(?:возраст\p{L}*|месячн\p{L}*|младен\p{L}*|новорожд\p{L}*|грудн\p{L}*|грудничк\p{L}*|малыш\p{L}*|недельн\p{L}*|младше)(?!\p{L})|\d+\s*-?\s*(?:го|ти|х|ми)?\s*(?:мес\p{L}*|недел\p{L}*|лет|год\p{L}*)/iu;

/**
 * Отказ: приём «не проводится», «не подходит», «рано», «с более старшего
 * возраста». Положительное «принимаем с рождения», «с первого месяца» сюда не
 * попадает — в нём нет отрицания.
 */
const REFUSAL =
  /(?<!\p{L})(?:не\s+(?:принима\p{L}*|провод\p{L}*|предусмотр\p{L}*|подход\p{L}*|подойд\p{L}*|дела\p{L}*|вед[её]\p{L}*|получится|работаем|рекоменду\p{L}*|показан\p{L}*)|рано|слишком\s+мал\p{L}*|с\s+более\s+(?:старш|поздн)\p{L}*|противопоказ\p{L}*)(?!\p{L})/iu;

/** Число в возрастной границе: «3 месяцев», «1-го месяца», «2 лет». */
const AGE_NUMBER = /(\d{1,2})\s*-?\s*(?:го|ти|х|ми)?\s*(?:мес\p{L}*|недел\p{L}*|лет|год\p{L}*)/iu;

/**
 * Отказ по возрасту БЕЗ числа — или с месяцами, — которого нет в справке.
 *
 * Живой диалог 2 октября: «Хотела записать месячного ребенка на приём» → «К
 * сожалению, остеопатический приём для детей в нашей клинике начинается с более
 * старшего возраста. Месячному малышу остеопатия в нашем формате не подходит».
 * Клиника принимает детей как раз с первого месяца жизни — так написано и в её
 * справке. Проверка выше ловила только «до N лет»: отказ без числа проходил
 * насквозь, а это самый дорогой отказ — человек уходит в другую клинику.
 *
 * Правило то же: отказывать по возрасту может только справка. Есть в ней
 * отрицание про возраст («до 1 месяца не принимаем») — модель его повторяет;
 * нет — отказ выдуман. Число в отказе обязано стоять в такой же фразе справки.
 */
export function ungroundedAgeRefusal(answer: string, knowledge: string): string | null {
  const refSentences = norm(knowledge).split(/(?<=[.!?\n])/);
  for (const sentence of norm(answer).split(/(?<=[.!?\n])/)) {
    if (!AGE_WORDS.test(sentence) || !REFUSAL.test(sentence)) continue;
    const num = AGE_NUMBER.exec(sentence)?.[1] ?? null;
    const grounded = refSentences.some((ref) => {
      if (!AGE_WORDS.test(ref) || !(REFUSAL.test(ref) || RULE_WORDS.test(ref)) || PRICE_WORDS.test(ref)) return false;
      if (num === null) return REFUSAL.test(ref);
      return new RegExp(`(?<!\\d)${num}\\s*-?\\s*(?:го|ти|х|ми)?\\s*(?:мес|недел|лет|год)`, "u").test(ref);
    });
    if (!grounded) return sentence.trim();
  }
  return null;
}

/**
 * Вопрос про младенца: возраст в месяцах или неделях, «месячный»,
 * «новорождённый», «грудничок».
 */
const INFANT_ASKED =
  /(?<!\p{L})(?:месячн\p{L}*|новорожд\p{L}*|грудн\p{L}*|грудничк\p{L}*|младен\p{L}*|недельн\p{L}*)(?!\p{L})|\d+(?:[.,]\d+)?\s*-?\s*(?:х|ти|ми)?\s*(?:мес\p{L}*|недел\p{L}*)/iu;

/** Запись справочника о том, с какого возраста принимают малышей. */
const INFANT_RULE =
  /с\s+рождения|новорожд\p{L}*|грудн\p{L}*|грудничк\p{L}*|младен\p{L}*|\d+\s*-?\s*(?:го|х)?\s*(?:месяц\p{L}*|мес\.?)\s*(?:жизни)?|(?:первого|первом|1-го)\s+месяц\p{L}*/iu;

export function asksAboutInfant(text: string): boolean {
  return INFANT_ASKED.test(norm(text));
}

/**
 * Записи справочника про возраст малышей — первыми, если спросили про малыша.
 *
 * Живой диалог 2 октября: «Хотела записать месячного ребенка на приём» — и
 * отказ «с более старшего возраста». В справке клиники написано «с 1-го месяца
 * жизни», но подбор по общим словам эту запись не находил: в вопросе
 * «месячного ребенка», в записи «новорождённого, грудничка, с рождения» — ни
 * одного общего корня. Модели велено брать возраст ТОЛЬКО из справки, и без
 * записи она честно «уточняла у администратора» — или выдумывала отказ.
 */
export function infantRulesFirst<T extends { topic: string; question: string; answer: string }>(
  rows: T[],
  ranked: T[],
  question: string | undefined,
): T[] {
  if (!question || !asksAboutInfant(question)) return ranked;
  const infant = rows.filter((r) => INFANT_RULE.test(norm(`${r.topic} ${r.question} ${r.answer}`)));
  if (infant.length === 0) return ranked;
  return [...infant, ...ranked.filter((r) => !infant.includes(r))];
}
