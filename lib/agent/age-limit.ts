/**
 * Возрастная граница — правило клиники, а не вывод из названия услуги.
 *
 * Живой прогон: ребёнку 11 лет, и агент ответил «детский приём остеопата
 * ведётся только до 10 лет включительно, а вашему ребёнку 11 — для подростков
 * приём не предусмотрен». Звучит как правило клиники, а взято из строки прайса
 * «Детский прием до 10 л - остеопатия». В справке клиники при этом написано
 * другое: «Мальчиков принимаем до 14 лет включительно».
 *
 * Название услуги — это ценник, а не регламент: в нём пишут «до 10 л», чтобы
 * различать две цены, а не чтобы отказывать людям. Отказ по возрасту стоит
 * человеку зря потраченного дня и потерянного пациента, поэтому проверяем его
 * так же, как показания (`inventedIndication`): граница обязана стоять в
 * СПРАВКЕ. Нет — ответ не отправляем и зовём администратора.
 *
 * Цену с возрастом в названии это не задевает: «Детский приём до 10 лет —
 * 5000 ₽» ничего не запрещает, и правило его не трогает.
 */

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/** Возрастная граница: «до 10 лет», «старше 10 лет», «с 4 лет». */
const AGE_LIMIT = /(?:до|старше|с|от)\s+(\d{1,2})(?:[.,]\d)?\s*(?:лет|года|год)(?!\p{L})/giu;

/**
 * Слова, которые превращают число в ЗАПРЕТ.
 *
 * «Детский приём до 10 лет — 5000 ₽» — ценник. «Только до 10 лет»,
 * «не принимаем», «не предусмотрен» — правило, по которому человеку
 * отказывают. Разница в этих словах, поэтому смотрим на них, а не на само
 * число.
 */
const RESTRICTION =
  /(?<!\p{L})(?:только|исключительно|включительно|нельзя|невозможно|не\s+(?:принима\p{L}*|провод\p{L}*|предусмотр\p{L}*|подход\p{L}*|дела\p{L}*|вед[её]\p{L}*|получится)|старше|младше|ограничен\p{L}*)(?!\p{L})/iu;

/** Сколько символов вокруг границы считаем её окружением. */
const WINDOW = 140;

/**
 * Отказ по возрасту, которого нет в справке. Возвращает саму формулировку —
 * её видно в журнале, и по ней понятно, что именно агент выдумал.
 *
 * `knowledge` — только справка клиники. Прайс сюда передавать нельзя: именно
 * из него и берётся выдуманная граница.
 */
export function ungroundedAgeLimit(answer: string, knowledge: string): string | null {
  const text = norm(answer);
  const ref = norm(knowledge);

  for (const m of text.matchAll(AGE_LIMIT)) {
    const at = m.index ?? 0;
    const from = Math.max(0, at - WINDOW / 2);
    const window = text.slice(from, at + WINDOW / 2);
    if (!RESTRICTION.test(window)) continue;

    /**
     * Та же граница в справке — значит правило клиники, и агент его только
     * повторяет. Ищем число рядом со словом «лет» в любом падеже: клиника
     * пишет и «до 14 лет», и «с 14 лет», и «14 лет включительно».
     */
    const years = m[1];
    /**
     * Слева обязательно НЕ цифра: «4 лет» иначе находилось внутри «14 лет», и
     * выдуманная граница «с 4 лет» считалась подтверждённой справкой, где
     * написано «до 14 лет».
     */
    const grounded = new RegExp(`(?<!\\d)${years}\\s*(?:лет|года|год)(?!\\p{L})`, "u").test(ref);
    if (!grounded) return m[0];
  }
  return null;
}
