import { describe, expect, it } from "vitest";
import { asksForConsent, withoutConsentRequest } from "./consent";

/**
 * Согласие ведёт платформа, а не модель.
 *
 * Пациент ответил «Да», получил приветствие клиники и следом «теперь мне
 * нужно ваше согласие… согласны ли вы?» — модель повторила просьбу за нами, и
 * разговор закольцевался на том, что уже сделано.
 */
describe("просьба о согласии в ответе модели", () => {
  it("вырезается, а полезное остаётся", () => {
    const text =
      "Взрослый приём остеопата — 8000 ₽, 45 минут. Теперь мне нужно ваше согласие на обработку персональных данных. Согласны ли вы?";
    const out = withoutConsentRequest(text);
    expect(out).toContain("8000");
    expect(out).not.toContain("согласие");
    expect(out).not.toContain("Согласны ли вы");
  });

  it("ответ без просьбы не трогает", () => {
    const text = "Взрослый приём — 8000 ₽, 45 минут. Для взрослого или для ребёнка?";
    expect(withoutConsentRequest(text)).toBe(text);
  });
});

/**
 * Согласие просит платформа, и она одна.
 *
 * Живой диалог 11 сентября: пациент написал «хочу записаться к остеопату» и
 * получил в ОДНОМ сообщении два разных запроса согласия подряд — свой у
 * модели, свой у платформы.
 */
describe("просьба модели о согласии снимается", () => {
  it("«ответьте: „Согласен/Согласна“» — снимается, вопрос по делу остаётся", () => {
    const text =
      "Подскажите, к какому врачу вы хотели бы записаться? " +
      "Пожалуйста, ответьте: «Согласен/Согласна».";
    expect(withoutConsentRequest(text)).toBe("Подскажите, к какому врачу вы хотели бы записаться?");
  });

  it("«нам нужно ваше согласие» — снимается", () => {
    expect(withoutConsentRequest("Приём стоит 8000 ₽. Нам нужно ваше согласие.")).toBe(
      "Приём стоит 8000 ₽.",
    );
  });

  it("«подтвердите согласие» — снимается", () => {
    expect(withoutConsentRequest("Работаем с 9 до 21. Подтвердите согласие, пожалуйста.")).toBe(
      "Работаем с 9 до 21.",
    );
  });

  it("цена и услуга не трогаются", () => {
    const text = "Взрослый приём остеопата — 8 000 ₽, длительность до 30 минут.";
    expect(withoutConsentRequest(text)).toBe(text);
  });
});

describe("согласие словами модели, с падежом и вставным словом", () => {
  it("«Согласны на их обработку … Политикой обработки персональных данных?» снимается", () => {
    const text =
      "Взрослый приём остеопата стоит 8 000 ₽. Согласны на их обработку Клиникой доктора " +
      "Алункачевой в целях оформления записи и оказания медицинских услуг в соответствии с " +
      "Политикой обработки персональных данных?";
    expect(withoutConsentRequest(text)).toBe("Взрослый приём остеопата стоит 8 000 ₽.");
  });
});

/**
 * Живой диалог 14 сентября: модель спросила согласие своими словами, без
 * ссылки на политику. «Да» платформа не приняла и спросила второй раз — по
 * форме. Такой вопрос обязан узнаваться, чтобы его заменил запрос платформы.
 */
describe("asksForConsent", () => {
  it("узнаёт вопрос модели о согласии", () => {
    const model =
      "Отлично 🌿 Детский приём остеопата у Алункачевой Ирины Алилгаджиевны — 5 000 ₽, длительность около 20 минут.\n\n" +
      "Для записи мне нужно Ваше согласие на обработку персональных данных. Вы согласны?";
    expect(asksForConsent(model)).toBe(true);
    const cleaned = withoutConsentRequest(model);
    expect(cleaned).toContain("5 000 ₽");
    expect(cleaned).not.toMatch(/соглас/i);
  });

  it("обычный ответ вопросом о согласии не считается", () => {
    for (const t of [
      "Детский приём остеопата — 5 000 ₽, около 20 минут.",
      "Время подберёт администратор — он напишет здесь же.",
      "Вы согласны на время 14:00, которое предложил администратор",
    ]) {
      expect(asksForConsent(t), t).toBe(false);
    }
  });
});
