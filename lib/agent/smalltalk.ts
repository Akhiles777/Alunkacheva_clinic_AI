/**
 * Реплики, которые не требуют ни справочника, ни администратора.
 *
 * «Хорошо», «ок», «спасибо», «понятно» — это подтверждение, что человека
 * услышали, а не вопрос. На боевом стенде такое «Хорошо» ушло в модель, та
 * промолчала, и сработал запасной путь: «Секунду, передаю ваш вопрос
 * администратору». Администратора позвали на слово «хорошо».
 *
 * Отвечаем сами и коротко. Ошибиться здесь трудно: если в сообщении есть хоть
 * что-то, кроме вежливости, оно сюда не попадёт и пойдёт обычным путём.
 */

import { normalize } from "./text-actions";

/** Согласие и подтверждение: разговор продолжать не нужно. */
const ACKNOWLEDGEMENTS = [
  "хорошо",
  "хорошо спасибо",
  "ок",
  "окей",
  "ага",
  "угу",
  // «да» сюда не входит: это ответ на вопрос агента («приём для взрослого?»),
  // и отвечать на него «хорошо, если появятся вопросы — я здесь» значит
  // оборвать разговор на середине.
  "понятно",
  "поняла",
  "понял",
  "ясно",
  "принято",
  "договорились",
  "ладно",
  "буду знать",
  "супер",
  "отлично",
  "класс",
];

const THANKS = ["спасибо", "спс", "благодарю", "спасибо большое", "огромное спасибо", "спасибки"];

const FAREWELLS = ["до свидания", "всего доброго", "всего хорошего", "пока", "до встречи", "спокойной ночи"];

/** Вежливые довески, которые не меняют смысл реплики. */
const FILLER = ["большое", "огромное", "вам", "тебе", "очень", "и", "а", "ну", "же", "то", "уж"];

/** Осталось ли в сообщении что-то, кроме перечисленных слов. */
function onlyFrom(text: string, phrases: string[]): boolean {
  let rest = ` ${normalize(text)} `;
  if (rest.trim().length === 0) return false;

  // Длинные обороты снимаем первыми: «спасибо большое» иначе распадётся.
  for (const phrase of [...phrases, ...FILLER].sort((a, b) => b.length - a.length)) {
    rest = rest.split(` ${phrase} `).join(" ");
  }
  return rest.trim().length === 0;
}

/** «Хорошо», «ок», «понятно» — подтверждение, а не вопрос. */
export function isAcknowledgement(text: string): boolean {
  return onlyFrom(text, ACKNOWLEDGEMENTS);
}

/** «Спасибо» и его формы. */
export function isThanks(text: string): boolean {
  return onlyFrom(text, [...THANKS, ...ACKNOWLEDGEMENTS]) && /спасиб|спс|благодар/i.test(text);
}

/** «До свидания», «всего доброго». */
export function isFarewell(text: string): boolean {
  return onlyFrom(text, [...FAREWELLS, ...THANKS, ...ACKNOWLEDGEMENTS]) && /свидан|пока|встреч|доброго|хорошего|ночи/i.test(text);
}

/**
 * Что ответить. Коротко и без предложения помощи: человек и так знает, где нас
 * найти, а «чем ещё могу помочь?» после «хорошо» выглядит навязчиво.
 */
export function smallTalkReply(text: string): string | null {
  if (isFarewell(text)) return "Всего доброго! Будем рады видеть вас в клинике.";
  if (isThanks(text)) return "Пожалуйста! Если что-то понадобится — напишите.";
  if (isAcknowledgement(text)) return "Хорошо, если появятся вопросы — я здесь.";
  return null;
}
