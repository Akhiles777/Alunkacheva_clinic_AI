import { describe, expect, it } from "vitest";
import { medical, scheduleTopic, wantsHuman, cantCome, asksForSlot } from "./triggers";

/**
 * Триггеры эскалации из §6. Проверка появилась после находки: правила были
 * написаны через \b, который в JavaScript опирается на латинский \w и рядом с
 * кириллицей границы не находит. «боль», «человека», «окно», «доза» не
 * срабатывали никогда — выглядело как рабочее правило, а по факту тишина.
 */
describe("расписание — зона администратора", () => {
  it("ловит просьбы про запись и окна", () => {
    for (const t of ["хочу записаться", "нужна запись", "есть окно завтра", "свободные окна", "можно перенести приём", "отменить запись"]) {
      expect(scheduleTopic(t), t).toBe(true);
    }
  });
  it("не считает расписанием обычные вопросы", () => {
    expect(scheduleTopic("сколько стоит остеопатия")).toBe(false);
    expect(scheduleTopic("какой у вас адрес")).toBe(false);
  });
});

describe("медицинские темы", () => {
  it("ловит жалобы и препараты", () => {
    for (const t of ["у меня боль", "сильная боль в спине", "какая доза препарата", "можно ли мне это", "есть противопоказания", "болит спина"]) {
      expect(medical(t), t).toBe(true);
    }
  });
  it("не считает медициной цену и адрес", () => {
    expect(medical("сколько стоит приём")).toBe(false);
    expect(medical("как до вас доехать")).toBe(false);
  });
});

describe("просьба позвать человека", () => {
  it("ловит прямые просьбы", () => {
    for (const t of ["позовите человека", "нужен человек", "дайте администратора", "есть живой оператор"]) {
      expect(wantsHuman(t), t).toBe(true);
    }
  });
  it("не срабатывает на обычный вопрос", () => {
    expect(wantsHuman("сколько длится приём")).toBe(false);
  });
});

/**
 * Вопросы про исход лечения. На живом диалоге пациентка спросила «можно ли
 * исправить форму черепа у ребёнка, или уже поздно» — ни одно правило не
 * сработало, и ассистент принялся рассуждать сам, да ещё и с ценами, которых
 * в прайсе нет.
 */
describe("вопросы про лечение — человеку", () => {
  it("узнаёт вопрос про исход лечения", () => {
    for (const t of [
      "Можно ли исправить форму черепа у пятилетнего ребенка ? Или уже поздно ?",
      "Поможет ли остеопат при сколиозе?",
      "Это лечится вообще?",
      "В каком возрасте лучше начинать?",
    ]) {
      expect(medical(t), t).toBe(true);
    }
  });

  it("не считает медициной обычные вопросы клиники", () => {
    for (const t of [
      "Сколько стоит приём?",
      "Ирина Алункачева принимает?",
      "Где вы находитесь?",
      "Какие услуги есть?",
      "Хотела записаться к остеопату",
    ]) {
      expect(medical(t), t).toBe(false);
    }
  });
});

/**
 * Граница между тяжёлым медицинским вопросом и обычным вопросом про клинику.
 *
 * Она проходит не по слову «нет» в ответе, а по существу вопроса. «Ребёнок
 * плохо говорит, что посоветуете» — про здоровье, решает врач после осмотра.
 * «У вас есть горки?» — про клинику, и ответить «нет» здесь совершенно
 * нормально.
 */
describe("описание состояния — человеку", () => {
  it("узнаёт описание состояния", () => {
    for (const t of [
      "Ребёнок плохо говорит, нам невролог посоветовал что-то для развития речи",
      "Ребёнок не спит по ночам",
      "Нам поставили диагноз кривошея",
      "У сына энурез, поможете?",
      "Ортопед направил к остеопату",
    ]) {
      expect(medical(t), t).toBe(true);
    }
  });

  it("обычные вопросы про клинику отвечает сам", () => {
    for (const t of [
      "У вас есть парковка?",
      "У вас есть горки для детей?",
      "Вы делаете МРТ?",
      "Картой можно оплатить?",
      "Сколько стоит детский приём?",
      "Хочу записаться к остеопату",
    ]) {
      expect(medical(t), t).toBe(false);
    }
  });
});

/**
 * Отмена и перенос, сказанные по-человечески. Пациентка написала «извините, не
 * могу придти, всю ночь озноб» — ни одно правило не срабатывало, а это отмена
 * записи на сегодня, и администратору о ней нужно знать немедленно.
 */
describe("не смогу прийти", () => {
  it("узнаёт отмену и перенос", () => {
    for (const t of [
      "Извините, но я не могу придти, всю ночь озноб и диарея",
      "Мы не придём завтра",
      "Хочу отменить запись на завтра",
      "Можно перенести приём на 15 сентября?",
    ]) {
      expect(cantCome(t), t).toBe(true);
      // Это всегда вопрос расписания — значит администратор узнает о нём.
      expect(scheduleTopic(t), t).toBe(true);
    }
  });

  it("обычную запись отменой не считает", () => {
    for (const t of ["Хочу записаться к остеопату", "Сколько стоит приём?"]) {
      expect(cantCome(t), t).toBe(false);
    }
  });
});

/** Вопрос про свободное время: уточнять нечего, расписания агент не видит. */
describe("вопрос про окошко", () => {
  it("узнаёт вопрос про свободное время", () => {
    for (const t of ["Добрый день🌹 Ещё свободно окошко?", "Какие есть окна на неделе?", "На какое время можно?"]) {
      expect(asksForSlot(t), t).toBe(true);
    }
  });

  it("не путает с обычной записью", () => {
    for (const t of ["Хотела бы записаться к остеопату", "Сколько стоит детский приём?"]) {
      expect(asksForSlot(t), t).toBe(false);
    }
  });
});
