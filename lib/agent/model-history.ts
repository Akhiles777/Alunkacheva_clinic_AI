import type { Turn } from "./llm";
import { looksLikeIntake } from "./intake";

/**
 * История разговора — такой, какой её можно отдать внешней модели.
 *
 * В модель уходили последние реплики целиком, включая присланные анкеты:
 * «Мамаев Умакай Заурович, 10 лет, недержание кала». Это ФИО и сведения о
 * здоровье — ровно то, что §6.5 и §7 запрещают передавать наружу (152-ФЗ,
 * врачебная тайна по ст. 13 323-ФЗ).
 *
 * Модели для продолжения разговора нужно знать ФАКТ — данные присланы, — а не
 * сами данные: дальше их читает администратор, а не она. Поэтому анкета
 * заменяется пометкой. Правила агента при этом видят полный текст: они
 * работают на нашем сервере, и эта функция применяется только к тому, что
 * уходит за его пределы.
 */
export const INTAKE_PLACEHOLDER = "[пациент прислал данные для записи: ФИО, возраст и причину обращения]";

export function historyForModel(turns: Turn[], staffNames: string[] = []): Turn[] {
  return turns.map((t) =>
    t.role === "user" && looksLikeIntake(t.content, staffNames) ? { ...t, content: INTAKE_PLACEHOLDER } : t,
  );
}

/**
 * Текущее сообщение — тоже без анкеты.
 *
 * «Степан Андрей Павлович, 15 лет, 35 кг, город Махачкала, извиняюсь, а у вас
 * же город тоже Махачкала?» — модели нужен вопрос, а не ФИО и вес. Оставляем
 * только части с вопросительным знаком и пометку, что данные присланы.
 */
export function questionForModel(text: string, staffNames: string[] = []): string {
  if (!looksLikeIntake(text, staffNames)) return text;
  const questions = text
    .split(/(?<=[.!?\n])|,\s*/)
    .map((p) => p.trim())
    .filter((p) => p.includes("?"));
  return [INTAKE_PLACEHOLDER, ...questions].join("\n");
}
