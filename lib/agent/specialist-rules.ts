/**
 * Правила разговора с врачом и руководством клиники.
 *
 * Отдельно от механики, потому что решения здесь дороже кода. Ошибиться можно
 * в обе стороны, и обе плохи: переслать врачу вопрос, ответ на который есть в
 * справочнике, — значит будить человека десять раз в день, и он перестанет
 * читать; принять её служебную реплику «не отправляй, я сама» за ответ —
 * значит переслать пациенту фразу, обращённую к боту.
 *
 * Эти функции чистые: их проверяют тесты, не поднимая ни базы, ни каналов.
 */
import { wordRe } from "./word-boundary";

/**
 * Специалист просит НЕ передавать ответ пациенту.
 *
 * Заказчик описал этот случай прямо: «если руководитель напишет „не отправляй
 * ответ, я сама отвечу“, бот не должен думать, что это ответ пациенту». Список
 * покрывает то, как это говорят вживую: коротко и в повелительном наклонении.
 *
 * Проверяется ПЕРВЫМ: сомнение всегда решается в пользу молчания. Ошибиться,
 * промолчав, — значит потерять минуту; ошибиться, переслав, — значит показать
 * пациенту служебную переписку клиники.
 */
const DECLINE = [
  /(?<!\p{L})не\s+(?:отправля\p{L}*|пересыла\p{L}*|отвеча\p{L}*|пиши|пишите|надо|нужно)(?!\p{L})/iu,
  /(?<!\p{L})(?:я\s+)?сам[аи]?\s+(?:отвечу|напишу|позвоню|свяжусь|разберусь|решу)(?!\p{L})/iu,
  /(?<!\p{L})(?:отвечу|напишу|позвоню|свяжусь|разберусь)\s+сам[аи]?(?!\p{L})/iu,
  /(?<!\p{L})(?:погод[иь]|подожд\p{L}*|стоп|отставить)(?!\p{L})/iu,
  wordRe("не\\s+передавай|не\\s+передавайте|молчи|ничего\\s+не\\s+говори"),
  /(?<!\p{L})позвон\p{L}*\s+(?:ей|ему|им|сам[аи]?)(?!\p{L})/iu,
];

export function declinesRelay(text: string): boolean {
  return DECLINE.some((re) => re.test(text));
}

/**
 * Вопрос к клинике как к организации, а не к врачу.
 *
 * Работа, реклама, сотрудничество, аренда, поставки. Такие письма приходят в
 * тот же пациентский чат, и отвечать на них «этот вопрос лучше уточнить у
 * специалиста» — глупость: человек не лечиться пришёл. Формулировка для
 * пациента здесь тоже другая — «передал(а) руководству клиники».
 */
const MANAGEMENT = [
  /(?<!\p{L})(?:вакан\p{L}*|устроит\p{L}*|трудоустро\p{L}*|резюме|подработ\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:работу|работа)\s+(?:у\s+вас|в\s+клиник|есть)(?!\p{L})/iu,
  /(?<!\p{L})(?:ищете|нужен|нужны|требуется|требуются)\s+(?:ли\s+)?(?:сотрудник\p{L}*|врач\p{L}*|админист\p{L}*|массажист\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:реклам\p{L}*|продвижен\p{L}*|маркетинг\p{L}*|таргет\p{L}*|блогер\p{L}*|бартер\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:сотрудничеств\p{L}*|партнёрств\p{L}*|партнерств\p{L}*|коммерческ\p{L}*\s+предложен\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:аренд\p{L}*|поставк\p{L}*|поставщик\p{L}*|оборудован\p{L}*\s+продаём)(?!\p{L})/iu,
];

export function managementTopic(text: string): boolean {
  return MANAGEMENT.some((re) => re.test(text));
}

/**
 * Вопрос, ради которого стоит беспокоить врача.
 *
 * Не всякий медицинский вопрос требует её ответа. «А это больно?», «сколько
 * длится приём», «можно ли поесть перед приёмом» — мелочи, на которые
 * администратор ответит быстрее и которые врач читать не должна: письма по
 * пустякам перестают читать, а вместе с ними перестают читать и настоящие.
 *
 * Вот пример вопроса, ради которого функция и появилась:
 *
 *   «Дело в том что у меня ДЦП и я не знаю что и как мне нужно делать.
 *    И нужно ли вообще. Мне 33 года. Думала просто может консультация.
 *    Потом подберут лечение. Я не знаю»
 *
 * Здесь человек описал состояние и просит решить, что ему делать. Ответить на
 * такое может только врач, и администратор всё равно пойдёт к ней.
 *
 * Признак сложности — один из трёх: названо состояние или диагноз; человек
 * просит совета о тактике («что мне делать», «нужно ли», «поможет ли»);
 * разговор опирается на приём или назначение врача («она говорила», «после
 * приёма»).
 */
const CONDITION_NAMED = [
  /(?<!\p{L})(?:дцп|аутизм\p{L}*|эпилепс\p{L}*|сколиоз\p{L}*|кифоз\p{L}*|грыж\p{L}*|протруз\p{L}*|остеохондроз\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:кривошея|дисплаз\p{L}*|гидроцефал\p{L}*|энурез\p{L}*|заикан\p{L}*|гиперактивн\p{L}*|задержк\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:диагноз\p{L}*|операц\p{L}*|травм\p{L}*|перелом\p{L}*|инсульт\p{L}*|онколог\p{L}*|диабет\p{L}*|астм\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:хроническ\p{L}*|врожденн\p{L}*|врождённ\p{L}*|инвалидност\p{L}*)(?!\p{L})/iu,
  /(?<!\p{L})(?:беременн\p{L}*|после\s+родов|кесарев\p{L}*)(?!\p{L})/iu,
];

const ASKS_ADVICE = [
  /(?:что\s+(?:мне|нам|ему|ей)\s+(?:делать|нужно|надо)|что\s+и\s+как)/iu,
  /(?:нужно\s+ли|надо\s+ли|стоит\s+ли|имеет\s+ли\s+смысл|есть\s+ли\s+смысл)/iu,
  /(?:помож\p{L}*\s+ли|подойд\p{L}*\s+ли|подход\p{L}*\s+ли|с\s+чего\s+начать)/iu,
  /(?:не\s+знаю,?\s+(?:что|как|нужно|надо|стоит)|не\s+понимаю,?\s+что)/iu,
  /(?:что\s+(?:вы\s+)?посоветуете|какое\s+лечение|подберут\s+лечение)/iu,
];

const AFTER_VISIT = [
  /(?:она\s+говорила|врач\s+сказал\p{L}*|доктор\s+сказал\p{L}*|нам\s+сказали)/iu,
  /(?:после\s+(?:приёма|приема|сеанса|процедуры|остеопат\p{L}*|капельниц\p{L}*|инфузи\p{L}*|укол\p{L}*|бос\p{L}*)|были\s+на\s+приёме|были\s+на\s+приеме)/iu,
  /**
   * «Это нормально?» — вопрос о собственном самочувствии, и отвечает на него
   * врач. Пациентка спросила про головокружение после капельницы, вопрос до
   * врача не дошёл, и её ответ потом некуда было приложить.
   */
  /(?:это\s+нормально|так\s+и\s+должно\s+быть|это\s+не\s+опасно)/iu,
  /(?:назначил\p{L}*|направил\p{L}*|прописал\p{L}*|рекомендовал\p{L}*)/iu,
];

export function complexMedical(text: string): boolean {
  return (
    CONDITION_NAMED.some((re) => re.test(text)) ||
    ASKS_ADVICE.some((re) => re.test(text)) ||
    AFTER_VISIT.some((re) => re.test(text))
  );
}

/** Как вопрос помечен в сообщении специалисту: по метке узнаём ответ. */
export function refMark(ref: number): string {
  return `#${ref}`;
}

/**
 * Номер вопроса из цитаты.
 *
 * Отвечая свайпом, специалист присылает наш же текст в цитате — там и стоит
 * метка. Это самый надёжный способ понять, к чему относится ответ, когда
 * открытых вопросов несколько.
 */
export function refFromQuote(text: string): number | null {
  const m = /#(\d{1,6})(?!\d)/.exec(text);
  return m ? Number(m[1]) : null;
}
