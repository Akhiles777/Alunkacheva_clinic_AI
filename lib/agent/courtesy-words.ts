/**
 * Вежливые формулы, которые пишут пациенты клиники в Дагестане:
 * «джазакиЛляху хайран», «баракаЛлаху фики», «амин», «иншаАллах».
 *
 * Живой диалог 9 октября. Разговор закончился («нельзя оказывается, хорошо,
 * что уточнили»), пациентка поблагодарила — «джазакиЛляху хайран» — и
 * получила «Ва iyyaka 🌿» вперемешку с латиницей и прайсом двух остеопатов.
 * Следом на «амин» агент ответил «вы выбрали инфузию „Амино-Архитектура“ —
 * 8500 ₽» и попросил ФИО: слово совпало с названием услуги по четырём буквам.
 *
 * Ни одна из этих формул не вопрос и не название услуги. Правила вежливости
 * (`nothingToAnswer`, `smallTalkReply`) знали только «спасибо» и «хорошо», а
 * подбор услуги — только русские служебные слова. Список один на все три
 * места: разойдясь, они дали бы тот же провал с другой стороны.
 *
 * Слова сравниваются после `normalize` (нижний регистр, «ё» → «е», без
 * знаков): «джазакиЛляху» приходит как «джазакилляху».
 */

/**
 * Благодарность: «джазакаЛлаху хайран» и её написания, «баракаЛлаху фики».
 * Отвечать на неё можно так же, как на «спасибо».
 */
const THANKS_FORMULA =
  /^(?:джазак\p{L}*|жазак\p{L}*|хайр\p{L}{0,3}|барак\p{L}*|фик[иа]?|фикум|ва|ийя\p{L}*|иййа\p{L}*|ияк\p{L}*|иййя\p{L}*|а?лл[аяе]х[уиа]?|ллаху|лляху|аллагь\p{L}*)$/u;

/**
 * Пожелание и согласие: «амин», «иншаАллах», «машаАллах», «альхамдулиллях».
 * Это не благодарность и не вопрос. «ИншаАллах» в ответ на «записать вас на
 * 12:15?» бывает согласием — поэтому такие слова НЕ отвечаются заготовкой, а
 * только не считаются ни вопросом, ни названием услуги.
 *
 * Имя «Амина» и «Аминат» сюда не попадает: сравнение по слову целиком.
 */
const WISH_FORMULA =
  /^(?:амин[ьй]?|амиин[ьй]?|иншаа?лл\p{L}*|машаа?лл\p{L}*|альхамдули?лл\p{L}*|альхамдулилях\p{L}*|хамдулилл\p{L}*|субхана?лл\p{L}*|а?лл[аяе]х[уиа]?|ллаху|лляху)$/u;

/**
 * «Ин ша Аллах», «маша Аллах» пишут и раздельно. Склеиваем до разбора на
 * слова: отдельное «маша» — это ещё и имя, и считать его формулой нельзя.
 */
export function collapseFormulas(normalizedText: string): string {
  return normalizedText.replace(/(?<!\p{L})(ин\s*ша|маша)\s+(?=а?лл)/gu, (_m, head: string) => head.replace(/\s+/g, ""));
}

/** Слово — часть религиозной вежливой формулы. */
export function courtesyFormulaWord(word: string): boolean {
  return THANKS_FORMULA.test(word) || WISH_FORMULA.test(word);
}

/**
 * Благодарность формулой — по слову-ядру, а не по служебным «ва», «фики»:
 * «ва» само по себе ничего не благодарит.
 */
export function thanksFormula(normalizedText: string): boolean {
  return /(?<!\p{L})(?:джазак|жазак|барак)\p{L}*/u.test(normalizedText);
}

/**
 * Одно «амин» («аминь») — без вопроса и без согласия.
 *
 * «ИншаАллах» в ответ на «записать вас на 12:15?» бывает согласием, а «амин» —
 * никогда: это завершение чужого пожелания. Отвечать на него нечем, и модель
 * отвечала «Аминь. Будем рады видеть вас» — разговором ради разговора.
 */
export function amenOnly(text: string): boolean {
  if (text.includes("?")) return false;
  const words = text
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
  return words.length > 0 && words.length <= 2 && words.every((w) => /^ами+н[ьй]?$/u.test(w));
}
