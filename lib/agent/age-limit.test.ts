import { describe, expect, it } from "vitest";
import { asksAboutInfant, infantRulesFirst, ungroundedAgeLimit, ungroundedAgeRefusal } from "./age-limit";

/**
 * Справка клиники — та, что заведена в базе знаний. Возрастное правило в ней
 * одно: мальчиков принимают до 14 лет. Числа «10» в ней нет вовсе — оно живёт
 * только в названии услуги «Детский прием до 10 л - остеопатия».
 */
const KNOWLEDGE = [
  "Приём мужчин. Остеопатический приём взрослых мужчин не проводится.",
  "Мальчиков принимаем до 14 лет включительно.",
  "С какого возраста принимаем детей. Детей принимаем с рождения.",
].join("\n");

describe("возрастная граница из названия услуги", () => {
  it("отказ по границе, которой нет в справке, не проходит", () => {
    const answer =
      "К сожалению, детский приём остеопата ведётся только до 10 лет включительно, " +
      "а вашему ребёнку 11. Для подростков приём не предусмотрен.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toContain("10");
  });

  it("граница из справки — правило клиники, и агент его повторяет", () => {
    const answer = "Мальчиков принимаем до 14 лет включительно, поэтому приём возможен.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toBeNull();
  });

  it("цена с возрастом в названии ничего не запрещает", () => {
    for (const answer of [
      "Детский приём до 10 лет — 5000 ₽, 40 минут.",
      "Взрослый приём — 8000 ₽, 45 минут. Детский приём до 10 лет — 5000 ₽.",
    ]) {
      expect(ungroundedAgeLimit(answer, KNOWLEDGE), answer).toBeNull();
    }
  });

  it("ответ без возраста правило не трогает", () => {
    expect(ungroundedAgeLimit("Детский приём ведёт Ирина Алилгаджиевна.", KNOWLEDGE)).toBeNull();
  });

  it("«принимаем с 4 лет» без справки — тоже выдумка", () => {
    // БОС-терапию «с 4–5 лет» агент однажды назвал сам: в справке этого нет.
    const answer = "БОС-терапию проводим только с 4 лет, младше не получится.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toContain("4");
  });
});

/**
 * Цена в справке — не правило приёма.
 *
 * Живой прогон: отказ «остеопатический приём для детей старше 10 лет не
 * проводится» проходил проверку, потому что в справке стояла СТРОКА ПРАЙСА
 * «Детский приём до 10 лет — 5000 ₽». Рядом в той же справке написано, что
 * мальчиков принимают до 14 лет.
 */
describe("ценник в справке границу не подтверждает", () => {
  const knowledge = [
    "Сколько стоит приём остеопата. Взрослый приём — 8000 ₽, 45 минут. Детский приём до 10 лет — 5000 ₽, 40 минут.",
    "Детский приём. Мальчиков принимаем до 14 лет включительно.",
  ].join("\n");

  it("отказ по цене из прайса не проходит", () => {
    const answer = "К сожалению, остеопатический приём для детей старше 10 лет не проводится.";
    expect(ungroundedAgeLimit(answer, knowledge)).toContain("10");
  });

  it("правило приёма из справки проходит", () => {
    const answer = "Мальчиков принимаем до 14 лет включительно, поэтому записать можно.";
    expect(ungroundedAgeLimit(answer, knowledge)).toBeNull();
  });
});

/**
 * Живой диалог 2 октября: «Хотела записать месячного ребенка на приём» — и
 * отказ без единого числа, хотя клиника принимает детей с первого месяца.
 */
describe("отказ по возрасту без числа", () => {
  const KB = "Остеопатический приём детей проводится с 1-го месяца жизни. Приходите вместе с ребёнком.";
  const LIVE =
    "Здравствуйте! К сожалению, остеопатический приём для детей в нашей клинике начинается с более старшего возраста. " +
    "Месячному малышу остеопатия в нашем формате не подходит.";

  it("живой ответ — выдуманный отказ", () => {
    expect(ungroundedAgeRefusal(LIVE, KB)).not.toBeNull();
    expect(ungroundedAgeRefusal("Новорождённых мы не принимаем.", KB)).not.toBeNull();
    expect(ungroundedAgeRefusal("Малышу в этом возрасте ещё рано на приём.", KB)).not.toBeNull();
    expect(ungroundedAgeRefusal("Детям младше 3 месяцев приём не проводится.", KB)).not.toBeNull();
  });

  it("согласие и факты отказом не считаются", () => {
    for (const t of [
      "Остеопатический приём детей проводится с 1-го месяца жизни, поэтому для вашего малыша это подходит.",
      "Детей принимаем с рождения — приходите вместе с малышом.",
      "Детский приём до 10 лет — 5000 ₽, 40 мин.",
      "Взрослых мужчин на остеопатию не принимаем.",
      "Если время не подходит, администратор подберёт другое.",
    ]) {
      expect(ungroundedAgeRefusal(t, KB), t).toBeNull();
    }
  });

  it("отказ, который стоит в справке, повторять можно", () => {
    const strict = "Детей до 3 месяцев на остеопатию не принимаем.";
    expect(ungroundedAgeRefusal("Детям младше 3 месяцев приём не проводится.", strict)).toBeNull();
    expect(ungroundedAgeRefusal("Новорождённых мы не принимаем.", "Новорождённых не принимаем.")).toBeNull();
    // Другое число — уже выдумка.
    expect(ungroundedAgeRefusal("Детям младше 6 месяцев приём не проводится.", strict)).not.toBeNull();
  });
});

describe("вопрос про малыша находит справку о возрасте", () => {
  const rows = [
    { topic: "Оплата", question: "Как оплатить", answer: "Картой или наличными." },
    { topic: "С какого возраста", question: "грудничка принимаете / новорождённого", answer: "Детей принимаем с рождения." },
    { topic: "Приём детей", question: "детский приём", answer: "Остеопатический приём детей проводится с 1-го месяца жизни." },
    { topic: "БОС", question: "с какого возраста БОС", answer: "БОС-терапию проводим детям с 4 лет." },
  ];

  it("узнаёт вопрос про малыша", () => {
    expect(asksAboutInfant("Хотела записать месячного ребенка на прием")).toBe(true);
    expect(asksAboutInfant("Малышу 2 месяца")).toBe(true);
    expect(asksAboutInfant("Ребенку 2,5 месяца")).toBe(true);
    expect(asksAboutInfant("Сыну 5 лет")).toBe(false);
  });

  it("записи про малышей — первыми, про БОС с 4 лет — нет", () => {
    const out = infantRulesFirst(rows, [], "Хотела записать месячного ребенка на прием");
    expect(out.map((r) => r.topic)).toEqual(["С какого возраста", "Приём детей"]);
  });

  it("без вопроса про малыша порядок не меняется", () => {
    expect(infantRulesFirst(rows, [rows[0]], "Как оплатить?")).toEqual([rows[0]]);
  });
});
