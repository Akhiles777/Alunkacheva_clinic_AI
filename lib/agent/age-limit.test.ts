import { describe, expect, it } from "vitest";
import { ungroundedAgeLimit } from "./age-limit";

/**
 * Справка клиники — та, что заведена в базе знаний. Возрастное правило в ней
 * одно: мальчиков принимают до 14 лет. Числа «10» в ней нет вовсе — оно живёт
 * только в названии услуги «Детский прием до 10 л - остеопатия».
 */
const KNOWLEDGE = [
  "Приём мужчин. Остеопатический приём взрослых мужчин не проводится.",
  "Мальчиков принимаем до 14 лет включительно.",
  "С какого возраста принимаем детей. Детей принимаем с рождения.",
].join("\n");

describe("возрастная граница из названия услуги", () => {
  it("отказ по границе, которой нет в справке, не проходит", () => {
    const answer =
      "К сожалению, детский приём остеопата ведётся только до 10 лет включительно, " +
      "а вашему ребёнку 11. Для подростков приём не предусмотрен.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toContain("10");
  });

  it("граница из справки — правило клиники, и агент его повторяет", () => {
    const answer = "Мальчиков принимаем до 14 лет включительно, поэтому приём возможен.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toBeNull();
  });

  it("цена с возрастом в названии ничего не запрещает", () => {
    for (const answer of [
      "Детский приём до 10 лет — 5000 ₽, 40 минут.",
      "Взрослый приём — 8000 ₽, 45 минут. Детский приём до 10 лет — 5000 ₽.",
    ]) {
      expect(ungroundedAgeLimit(answer, KNOWLEDGE), answer).toBeNull();
    }
  });

  it("ответ без возраста правило не трогает", () => {
    expect(ungroundedAgeLimit("Детский приём ведёт Ирина Алилгаджиевна.", KNOWLEDGE)).toBeNull();
  });

  it("«принимаем с 4 лет» без справки — тоже выдумка", () => {
    // БОС-терапию «с 4–5 лет» агент однажды назвал сам: в справке этого нет.
    const answer = "БОС-терапию проводим только с 4 лет, младше не получится.";
    expect(ungroundedAgeLimit(answer, KNOWLEDGE)).toContain("4");
  });
});

/**
 * Цена в справке — не правило приёма.
 *
 * Живой прогон: отказ «остеопатический приём для детей старше 10 лет не
 * проводится» проходил проверку, потому что в справке стояла СТРОКА ПРАЙСА
 * «Детский приём до 10 лет — 5000 ₽». Рядом в той же справке написано, что
 * мальчиков принимают до 14 лет.
 */
describe("ценник в справке границу не подтверждает", () => {
  const knowledge = [
    "Сколько стоит приём остеопата. Взрослый приём — 8000 ₽, 45 минут. Детский приём до 10 лет — 5000 ₽, 40 минут.",
    "Детский приём. Мальчиков принимаем до 14 лет включительно.",
  ].join("\n");

  it("отказ по цене из прайса не проходит", () => {
    const answer = "К сожалению, остеопатический приём для детей старше 10 лет не проводится.";
    expect(ungroundedAgeLimit(answer, knowledge)).toContain("10");
  });

  it("правило приёма из справки проходит", () => {
    const answer = "Мальчиков принимаем до 14 лет включительно, поэтому записать можно.";
    expect(ungroundedAgeLimit(answer, knowledge)).toBeNull();
  });
});
