import { describe, expect, it } from "vitest";
import { unaskedAudience, withoutUnaskedAudience } from "./unasked-group";

/**
 * Запись клиники, которая три раза уходила не по делу. Текст дословный —
 * именно он приходил пациентам.
 */
const MEN_ENTRY = [
  "Остеопатический приём взрослых мужчин в нашей клинике не проводится.",
  "Мальчиков принимаем до 14 лет включительно.",
  "Взрослым мужчинам рекомендуем врача-остеопата Исаева Сайфутдина Юрьевича, принимает в Махачкале: 8 966 745-18-44.",
  "При этом будем рады видеть мужчин в нашей клинике на IV-терапии — программы подбираются индивидуально.",
].join("\n");

describe("справка о тех, о ком не спрашивали", () => {
  it("запись про мужчин не уходит женщине, которая про мужчин не говорила", () => {
    // Живой диалог: пациентка пересказала назначение своего врача.
    const said = [
      "Здравствуйте",
      "Мне Ирина Алилгаджиевна говорила, если проблема повторится, то надо прийти сразу не ждать следующего приёма.",
    ];
    expect(unaskedAudience(MEN_ENTRY, said)).toContain("мужчин");
    // Ответ был про мужчин целиком — отправлять нечего.
    expect(withoutUnaskedAudience(MEN_ENTRY, said)).toBe("");
  });

  it("та же запись на «как попасть на приём» и на «Ок» — тоже не уходит", () => {
    for (const said of [["Как можно попасть на приём ?"], ["Ок"]]) {
      expect(unaskedAudience(MEN_ENTRY, said), said[0]).not.toBeNull();
    }
  });

  it("спросили про мужа — запись уходит целиком", () => {
    const said = ["Здравствуйте, можно мужа записать к остеопату?"];
    expect(unaskedAudience(MEN_ENTRY, said)).toBeNull();
    expect(withoutUnaskedAudience(MEN_ENTRY, said)).toBe(MEN_ENTRY);
  });

  it("спросили прямо про мужчин — тоже уходит", () => {
    for (const said of [
      ["Принимаете ли вы мужчин?"],
      ["Я мужчина, можно на остеопатию?"],
      ["Хотела записать сына, ему 12"],
    ]) {
      expect(unaskedAudience(MEN_ENTRY, said), said[0]).toBeNull();
    }
  });

  it("правило про мальчиков остаётся родителю ребёнка", () => {
    // Пол ребёнка мама не назвала, но говорит она именно о ребёнке —
    // возрастное правило клиники к нему и относится.
    const answer = "Детский приём ведёт Ирина Алилгаджиевна. Мальчиков принимаем до 14 лет включительно.";
    expect(unaskedAudience(answer, ["Ребенку 11 лет"])).toBeNull();
  });

  it("лишнее предложение убирается, полезное остаётся", () => {
    const answer =
      "Взрослый приём остеопата — 8000 ₽, 45 минут. Детский приём до 10 лет — 5000 ₽, 40 минут.\n" +
      "Остеопатический приём взрослых мужчин не проводится.";
    const said = ["Сколько стоит остеопатия?"];
    expect(unaskedAudience(answer, said)).toContain("мужчин");
    const kept = withoutUnaskedAudience(answer, said);
    expect(kept).toContain("8000 ₽");
    expect(kept).not.toContain("мужчин");
  });

  it("обычный ответ правило не трогает", () => {
    for (const answer of [
      "Работаем с понедельника по субботу с 09:00 до 21:00.",
      "Наш адрес: Махачкала, улица Ленина, 1.",
      "Приём ведёт Ирина Алилгаджиевна, детский и взрослый.",
      "Уточню у врача и напишу вам здесь же.",
    ]) {
      expect(unaskedAudience(answer, ["Здравствуйте"]), answer).toBeNull();
      expect(withoutUnaskedAudience(answer, ["Здравствуйте"]), answer).toBe(answer);
    }
  });
});
