/**
 * Цитата в начале сообщения — и слова самого пациента.
 *
 * Отвечая свайпом, человек присылает нам две вещи сразу: реплику, на которую
 * он отвечает, и собственные слова. Провайдер их не разделяет, поэтому строку
 * «В ответ на: «…»» дописываем мы сами — без неё «да» в переписке не говорит
 * ни администратору, ни агенту, к чему оно относится.
 *
 * Но правила агента должны читать ТОЛЬКО собственные слова пациента. Пациентка
 * ответила на сообщение клиники «Окошко на завтра к Ирине Алилгаджиевне ✅
 * 09:40 (детский)» словами «Запишите пожалуйста племянника моего» — и получила
 * «передал(а) администратору». Сработало стоп-слово «окошко»… из текста самой
 * клиники. Человек просил записать ребёнка, а его молча отправили ждать: в его
 * сообщении не было ни одного стоп-слова.
 *
 * Отсюда разделение: цитата остаётся в переписке и уходит модели как контекст
 * (там она полезна — понятно, о какой услуге речь), а стоп-слова, медицинские
 * правила и разбор темы смотрят на то, что человек написал сам.
 */

/** Сколько знаков цитаты показываем: она подсказка, а не сообщение. */
export const QUOTE_LIMIT = 120;

const LEAD = "В ответ на";

/** Цитата с текстом: «В ответ на: «…»». */
export function quoteOfText(text: string): string {
  const t = text.trim();
  const short = t.length > QUOTE_LIMIT ? `${t.slice(0, QUOTE_LIMIT)}…` : t;
  return `${LEAD}: «${short}»`;
}

/**
 * Цитата без текста: отвечали на фотографию или голосовое. Называем тип —
 * понять, к чему относится ответ, всё равно важнее, чем ничего.
 */
export function quoteOfKind(label: string | null): string {
  return label ? `${LEAD}: ${label}` : `${LEAD} сообщение`;
}

/**
 * Строки цитаты. Первым — вариант с текстом: он длиннее и его надо примерять
 * раньше, иначе общий вариант отрежет только первую строку многострочной
 * цитаты и остаток уедет в «слова пациента».
 */
const QUOTED_TEXT = /^В ответ на: «[\s\S]*?»[^\S\n]*(?:\n|$)/;
const QUOTED_OTHER = /^В ответ на(?::[^\n]*| сообщение)[^\S\n]*(?:\n|$)/;

/**
 * Что написал сам пациент, без цитаты.
 *
 * Сообщение из одной цитаты возвращаем как есть: там больше ничего нет, и
 * пустая строка вместо текста хуже — она означала бы «пациент промолчал».
 */
export function withoutQuote(text: string): string {
  const m = QUOTED_TEXT.exec(text) ?? QUOTED_OTHER.exec(text);
  if (!m) return text;
  const own = text.slice(m[0].length).trim();
  return own.length > 0 ? own : text;
}

/** Есть ли в сообщении цитата — для тестов и для отладки. */
export function hasQuote(text: string): boolean {
  return QUOTED_TEXT.test(text) || QUOTED_OTHER.test(text);
}

/**
 * Разделить сообщение на цитату и собственные слова — для показа в переписке.
 *
 * В инбоксе цитата шла обычным текстом первой строкой пузыря, и ответ пациента
 * читался как одно сплошное сообщение: «В ответ на: «Окошко на завтра…»
 * Запишите племянника». Глазами это разбирается плохо, а именно здесь
 * администратор решает, о чём речь. Показываем цитату отдельной строкой — так
 * же, как показываем свою.
 *
 * Сообщение, в котором кроме цитаты ничего нет, не разделяем: пустой пузырь
 * означал бы, что пациент промолчал.
 */
export function splitQuote(text: string): { quote: string | null; own: string } {
  const m = QUOTED_TEXT.exec(text) ?? QUOTED_OTHER.exec(text);
  if (!m) return { quote: null, own: text };
  const own = text.slice(m[0].length).trim();
  if (own.length === 0) return { quote: null, own: text };
  const quote = m[0].trim().replace(/^В ответ на:?\s*/, "").replace(/^«|»$/g, "");
  return { quote: quote || null, own };
}
