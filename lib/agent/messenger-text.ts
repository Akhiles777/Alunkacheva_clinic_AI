/**
 * Разметка в текст мессенджера.
 *
 * Клиника набирает справочник в редакторе и ставит списки звёздочками. В
 * мессенджере звёздочка так и остаётся звёздочкой: пациент видит «* взрослый
 * приём» и решает, что сообщение сломалось. Меняем только маркер списка —
 * сами слова клиники не трогаем.
 */
export function forMessenger(text: string): string {
  return text
    .split("\n")
    .map((line) => line.replace(/^(\s*)[*+]\s+/, "$1• "))
    .join("\n")
    /**
     * Жирный и курсив разметкой. WhatsApp понимает свой формат (*текст*), а
     * модель пишет по-марклаудновски (**текст**) — в переписке это выглядит как
     * «**персональный план**» со звёздочками наружу. Убираем сами звёздочки, а
     * слова оставляем: подчёркивание в мессенджере не стоит мусора на экране.
     */
    .replace(/\*\*([^*\n]+)\*\*/g, "$1")
    .replace(/(?<![\p{L}\d*])\*([^*\n]+)\*(?![\p{L}\d*])/gu, "$1")
    .replace(/__([^_\n]+)__/g, "$1")
    // Заголовки решёткой: модель ставит их по привычке, в мессенджере это шум.
    .replace(/^#{1,6}\s+/gm, "")
    // Одинокие звёздочки, оставшиеся от незакрытой разметки. Вместе с
    // звёздочкой убираем и лишний пробел, иначе в строке остаётся двойной.
    .replace(/ \*(?= )/g, "")
    .replace(/(?<!\S)\*(?!\S)/g, "")
    .trimEnd();
}

