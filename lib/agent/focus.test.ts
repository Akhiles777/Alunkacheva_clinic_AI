import { describe, expect, it } from "vitest";
import { focusLine, focusOf, searchText } from "./focus";

const STAFF = ["Ирина Алилгаджиевна", "Ирина Омарова", "Разият Ризвановна", "Нурият Абулкасимовна"];

/**
 * Живой диалог, из-за которого всё это и появилось: пациент спросил цену
 * детского приёма у названного врача, получил весь раздел справочника с
 * четырьмя ценами, переспросил — и услышал про программу «Лотос».
 */
describe("что искать по уточнению", () => {
  it("уточнение ищется вместе с вопросом, к которому относится", () => {
    const previous = ["Хочу записать ребенка к Ирине Алункачевой на остеопатию, сколько стоит?"];
    const out = searchText("Я же сказал лишь Ирина Алункачева", previous);
    // Без предыдущего вопроса в строке остаётся одно имя — и справочник
    // честно находит по нему «Лотос», где это имя тоже есть.
    expect(out).toContain("остеопатию");
    expect(out).toContain("ребенка");
  });

  it("короткая реплика без вопроса рядом — ищется как есть", () => {
    expect(searchText("Сколько стоит?", [])).toBe("Сколько стоит?");
  });

  it("полноценный новый вопрос предыдущим не разбавляется", () => {
    const previous = ["Хочу записать ребенка к Ирине Алункачевой на остеопатию, сколько стоит?"];
    const now = "А подскажите, пожалуйста, как проехать к вам от железнодорожного вокзала?";
    expect(searchText(now, previous)).toBe(now);
  });

  it("пустая реплика ничего не ломает", () => {
    expect(searchText("   ", ["что-то"])).toBe("");
  });
});

describe("о чём именно спросили", () => {
  it("возвращает имя словами пациента, а не карточкой справочника", () => {
    // Пациент пишет «Ирине Алункачевой», в справочнике «Ирина Алилгаджиевна».
    // В клинике две Ирины — выбирать карточку значило бы угадывать.
    const f = focusOf("Хочу записать ребенка к Ирине Алункачевой", "child", STAFF);
    expect(f.staffMentioned).toBe("Ирине Алункачевой");
    expect(f.whom).toBe("child");
  });

  it("узнаёт врача, названного одним именем", () => {
    expect(focusOf("Записаться к Разият", "unknown", STAFF).staffMentioned).toBe("Разият");
  });

  it("врача не назвали — не выдумываем", () => {
    expect(focusOf("Сколько стоит остеопатия?", "unknown", STAFF).staffMentioned).toBeNull();
  });

  it("короткие слова врачами не считаются", () => {
    // Иначе «мне», «цена», «этот» начнут находить специалистов.
    expect(focusOf("Цена?", "unknown", STAFF).staffMentioned).toBeNull();
  });
});

describe("указание для модели", () => {
  it("называет и возраст, и врача", () => {
    const line = focusLine({ whom: "child", staffMentioned: "Ирина Алилгаджиевна" });
    expect(line).toContain("ДЕТСКИЙ");
    expect(line).toContain("Ирина Алилгаджиевна");
    expect(line).toContain("не перечисляй остальные");
  });

  it("ничего не сузилось — указания нет", () => {
    // Лишнее ограничение хуже отсутствующего: агент начнёт молчать там, где
    // мог ответить.
    expect(focusLine({ whom: null, staffMentioned: null })).toBe("");
  });
});

/**
 * Живой сбой: короткая реплика приклеивалась к прошлому вопросу.
 *
 * Правило «короче шестидесяти знаков — значит уточнение» брало почти любое
 * сообщение. «Доброго дня» склеивалось с прошлым вопросом собеседника, и
 * человек получал в ответ карточку услуги из того разговора; «На завтра все
 * подтвердили?» — график работы клиники.
 */
describe("что не считается уточнением", () => {
  const before = ["Сколько стоит тихая терапия «Перезагрузка»?"];

  it("приветствие ищется само по себе", () => {
    expect(searchText("Доброго дня ☘️", before)).toBe("Доброго дня ☘️");
  });

  it("благодарность тоже", () => {
    expect(searchText("Спасибо большое", before)).toBe("Спасибо большое");
  });

  it("законченный вопрос не приклеивается к прошлому", () => {
    expect(searchText("На завтра все подтвердили ?", before)).toBe("На завтра все подтвердили ?");
  });

  it("а обрывок — приклеивается, как и раньше", () => {
    expect(searchText("лишь Ирина Алункачева", before)).toBe(
      "Сколько стоит тихая терапия «Перезагрузка»? лишь Ирина Алункачева",
    );
  });
});
