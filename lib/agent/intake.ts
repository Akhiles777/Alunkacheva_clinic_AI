/**
 * Инструкция ассистента, которую клиника правит сама.
 *
 * До сих пор всё поведение агента было зашито в код: чтобы поменять порядок
 * разговора о записи, нужен был программист. Клиника при этом лучше знает, что
 * спрашивать у пациента — в живых переписках администратор каждый раз просит
 * один и тот же набор: ФИО, возраст, вес, жалобу, город.
 *
 * Поэтому текст инструкции лежит в настройках и дописывается к базовым
 * правилам. Базовые правила остаются всегда и отсюда не отключаются: не
 * обещать запись, не выдумывать цены, медицинские вопросы — человеку. Их цена
 * — не удобство, а безопасность пациента (§6).
 */

/**
 * Образец инструкции — с порядком разговора о записи, который в переписках
 * ведёт администратор. Клиника меняет его под себя, но из коробки агент должен
 * вести человека к записи, а не обрывать разговор на «обратитесь к
 * администратору».
 */
export const DEFAULT_INTAKE_PROMPT = [
  "Когда человек хочет записаться, доведи разговор до конца, а не отсылай сразу к администратору.",
  "Порядок такой:",
  "1) Уточни, для кого приём — взрослому или ребёнку, и на какую услугу.",
  "2) Назови услугу и цену из справки, коротко скажи, сколько длится приём.",
  "3) Попроси данные для записи ОДНИМ сообщением: ФИО, возраст, вес, жалобу, город или село.",
  "4) Скажи, что администратор подберёт ближайшее удобное время и напишет здесь же.",
  "Данные не проверяй и не оценивай — просто прими и подтверди, что передал администратору.",
  "Не задавай больше одного уточняющего вопроса за раз и не спрашивай то, что человек уже сказал.",
  "Как только знаешь услугу и для кого приём — сразу проси данные, не растягивай на несколько сообщений.",
  "Если вместе с данными человек о чём-то спросил — сначала ответь на вопрос, потом подтверди, что данные переданы.",
  "Время приёма, свободные окна и подтверждение записи не называй никогда: это администратор.",
].join("\n");

/** Инструкция целиком: то, что клиника завела, или образец. */
export function intakePrompt(configured?: string | null): string {
  const own = (configured ?? "").trim();
  return own || DEFAULT_INTAKE_PROMPT;
}

/**
 * Похоже ли сообщение на присланные данные для записи.
 *
 * Нужно, чтобы такое сообщение точно дошло до администратора с пометкой, а не
 * растворилось в переписке: пациент прислал ФИО и жалобу — дальше нужен
 * человек, который поставит время.
 *
 * Признак — не разметка, а состав: имя из нескольких слов и число рядом
 * (возраст или вес). Именно так это выглядит в живых переписках:
 * «Магомедова Гульбара Халитовна 23 года 61 кг боли в пояснице».
 */
export function looksLikeIntake(text: string): boolean {
  const t = text.trim();
  if (t.length < 12) return false;

  // Два слова с заглавной буквы подряд — фамилия и имя.
  const hasName = /(?:^|[\s,])\p{Lu}\p{Ll}+\s+\p{Lu}\p{Ll}+/u.test(t);
  if (!hasName) return false;

  // Возраст или вес: число рядом со словом или просто отдельным числом.
  const hasNumber = /(?<!\p{L})\d{1,3}(?!\p{L})/u.test(t);
  return hasNumber;
}

/**
 * Агент только что спросил данные для записи?
 *
 * Нужно, чтобы не отфутболить собственный вопрос. Живой случай: агент спросил
 * «для взрослого или ребёнка, и с какой жалобой», пациентка ответила «взрослая
 * женщина, головная боль» — и получила «этот вопрос лучше уточнить у
 * специалиста». Слово «боль» есть, значит медицина; то, что жалобу запросил он
 * сам минуту назад, никто не проверял. Человек выполнил просьбу и был послан
 * по кругу.
 *
 * Смотрим на последнюю реплику агента: если он спрашивал, для кого приём, с
 * какой жалобой или просил данные — следующий ответ пациента относится к
 * записи, а не является медицинским вопросом.
 */
const INTAKE_QUESTIONS = [
  /жалоб/i,
  /для\s+кого/i,
  /взросл\p{L}*\s+или\s+(?:ребён|ребен)/iu,
  /(?:ребён|ребен)\p{L}*\s+или\s+взросл/iu,
  /(?:пришлите|напишите|укажите|попрошу|нужны)\p{L}*[^.!?\n]{0,40}(?:данн|фио|имя|возраст|вес)/iu,
  /сколько\s+лет/i,
  /как\s+вас\s+зовут|как\s+к\s+вам\s+обращаться/i,
];

export function asksForIntake(text: string): boolean {
  return INTAKE_QUESTIONS.some((re) => re.test(text));
}

/** Идёт ли сейчас оформление записи: последнее слово было за вопросом агента. */
export function inIntakeFlow(history: { role: "user" | "assistant"; content: string }[]): boolean {
  for (let i = history.length - 1; i >= 0; i -= 1) {
    if (history[i].role !== "assistant") continue;
    return asksForIntake(history[i].content);
  }
  return false;
}

/**
 * ФИО из присланной анкеты.
 *
 * Пациент представился полным именем, а через две реплики на вопрос «как меня
 * зовут?» услышал «вы его не называли». Имя было в переписке, но до модели не
 * доходило: в промпт уходят последние реплики, и всё, что дальше, для агента
 * не существует. Поэтому имя вынимаем из анкеты и держим отдельно — в карточке
 * пациента, а не в глубине переписки.
 *
 * Берём подряд идущие слова с заглавной буквы в начале строки: именно так люди
 * и пишут — «Магомедова Гульбара Халитовна 23 года 61 кг».
 */
export function nameFromIntake(text: string): string | null {
  const match = text
    .trim()
    .match(/^(\p{Lu}\p{Ll}+(?:\s+\p{Lu}\p{Ll}+){1,2})/u);
  return match ? match[1] : null;
}

/**
 * Есть ли в сообщении вопрос помимо данных.
 *
 * Пациент прислал анкету и тут же спросил: «извиняюсь, а у вас же город тоже
 * Махачкала?» — и получил только «спасибо, записал(а)». Вопрос остался без
 * ответа: сообщение целиком считалось анкетой, а на анкету у нас готовая
 * фраза.
 */
export function hasQuestion(text: string): boolean {
  return /\?/.test(text);
}
