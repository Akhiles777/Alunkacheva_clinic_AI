/**
 * Инструкция ассистента, которую клиника правит сама.
 *
 * До сих пор всё поведение агента было зашито в код: чтобы поменять порядок
 * разговора о записи, нужен был программист. Клиника при этом лучше знает, что
 * спрашивать у пациента — в живых переписках администратор каждый раз просит
 * один и тот же набор данных.
 *
 * Набор при этом должен быть коротким. Агент просил ещё вес, город или село и
 * «первичный это приём или повторный» — заказчик убрал: для звонка клинике
 * хватает имени, возраста и повода, а всё лишнее человек воспринимает как
 * анкету и бросает разговор.
 *
 * Поэтому текст инструкции лежит в настройках и дописывается к базовым
 * правилам. Базовые правила остаются всегда и отсюда не отключаются: не
 * обещать запись, не выдумывать цены, медицинские вопросы — человеку. Их цена
 * — не удобство, а безопасность пациента (§6).
 */

