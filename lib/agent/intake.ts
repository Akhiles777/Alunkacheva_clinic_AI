/**
 * Сколько текста инструкции берём.
 *
 * Ограничение не про экономию, а про поведение: чем длиннее инструкция, тем
 * слабее модель держится за базовые правила, которые идут ПЕРЕД ней. Двадцать
 * тысяч знаков клинического регламента вытесняют «не обещай запись» — а это
 * правило дороже любой инструкции.
 */
export const MAX_INSTRUCTION_CHARS = 6000;

/**
 * Инструкция целиком: то, что клиника завела, или образец.
 *
 * Клиника заменяет ПОРЯДОК разговора о записи — и только его. Базовые
 * ограничения живут отдельным системным сообщением, идут первыми и отсюда не
 * отключаются: не обещать запись, не выдумывать цены, медицинские вопросы —
 * человеку (§6). Их цена — безопасность пациента, а не удобство.
 */
export function intakePrompt(configured?: string | null): string {
  const own = (configured ?? "").trim();
  if (!own) return DEFAULT_INTAKE_PROMPT;
  return own.length > MAX_INSTRUCTION_CHARS ? own.slice(0, MAX_INSTRUCTION_CHARS) : own;
}

/**
 * Похоже ли сообщение на присланные данные для записи.
 *
 * Нужно, чтобы такое сообщение точно дошло до администратора с пометкой, а не
 * растворилось в переписке: пациент прислал ФИО и жалобу — дальше нужен
 * человек, который поставит время.
 *
 * Признак — не разметка, а состав: имя из нескольких слов и число рядом
 * (возраст или вес). Именно так это выглядит в живых переписках:
 * «Магомедова Гульбара Халитовна 23 года 61 кг боли в пояснице».
 */
/**
 * Слова, которые стоят перед возрастом, но именем не являются.
 *
 * «Здравствуйте! Можно ли у вас устроиться массажистом? Опыт 5 лет» — человек
 * искал работу, а сообщение было принято за анкету пациента, и вместо ответа
 * руководства он получил юридическую стену про обработку данных.
 */
const NOT_A_NAME = new Set([
  "опыт", "стаж", "возраст", "срок", "работа", "работаю", "живу", "прошло",
  // Приветствия: «Здравствуйте Ирина Алилгаджиевна» — не анкета пациента.
  "здравствуйте", "здраствуйте", "добрый", "доброе", "доброго", "привет",
  "спасибо", "пожалуйста", "подскажите", "скажите", "можно", "хочу",
  "ребенок", "ребенку", "сын", "сыну", "дочь", "дочери", "внук", "внуку",
  // «Взрослый Разият Резванова» — это вид приёма и имя ВРАЧА, а не ФИО пациента.
  "взрослый", "взрослая", "взрослого", "взрослому", "детский", "детская", "детского",
  "первичный", "повторный", "прием", "приём",
  "мама", "маме", "папа", "папе", "муж", "мужу", "жена", "жене", "брат", "сестра",
  // Первые слова обычной фразы, которые пишут с заглавной без запятой.
  "день", "вечер", "утро", "ночи", "здравствуй", "салам", "ассаламу", "алейкум",
  "извините", "простите", "уважаемые", "девушка", "доктор", "врач", "администратор",
  "запишите", "подскажите", "будьте", "добрый",
]);

/**
 * Три слова подряд с заглавной буквы — ФИО.
 *
 * Приветствие впереди («Здравствуйте Ирина Алилгаджиевна») именем не делает:
 * слова из NOT_A_NAME в счёт не идут.
 */
/**
 * Слова из имён сотрудников клиники — по ним ФИО пациента не опознаётся.
 *
 * «Взрослый Разият Резванова» — три слова с заглавной буквы, и правило приняло
 * это за присланное ФИО: агент завёл эскалацию «прислал данные до согласия» и
 * ответил юридическим текстом вместо подтверждения выбора. Человек назвал вид
 * приёма и ВРАЧА. Имя врача — не персональные данные пациента.
 *
 * Сравниваем по началу слова: пациент пишет и «Резванова» вместо
 * «Ризвановна», и «Алункачевой» вместо «Алункачева».
 */
function staffWordsOf(names: string[]): string[] {
  // Основа короче слова на букву: «Ирина» узнаётся и в «Ирине», «Ириной», «Ирину».
  return names
    .flatMap((n) => n.toLowerCase().replace(/ё/g, "е").split(/[^\p{L}]+/u))
    .filter((w) => w.length >= 4)
    .map((w) => w.slice(0, Math.min(5, w.length - 1)));
}

function isStaffWord(word: string, staffWords: string[]): boolean {
  const w = word.toLowerCase().replace(/ё/g, "е");
  return staffWords.some((s) => w.startsWith(s));
}

function fullName(text: string, staffWords: string[] = []): boolean {
  const words = text.split(/[\s,;:—-]+/).filter(Boolean);
  let run = 0;
  for (const w of words) {
    const bare = w.replace(/[^\p{L}]/gu, "");
    const isName =
      /^\p{Lu}\p{Ll}{2,}$/u.test(bare) &&
      !NOT_A_NAME.has(bare.toLowerCase().replace(/ё/g, "е")) &&
      !isStaffWord(bare, staffWords);
    run = isName ? run + 1 : 0;
    if (run >= 3) return true;
  }
  return false;
}

/** «Ислам 8 лет» — имя и возраст рядом; «Опыт 5 лет» — нет. */
/**
 * Два слова с заглавной буквы подряд — имя и фамилия. Имена сотрудников в счёт
 * не идут: «Разият Резванова» это врач, а не пациент.
 */
function twoNames(text: string, staffWords: string[]): boolean {
  const re = /(?:^|[\s,;:—-])(\p{Lu}\p{Ll}+)[\s,;:—-]+(\p{Lu}\p{Ll}+)/gu;
  /**
   * Слова из NOT_A_NAME именем не считаются и здесь, как в соседних правилах.
   * Без этой проверки «Здравствуйте Можно запись с 7 сентября на 15 сентября
   * перенести?» было «фамилией и именем» с числами рядом — то есть анкетой: вместо
   * передачи администратору просьбы о переносе уходил один текст согласия.
   */
  const notName = (w: string) => NOT_A_NAME.has(w.toLowerCase().replace(/ё/g, "е"));
  for (const m of text.matchAll(re)) {
    if (notName(m[1]) || notName(m[2])) continue;
    if (!isStaffWord(m[1], staffWords) && !isStaffWord(m[2], staffWords)) return true;
  }
  return false;
}

function nameWithAge(text: string, staffWords: string[] = []): boolean {
  const re = /(?:^|[\s,;:—-])(\p{Lu}\p{Ll}+)\s+\d{1,2}\s*(?:лет|года|год)(?!\p{L})/gu;
  for (const m of text.matchAll(re)) {
    const word = m[1].toLowerCase().replace(/ё/g, "е");
    if (!NOT_A_NAME.has(word) && !isStaffWord(word, staffWords)) return true;
  }
  return false;
}

export function looksLikeIntake(
  text: string,
  /** Имена сотрудников клиники: их пациент называет, выбирая врача. */
  staffNames: string[] = [],
): boolean {
  const t = text.trim();
  if (t.length < 12) return false;
  const staffWords = staffWordsOf(staffNames);

  /**
   * Два слова с заглавной буквы подряд — фамилия и имя.
   *
   * Между ними бывает знак: «Магомедовы: Ислам 8 лет и Амина 12 лет». Раньше
   * двоеточие разрывало правило, сообщение не считалось анкетой — и данные
   * двоих детей были приняты и переданы администратору без согласия на
   * обработку. Точку, восклицательный и вопросительный знаки не пускаем:
   * «Здравствуйте! Ирина принимает 8 числа?» — не анкета.
   */
  /**
   * ФИО целиком — персональные данные и без возраста.
   *
   * «Магомедова Гульбара Халитовна» числа не содержит, и правило её
   * пропускало: имя, отчество и фамилия принимались и уходили администратору
   * без согласия на обработку. Три слова подряд с заглавной буквы — это ФИО, и
   * ничего другого в переписке с клиникой так не пишут.
   */
  if (fullName(t, staffWords)) return true;

  const hasName =
    twoNames(t, staffWords) ||
    // «Ислам 8 лет» — имя и возраст рядом, фамилия могла остаться выше.
    /*
     * Без флага `i` намеренно: с ним `\p{Lu}` в JavaScript совпадает и со
     * строчными буквами (регистронезависимое сопоставление складывает
     * регистры), и «ему 8 лет» проходило как имя с возрастом.
     */
    nameWithAge(t, staffWords);
  if (!hasName) return false;

  // Возраст или вес: число рядом со словом или просто отдельным числом.
  const hasNumber = /(?<!\p{L})\d{1,3}(?!\p{L})/u.test(t);
  return hasNumber;
}

/**
 * Ответ на НАШУ просьбу прислать данные — анкета, чьи бы имена в нём ни стояли.
 *
 * Живой диалог 6 октября: агент попросил «ФИО ребёнка, возраст, имя родителя»,
 * мама прислала «Баринова Сафия 7 лет Саида» — и получила «Хорошо» и ту же
 * просьбу заново. По одним словам анкета узнаётся с оговоркой: имена,
 * совпадающие с именами сотрудников, в счёт не идут (иначе выбор врача
 * «Разият Резванова» сходил за ФИО), а у сотрудников клиники бывают те же
 * имена, что у пациентов. Здесь есть то, чего нет в словах: мы сами только что
 * попросили данные. Имя и возраст в ответе — данные; без возраста — два имени,
 * не совпадающих с сотрудниками. Вопрос в сообщении правило снимает: «а к
 * Разият можно, ей 7 лет?» — это не анкета.
 */
const NOT_A_NAME_IN_ANSWER =
  /^(?:ему|ей|мне|нам|им|его|её|ее|их|она|он|они|мы|вы|это|эта|этот|там|тут|да|нет|хорошо|спасибо|сейчас|уже|пока|только|для|вот|так|как|где|что|чтобы|если|или|тоже|ещё|еще|все|всё|мой|моя|моё|мое|мою|моему|моей|моих|наш|наша|наше|нашей|нашему|наших|хочу|хотим|хотела|хотели|можно|нужно|надо|запиш\p{L}*|записат\p{L}*|здравствуйте|добрый|доброе|привет|сегодня|завтра|утром|вечером|ок|окей|ладно|понятно|поняла|понял|сын\p{L}*|доч\p{L}*|ребен\p{L}*|ребён\p{L}*|мальчик\p{L}*|девочк\p{L}*|малыш\p{L}*|мам\p{L}*|пап\p{L}*|бабушк\p{L}*|дедушк\p{L}*|внук\p{L}*|внучк\p{L}*|племян\p{L}*|муж\p{L}*|жен\p{L}*|брат\p{L}*|сестр\p{L}*|возраст\p{L}*|вес\p{L}*|рост\p{L}*|жалоб\p{L}*|причин\p{L}*)$/iu;
const AGE_IN_ANSWER = /(?<![\p{L}\d])\d{1,2}(?:[.,]\d)?\s*(?:лет|год\p{L}*|мес\p{L}*|г\.)(?!\p{L})/iu;

export function answersDataRequest(text: string, lastAgent: string, staffNames: string[] = []): boolean {
  /**
   * Только настоящая просьба о ДАННЫХ (ФИО, возраст), а не «для кого приём»:
   * на вопрос «к кому и для кого?» ответ «Ребенку 3 года к Ирине» — выбор, а не
   * анкета (прогон 8 октября: вместо цены ушёл один запрос согласия).
   */
  if (!lastAgent || !asksForPersonalData(lastAgent)) return false;
  const t = text.trim();
  if (t.length < 8 || /\?/.test(t)) return false;
  const staffWords = staffWordsOf(staffNames);
  // «Ему 6 лет», «Сыну 7 лет», «Мама Зарема» — первое слово с заглавной не имя.
  const names = (t.match(/\p{Lu}\p{Ll}{2,}/gu) ?? []).filter(
    (w) => !NOT_A_NAME.has(w.toLowerCase().replace(/ё/g, "е")) && !NOT_A_NAME_IN_ANSWER.test(w),
  );
  const patientNames = names.filter((w) => !isStaffWord(w, staffWords));
  if (AGE_IN_ANSWER.test(t)) return patientNames.length >= 1;
  return patientNames.length >= 2;
}

/**
 * Агент только что спросил данные для записи?
 *
 * Нужно, чтобы не отфутболить собственный вопрос. Живой случай: агент спросил
 * «для взрослого или ребёнка, и с какой жалобой», пациентка ответила «взрослая
 * женщина, головная боль» — и получила «этот вопрос лучше уточнить у
 * специалиста». Слово «боль» есть, значит медицина; то, что жалобу запросил он
 * сам минуту назад, никто не проверял. Человек выполнил просьбу и был послан
 * по кругу.
 *
 * Смотрим на последнюю реплику агента: если он спрашивал, для кого приём, с
 * какой жалобой или просил данные — следующий ответ пациента относится к
 * записи, а не является медицинским вопросом.
 */
const INTAKE_QUESTIONS = [
  /жалоб/i,
  /для\s+кого/i,
  /взросл\p{L}*\s+или\s+(?:ребён|ребен)/iu,
  /(?:ребён|ребен)\p{L}*\s+или\s+взросл/iu,
  /(?:пришлите|напишите|укажите|попрошу|нужны|дайте|предоставьте|оставьте|направьте|продиктуйте)\p{L}*[^.!?\n]{0,40}(?:данн|фио|имя|возраст|вес)/iu,
  /сколько\s+лет/i,
  /как\s+вас\s+зовут|как\s+к\s+вам\s+обращаться/i,
];

/**
 * Просим ли мы персональные данные.
 *
 * По §7 и по инструкции клиники согласие берётся ПЕРЕД запросом таких данных,
 * а не при первом «здравствуйте». «Для взрослого или ребёнка?» под это не
 * подпадает: возрастная группа услуги — не персональные данные, и спрашивать
 * её можно свободно. ФИО, дата рождения, возраст, город и жалобы — подпадают.
 */
const PERSONAL_DATA_REQUEST = [
  /**
   * Глаголов просьбы больше, чем кажется: «Для записи ДАЙТЕ, пожалуйста, одним
   * сообщением: ФИО, возраст…» (прогон 4 октября) прошло до согласия, потому
   * что «дайте» в списке не было.
   */
  /(?:пришлите|напишите|укажите|отправьте|попрошу|нужны|подскажите|скажите|сообщите|дайте|предоставьте|оставьте|направьте|присылайте|продиктуйте)[^.!?\n]{0,80}(?:фио|ф\.и\.о|имя|фамили\p{L}*|дат\p{L}*\s+рождения|возраст|город|жалоб\p{L}*|причин\p{L}*\s+обращения)/iu,
  /**
   * Спросить данные можно и без глагола «пришлите».
   *
   * «Как вас зовут?», «Сколько вам лет?», «Ваше ФИО?» — те же персональные
   * данные, и до согласия их спрашивать нельзя. Правило ловило только просьбу
   * с глаголом, и половина формулировок модели проходила мимо.
   */
  /(?:как\s+вас\s+зовут|как\s+к\s+вам\s+обраща\p{L}*|ваше\s+имя|ваши\s+фио|ваше\s+фио|ваша\s+фамили\p{L}*)/iu,
  /**
   * Точный возраст — персональные данные, возрастная ГРУППА — нет.
   *
   * «Для взрослого или для ребёнка?» агент спрашивает свободно: без этого он
   * не назовёт правильную цену. «Сколько лет ребёнку?» — уже шаг 4 инструкции
   * клиники, он идёт после согласия.
   */
  /**
   * Кого спрашивают, человек называет по-разному: «сколько лет девочке?»,
   * «мальчику сколько?», «внучке сколько лет?». Список был короче, и возраст
   * ребёнка спрашивался до согласия — а это персональные данные (§7).
   */
  /(?:сколько\s+(?:лет\s+)?(?:вам|ему|ей|реб[её]нку|сыну|дочери|дочке|девочке|мальчику|внуку|внучке|малышу|племянник\p{L}*)|(?:вам|ему|ей|реб[её]нку|сыну|дочери|дочке|девочке|мальчику|внуку|внучке|малышу|племянник\p{L}*)\s+сколько|дат\p{L}*\s+рождения|полных\s+лет)/iu,
  /(?:представьтесь|назовите\s+(?:себя|имя|фио|возраст))/iu,
  /**
   * Вес — тоже персональные данные, и его спрашивают на остеопатии.
   *
   * «Также нужен вес ребёнка» уходило ДО согласия: в списке стояли ФИО, возраст
   * и город, а веса не было. Границы слова через отсутствие соседней буквы:
   * `\b` рядом с кириллицей в JavaScript не работает (§6).
   */
  /(?:нужен|нужно|пришлите|напишите|укажите|скажите|сообщите|назовите)[^.!?\n]{0,30}(?<!\p{L})вес(?!\p{L})/iu,
  // «Жду ваши данные», «нужны ваши данные» — та же просьба другими словами.
  /(?:жду|нужны|пришлите|отправьте|напишите|скажите|сообщите|укажите|назовите)\s+(?:ваши\s+|свои\s+|мне\s+)?данн\p{L}*/iu,
  /**
   * «Нам понадобятся ваши персональные данные» — та же просьба безличным
   * оборотом. Глагола-приказа в ней нет, и список выше её пропускал: модель
   * объявляла о сборе данных до согласия, и предложение доезжало до пациента.
   */
  /(?:понадоб\p{L}*|потребу\p{L}*)\s+(?:\p{L}+\s+){0,3}данн\p{L}*/iu,
];

export function asksForPersonalData(text: string): boolean {
  return text
    .split(/(?<=[.!?\n])/)
    .some((sentence) => PERSONAL_DATA_REQUEST.some((re) => re.test(sentence)));
}

/**
 * Ответ без просьбы прислать данные.
 *
 * Убираем ровно те предложения, где мы их просим, — остальное (услуга, цена,
 * длительность) человеку полезно и остаётся. Так порядок из инструкции клиники
 * соблюдается сам собой: сначала ответ по услуге, потом согласие, и только
 * потом данные.
 */
export function withoutPersonalDataRequest(text: string): string {
  return text
    .split(/(?<=[.!?\n])/)
    .filter((sentence) => !PERSONAL_DATA_REQUEST.some((re) => re.test(sentence)))
    .join("")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}

/**
 * Агент ещё ВЫБИРАЕТ услугу или врача — данных он пока не просит.
 *
 * Живой случай, из-за которого правило появилось. «Хотела девочку записать к
 * остеопату» — и в ответ: «Подскажите, к какому врачу хотите — к Ирине
 * Алилгаджиевне или к Разият Ризвановне? Прежде чем продолжить: нам нужно
 * ваше согласие на обработку персональных данных». Человека спрашивают, к
 * кому он идёт, и тут же требуют юридического согласия, которое по порядку
 * клиники берётся двумя шагами позже — перед ФИО и возрастом.
 *
 * Получалось это само: мы дописывали к ответу просьбу прислать данные, она
 * поднимала запрос согласия, а потом сама же вырезалась как преждевременная —
 * и до пациента доезжало согласие без единой просьбы о данных.
 *
 * Поэтому вопрос «на какую услугу» и «к какому врачу» опознаётся отдельно:
 * пока звучит он, шаг с данными ещё не наступил (§7, порядок клиники —
 * услуга и цена, потом согласие, потом данные).
 */
const CHOICE_QUESTIONS = [
  /на\s+как(?:ую|ой|ие)\s+(?:услуг|приём|прием|процедур|специалист)/iu,
  /к\s+как(?:ому|ой)\s+(?:врач|специалист|доктор|остеопат|из)/iu,
  /как(?:ая|ую|ой)\s+(?:именно\s+)?услуг/iu,
  /к\s+кому\s+(?:из|вы|хотите|бы|записыва)/iu,
  /**
   * «Для взрослого или ДЛЯ ребёнка?» — предлог между половинами обычен, и не
   * только предлог: «вы хотите записаться на взрослый ПРИЁМ или это для
   * ребёнка?» — тот же вопрос, а правило его не видело, и человек получал
   * согласие на шаге выбора.
   */
  /(?:взросл\p{L}*(?:\s+\p{L}+){0,2}\s+или\s+(?:это\s+)?(?:для\s+)?(?:ребён|ребен)|(?:ребён|ребен)\p{L}*(?:\s+\p{L}+){0,2}\s+или\s+(?:это\s+)?(?:для\s+)?взросл)/iu,
  /для\s+кого\s+(?:приём|прием|запис|услуг)/iu,
  /кого\s+(?:записыва|будем\s+записыва)/iu,
];

/**
 * Спрашивают именно «для кого» — взрослый или ребёнок.
 *
 * Отдельно от остального выбора: пока это неизвестно, цену нельзя называть
 * только взрослую. Живой ответ: «это запись для взрослого или для ребёнка?» и
 * следом три взрослые цены — человек читает вопрос и уже видит ответ не на
 * него.
 */
export function asksWhom(text: string): boolean {
  /**
   * Тот же вопрос модель задаёт по-разному: «взрослый или для ребёнка?», «вы
   * хотите записаться сами или записываете ребёнка?», «для себя или для
   * ребёнка?». Пока список был короче, догадка «взрослый» считалась ответом, и
   * рядом с вопросом стояла одна взрослая цена.
   */
  return [
    /взросл\p{L}*(?:\s+\p{L}+){0,2}\s+или\s+(?:это\s+)?(?:для\s+)?(?:ребён|ребен)/iu,
    /(?:ребён|ребен)\p{L}*(?:\s+\p{L}+){0,2}\s+или\s+(?:это\s+)?(?:для\s+)?взросл/iu,
    /для\s+кого\s+(?:приём|прием|запис|услуг)/iu,
    /(?:сами|себя|себе)(?:\s+\p{L}+){0,3}\s+или(?:\s+\p{L}+){0,3}\s+(?:ребён|ребен|сын|доч|мальчик|девочк)/iu,
    /(?:ребён|ребен|сын|доч)\p{L}*(?:\s+\p{L}+){0,3}\s+или(?:\s+\p{L}+){0,3}\s+(?:сами|себя|себе)/iu,
    // «Это для вас или для ребёнка?» (прогон 5 октября) — «вас» вместо «себя».
    /(?<!\p{L})(?:для\s+)?вас(?:\s+\p{L}+){0,2}\s+или\s+(?:для\s+)?(?:ребён|ребен|сын|доч|мальчик|девочк)/iu,
  ].some((re) => re.test(text));
}

/** Спрашивают, на какую услугу. */
export function asksService(text: string): boolean {
  return /(?:на\s+как(?:ую|ой|ие)\s+(?:услуг|приём|прием|процедур)|как(?:ая|ую|ой)\s+(?:именно\s+)?услуг|что\s+вас\s+интересует)/iu.test(
    text,
  );
}

/**
 * Спрашивают про врача — или обещают подобрать его сами.
 *
 * Второе тоже считается: «уточню у администратора, какой врач сможет принять» —
 * значит шаг уже закрыт, и наш вопрос «к кому хотите записаться?» рядом с ним
 * читается как два разных плана в одном сообщении.
 */
export function asksDoctor(text: string): boolean {
  return /(?:к\s+как(?:ому|ой)\s+(?:врач|специалист|доктор|остеопат|из)|к\s+кому\s+(?:из|вы|хотите|бы|записыва)|какой\s+врач|кто\s+(?:вас\s+)?примет|врача\s+(?:подбер|уточн)|подбер[её]м\s+врача)/iu.test(
    text,
  );
}

export function asksToChoose(text: string): boolean {
  return text
    .split(/(?<=[.!?\n])/)
    .some((sentence) => CHOICE_QUESTIONS.some((re) => re.test(sentence)));
}

export function asksForIntake(text: string): boolean {
  return INTAKE_QUESTIONS.some((re) => re.test(text));
}

/** Идёт ли сейчас оформление записи: последнее слово было за вопросом агента. */
export function inIntakeFlow(history: { role: "user" | "assistant"; content: string }[]): boolean {
  for (let i = history.length - 1; i >= 0; i -= 1) {
    if (history[i].role !== "assistant") continue;
    return asksForIntake(history[i].content);
  }
  return false;
}

/**
 * ФИО из присланной анкеты.
 *
 * Пациент представился полным именем, а через две реплики на вопрос «как меня
 * зовут?» услышал «вы его не называли». Имя было в переписке, но до модели не
 * доходило: в промпт уходят последние реплики, и всё, что дальше, для агента
 * не существует. Поэтому имя вынимаем из анкеты и держим отдельно — в карточке
 * пациента, а не в глубине переписки.
 *
 * Берём подряд идущие слова с заглавной буквы в начале строки: именно так люди
 * и пишут — «Магомедова Гульбара Халитовна 23 года 61 кг».
 */
export function nameFromIntake(text: string): string | null {
  const match = text
    .trim()
    .match(/^(\p{Lu}\p{Ll}+(?:\s+\p{Lu}\p{Ll}+){1,2})/u);
  return match ? match[1] : null;
}

/**
 * Есть ли в сообщении вопрос помимо данных.
 *
 * Пациент прислал анкету и тут же спросил: «извиняюсь, а у вас же город тоже
 * Махачкала?» — и получил только «спасибо, записал(а)». Вопрос остался без
 * ответа: сообщение целиком считалось анкетой, а на анкету у нас готовая
 * фраза.
 */
export function hasQuestion(text: string): boolean {
  return /\?/.test(text);
}
