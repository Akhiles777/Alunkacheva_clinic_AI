import { describe, expect, it } from "vitest";
import { hasQuote, quoteOfKind, quoteOfText, withoutQuote } from "./quoted";

/**
 * Цитата принадлежит собеседнику, а не пациенту.
 *
 * Из-за того, что правила читали её вместе со словами пациента, стоп-слово
 * «окошко» из сообщения САМОЙ клиники обрывало просьбу записать ребёнка.
 */
describe("withoutQuote", () => {
  it("снимает цитату с текстом", () => {
    const body = `${quoteOfText("Окошко на завтра к Ирине Алилгаджиевне ✅ 09:40 (детский)")}\nЗапишите пожалуйста племянника моего`;
    expect(withoutQuote(body)).toBe("Запишите пожалуйста племянника моего");
  });

  it("снимает цитату без текста — фото и голосовое", () => {
    expect(withoutQuote(`${quoteOfKind("фото")}\nчто скажете?`)).toBe("что скажете?");
    expect(withoutQuote(`${quoteOfKind(null)}\nда`)).toBe("да");
  });

  it("снимает многострочную цитату целиком", () => {
    const body = `${quoteOfText("Вы записаны на услугу\nДетский прием до 10 л\nна 8 сентября в 09:00")}\nМожете перенести нашу запись`;
    expect(withoutQuote(body)).toBe("Можете перенести нашу запись");
  });

  it("обрезает длинную цитату, но снимается она так же", () => {
    const long = "а".repeat(400);
    const body = `${quoteOfText(long)}\nсколько стоит?`;
    expect(withoutQuote(body)).toBe("сколько стоит?");
  });

  it("обычное сообщение не трогает", () => {
    expect(withoutQuote("Здравствуйте, сколько стоит остеопатия?")).toBe(
      "Здравствуйте, сколько стоит остеопатия?",
    );
  });

  it("сообщение из одной цитаты оставляет как есть: другого текста нет", () => {
    const body = quoteOfText("Вы записаны на 8 сентября");
    expect(withoutQuote(body)).toBe(body);
  });

  it("текст, начинающийся похоже, но не цитата", () => {
    expect(withoutQuote("В ответ на ваше сообщение хочу сказать спасибо")).toBe(
      "В ответ на ваше сообщение хочу сказать спасибо",
    );
  });

  it("узнаёт цитату", () => {
    expect(hasQuote(`${quoteOfText("привет")}\nда`)).toBe(true);
    expect(hasQuote("Здравствуйте")).toBe(false);
  });
});
