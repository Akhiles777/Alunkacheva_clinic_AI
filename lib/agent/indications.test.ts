import { describe, expect, it } from "vitest";
import { inventedIndication } from "./indications";

/** Справка клиники: названия, цены, длительность — и ни слова о показаниях. */
const REFERENCE = [
  "Услуги и цены:",
  '• Инфузия "Био-Ресурс" — 1000 ₽, 40 мин',
  '• Инфузия "Абсолютный ресурс" — 9000 ₽, 60 мин',
  '• Инфузия "Ферро-Баланс" (Энергия крови) — 5500 ₽, 60 мин',
  "• БОС-терапия — 2800 ₽, 40 мин",
  "Адрес: Махачкала, улица Ленина, 1.",
].join("\n");

describe("придуманное показание", () => {
  it("ловит связку услуги с состоянием, которого нет в справке", () => {
    const answer =
      "При постоянной усталости часто подбирают инфузию «Био-Ресурс» — она стоит 1000 ₽.";
    expect(inventedIndication(answer, REFERENCE)).not.toBeNull();
  });

  it("ловит «капельница от усталости — это …»", () => {
    expect(
      inventedIndication("Капельница от усталости — это инфузия «Био-Ресурс», 1000 ₽.", REFERENCE),
    ).not.toBeNull();
  });

  it("ловит обещание помочь при бессоннице", () => {
    expect(
      inventedIndication("БОС-терапия помогает при бессоннице и стрессе.", REFERENCE),
    ).not.toBeNull();
  });

  it("пропускает то, что написано в справке", () => {
    const ref = `${REFERENCE}\nБОС-терапия помогает при бессоннице — так написала клиника.`;
    expect(inventedIndication("БОС-терапия помогает при бессоннице.", ref)).toBeNull();
  });

  it("слово из названия услуги показанием не считает", () => {
    expect(
      inventedIndication('Инфузия "Ферро-Баланс" — для энергии крови, 5500 ₽.', REFERENCE),
    ).toBeNull();
  });

  it("обычный ответ про цену и адрес не трогает", () => {
    for (const a of [
      "Взрослый приём — 8000 ₽, 45 минут.",
      "Мы находимся в Махачкале, улица Ленина, 1, второй этаж.",
      "Работаем с понедельника по субботу с 09:00 до 21:00.",
      "Для записи напишите ФИО, возраст и кратко причину обращения.",
    ]) {
      expect(inventedIndication(a, REFERENCE), a).toBeNull();
    }
  });

  it("пересказ анкеты назначением не считает", () => {
    expect(
      inventedIndication("Спасибо, записал(а): боли в пояснице, онемение тела.", REFERENCE),
    ).toBeNull();
  });

  it("отказ отвечать назначением не считает", () => {
    expect(
      inventedIndication(
        "Что именно вам подойдёт, скажет специалист на приёме — передал(а) администратору.",
        REFERENCE,
      ),
    ).toBeNull();
  });
});
