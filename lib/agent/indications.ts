/**
 * Придуманное показание — самая опасная выдумка ассистента.
 *
 * Живой прогон. Пациентка: «Постоянная усталость, ничего не помогает. Слышала,
 * у вас капельницы есть». Ассистент: «При постоянной усталости часто подбирают
 * инфузию „Био-Ресурс“ — 1000 ₽». Дальше: «Капельница от усталости — это
 * инфузия „Био-Ресурс“».
 *
 * В справке клиники нет ни слова о том, при чём какая инфузия. Модель
 * сопоставила усталость с названием «Ресурс» и фактически назначила лечение.
 * Человек придёт и попросит именно эту капельницу — со ссылкой на клинику.
 *
 * Просьбами в промпте это не лечится: правило «что услуга лечит — только
 * дословно из справки» там стоит, и модель его нарушила. Поэтому проверяем
 * готовый ответ так же, как проверяем числа (lib/agent/grounding): состояние,
 * связанное с услугой, обязано стоять в справке клиники. Нет — ответ не
 * отправляем, зовём человека.
 *
 * Слова пациента справкой НЕ считаются намеренно. То, что человек назвал свою
 * усталость, не даёт клинике права утверждать, при чём помогает её капельница.
 */

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е");

/**
 * Состояния и жалобы — то, ради чего человек приходит в клинику.
 *
 * Список намеренно широкий: лишняя передача администратору стоит минуты, а
 * пропущенное показание — здоровья пациента и репутации клиники (§6).
 */
const CONDITIONS = [
  "усталост", "устаете", "устаешь", "слабост", "упадок сил", "нет сил",
  "бессонниц", "не спите", "плохо спите", "сонливост",
  "стресс", "тревог", "депресс", "паническ", "нервн", "выгоран",
  // «безболезнен» отдельной строкой: поиск идёт по НАЧАЛУ слова, и приставка
  // «без-» делает его другим словом. Морфологию тут разводить незачем.
  "мигрен", "головн", "боль", "боли", "болев", "болезнен", "безболезнен",
  "спазм", "неприятн",
  "давлен", "гипертон", "гипотон", "аритм",
  "иммунит", "детокс", "интоксикац", "токсин", "похмел",
  "похуд", "лишний вес", "метаболизм", "обмен веществ",
  "аллерг", "астм", "дыхан",
  "печен", "гепат", "почк", "желудк", "кишечник",
  "анеми", "гемоглобин", "железодефицит",
  "выносливост", "памят", "концентрац", "внимани", "речь",
  "отек", "воспален", "простуд", "вирус", "инфекц",
  "гормон", "климакс", "щитовидн", "беременност",
  "кожа", "волос", "ногт",
  "гиперактивн", "дцп", "аутизм", "заикан", "энурез", "сколиоз",
];

/**
 * Слова, которыми ответ связывает услугу с состоянием. Без такой связки
 * упоминание жалобы безобидно: «спасибо, записал(а): боли в пояснице» —
 * это пересказ анкеты, а не назначение.
 */
const LINKS =
  /(?<!\p{L})(?:при|от|для|помога\p{L}*|подход\p{L}*|подойд\p{L}*|подбира\p{L}*|подберут|назнача\p{L}*|рекоменду\p{L}*|показан\p{L}*|применяют|используют|эффективн\p{L}*|улучша\p{L}*|восстанавлива\p{L}*|вызыва\p{L}*|ощуща\p{L}*|переносит\p{L}*|безболезнен\p{L}*|снима\p{L}*|устраня\p{L}*)(?!\p{L})/giu;

/** Сколько знаков после связки считаем одной мыслью. */
const WINDOW = 70;

/**
 * Связал ли ответ услугу с состоянием, которого нет в справке.
 *
 * Возвращает саму фразу — её видно в журнале, и по ней сразу понятно, что
 * именно модель придумала. null — придуманных показаний нет.
 */
/**
 * Слова текста — для поиска состояния по НАЧАЛУ слова, а не по подстроке.
 *
 * Подстрока обманывает молча и обидно: «Инфузия „Мета-Контур“
 * (Турбо-метаболизм)» содержит «боли» внутри слова «метаболизм», и справка
 * считалась подтверждающей утверждение «остеопатия не вызывает боли». Проверка
 * молча пропускала придуманное — то есть выглядела работающей и не работала.
 */
function wordsOf(text: string): string[] {
  return text.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
}

/** Есть ли среди слов такое, что начинается с этой основы. */
function hasStem(words: string[], stem: string): boolean {
  return words.some((w) => w.startsWith(stem));
}

export function inventedIndication(answer: string, reference: string): string | null {
  const text = norm(answer);
  const refWords = wordsOf(norm(reference));

  for (const m of text.matchAll(LINKS)) {
    const at = m.index ?? 0;
    const window = text.slice(at, at + WINDOW);
    const windowWords = wordsOf(window);
    for (const c of CONDITIONS) {
      /**
       * Состояние из нескольких слов («упадок сил», «лишний вес») ищем как
       * есть: у него нет одной основы.
       */
      const inWindow = c.includes(" ") ? window.includes(c) : hasStem(windowWords, c);
      if (!inWindow) continue;
      const inRef = c.includes(" ") ? norm(reference).includes(c) : hasStem(refWords, c);
      if (!inRef) return window.trim();
    }
  }
  return null;
}
