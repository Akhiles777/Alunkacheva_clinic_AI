/**
 * Когда диалог просится в «Нужен ответ» — правило заказчика.
 *
 * Метка означает новое обращение, а не любое неотвеченное сообщение. Иначе она
 * висит на каждом «спасибо» после разговора, список наполняется тем, что
 * ответа не требует, и администратор перестаёт в него смотреть.
 *
 * Обращением считаем два случая: совсем новый диалог, где мы ещё ни разу не
 * отвечали, и сообщение, пришедшее больше чем через сутки после предыдущего.
 * Ровно так же в §8 считается граница обращения для метрик — одно правило на
 * экран и на отчёт.
 *
 * Отдельным файлом, потому что здесь легко ошибиться на ровном месте:
 * промежуток надо мерить у ПЕРВОГО неотвеченного сообщения, а не у последнего.
 * Пока мерили у последнего, пациент, написавший «Здравствуйте», а через минуту
 * «хочу записаться», метку терял — вторым сообщением он сам её и снимал.
 */

/** Граница нового обращения — те же сутки, что в §8. */
export const NEW_INQUIRY_MS = 24 * 60 * 60 * 1000;

export interface InboxMessage {
  direction: "IN" | "OUT";
  createdAt: Date;
}

/**
 * Ждёт ли диалог ответа как новое обращение.
 *
 * Сообщения — по возрастанию времени. Прочитанность и статус диалога решаются
 * снаружи: здесь только про то, обращение это или продолжение разговора.
 */
export function isNewInquiryWaiting(messages: InboxMessage[]): boolean {
  const last = messages[messages.length - 1];
  if (!last || last.direction !== "IN") return false;

  // Начало непрерывной череды входящих: с него и начался разговор, на который
  // мы ещё не ответили.
  let runStart = messages.length - 1;
  while (runStart > 0 && messages[runStart - 1].direction === "IN") runStart -= 1;

  // Мы не отвечали ни разу — это обращение по определению.
  if (runStart === 0) return true;

  const first = messages[runStart];
  const before = messages[runStart - 1];
  return first.createdAt.getTime() - before.createdAt.getTime() >= NEW_INQUIRY_MS;
}
