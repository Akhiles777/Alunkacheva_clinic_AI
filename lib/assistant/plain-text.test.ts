import { describe, expect, it } from "vitest";
import { toPlainText } from "./plain-text";

describe("ответ без разметки", () => {
  it("снимает жирный, оставляя числа", () => {
    expect(toPlainText("провела **39 визитов** и принесла **194 285 ₽**")).toBe(
      "провела 39 визитов и принесла 194 285 ₽",
    );
  });

  it("снимает курсив и подчёркивание", () => {
    expect(toPlainText("это _важно_ и *срочно*")).toBe("это важно и срочно");
  });

  it("не трогает звёздочку внутри слова и умножение", () => {
    expect(toPlainText("2 * 3 = 6")).toBe("2 * 3 = 6");
  });

  it("заголовки превращает в строки текста", () => {
    expect(toPlainText("## Итог\nвыручка 20 500 ₽")).toBe("Итог\nвыручка 20 500 ₽");
  });

  it("маркеры списка заменяет на тире, а нумерацию не трогает", () => {
    expect(toPlainText("- первый\n- второй")).toBe("— первый\n— второй");
    expect(toPlainText("1. первый\n2. второй")).toBe("1. первый\n2. второй");
  });

  it("снимает обратные кавычки", () => {
    expect(toPlainText("услуга `КОНТРОЛЬ` стоит 3 000 ₽")).toBe("услуга КОНТРОЛЬ стоит 3 000 ₽");
  });

  it("обычный текст оставляет как есть", () => {
    const text = "Сегодня пришли 5 человек, из них первичных 2.";
    expect(toPlainText(text)).toBe(text);
  });
});
