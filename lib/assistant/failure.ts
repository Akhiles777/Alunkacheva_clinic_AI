/**
 * Почему разбора нет — словами и по делу.
 *
 * Здесь стояла подмена: не ответила модель — отвечал локальный движок по
 * правилам. Владелец спрашивал «как повысить выручку» и получал сводку по
 * случайному пациенту, а следом «скоро подключим полноценный ИИ». Уверенный
 * ответ не на заданный вопрос хуже молчания: по нему нельзя понять, что
 * разбора не было вовсе.
 *
 * Причина называется конкретно: ключ не задан, провайдер отказал и долгий
 * разбор не уложился в срок требуют разных действий от разных людей.
 */
export function aiFailureText(error?: string): string {
  if (error === "not_configured") {
    return "Ассистент не настроен: на сервере не задан ключ ИИ. Это настройка, а не сбой — передайте разработчику.";
  }
  if (error === "http_401" || error === "http_403") {
    return "Провайдер ИИ отклонил ключ. Ответ не получен — передайте разработчику.";
  }
  if (error === "http_429") {
    return "Провайдер ИИ ограничил частоту запросов. Повторите вопрос через минуту.";
  }
  if (error === "AbortError" || error === "TimeoutError") {
    return "Ответ не уложился в 40 секунд и был прерван. Повторите вопрос.";
  }
  return `Ответ не получен: ${error ?? "причина неизвестна"}. Повторите вопрос; если повторяется — передайте разработчику.`;
}
