const BY_ROLE: Record<Role, string[]> = {
  OWNER: OWNER,
  MANAGER: MANAGER,
  ADMIN: ADMIN,
  DOCTOR: DOCTOR,
};

/**
 * Промпт для роли. canSeeRevenue — право VIEW_REVENUE: без него ассистент не
 * должен называть суммы, даже если они случайно попали в выжимку. Права
 * проверяются и на данных, но модель не должна зависеть от того, что кто-то
 * не забыл их отфильтровать.
 */
export function personaFor(role: Role, canSeeRevenue: boolean): string {
  const parts = [...(BY_ROLE[role] ?? ADMIN), ...COMMON];
  if (!canSeeRevenue) {
    parts.push(
      "Суммы, выручку и средний чек не называй и не обсуждай: у этого сотрудника нет такого доступа.",
    );
  }
  return parts.join(" ");
}
