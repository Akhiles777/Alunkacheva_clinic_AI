/**
 * Ответ ассистента — обычный текст, без разметки.
 *
 * Модель по привычке выделяет числа звёздочками: «провела **39 визитов**».
 * В нашем окне разметка не рисуется, и владелец видит сами звёздочки — они
 * читаются как мусор и мешают счёту. Просить модель в промпте недостаточно:
 * она соблюдает это через раз, а ответ уходит человеку каждый раз.
 *
 * Поэтому снимаем разметку на выходе. Это именно снятие оформления, а не
 * правка текста: слова и числа остаются как есть.
 */

/** Убрать markdown-оформление, оставив текст. */
export function toPlainText(raw: string): string {
  let out = raw;

  // Жирный и курсив: **слово**, __слово__, *слово*, _слово_.
  out = out.replace(/\*\*([^*]+)\*\*/g, "$1");
  out = out.replace(/__([^_]+)__/g, "$1");
  out = out.replace(/(^|[^\p{L}\p{N}*])\*([^*\n]+)\*(?=[^\p{L}\p{N}*]|$)/gu, "$1$2");
  out = out.replace(/(^|[^\p{L}\p{N}_])_([^_\n]+)_(?=[^\p{L}\p{N}_]|$)/gu, "$1$2");

  // Заголовки «## Итог» и цитаты — от них остаётся только текст.
  out = out.replace(/^\s{0,3}#{1,6}\s+/gm, "");
  out = out.replace(/^\s{0,3}>\s?/gm, "");

  /**
   * Маркеры списка заменяем на «— »: перечисление у аналитика бывает по делу,
   * и стирать его целиком значит слепить строки в кашу. Нумерованный список
   * не трогаем: «1.» это часть текста, а не оформление.
   */
  out = out.replace(/^(\s*)[*+-]\s+/gm, "$1— ");

  // Код и разделители: обратные кавычки и линии из дефисов.
  out = out.replace(/```+/g, "").replace(/`([^`]+)`/g, "$1");
  out = out.replace(/^\s*([-*_]\s?){3,}\s*$/gm, "");

  // Пустых строк подряд не больше одной — иначе после чистки остаются дыры.
  return out.replace(/\n{3,}/g, "\n\n").trim();
}
