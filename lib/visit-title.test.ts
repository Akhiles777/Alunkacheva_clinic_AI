import { describe, expect, it } from "vitest";
import { needsBreakdown, NO_SERVICE, visitTitle } from "./visit-title";

describe("название визита", () => {
  it("одна услуга — её название", () => {
    expect(visitTitle([{ title: "Взрослый прием - остеопатия" }], "что угодно")).toBe(
      "Взрослый прием - остеопатия",
    );
  });

  /**
   * Живой случай: мать записала себя и ребёнка одной записью. Название бралось
   * у первой услуги, сумма — за обе, и выходило «Взрослый приём, 13 000 ₽» при
   * цене приёма 8 000.
   */
  it("несколько услуг — все, через «+»", () => {
    expect(
      visitTitle(
        [{ title: "Взрослый прием - остеопатия" }, { title: "Детский прием до 10 л - остеопатия" }],
        "Взрослый прием - остеопатия",
      ),
    ).toBe("Взрослый прием - остеопатия + Детский прием до 10 л - остеопатия");
  });

  it("повтор одной услуги в названии не двоится", () => {
    expect(
      visitTitle([{ title: "Капельница" }, { title: "Капельница" }], "Капельница"),
    ).toBe("Капельница");
  });

  it("состава нет — остаётся основная услуга записи", () => {
    expect(visitTitle(undefined, "Сдача анализов")).toBe("Сдача анализов");
    expect(visitTitle([], "Сдача анализов")).toBe("Сдача анализов");
  });

  it("не осталось ничего — говорим это прямо, а не прочерком", () => {
    expect(visitTitle([], "")).toBe(NO_SERVICE);
    expect(visitTitle([{ title: "   " }], "  ")).toBe(NO_SERVICE);
  });
});

describe("расписывать ли состав", () => {
  it("одна услуга — незачем: она уже названа", () => {
    expect(needsBreakdown([{ title: "Капельница" }])).toBe(false);
    expect(needsBreakdown([{ title: "Капельница" }, { title: "Капельница" }])).toBe(false);
  });

  it("две разные — да: они объясняют сумму", () => {
    expect(needsBreakdown([{ title: "Взрослый" }, { title: "Детский" }])).toBe(true);
  });

  it("состава нет — расписывать нечего", () => {
    expect(needsBreakdown(undefined)).toBe(false);
  });
});
