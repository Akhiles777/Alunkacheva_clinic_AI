/**
 * Что удалять при сохранении списка.
 *
 * Разделы настроек сохраняются целиком: экран присылает список, сервер считает
 * удалённым всё, чего в нём нет. Пока редактор один, это работает. Но стоит
 * появиться второму источнику строк — выгрузке из YCLIENTS, второй вкладке,
 * коллеге за соседним компьютером — и сохранение со страницы, открытой раньше,
 * молча сносит всё, что появилось после её загрузки.
 *
 * Перед подключением YCLIENTS это уже не теория: импорт заводит услуги и
 * специалистов, и одно случайное сохранение из открытой вкладки удалило бы их
 * все.
 *
 * Поэтому удаляем только то, что человек действительно видел и убрал: строки,
 * которые были на экране при загрузке и не вернулись при сохранении. Всё
 * появившееся позже не трогаем — мы про него ничего не знаем.
 */
export function idsToDelete(input: {
  /** Что сейчас есть в базе. */
  existing: string[];
  /** Что прислал экран (без новых строк). */
  submitted: string[];
  /**
   * Что экран видел при загрузке. Не задано — работаем по-старому: удаляем всё
   * лишнее. Так ведут себя старые вкладки, которые про этот список не знают.
   */
  known?: string[] | null;
}): string[] {
  const submitted = new Set(input.submitted);
  const candidates = input.existing.filter((id) => !submitted.has(id));
  if (!input.known || input.known.length === 0) return candidates;

  const known = new Set(input.known);
  return candidates.filter((id) => known.has(id));
}
