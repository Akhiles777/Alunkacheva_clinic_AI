import { describe, expect, it } from "vitest";
import { numbersAreOurs, writtenForOwner } from "./weekly-digest";

describe("writtenForOwner", () => {
  const obs = ["новых пациентов 42, обычно 31", "визиты без отметки о посещении: 5, обычно 0"];

  it("сводка с числами наблюдений — годится", () => {
    const t = "Новых пациентов за неделю 42 — выше обычных 31. Визитов без отметки о посещении 5, обычно 0.";
    expect(writtenForOwner(t, obs)).toBe(true);
  });

  it("просьба к нам вместо сводки — брак (демо-прогон 12 октября)", () => {
    const t = "Пожалуйста, предоставьте остальные наблюдения с числами за неделю — пока дан только один пункт (5, обычно 0).";
    expect(writtenForOwner(t, obs)).toBe(false);
  });

  it("обращение на «ты» вместо сводки — брак", () => {
    expect(writtenForOwner("Поделись самими наблюдениями по неделе. Пока у меня есть только одна цифра (5, обычно 0).", obs)).toBe(false);
  });

  it("своя причина без нашей гипотезы — брак", () => {
    const t = "Новых пациентов 42, обычно 31. Возможно, это связано с сезонным фактором. Без отметки 5, обычно 0.";
    expect(writtenForOwner(t, obs, false)).toBe(false);
    expect(writtenForOwner(t, obs, true)).toBe(true);
  });

  it("«других наблюдений не предоставлено» — разговор с нами, а не сводка", () => {
    expect(writtenForOwner("Новых пациентов 42, обычно 31. Без отметки 5, обычно 0. Других наблюдений за эту неделю не предоставлено.", obs)).toBe(false);
  });

  it("вступление модели о себе — брак", () => {
    expect(writtenForOwner("Напишу абзац по этому единственному наблюдению, без добавления чисел. Без отметки 5, обычно 0. Новых 42, обычно 31.", obs)).toBe(false);
  });

  it("пропало наблюдение — брак", () => {
    expect(writtenForOwner("Новых пациентов 42 — выше обычных 31.", obs)).toBe(false);
  });

  it("чужое число по-прежнему ловит numbersAreOurs", () => {
    expect(numbersAreOurs("Выручка 300 100 ₽", ["Выручка 396 080 ₽"])).toBe(false);
  });
});
