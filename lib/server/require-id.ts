/**
 * Идентификатор из внешнего вызова — обязателен и непуст.
 *
 * В Prisma `where: { id: undefined }` не сужает выборку, а СНИМАЕТ условие:
 * `updateMany` с таким фильтром меняет все строки, до которых дотягивается
 * остальная часть условия. Опечатка или потерянный аргумент превращаются в
 * массовую правку без единой ошибки в журнале.
 *
 * Так и вышло: выключение агента в одном диалоге погасило его во всех.
 * Условие было написано верно — `{ id: conversationId, companyId }`, — но
 * стоило идентификатору не доехать, и от условия осталась одна клиника.
 *
 * Поэтому каждый идентификатор, пришедший снаружи, проходит через эту
 * проверку. Падение с внятным сообщением лучше молчаливой правки всего.
 */
export function requireId(value: unknown, what: string): string {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error(`Не передан ${what}: без него запрос затронул бы все записи клиники`);
  }
  return value;
}

/** То же для списка: пустой список фильтром тоже не является. */
export function requireIds(values: unknown, what: string): string[] {
  if (!Array.isArray(values) || values.length === 0) {
    throw new Error(`Не передан ${what}: пустой список затронул бы все записи клиники`);
  }
  return values.map((v, i) => requireId(v, `${what}[${i}]`));
}
