/**
 * Работа после ответа вебхуку.
 *
 * Мессенджер ждёт ответа считанные секунды, а разговор с моделью занимает
 * секунды же — иногда больше. Пока обработка шла внутри запроса, случалось
 * худшее из возможного: провайдер не дожидался, обрывал соединение и присылал
 * сообщение заново, а у нас оно уже было сохранено — повторная доставка
 * отбрасывалась как дубль. Сообщение пациента лежало в переписке без ответа, и
 * человеку приходилось писать второй и третий раз, чтобы получить хоть что-то.
 *
 * Поэтому вебхуку отвечаем сразу, а разговор ведём после ответа. Своё
 * приложение под pm2 живёт постоянно — процесс никуда не денется, в отличие от
 * бессерверного хостинга, где такой приём не работает.
 *
 * Второе назначение — очередь по собеседнику. Два сообщения подряд («хочу
 * записаться», «взрослому») раньше обрабатывались одновременно: оба видели
 * одинаковую историю, оба здоровались, оба спрашивали одно и то же. Теперь
 * задачи одного чата идут строго по очереди.
 */

/** Хвост очереди для каждого собеседника. */
const chains = new Map<string, Promise<unknown>>();

/**
 * Задачи, которые сейчас выполняются. Ссылка нужна, чтобы сборщик мусора не
 * забрал незавершённое обещание, на которое никто не смотрит.
 */
const running = new Set<Promise<unknown>>();

export function runSerial(key: string, task: () => Promise<void>): void {
  const previous = chains.get(key) ?? Promise.resolve();

  const next = previous
    .catch(() => undefined)
    .then(task)
    .catch((e) => {
      // Тело сообщения в журнал не пишем (§7): только то, что сорвалось.
      console.error(`[background] обработка ${key} не удалась:`, (e as Error)?.message ?? e);
    });

  chains.set(key, next);
  running.add(next);

  void next.finally(() => {
    running.delete(next);
    // Очередь пуста — не держим ключ вечно: чатов за год наберутся тысячи.
    if (chains.get(key) === next) chains.delete(key);
  });
}

/** Дождаться всех задач. Нужно тестам и остановке процесса, не бизнес-логике. */
export async function drainBackground(): Promise<void> {
  while (running.size > 0) {
    await Promise.allSettled([...running]);
  }
}
