async function main() {
  const run = process.argv.includes("--run");
  /** `--only=4,6` — переспросить только названные сценарии: каждый стоит денег. */
  const only = process.argv.find((a) => a.startsWith("--only="))?.slice(7);
  const picked = only
    ? SCENARIOS.filter((_, i) => only.split(",").map(Number).includes(i + 1))
    : SCENARIOS;
  console.log(`сценариев: ${picked.length}`);
  if (!run) {
    picked.forEach((s, i) => console.log(`  ${i + 1}. ${s.title}: «${s.question}»`));
    console.log("\nзапустить по-настоящему (платно): npx tsx scripts/agent-live-test.ts --run");
    return;
  }
  if (!process.env.ROUTER_AI) {
    console.error("ROUTER_AI не задан — спрашивать некого");
    process.exitCode = 1;
    return;
  }

  let failed = 0;
  for (const s of picked) {
    const answer = await answerLLM(
      s.question,
      CONTEXT,
      s.history ?? [],
      intakePrompt(CLINIC_INSTRUCTION),
      "Гульбара",
    );

    console.log(`\n── ${s.title}`);
    console.log(`   вопрос: ${s.question}`);
    if (!answer) {
      console.log("   ✗ модель не ответила");
      failed += 1;
      continue;
    }
    console.log(`   ответ: ${answer.replace(/\n/g, "\n          ")}`);

    for (const c of s.checks) {
      const ok = c.ok(answer);
      if (!ok) failed += 1;
      console.log(`   ${ok ? "✓" : "✗"} ${c.name}${ok ? "" : ` — ${c.why}`}`);
    }
    for (const e of s.expect ?? []) {
      const ok = e.re.test(answer);
      if (!ok) failed += 1;
      console.log(`   ${ok ? "✓" : "✗"} ${e.name}${ok ? "" : ` — ${e.why}`}`);
    }
  }

  console.log(
    failed === 0
      ? "\nвсе проверки пройдены: инструкция клиники работает, базовые ограничения держатся"
      : `\nпровалов: ${failed} — смотрите строки со знаком ✗`,
  );
  if (failed > 0) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
