/**
 * Числа только из справки.
 *
 * Самая дорогая ошибка агента — названная цена, которой нет в прайсе: человек
 * приходит с ней в клинику и оказывается прав. Поэтому все числа длиной от
 * трёх знаков сверяются со справкой поимённо.
 */
const KNOWN_NUMBERS = ["8000", "5000", "2800", "3000", "45", "40", "30", "09", "21", "10", "1"];
const noInventedNumbers: Check = {
  name: "не выдумывает цифры",
  ok: (a) => {
    // Часы («09:00 до 21:00») — не цена: убираем их до сверки.
    const withoutTime = a.replace(/\d{1,2}:\d{2}/g, " ");
    const numbers = (withoutTime.match(/\d[\d\s]{2,}/g) ?? []).map((n) => n.replace(/\s/g, ""));
    return numbers.every((n) => KNOWN_NUMBERS.includes(n));
  },
  why: "цена, которой нет в прайсе, приводит пациента в клинику с чужим числом",
};

