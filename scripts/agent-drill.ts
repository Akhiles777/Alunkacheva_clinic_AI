/**
 * Реплика пациента. Обычно строка; объект — когда в сообщении есть вложение.
 *
 * Фотография направления и голосовое — обычное дело в переписке клиники, и
 * ведёт себя агент на них по-особому: читать он их не может и сразу зовёт
 * человека. Проверять это надо тем же прогоном, а не рассуждением.
 */
type DrillTurn =
  | string
  | { text?: string; attachment: AttachmentKind }
  /**
   * Реплика ВРАЧА, а не пациента: она приходит с её номера и разбирается
   * отдельным путём (lib/agent/specialist). Так проверяется вся цепочка —
   * вопрос ушёл, ответ вернулся, пациент его получил.
   */
  | { specialist: string }
  /**
   * Ответ пациента на статус клиники с окошком — так, как его присылает
   * провайдер: цитата структурно, с идентификатором статуса и автором.
   *
   * В тексте статуса можно писать `{d+1}` / `{d-1}` (дата через N дней, «30.09»)
   * и `{upcoming}` (день записи постоянных пациенток песочницы): статус «на
   * конкретную дату» иначе протухал бы, как когда-то запись на 8 сентября.
   */
  | {
      status: string;
      text: string;
      /**
       * Когда статус выложен. Не задано — время публикации неизвестно, как
       * бывает, когда провайдер его не прислал: «на завтра» тогда уточняется.
       */
      postedMinutesAgo?: number;
      /** Цитата написана клиникой. false — подделка или собственное сообщение пациента. */
      byClinic?: boolean;
    }
  /**
   * Ответ свайпом на реплику агента — цитата структурно, от клиники. По
   * умолчанию на последнюю; `back: 1` — на предыдущую (живой диалог: «Да»
   * свайпом на вопрос о согласии, между ними агент ответил ещё раз).
   */
  | { replyToLast: string; back?: number; quoteStaff?: boolean }
  /**
   * Прошло столько-то часов: вся переписка сдвигается в прошлое, как будто
   * разговор шёл вчера (живой диалог 9 октября — просьба записаться вчера,
   * «нельзя оказывается» сегодня). Без этого прогон видит весь разговор одним
   * сеансом и не ловит того, что ломается на границе дня.
   */
  | { hoursPass: number }
  /**
   * Реплика сотрудника — как с телефона клиники: агент после неё молчит (пауза).
   * `handedBack` — прошло четыре часа, диалог вернулся агенту, как это делает
   * планировщик (`handBackAndRemind`).
   */
  | { staff: string; handedBack?: boolean };

interface Scenario {
  title: string;
  /** Что проверяем: по этому судим, хорош ли ответ. */
  expect: string;
  turns: DrillTurn[];
  /**
   * Канал разговора. По умолчанию Telegram: такие диалоги не показываются в
   * инбоксе, и прогон не засоряет рабочий экран администратора. WhatsApp
   * нужен там, где проверяется именно он — цитата ответом свайпом приходит
   * только оттуда.
   */
  channel?: "TELEGRAM" | "WHATSAPP";
  /**
   * Номер, известный из канала: так карточка пациента привязывается к диалогу
   * с первого сообщения, как в настоящем WhatsApp. Без него агент не знает ни
   * визитов человека, ни его записей — а половина жалоб именно об этом.
   */
  knownPhone?: string;
  /** Агент выключен в диалоге кнопкой — как это сделал заказчик у сотрудников. */
  agentDisabled?: boolean;
}

