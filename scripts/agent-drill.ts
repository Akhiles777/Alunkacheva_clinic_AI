/**
 * Последний ответ, ушедший пациенту.
 *
 * Нужен, чтобы проверить не слова, а факт: ответ врача обязан появиться в
 * переписке. «Передал пациенту» без строки в переписке — это ровно тот случай,
 * когда система уверенно врёт о выполненной работе.
 */
async function lastPatientMessage(companyId: string, externalUserId: string): Promise<string | null> {
  const row = await prisma.message.findFirst({
    where: {
      companyId,
      direction: "OUT",
      deletedAt: null,
      conversation: { externalUserId },
    },
    orderBy: { createdAt: "desc" },
    select: { body: true },
  });
  return row?.body ?? null;
}

function log(line = "") {
  process.stdout.write(`${line}\n`);
}

async function main() {
  const keep = process.argv.includes("--keep");
  /**
   * `--only=30-39` или `--only=2,5` — прогнать названные сценарии.
   *
   * Каждая реплика, дошедшая до модели, стоит денег, и гонять все тридцать
   * девять ради одной правки незачем.
   */
  const only = process.argv.find((a) => a.startsWith("--only="))?.slice(7);
  const wanted = new Set<number>();
  for (const part of only?.split(",") ?? []) {
    const range = part.match(/^(\d+)-(\d+)$/);
    if (range) {
      for (let i = Number(range[1]); i <= Number(range[2]); i += 1) wanted.add(i);
    } else if (part.trim()) {
      wanted.add(Number(part));
    }
  }
  const chosen = wanted.size > 0 ? SCENARIOS.filter((_, i) => wanted.has(i + 1)) : SCENARIOS;
  if (process.argv.includes("--list")) {
    SCENARIOS.forEach((s, i) => log(`${i + 1}. ${s.title}`));
    return;
  }

  /**
   * Клиника берётся первой по дате создания — на боевом сервере она одна. На
   * местной проверке рядом стоит песочница (scripts/agent-sandbox-seed.ts), и
   * прогон должен идти по ней: `--sandbox`.
   */
  const sandbox = process.argv.includes("--sandbox");
  const company = sandbox
    ? await prisma.company.findFirstOrThrow({ where: { yclientsId: SANDBOX_YCLIENTS_ID } })
    : await prisma.company.findFirstOrThrow({ orderBy: { createdAt: "asc" } });

  /**
   * На боевой базе прогон не идёт.
   *
   * Он создаёт десятки диалогов, сообщений и эскалаций — а это метрики
   * клиники и вызовы администраторов. Раньше это было допустимо: сценариев
   * было мало и своей базы у прогона не было. Теперь есть песочница, и
   * запускать разговоры на живой клинике незачем.
   */
  if (!sandbox) {
    const visits = await prisma.appointment.count({ where: { companyId: company.id } });
    if (visits > 0 && process.env.DRILL_ON_LIVE !== "1") {
      log(`Это боевая база: клиника «${company.name}», визитов ${visits}.`);
      log("Прогон создаёт диалоги, сообщения и эскалации — здесь он их создавать не будет.");
      log("Проверка идёт на песочнице разработчика:");
      log("  npx tsx scripts/agent-sandbox-seed.ts");
      log("  AGENT_DRILL=1 npx tsx scripts/agent-drill.ts --sandbox --only=30-44");
      return;
    }
  }

  const [services, knowledge, staff] = await Promise.all([
    prisma.service.count({ where: { companyId: company.id } }),
    prisma.knowledgeEntry.count({ where: { companyId: company.id, isActive: true } }),
    prisma.staff.count({ where: { companyId: company.id, isActive: true } }),
  ]);

  const out: string[] = [];
  out.push(`# Прогон ассистента — ${new Date().toLocaleString("ru-RU")}`);
  out.push("");
  out.push(
    `Клиника «${company.name}». В справке: услуг ${services}, записей базы знаний ${knowledge}, ` +
      `специалистов ${staff}.`,
  );
  out.push("");
  out.push(
    "Разговоры настоящие: та же модель, та же справка, те же правила, что и у пациентов в " +
      "мессенджере. Push администраторам отключены, эскалации создаются — по ним видно, когда " +
      "агент зовёт человека.",
  );
  out.push("");

  /**
   * Кому агент задаёт вопросы. В песочнице он один; на боевой базе прогон не
   * идёт вовсе, так что живого врача проверка не потревожит.
   */
  const specialist = await prisma.clinicSpecialist.findFirst({
    where: { companyId: company.id, isActive: true },
    select: { id: true, name: true },
  });
  const specialistName = specialist?.name ?? "Специалист";

  const createdConversations: string[] = [];
  const createdStatuses: string[] = [];
  let escalatedCount = 0;

  /** Дата записи постоянных пациенток песочницы — для статусов «на эту дату». */
  const upcoming = await prisma.appointment.findFirst({
    where: { companyId: company.id, startAt: { gt: new Date() }, deletedAt: null, status: { not: "CANCELLED" } },
    orderBy: { startAt: "asc" },
    select: { startAt: true },
  });
  const ddmm = (at: Date) => {
    const key = clinicDateKey(at);
    return `${key.slice(8, 10)}.${key.slice(5, 7)}`;
  };
  const expandDates = (text: string) =>
    text
      .replace(/\{upcoming\}/g, upcoming ? ddmm(upcoming.startAt) : "01.01")
      .replace(/\{d([+-])(\d+)\}/g, (_m, sign: string, n: string) =>
        ddmm(new Date(Date.now() + (sign === "-" ? -1 : 1) * Number(n) * 86_400_000)),
      );
  let silentCount = 0;

  for (const [i, scenario] of chosen.entries()) {
    const channel = scenario.channel ?? "TELEGRAM";
    const externalUserId = `drill-${randomUUID()}`;
    log(`[${i + 1}/${chosen.length}] ${scenario.title}`);

    out.push(`## ${i + 1}. ${scenario.title}`);
    out.push("");
    out.push(`_Ожидаем: ${scenario.expect}_`);
    out.push("");

    /**
     * Выключатель ставим до первой реплики: диалога ещё нет, поэтому создаём
     * его сами — ровно так же, как это делает loadConversation.
     */
    if (scenario.agentDisabled) {
      await prisma.conversation.create({
        data: {
          companyId: company.id,
          channel,
          externalUserId,
          contactName: "Проверка ассистента",
          status: "BOT_ACTIVE",
          agentDisabled: true,
          startedAt: new Date(),
          lastMessageAt: new Date(),
        },
      });
    }

    for (const turn of scenario.turns) {
      /** Сотрудник пишет сам: агента не зовём, только переписка и пауза. */
      if (typeof turn !== "string" && "staff" in turn) {
        out.push(`**Администратор:** ${turn.staff}`);
        out.push("");
        const conv = await prisma.conversation.findFirst({
          where: { companyId: company.id, externalUserId },
          select: { id: true },
        });
        if (conv) {
          await prisma.message.create({
            data: {
              companyId: company.id,
              conversationId: conv.id,
              channel,
              direction: "OUT",
              authorType: "STAFF",
              body: turn.staff,
              status: "SENT",
              sentAt: new Date(),
            },
          });
          const now = new Date();
          await prisma.conversation.update({
            where: { id: conv.id },
            data: turn.handedBack
              ? { status: "BOT_ACTIVE", botPausedUntil: now, lastMessageAt: now }
              : { status: "HUMAN_TAKEOVER", botPausedUntil: new Date(now.getTime() + 4 * 3600_000), lastMessageAt: now },
          });
        }
        continue;
      }

      /** Ответ специалиста идёт своим путём — пациентского агента он не касается. */
      if (typeof turn !== "string" && "specialist" in turn) {
        out.push(`**${specialistName}:** ${turn.specialist}`);
        out.push("");
        const before = await lastPatientMessage(company.id, externalUserId);
        const outcome = specialist
          ? await handleSpecialistReply({
              companyId: company.id,
              specialist,
              raw: turn.specialist,
            })
          : { kind: "ignored" as const, reason: "специалист не заведён в песочнице" };
        if (outcome.kind === "relayed") {
          out.push(`**Агент → пациенту:** ${outcome.text}`);
        } else if (outcome.kind === "declined") {
          out.push("**Агент → пациенту:** _(ничего — специалист ответит сам)_");
        } else if (outcome.kind === "ambiguous") {
          out.push(`**Агент → специалисту:** _(уточнил, к какому вопросу ответ: ${outcome.refs.join(", ")})_`);
        } else {
          out.push(`**Агент:** _(ответ специалиста не разобран: ${outcome.reason})_`);
        }
        const after = await lastPatientMessage(company.id, externalUserId);
        if (outcome.kind === "relayed" && before === after) {
          out.push("");
          out.push("> ВНИМАНИЕ: ответ не попал в переписку пациента");
        }
        out.push("");
        continue;
      }

      /** Ответ на статус: цитата структурно — как её присылает провайдер. */
      let quote: { id: string; text: string; byClinic: boolean } | null = null;
      if (typeof turn !== "string" && "status" in turn) {
        const statusText = expandDates(turn.status);
        const id = `drill-status-${randomUUID()}`;
        if (turn.postedMinutesAgo !== undefined) {
          await prisma.clinicStatus.create({
            data: {
              companyId: company.id,
              externalId: id,
              text: statusText,
              postedAt: new Date(Date.now() - turn.postedMinutesAgo * 60_000),
              source: "webhook",
            },
          });
          createdStatuses.push(id);
        }
        quote = { id, text: statusText, byClinic: turn.byClinic ?? true };
      }

      if (typeof turn !== "string" && "replyToLast" in turn) {
        const lastAgent = await prisma.message.findFirst({
          where: { conversation: { externalUserId }, direction: "OUT", authorType: "BOT" },
          orderBy: { createdAt: "desc" },
          skip: turn.back ?? 0,
          select: { body: true, externalId: true },
        });
        quote = lastAgent
          ? { id: lastAgent.externalId ?? `drill-out-${randomUUID()}`, text: lastAgent.body, byClinic: true }
          : null;
      }

      const text =
        typeof turn === "string"
          ? turn
          : "status" in turn
            ? `${quoteOfText(quote!.text)}\n${turn.text}`
            : "replyToLast" in turn
              ? quote
                ? `${quoteOfText(quote.text)}\n${turn.replyToLast}`
                : turn.replyToLast
              : (turn.text ?? "");
      const attachments =
        typeof turn === "string" || !("attachment" in turn)
          ? []
          : [{ kind: turn.attachment, label: KIND_LABEL[turn.attachment], source: { provider: "NONE" as const } }];
      out.push(
        `**Пациент:** ${attachments.map((a) => `[${a.label}]`).join(" ")}${attachments.length && text ? " " : ""}${text}`,
      );
      let reply: { text: string } | null = null;
      try {
        reply = await handlePatientMessage(
          {
            companyId: company.id,
            // Telegram по умолчанию: такие диалоги не показываются в списке
            // инбокса, значит проверка не засоряет рабочий экран администратора.
            channel,
            externalUserId,
            displayName: "Проверка ассистента",
          },
          {
            text,
            attachments,
            externalId: `drill-${randomUUID()}`,
            knownPhone: scenario.knownPhone ?? null,
            quote,
          },
        );
      } catch (e) {
        out.push("");
        out.push(`**СБОЙ:** ${String((e as Error)?.message ?? e)}`);
        out.push("");
        continue;
      }

      out.push("");
      if (reply?.text) {
        out.push(`**Агент:** ${reply.text}`);
      } else {
        silentCount += 1;
        out.push("**Агент:** _(промолчал — диалог передан человеку)_");
      }
      out.push("");
    }

    const conv = await prisma.conversation.findFirst({
      where: { companyId: company.id, channel, externalUserId },
      select: { id: true, status: true },
    });
    if (conv) {
      createdConversations.push(conv.id);
      const escalations = await prisma.escalation.findMany({
        where: { conversationId: conv.id },
        select: { reason: true },
      });
      if (escalations.length > 0) {
        escalatedCount += 1;
        out.push(`> Позвал человека: ${escalations.map((e) => e.reason).join(", ")}`);
        out.push("");
      }
    }
  }

  out.splice(
    4,
    0,
    `Сценариев: ${chosen.length}. Позвал человека в ${escalatedCount}. ` +
      `Промолчал ${silentCount} раз.`,
    "",
  );

  writeFileSync("data/agent-drill.md", out.join("\n"), "utf8");
  log("");
  log(`готово: data/agent-drill.md — сценариев ${chosen.length}, эскалаций ${escalatedCount}`);

  if (!keep && createdConversations.length > 0) {
    await prisma.escalation.deleteMany({ where: { conversationId: { in: createdConversations } } });
    await prisma.clinicStatus.deleteMany({ where: { companyId: company.id, externalId: { in: createdStatuses } } });
    await prisma.message.deleteMany({ where: { conversationId: { in: createdConversations } } });
    await prisma.conversation.deleteMany({ where: { id: { in: createdConversations } } });
    log(`диалоги прогона удалены: ${createdConversations.length}`);
  }

  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error("прогон упал:", e);
  await prisma.$disconnect();
  process.exit(1);
});
