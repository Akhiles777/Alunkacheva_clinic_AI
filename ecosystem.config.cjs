/**
 * Запуск под pm2 на обычном сервере (без Docker).
 *
 * Почему не `.next/standalone/server.js`, как было настроено раньше:
 *
 *   1. Автономная сборка не читает `.env`. Переменные в неё передаёт тот, кто
 *      её запускает, и pm2 их не передавал — приложение поднималось без
 *      строки подключения и отвечало «A server error occurred» на любой
 *      странице, включая регистрацию. В журнале это одна строка про
 *      DATABASE_URL, которую легко принять за проблему с базой.
 *   2. Автономная сборка не копирует к себе `public` и `.next/static`. Это
 *      делает сборщик образа вручную; на сервере никто этого не делал, и
 *      стили со скриптами отдавались бы 404.
 *
 * `next start` решает оба: сам читает `.env` и сам отдаёт статику.
 *
 * Важно: процесс пересоздаётся, а не перезапускается. `pm2 restart` и
 * `pm2 startOrRestart` поднимают приложение с ТОЙ конфигурацией, которую pm2
 * сохранил при первом запуске, и новый путь из этого файла не подхватывают.
 * Из-за этого сервер продолжал крутить автономную сборку даже после перехода
 * на `next start`: страницы отдавались, а все скрипты и стили — 404, и
 * браузер показывал «This page couldn't load». Поэтому `npm run deploy`
 * сначала удаляет процесс, а потом создаёт заново.
 *
 * Порт берём из окружения. На этом сервере 3000 занят другим проектом, и
 * молчаливый уход Next на соседний свободный порт как раз и приводил к тому,
 * что nginx стучался не туда.
 */
require("dotenv").config({ path: `${__dirname}/.env` });

module.exports = {
  apps: [
    {
      name: "clinic",
      cwd: __dirname,
      script: "node_modules/next/dist/bin/next",
      args: `start -p ${process.env.PORT || 3001}`,
      instances: 1,
      exec_mode: "fork",
      env: { ...process.env, NODE_ENV: "production" },
      // Перезапуск по памяти: утечка не должна ронять клинику на весь день.
      max_memory_restart: "600M",
      // Бесконечный цикл перезапусков при поломке конфигурации только мешает
      // читать журнал — даём паузу.
      restart_delay: 3000,
      max_restarts: 10,
      merge_logs: true,
      time: true,
    },
  ],
};
