/**
 * Запуск под pm2 на обычном сервере (без Docker).
 *
 * Почему не `.next/standalone/server.js`, как было настроено раньше:
 *
 *   1. Автономная сборка не читает `.env`. Переменные в неё передаёт тот, кто
 *      её запускает, и pm2 их не передавал — приложение поднималось без
 *      строки подключения и отвечало «A server error occurred» на любой
 *      странице, включая регистрацию. В журнале это одна строка про
 *      DATABASE_URL, которую легко принять за проблему с базой.
 *   2. Автономная сборка не копирует к себе `public` и `.next/static`. Это
 *      делает сборщик образа вручную; на сервере никто этого не делал, и
 *      стили со скриптами отдавались бы 404.
 *
 * `next start` решает оба: сам читает `.env` и сам отдаёт статику.
 *
 * Важно: процесс пересоздаётся, а не перезапускается. `pm2 restart` и
 * `pm2 startOrRestart` поднимают приложение с ТОЙ конфигурацией, которую pm2
 * сохранил при первом запуске, и новый путь из этого файла не подхватывают.
 * Из-за этого сервер продолжал крутить автономную сборку даже после перехода
 * на `next start`: страницы отдавались, а все скрипты и стили — 404, и
 * браузер показывал «This page couldn't load». Поэтому `npm run deploy`
 * сначала удаляет процесс, а потом создаёт заново.
 *
 * Порт берём из окружения. На этом сервере 3000 занят другим проектом, и
 * молчаливый уход Next на соседний свободный порт как раз и приводил к тому,
 * что nginx стучался не туда.
 */
require("dotenv").config({ path: `${__dirname}/.env` });

module.exports = {
  apps: [
    {
      name: "clinic",
      cwd: __dirname,
      script: "node_modules/next/dist/bin/next",
      args: `start -p ${process.env.PORT || 3001}`,
      instances: 1,
      exec_mode: "fork",
      env: {
        ...process.env,
        NODE_ENV: "production",
        /*
         * Часовой пояс процесса — пояс клиники.
         *
         * Серверы обычно живут по UTC. Код, где это важно, пояс указывает явно,
         * но полагаться на то, что ни одна строка о нём не забудет, нельзя:
         * ошибка тихая — время выглядит правдоподобно, просто оно на три часа
         * раньше настоящего. Задаём пояс процессу, чтобы даже забытое место
         * ошибалось в пользу клиники.
         */
        TZ: process.env.CLINIC_TIMEZONE || "Europe/Moscow",
        /*
         * Тот же предел — самому приложению, чтобы раздел /sistem показывал
         * не догадку, а настоящее число, по которому его убивают.
         */
        PM2_MAX_MEMORY_MB: String(process.env.PM2_MAX_MEMORY_MB || 900),
      },
      /**
       * Перезапуск по памяти.
       *
       * Стояло 600M — и это оказалось причиной жалобы «платформа иногда
       * слетает». Предел был ниже обычного расхода: даже на пустой базе
       * процесс держит около 220 МБ и в пиках доходит до 330, а на боевых
       * данных сверху ложится полный круг выгрузки — справочник клиентов,
       * касса за двести дней, месяц истории. Приложение переходило порог
       * несколько раз в день, pm2 молча его убивал, несколько секунд
       * соединения не принимались, а service worker показывал офлайн-
       * заглушку. Со стороны это ровно «слетело и перебросило».
       *
       * Смысл предела при этом остаётся: настоящая утечка не должна съесть
       * сервер целиком — рядом живёт второй проект и Postgres. Поэтому число
       * вынесено в окружение (`PM2_MAX_MEMORY_MB`) — подбирать его нужно по
       * фактам конкретного сервера, а не правкой кода. Сколько памяти
       * процесс занимает на самом деле и как часто перезапускается, видно в
       * разделе /sistem.
       */
      max_memory_restart: `${process.env.PM2_MAX_MEMORY_MB || 900}M`,
      // Пауза между перезапусками: бесконечный цикл при поломке конфигурации
      // только мешает читать журнал.
      restart_delay: 3000,
      /**
       * Предел перезапусков был 10 — и это оказалось причиной «постоянного
       * 502».
       *
       * pm2 считает перезапуски за всё время жизни процесса, а не за час.
       * Десять падений подряд (кончилась память, упал запрос) — и pm2 больше
       * не поднимает приложение НИКОГДА, до ручного вмешательства. Клиника
       * при этом видит страницу nginx, а не свою систему.
       *
       * Приложение должно подниматься само. `min_uptime` отделяет настоящий
       * старт от падения на старте: прожил меньше — считается неудачей, и
       * пауза между попытками работает как задумано.
       */
      autorestart: true,
      min_uptime: "20s",
      max_restarts: 1000,
      /**
       * Дать текущим запросам договорить перед остановкой.
       *
       * По умолчанию pm2 ждёт 1,6 с и рубит процесс. Запрос, попавший в этот
       * момент, обрывается на полпути: администратор видит ошибку на ровном
       * месте, а отправленное сообщение остаётся в неизвестном состоянии.
       * Восьми секунд хватает, чтобы отдать начатое.
       */
      kill_timeout: 8000,
      merge_logs: true,
      time: true,
    },
  ],
};
