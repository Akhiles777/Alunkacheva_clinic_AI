import { NextResponse } from "next/server";

/**
 * Проверка живости процесса. Намеренно не трогает базу.
 *
 * Разница с /api/health принципиальная: health отвечает на вопрос «всё ли
 * настроено», а ping — «жив ли процесс». Если бы оркестратор проверял живость
 * запросом к базе, недоступность базы перезапускала бы приложение по кругу:
 * контейнер поднимается, не может достучаться до базы, объявляется больным,
 * убивается — и так до бесконечности, вместо того чтобы спокойно дождаться
 * возвращения базы и продолжить.
 */
export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export async function GET() {
  /**
   * Отпечаток сборки — чтобы вкладка узнала, что устарела.
   *
   * Значение подставляется в бандл на сборке, поэтому у старой вкладки оно
   * своё, а здесь — нынешнее. Сравнение этих двух строк и есть единственный
   * надёжный способ поймать «Failed to find Server Action»: в проде текст
   * этой ошибки до браузера не доезжает.
   */
  return NextResponse.json({
    ok: true,
    at: new Date().toISOString(),
    build: process.env.NEXT_PUBLIC_BUILD_ID ?? null,
  });
}
