-- Напоминания по диалогу, который ждёт ответа человека.
--
-- Пациент написал, диалог ведёт администратор, ответа нет полчаса — надо
-- напомнить. Без отметки о напоминании круг расписания слал бы push каждые
-- пятнадцать минут, и его перестали бы читать; без счётчика напоминания шли
-- бы сутки подряд.
ALTER TABLE "conversations"
  ADD COLUMN "remindedAt" TIMESTAMPTZ(3),
  ADD COLUMN "reminderCount" INTEGER NOT NULL DEFAULT 0;
