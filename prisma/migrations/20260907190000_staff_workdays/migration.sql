-- В какие дни недели принимает специалист.
--
-- График клиники и график врача — разные вещи: клиника работает в субботу, а
-- из остеопатов в этот день принимает только одна. Пациентка спросила «работаете
-- ли в выходные и сколько стоит приём» и получила цены обоих врачей, хотя один
-- из них в субботу не принимает.
--
-- Пустой массив — «не заполнено», а не «не работает»: пока клиника не задала
-- дни, агент об этом молчит.

ALTER TABLE "staff" ADD COLUMN IF NOT EXISTS "workdays" INTEGER[] NOT NULL DEFAULT ARRAY[]::INTEGER[];
