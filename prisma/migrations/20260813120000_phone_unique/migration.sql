-- Телефон принадлежит ровно одному пациенту.
--
-- До сих пор на номере был только индекс, а проверка при выгрузке смотрела
-- телефон в пределах уже найденной карточки. Клиент, заведённый вручную до
-- интеграции, при импорте из YCLIENTS получил бы вторую карточку с тем же
-- номером, после чего визиты распределялись бы между ними произвольно —
-- какую карточку вернёт запрос, к той и привяжутся.
--
-- По §4 телефон — единственный надёжный ключ сопоставления пациентов, и он
-- обязан быть уникальным.

-- Страховка на случай, если дубликаты уже успели появиться: оставляем самую
-- раннюю запись номера, остальные убираем. Основной телефон не теряется —
-- при равенстве дат первым идёт тот, что помечен основным.
DELETE FROM "patient_phones" WHERE id IN (
  SELECT id FROM (
    SELECT id, row_number() OVER (
      PARTITION BY "companyId", phone
      ORDER BY "isPrimary" DESC, "createdAt" ASC
    ) rn
    FROM "patient_phones"
  ) ranked WHERE rn > 1
);

CREATE UNIQUE INDEX "patient_phones_companyId_phone_key"
  ON "patient_phones" ("companyId", phone);
