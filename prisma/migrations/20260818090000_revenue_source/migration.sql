-- Откуда взялась сумма визита.
--
-- Ноль в стоимости записи YCLIENTS означал две разные вещи: услугу отдали
-- бесплатно и цену не проставили. Выгрузка закрывала любой ноль ценой из
-- прайса — пациентке со скидкой 100% встало 3000 ₽ выручки, которой не было.
-- Провенанс делает подстановку видимой: по нему можно и разобрать жалобу, и
-- пересчитать задним числом.
CREATE TYPE "RevenueSource" AS ENUM ('RECORD', 'PRICE_LIST', 'FREE', 'UNKNOWN');

ALTER TABLE "appointments"
  ADD COLUMN "revenueSource" "RevenueSource" NOT NULL DEFAULT 'RECORD';
