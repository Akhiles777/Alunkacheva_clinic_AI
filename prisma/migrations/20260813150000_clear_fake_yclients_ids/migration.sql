-- Снимаем выдуманные идентификаторы YCLIENTS со справочников.
--
-- Базовый сид проставлял услугам и кабинетам придуманные номера (1001, 2001,
-- 900…). Пока интеграция выключена, это незаметно. После подключения даёт две
-- беды, и обе вскрываются уже на боевых данных:
--
--   1. Сверка вечно показывает расхождение: «у них 8 услуг, у нас 16» — при
--      том, что выгрузка прошла верно. Отличить настоящую потерю данных от
--      этого шума невозможно.
--   2. Если в настоящем YCLIENTS найдётся услуга или ресурс с таким же
--      номером, выгрузка молча перезапишет ими строки клиники — две
--      несвязанные сущности сольются в одну.
--
-- Пустой идентификатор означает честное «в YCLIENTS этой строки пока нет».
-- Связь появится при выгрузке, когда придут настоящие номера.
--
-- Условие защищает от повторного применения к уже связанным строкам: чистим
-- только там, где выгрузка ни разу не выполнялась.

UPDATE "services" s SET "yclientsServiceId" = NULL
WHERE s."yclientsServiceId" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "sync_cursors" c
    WHERE c."companyId" = s."companyId" AND c."lastSyncedAt" IS NOT NULL
  );

UPDATE "rooms" r SET "yclientsResourceId" = NULL
WHERE r."yclientsResourceId" IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM "sync_cursors" c
    WHERE c."companyId" = r."companyId" AND c."lastSyncedAt" IS NOT NULL
  );
