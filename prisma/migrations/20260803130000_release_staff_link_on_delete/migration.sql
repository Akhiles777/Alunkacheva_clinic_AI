-- Мягко удалённая учётная запись продолжала удерживать привязку к специалисту.
-- StaffUser."staffId" уникален, поэтому специалист навсегда оставался «занятым»:
-- выдать ему новый логин было нельзя, и вместо привязки создавался дубль
-- специалиста — в расписании появлялись два одинаковых врача.
-- Удалённая учётка больше не держит специалиста.
UPDATE "staff_users"
SET "staffId" = NULL
WHERE "deletedAt" IS NOT NULL
  AND "staffId" IS NOT NULL;
